/**
 * Твердь: сквозь дом, ствол и лавку не проходят — ни машиной, ни ногами.
 *
 *   node --experimental-strip-types tools/твердь.ts            — обязано пройти
 *   node --experimental-strip-types tools/твердь.ts сквозь     — твердь пуста,
 *                                                  как до 25.09: ОБЯЗАНО упасть
 *   node --experimental-strip-types tools/твердь.ts по-кадрам  — машина упирается
 *                                   раз в кадр, а не на шаге физики: ОБЯЗАНО упасть
 *
 * Машина — настоящая (`car.ts`, паспорт Viper), пешеход — настоящий
 * (`person.ts`), вещь двора — из тех же частей, что рисуются (`частиВещи`).
 * Земля ровная: здесь меряется твердь, а не рельеф.
 */

import { VIPER } from '../src/car/passport.ts';
import { P_ZERO } from '../src/car/tyre.ts';
import { createCar, forwardSpeed, step } from '../src/car/car.ts';
import { ПЛЕЧИ, createPerson, step as шагнуть } from '../src/person/person.ts';
import { частиВещи } from '../src/модели.ts';
import {
  type Форма, ПУСТО, глубинаКруга, глубинаКузова, коробка, круг, пройти, собратьТвердь, упереть, формыВещи,
} from '../src/city/твердь.ts';

const вариант = process.argv[2] ?? '';
const ДОПУСК = 0.02;
const земля = { sample: () => ({ height: 0, nx: 0, ny: 1, nz: 0, material: 'asphalt' as const }) };
const ГАБАРИТ = { длина: VIPER.length, ширина: VIPER.width };
const ШАГ = 1 / 300;
let плохо = 0;
const сказать = (ок: boolean, имя: string, что: string): void => {
  if (!ок) плохо++;
  console.log(`  ${ок ? '✓' : '✗'} ${имя.padEnd(52, '.')} ${что}`);
};
const твердь = (формы: Форма[]) => (вариант === 'сквозь' ? ПУСТО : собратьТвердь(формы));

/**
 * Разогнать машину до 60 км/ч и пустить накатом в преграду. Возвращает
 * наибольшую глубину захода, скорость до и после удара и сколько её
 * закрутило.
 */
function вРазгон(формы: Форма[], вбок: number): { глубина: number; до: number; после: number; крутит: number; удар: number } {
  const т = твердь(формы);
  const car = createCar(VIPER, 0, вбок, 0);
  let глубина = 0, до = 0, после = Infinity, удар = 0, крутит = 0, t = 0, шагов = 0;
  const газ = { steer: 0, throttle: 1, brake: 0, handbrake: false, assist: true };
  const накат = { ...газ, throttle: 0 };
  while (t < 20) {
    const v = forwardSpeed(car);
    step(car, VIPER, P_ZERO, земля.sample, v < 60 / 3.6 && car.x < 60 ? газ : накат, ШАГ);
    t += ШАГ;
    шагов++;
    if (вариант !== 'по-кадрам' || шагов % 5 === 0) {
      const было = Math.hypot(car.vx, car.vz);
      const u = упереть(т, car, ГАБАРИТ, VIPER.mass, VIPER.yawInertia);
      if (u > 0 && удар === 0) до = было;
      удар = Math.max(удар, u);
      if (u > 0) после = Math.min(после, Math.hypot(car.vx, car.vz));
    }
    // инвариант меряется по ИСТИННОЙ тверди, даже когда проверяемый вариант её не видит
    глубина = Math.max(глубина, глубинаКузова(собратьТвердь(формы), car, ГАБАРИТ));
    крутит = Math.max(крутит, Math.abs(car.yawRate));
    if (car.x > 200) break;
  }
  return { глубина, до, после: после === Infinity ? до : после, крутит, удар };
}

/** Пешеход бежит курсом `курс` три секунды; наибольшая глубина и где оказался. */
function бегом(формы: Форма[], x: number, z: number, курс: number): { глубина: number; x: number; z: number } {
  const т = твердь(формы);
  const p = createPerson(x, z, земля, курс);
  let глубина = 0;
  for (let t = 0; t < 3; t += 1 / 60) {
    шагнуть(p, земля, { forward: 1, side: 0, run: true }, 1 / 60, {
      упор: (x0, z0, x1, z1) => пройти(т, x0, z0, x1, z1, ПЛЕЧИ),
    });
    глубина = Math.max(глубина, глубинаКруга(собратьТвердь(формы), p.x, p.z, ПЛЕЧИ));
  }
  return { глубина, x: p.x, z: p.z };
}

console.log(`\nТВЕРДЬ${вариант ? ` — ЗАВЕДОМО СЛОМАННО: ${вариант}` : ''}\n`);

// дом: стена поперёк пути в 80 м, 10 м вглубь, 24 м по фронту
const дом = [коробка(85, 0, 0, 10, 24)];
const вДом = вРазгон(дом, 0);
сказать(вДом.глубина <= ДОПУСК, 'машина в стену дома на 60 км/ч: не заходит внутрь', `глубже всего ${(вДом.глубина * 100).toFixed(1)} см`);
сказать(вДом.удар > 10, 'удар был, и на полной скорости', `${(вДом.удар * 3.6).toFixed(0)} км/ч по нормали`);
сказать(вДом.после <= вДом.до, 'удар не рождает энергию', `${(вДом.до * 3.6).toFixed(0)} → ${(вДом.после * 3.6).toFixed(0)} км/ч`);

// ствол липы: 0.38 м толщиной, удар правым углом — машину обязано закрутить
const ствол = [круг(85, -0.75, 0.19)];
const вСтвол = вРазгон(ствол, 0);
сказать(вСтвол.глубина <= ДОПУСК, 'машина углом в ствол: не проходит сквозь', `глубже всего ${(вСтвол.глубина * 100).toFixed(1)} см`);
сказать(вСтвол.крутит > 0.5, 'удар углом разворачивает машину', `до ${вСтвол.крутит.toFixed(2)} рад/с`);

// пешеход: в стену дома бегом и под углом вдоль неё
const вСтену = бегом(дом, 70, 0, 0);
сказать(вСтену.глубина <= ДОПУСК && вСтену.x < 80, 'пешеход бегом в стену: остаётся снаружи', `глубже всего ${(вСтену.глубина * 100).toFixed(1)} см, стоит на x=${вСтену.x.toFixed(2)}`);
const вдоль = бегом(дом, 79, -8, Math.PI / 6);
сказать(вдоль.z - -8 > 5 && вдоль.глубина <= ДОПУСК, 'под углом в стену — скользит вдоль неё', `прошёл вдоль стены ${(вдоль.z + 8).toFixed(1)} м`);

// лавка — из тех же частей, что рисуются; бежим поперёк сиденья
const лавка = формыВещи(частиВещи('лавка'), { x: 5, z: 0, курс: Math.PI / 2 });
сказать(лавка.length > 0, 'у лавки есть твердь из её частей', `${лавка.length} частей выше ступени`);
const вЛавку = бегом(лавка, 0, 0, 0);
сказать(вЛавку.глубина <= ДОПУСК && вЛавку.x < 5, 'пешеход в лавку: не проходит сквозь', `глубже всего ${(вЛавку.глубина * 100).toFixed(1)} см, x=${вЛавку.x.toFixed(2)}`);
// покрытие площадки — под ногами, не на пути
сказать(формыВещи(частиВещи('площадка'), { x: 0, z: 0, курс: 0 }).length === 0, 'покрытие площадки не преграда', 'ниже ступени — под ногами');

console.log(плохо === 0 ? '\nСКВОЗЬ НЕ ПРОЙТИ\n' : '\nПРОХОДИТ СКВОЗЬ\n');
process.exitCode = плохо === 0 ? 0 : 1;
