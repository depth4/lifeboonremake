/**
 * Проверка типов — и страницы, и инструментов.
 *
 * Зачем отдельный инструмент, а не строчка `tsc` в package.json: инструменты
 * из `tools/` запускаются через `--experimental-strip-types`, а он типы
 * СРЕЗАЕТ, не проверяя. Полгода в них никто не смотрел, и там нашлись четыре
 * настоящие ошибки — от неиспользованной переменной до подделки земли,
 * выданной за настоящую приведением типа. Теперь смотрит эта команда.
 *
 * Два разных мира и потому два разных набора правил:
 *   `tsconfig.json`       — `src/`, ему видно окно браузера, но не Node;
 *   `tsconfig.tools.json` — `tools/`, ему видно Node.
 *
 * Запуск:
 *   npm run types          — проверить
 *   npm run types сломать  — подложить заведомо сломанный файл и убедиться,
 *                            что проверка его ловит (правило 11)
 */

import { spawnSync } from 'node:child_process';
import { rmSync, writeFileSync } from 'node:fs';

const сломать = process.argv.includes('сломать');
/** Куда кладётся заведомо сломанный файл: внутрь tools, иначе его не видно. */
const ПОДДЕЛКА = 'tools/__заведомо-сломанный.ts';

function проверить(конфиг) {
  const r = spawnSync('npx', ['tsc', '--noEmit', '-p', конфиг], { encoding: 'utf8' });
  return { код: r.status ?? 1, вывод: (r.stdout ?? '') + (r.stderr ?? '') };
}

if (сломать) {
  // число, выданное за строку: это обязано быть поймано
  writeFileSync(ПОДДЕЛКА, 'export const сколько: string = 17;\n');
}

let плохо = 0;
try {
  for (const [имя, конфиг] of [['страница', 'tsconfig.json'], ['инструменты', 'tsconfig.tools.json']]) {
    const { код, вывод } = проверить(конфиг);
    console.log(`  ${код === 0 ? '✓' : '✗'} ${имя.padEnd(14, '.')} ${конфиг}`);
    if (код !== 0) { плохо++; console.log(вывод.trimEnd().split('\n').slice(0, 12).join('\n')); }
  }
} finally {
  if (сломать) rmSync(ПОДДЕЛКА, { force: true });
}

if (сломать) {
  // здесь успех — это провал проверки: она обязана была найти подделку
  if (плохо === 0) { console.log('\nПОДДЕЛКУ НЕ ЗАМЕТИЛИ — проверке типов верить нельзя'); process.exit(0); }
  console.log('\nподделка поймана — проверке типов можно верить');
  process.exit(1);
}

if (плохо > 0) { console.log(`\nТИПЫ: ${плохо} конфигурации не прошли`); process.exit(1); }
console.log('\nтипы в порядке');
process.exit(0);
