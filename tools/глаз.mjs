/**
 * Чего стоит зрение: проверка режима «глаз» в настоящем браузере.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ИНСТРУМЕНТ. Режим глаза не проверялся в браузере ВООБЩЕ:
 * `ride` ездит за рулём и пешком не ходит, `play` про инструмент дорог,
 * `walk` считает тело без экрана. Ровно поэтому 18 сентября наводка лучом
 * по всей сцене прожила до тех пор, пока Алекс не включил глаз и не сказал
 * «жёстко падает фреймрейт».
 *
 * ЧТО ЗДЕСЬ МЕРИТСЯ И ПОЧЕМУ ИМЕННО ЭТО. Не миллисекунды кадра: в контейнере
 * рисует программный отрисовщик, и его время ничего не говорит о машине
 * Алекса. Мерится СВОЯ РАБОТА ГЛАЗА — чистый счёт до отрисовки. У неё есть
 * свойство, которое проверять можно и нужно: она обязана быть ПОСТОЯННОЙ.
 * Работа, растущая вместе с городом, — это и есть беда, и растёт она молча:
 * на маленьком городе луч стоил 6.6 мс, на большом 17.55 — больше всего
 * бюджета кадра целиком.
 *
 * Запуск:  npm run глаз
 *          npm run глаз лучом — вернуть наводку лучом по всей сцене,
 *                               как было до 18.09: ОБЯЗАНА упасть
 */

import { createServer } from 'vite';
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';

/** Заведомо сломанный вариант: наводка лучом по всей сцене. */
const лучом = process.argv[2] === 'лучом';

/**
 * Предел своей работы глаза, мс на кадр. Взят не с потолка: всё, что глаз
 * делает сам, — это записать одно число в проход смаза. Десятая доля
 * миллисекунды — это уже с запасом в десять раз.
 */
const ПРЕДЕЛ = 0.5;

const PORT = 5199;
mkdirSync('shots', { recursive: true });

const server = await createServer({ server: { port: PORT, strictPort: true }, logLevel: 'warn' });
await server.listen();
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e).split('\n')[0]));

const checks = [];
const say = (имя, ок, что) => { checks.push([имя, ок, что]); };

const замер = async (сцена) => {
  const url = `http://localhost:${PORT}/?scene=${encodeURIComponent(сцена)}`
    // без травы: меряется СВОЯ работа глаза, а трава на программном
    // отрисовщике растянула бы каждый кадр в секунды (решение 093)
    + `&terrain=plateau&view=close&трава=нет${лучом ? '&глаз-лучом=1' : ''}`;
  /**
   * Загрузку эта проверка не мерит: «большой город» строится при загрузке
   * десятки секунд (поверхность одна — 14 с в контейнере). Ожидание по
   * умолчанию в 30 с было не решением, а случайностью, и 24.09 на GitHub
   * проверка упала по нему, ничего не сказав про зрение.
   */
  await page.goto(url, { waitUntil: 'load', timeout: 180000 });
  await page.waitForFunction(() => window.__ready === true, null, { timeout: 180000 });
  /**
   * Список «что нового» закрывается ДО клика. Он лежит поверх страницы,
   * и когда заголовки коммитов стали длиннее, он накрыл собой кнопку
   * «пешком»: клик не проходил, проверка падала по таймауту и не называла
   * виновного. Это не про зрение — это про то, что проверка обязана
   * кликать по тому же, по чему кликает человек, а человек список закроет.
   */
  await page.evaluate(() => document.getElementById('news')?.classList.remove('open'));
  /**
   * Жмём кнопку СТРАНИЦЫ, а не через драйвер: обычный `page.click` после
   * нажатия ждёт «запланированных переходов», а тяжёлая страница отдаёт
   * управление не сразу — и ожидание упиралось в таймаут на пустом месте.
   */
  await page.$eval('button[data-drive="afoot"]', (el) => el.click());
  // глазу надо несколько десятков кадров, чтобы среднее устоялось
  await page.waitForTimeout(2500);
  const глаз = await page.evaluate(() => ({
    включён: document.querySelector('button[data-drive="sight"]')?.getAttribute('aria-pressed'),
    мс: window.__глазМс?.() ?? null,
  }));
  return глаз;
};

const малый = await замер('город');
/**
 * Снимок глазами — ДО приговора и без права его решать.
 *
 * Первая редакция снимала в конце, и на заведомо сломанном варианте снимок
 * не успевал за тридцать секунд: страница с лучом тормозит так, что даже
 * кадр не отдаётся. Проверка обрывалась до того, как назвать виновного,
 * и падала «по-настоящему», но молча. Проверка, которая падает молча,
 * ничем не лучше зелёной галочки.
 */
try {
  await page.screenshot({ path: 'shots/глаз.png', timeout: 15000 });
} catch {
  console.log('  (снимок не снялся — страница не отдаёт кадр; на приговор не влияет)');
}
const большой = await замер('большой город');

say('глаз включается и отвечает, чего он стоит',
  малый.включён === 'true' && малый.мс !== null,
  `кнопка «глаз»: ${малый.включён}, счётчик: ${малый.мс === null ? 'нет' : 'есть'}`);

for (const [имя, г] of [['город', малый], ['большой город', большой]]) {
  say(`своя работа глаза не больше ${ПРЕДЕЛ} мс на кадр (${имя})`,
    г.мс !== null && г.мс <= ПРЕДЕЛ,
    `${г.мс === null ? '—' : г.мс.toFixed(2)} мс при бюджете кадра 16.7`);
}

/**
 * Главное утверждение. Город больше вчетверо по площади и вчетверо
 * по числу домов и деревьев. Если работа глаза от этого выросла — значит
 * он перебирает сцену, и завтра она вырастет ещё.
 */
const рост = малый.мс > 0.01 ? большой.мс / малый.мс : (большой.мс <= ПРЕДЕЛ ? 1 : 99);
say('работа глаза НЕ растёт вместе с городом', рост < 2,
  `малый ${малый.мс?.toFixed(2)} мс, большой ${большой.мс?.toFixed(2)} мс — в ${рост.toFixed(1)} раза`);

say('на странице нет ошибок', errors.length === 0, errors.join('; ') || 'чисто');

await browser.close();
server.close().catch(() => {});

console.log(`\nГЛАЗ${лучом ? ' — ЗАВЕДОМО СЛОМАННЫЙ: наводка лучом по всей сцене' : ''}\n`);
let упало = 0;
for (const [имя, ок, что] of checks) {
  if (!ок) упало++;
  console.log(`  ${ок ? '✓' : '✗'} ${имя.padEnd(52, '.')} ${что}`);
}
console.log(`\n${упало === 0 ? 'ЗРЕНИЕ НЕ СТОИТ НИЧЕГО ЛИШНЕГО' : `ГЛАЗ ПРОВАЛЕН: ${упало}`}\n`);
process.exit(упало === 0 ? 0 : 1);
