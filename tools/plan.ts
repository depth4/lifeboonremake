/**
 * Карта плана — чтобы план можно было УВИДЕТЬ, а не только прочитать цифрами.
 * Рисуется в SVG: это тот же план, только глазами, и никакой отдельной правды
 * в нём нет — всё берётся из посёлка.
 */
if (карта) {
  const ЦВЕТ: Record<string, string> = {
    жильё: '#bfae95', сад: '#e0c060', школа: '#b06a4a',
    магазин: '#6d93b8', поликлиника: '#e6e6e0',
  };
  const п = город;
  const R = п.половина;
  const в = (v: number): number => v + R;
  const части: string[] = [];
  for (const у of п.улицы) {
    const ш = у.вид === 'магистральная' ? 14 : 7;
    части.push(`<line x1="${в(у.a.x)}" y1="${в(у.a.z)}" x2="${в(у.b.x)}" y2="${в(у.b.z)}" `
      + `stroke="#3c4046" stroke-width="${ш}" />`);
  }
  /**
   * Дворы рисуются ПОД участками: двор — это то, что осталось от квартала,
   * и порядок отрисовки должен читаться так же, как порядок нарезки.
   */
  for (const к of п.кварталы) {
    if (к.двор === null) continue;
    части.push(`<rect x="${в(к.двор.x) - к.двор.ширина / 2}" y="${в(к.двор.z) - к.двор.глубина / 2}" `
      + `width="${к.двор.ширина}" height="${к.двор.глубина}" fill="#7ea866" `
      + `stroke="#00000033" stroke-width="0.8" />`);
    for (const вз of к.въезды) {
      // въезд рисуется от красной линии внутрь двора: видно, куда он ведёт
      const длина = ГЛУБИНА_УЧАСТКА;
      const кx = вз.x + Math.cos(вз.курс) * длина / 2;
      const кz = вз.z + Math.sin(вз.курс) * длина / 2;
      const поX = Math.abs(Math.cos(вз.курс)) > 0.5;
      части.push(`<rect x="${в(кx) - (поX ? длина : вз.ширина) / 2}" `
        + `y="${в(кz) - (поX ? вз.ширина : длина) / 2}" `
        + `width="${поX ? длина : вз.ширина}" height="${поX ? вз.ширина : длина}" `
        + `fill="#4a4e54" />`);
    }
  }
  /**
   * Дворы рисуются ПОД участками: двор — это то, что осталось от квартала,
   * и порядок отрисовки должен читаться так же, как порядок нарезки.
   */
  for (const к of п.кварталы) {
    if (к.двор === null) continue;
    части.push(`<rect x="${в(к.двор.x) - к.двор.ширина / 2}" y="${в(к.двор.z) - к.двор.глубина / 2}" `
      + `width="${к.двор.ширина}" height="${к.двор.глубина}" fill="#7ea866" `
      + `stroke="#00000033" stroke-width="0.8" />`);
    for (const вз of к.въезды) {
      // въезд рисуется от красной линии внутрь двора: видно, куда он ведёт
      const длина = ГЛУБИНА_УЧАСТКА;
      const кx = вз.x + Math.cos(вз.курс) * длина / 2;
      const кz = вз.z + Math.sin(вз.курс) * длина / 2;
      const поX = Math.abs(Math.cos(вз.курс)) > 0.5;
      части.push(`<rect x="${в(кx) - (поX ? длина : вз.ширина) / 2}" `
        + `y="${в(кz) - (поX ? вз.ширина : длина) / 2}" `
        + `width="${поX ? длина : вз.ширина}" height="${поX ? вз.ширина : длина}" `
        + `fill="#4a4e54" />`);
    }
  }
  for (const у of п.участки) {
    const ш = у.вдольX ? у.фронт : у.глубина;
    const г = у.вдольX ? у.глубина : у.фронт;
    части.push(`<rect x="${в(у.x) - ш / 2}" y="${в(у.z) - г / 2}" width="${ш}" height="${г}" `
      + `fill="${ЦВЕТ[у.что]}" stroke="#00000022" stroke-width="0.6" />`);
  }
  for (const о of п.остановки) {
    части.push(`<circle cx="${в(о.x)}" cy="${в(о.z)}" r="5" fill="#2f7d32" stroke="#fff" stroke-width="1.5" />`);
  }
  const подпись = (текст: string, цвет: string, i: number): string =>
    `<rect x="12" y="${14 + i * 26}" width="18" height="18" fill="${цвет}" />`
    + `<text x="38" y="${28 + i * 26}" font-size="15" fill="#eee" font-family="system-ui">${текст}</text>`;
  const легенда = [
    подпись(`жильё — ${город.людей} жителей`, ЦВЕТ.жильё, 0),
    подпись(`сады: ${город.есть.сад} (норма ${город.нужно.сад})`, ЦВЕТ.сад, 1),
    подпись(`школы: ${город.есть.школа} (норма ${город.нужно.школа})`, ЦВЕТ.школа, 2),
    подпись(`магазины: ${город.есть.магазин} (норма ${город.нужно.магазин})`, ЦВЕТ.магазин, 3),
    подпись(`поликлиники: ${город.есть.поликлиника}`, ЦВЕТ.поликлиника, 4),
    подпись(`остановки: ${город.остановки.length}`, '#2f7d32', 5),
    подпись(`дворы: ${город.кварталы.filter((к) => к.двор !== null).length}, `
      + `въездов ${город.кварталы.reduce((n, к) => n + к.въезды.length, 0)}, `
      + `машиномест ${город.кварталы.reduce((n, к) => n + к.мест, 0)}`, '#7ea866', 6),
  ].join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${R * 2}" height="${R * 2}" `
    + `viewBox="0 0 ${R * 2} ${R * 2}"><rect width="100%" height="100%" fill="#5f8a4a" />`
    + части.join('') + `</svg>`;
  const html = `<!doctype html><meta charset="utf-8"><title>план посёлка</title>`
    + `<style>body{margin:0;background:#14181d;color:#eee;font-family:system-ui;display:flex;gap:20px;padding:20px}`
    + `svg{background:#5f8a4a;box-shadow:0 0 0 1px #0006}</style>`
    + svg
    + `<div><h2 style="margin:0 0 8px">Посёлок по нормам, ${R * 2} × ${R * 2} м</h2>`
    + `<svg width="420" height="215">${легенда}</svg>`
    + `<p style="max-width:320px;line-height:1.5;opacity:.8">Улицы, участки и назначения `
    + `выведены из сида и норм: радиусы доступности, места на тысячу жителей, `
    + `красные линии. Ничего не расставлено рукой.</p></div>`;
  writeFileSync('build/план.html', html);
  console.log('карта плана: build/план.html');
}

process.exit(упало === 0 ? 0 : 1);