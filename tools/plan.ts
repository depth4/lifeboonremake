const checks: [string, boolean, string][] = [];
const say = (имя: string, ок: boolean, что: string): void => { checks.push([имя, ок, что]); };
const дист = (a: { x: number; z: number }, b: { x: number; z: number }): number =>
  Math.hypot(a.x - b.x, a.z - b.z);

/** Самый несчастный дом: до какого объекта идти дальше всех. */
function дальшеВсего(п: Посёлок, что: Участок['что']): { метров: number; сколько: number } {
  const цели = п.участки.filter((у) => у.что === что);
  const жильё = п.участки.filter((у) => у.что === 'жильё');
  if (цели.length === 0) return { метров: Infinity, сколько: 0 };
  let худшее = 0;
  for (const дом of жильё) {
    let ближе = Infinity;
    for (const ц of цели) ближе = Math.min(ближе, дист(дом, ц));
    худшее = Math.max(худшее, ближе);
  }
  return { метров: худшее, сколько: цели.length };
}

