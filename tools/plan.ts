// ── Красная линия: застройка за неё не заходит. Это устройство, не проверка,
//    но если устройство сломают — здесь будет видно.
{
  let ближе = Infinity;
  for (const у of город.участки) {
    const улица = город.улицы[у.улица];
    const вдольX = улица.a.z === улица.b.z;
    const доОси = вдольX ? Math.abs(у.z - улица.a.z) : Math.abs(у.x - улица.a.x);
    ближе = Math.min(ближе, доОси - у.глубина / 2 - улица.отступ);
  }
  say('застройка не заходит в красную линию', ближе >= -0.001,
    `самый близкий фасад на ${ближе.toFixed(2)} м от границы`);
}

/**
 * ── Перекрёсток остаётся открытым.
 *
 * Дом на углу закрывает видимость — это первое, что запрещают нормы
 * планировки. Проверяется не «красиво ли», а расстояние до ОСИ поперечной
 * улицы: ближе её красной линии застройки быть не может.
 *
 * Эта проверка нашла настоящую беду: квартал отсчитывался шагами от конца
 * улицы, и когда размер посёлка не был кратен шагу, вся раскладка съезжала
 * на полквартала. Все 180 участков стояли в углах, ближайший — ровно на оси
 * поперечной улицы. Снимок сверху это показывал, но никто не смотрел.
 */
for (const [имя, п] of [['город', город], ['деревня', деревня]] as const) {
  const оси = { вдольX: new Set<number>(), вдольZ: new Set<number>() };
  const красная = new Map<number, number>();
  for (const у of п.улицы) {
    const вдольX = у.a.z === у.b.z;
    const где = вдольX ? у.a.z : у.a.x;
    (вдольX ? оси.вдольX : оси.вдольZ).add(где);
    красная.set(где, Math.max(красная.get(где) ?? 0, у.отступ));
  }
  let ближе = Infinity;
  let виновник = '';
  for (const у of п.участки) {
    const поперёк = у.вдольX ? оси.вдольZ : оси.вдольX;
    const моя = у.вдольX ? у.x : у.z;
    for (const ось of поперёк) {
      // между фронтом участка и осью поперечной улицы должна быть её красная линия
      const зазор = Math.abs(моя - ось) - у.фронт / 2 - (красная.get(ось) ?? 0);
      if (зазор < ближе) { ближе = зазор; виновник = `участок (${у.x}, ${у.z}) против оси ${ось}`; }
    }
  }
  say(`перекрёстки не застроены (${имя})`, ближе >= -0.001,
    `самый близкий угол: ${ближе.toFixed(1)} м запаса — ${виновник}`);
}

// ── Участки не налезают друг на друга.
{
  let наложений = 0;
  const у = город.участки;
  /** Размер участка по осям мира: вдоль улицы это фронт, поперёк — глубина. */
  const поОсям = (a: Участок): { x: number; z: number } =>
    a.вдольX ? { x: a.фронт, z: a.глубина } : { x: a.глубина, z: a.фронт };
  for (let i = 0; i < у.length; i++) {
    const a = поОсям(у[i]);
    for (let j = i + 1; j < у.length; j++) {
      const b = поОсям(у[j]);
      const dx = Math.abs(у[i].x - у[j].x);
      const dz = Math.abs(у[i].z - у[j].z);
      if (dx < (a.x + b.x) / 2 - 0.01 && dz < (a.z + b.z) / 2 - 0.01) наложений++;
    }
  }
  say('участки не налезают друг на друга', наложений === 0, `${наложений} наложений`);
}

/**
 * КВАРТАЛ ИЗНУТРИ: двор, въезд, машиноместа.
 *
 * До 17.09 внутренности квартала не существовало в данных, и проверять было
 * нечего — ровно поэтому ни двора, ни въезда в городе и не было. Теперь
 * квартал это область, и у области есть что проверить.
 */
{
  for (const [имя, п] of [['город', город], ['деревня', деревня]] as const) {
    const сДвором = п.кварталы.filter((к) => к.двор !== null);
    const безВъезда = сДвором.filter((к) => к.въезды.length === 0);
    say(`у каждого двора есть въезд (${имя})`, безВъезда.length === 0,
      `${п.кварталы.length} кварталов, ${сДвором.length} с двором, `
      + `без въезда ${безВъезда.length}`);
  }

  /**
   * ── РАКУРС «ДВОР» СМОТРИТ ВО ДВОР.
   *
   * Проверка появилась 18.09 по прямому «где дворы, их нету блять». Дворы
   * были — все, с проездами и стоянками; на экране их не было, потому что
   * ни один ракурс в меню на них не смотрел. Построить и не показать —
   * то же самое, что не построить, и проверять это надо так же, как всё
   * остальное.
   *
   * Меряется не «есть ли кнопка», а КУДА СМОТРИТ КАМЕРА: точка взгляда
   * обязана лежать внутри квартала, а точка стояния — не дальше полуширины
   * въезда от его середины.
   */
  for (const [имя, п] of [['город', город], ['деревня', деревня]] as const) {
    const место = откудаСмотретьВоДвор(п, взглядНаружу ? { взгляд: 'наружу' } : {});
    if (место === null) { say(`ракурс «двор» смотрит во двор (${имя})`, false, 'двора не нашлось'); continue; }
    const к = п.кварталы[место.квартал];
    const внутри = (т: { x: number; z: number }): boolean =>
      т.x > к.x0 && т.x < к.x1 && т.z > к.z0 && т.z < к.z1;
    const л = к.проезд as readonly { x: number; z: number }[];
    /** Сколько метров от точки до полотна проезда. */
    const доПроезда = (т: { x: number; z: number }): number => {
      let ближе = Infinity;
      for (let i = 0; i + 1 < л.length; i++) {
        const dx = л[i + 1].x - л[i].x, dz = л[i + 1].z - л[i].z;
        const д2 = dx * dx + dz * dz;
        let t = д2 < 1e-9 ? 0 : ((т.x - л[i].x) * dx + (т.z - л[i].z) * dz) / д2;
        t = Math.max(0, Math.min(1, t));
        ближе = Math.min(ближе, Math.hypot(т.x - (л[i].x + dx * t), т.z - (л[i].z + dz * t)));
      }
      return ближе;
    };
    /**
     * Камера СТОИТ НА ПРОЕЗДЕ и смотрит В ГЛУБИНУ ДВОРА — туда, где площадка
     * и лавки. Мерится не «куда повёрнута», а где обе точки: стояние на
     * полотне, взгляд внутри квартала и дальше от полотна, чем стояние.
     */
    const ок = внутри(место.до) && доПроезда(место.от) < 6
      && доПроезда(место.до) > доПроезда(место.от) + 5;
    say(`ракурс «двор» смотрит во двор (${имя})`, ок,
      `стоим у проезда (${доПроезда(место.от).toFixed(1)} м от полотна), `
      + `смотрим ${внутри(место.до) ? 'внутрь' : 'НАРУЖУ'} квартала `
      + `на ${доПроезда(место.до).toFixed(0)} м от полотна`);
  }

  /**
   * ── ВО ДВОРЕ ЕСТЬ ЧТО-ТО, КРОМЕ ГАЗОНА, и оно не на дороге.
   *
   * Двор до 22.09 был газоном с дорогой: проезд есть, стоянка есть, подходы
   * есть — а самого двора как места нет. Проверяется не «нарисовали ли»,
   * а два числа: у каждого двора с проездом есть площадка, и ни одна вещь
   * не стоит на проезжей части, в доме или на дорожке.
   */
  for (const [имя, п] of [['город', город], ['деревня', деревня]] as const) {
    const свои = п.объекты.map((о) => домНаУчастке(о, п.вид, п.сид));
    const подходы = подходыПосёлка(п, свои);
    const занято = (x: number, z: number): boolean =>
      вДоме(свои, x, z, 1.5) || подПодходом(подходы, x, z, 1.0);
    const вещи = вещиПосёлка(п, занято,
      площадкаНаПроезде ? { площадка: 'на проезде' as const } : {});
    const мир = buildWorld(дорогиПосёлка(п), 'plain');
    const дворов = п.кварталы.filter((к) => к.двор !== null && к.проезд !== null).length;
    const площадок = вещи.filter((в) => в.что === 'площадка').length;
    let наДороге = 0, вДомах = 0;
    for (const в of вещи) {
      const рядом = nearestRoad(мир, в.x, в.z);
      if (рядом !== null && рядом.distance < рядом.halfWidth) наДороге++;
      if (вДоме(свои, в.x, в.z, 0)) вДомах++;
    }
    say(`во дворе есть площадка, и вещи не на дороге (${имя})`,
      площадок === дворов && наДороге === 0 && вДомах === 0,
      `${дворов} дворов, площадок ${площадок}, вещей ${вещи.length}; `
      + `на проезжей части ${наДороге}, в домах ${вДомах}`);
  }

  /**
   * ── В РАЗРЫВЕ ПОД ВЪЕЗД НЕ СТОИТ ДОМ.
   *
   * Въезд — это РАЗРЫВ В ЗАСТРОЙКЕ, и проверять надо застройку, а не запись
   * о въезде. 18.09 все записи были на месте, проезд доходил до улицы,
   * а в самом разрыве стояла школа в сорок девять метров: `занять` брала
   * соседние участки «по расстоянию» и перешагивала через разрыв. С улицы
   * это выглядело так: едешь во двор — упираешься в стену.
   */
  for (const [имя, п] of [['город', город], ['деревня', деревня]] as const) {
    const дома = п.объекты.map((о) => домНаУчастке(о, п.вид, п.сид));
    let худший = Infinity, кто = '';
    let въездов = 0;
    for (const к of п.кварталы) {
      for (const в of к.въезды) {
        въездов++;
        for (const д of дома) {
          const c = Math.cos(д.курс), s2 = Math.sin(д.курс);
          const dx = д.x - в.x, dz = д.z - в.z;
          const вдоль = dx * c + dz * s2, поперёк = -dx * s2 + dz * c;
          const зазор = Math.max(Math.abs(вдоль) - д.глубина / 2,
            Math.abs(поперёк) - д.ширина / 2);
          if (зазор < худший) {
            худший = зазор;
            кто = `дом ${д.ширина.toFixed(0)}×${д.глубина.toFixed(0)} у въезда `
              + `${в.x.toFixed(0)},${в.z.toFixed(0)}`;
          }
        }
      }
    }
    // проём свободен, если ни один дом не подошёл ближе половины его ширины
    const надо = въездов === 0 ? 0 : (п.кварталы.find((к) => к.въезды.length > 0)
      ?.въезды[0].ширина ?? 0) / 2;
    say(`в разрыве под въезд не стоит дом (${имя})`, въездов > 0 && худший >= надо,
      `${въездов} въездов, проём ${(надо * 2).toFixed(1)} м, `
      + `ближе всего ${худший === Infinity ? '—' : худший.toFixed(1) + ' м'}`
      + `${худший >= надо ? '' : ' — ' + кто}`);
  }

  /**
   * ── В КАЖДЫЙ ДВОР МОЖНО ВЪЕХАТЬ. Не «есть ли разрыв в застройке»,
   * а СВЯЗНА ЛИ ДОРОЖНАЯ СЕТЬ.
   *
   * Разница стоила всего: 18.09 у всех тридцати шести дворов «города»
   * был въезд, разрыв в домах и нарисованный проезд — и ни один не был
   * соединён с улицей. Проезд начинался на красной линии, а дороги
   * связываются осевыми линиями, до которых оставалось 10–20 метров.
   * Машины во дворе стояли, но приехать туда и уехать оттуда было нельзя.
   * «Въезд есть» этого не видит по устройству: въезд — свойство ЗАСТРОЙКИ,
   * а связность — свойство СЕТИ, и спрашивать надо у сети.
   *
   * Утверждение общее и не про дворы: до любой дороги посёлка можно
   * доехать с любой другой. Оторванная дорога — не дорога.
   */
  for (const [имя, п] of [['город', город], ['деревня', деревня]] as const) {
    const мир = buildWorld(дорогиПосёлка(п), 'plain');
    const сеть = buildNetwork(мир);
    const дошли = new Set<number>([0]);
    const очередь = [0];
    while (очередь.length > 0) {
      const si = очередь.pop() as number;
      for (const узел of сеть.nodes[si]) {
        for (const сосед of сеть.atJunction[узел.junction]) {
          if (дошли.has(сосед.shape)) continue;
          дошли.add(сосед.shape);
          очередь.push(сосед.shape);
        }
      }
    }
    const оторваны = мир.shapes.length - дошли.size;
    say(`до каждой дороги можно доехать (${имя})`, оторваны === 0,
      `${мир.shapes.length} дорог, оторвано ${оторваны}`);
  }

  /**
   * Каждый участок принадлежит РОВНО одному кварталу. Не «хотя бы одному»:
   * участок в двух кварталах — это две правды об одном месте, и население
   * посчиталось бы дважды.
   */
  const счёт = new Map<number, number>();
  for (const к of город.кварталы) {
    for (const i of к.участки) счёт.set(i, (счёт.get(i) ?? 0) + 1);
  }
  const ничьих = город.участки.filter((_, i) => !счёт.has(i)).length;
  const общих = [...счёт.values()].filter((n) => n > 1).length;
  say('каждый участок ровно в одном квартале', ничьих === 0 && общих === 0,
    `${город.участки.length} участков, ничьих ${ничьих}, в двух кварталах ${общих}`);

  /**
   * Въезд ведёт ВНУТРЬ квартала, а не наружу. Ошибка знака здесь дала бы
   * проезд, уходящий на проезжую часть, — и это ровно та ошибка, которую
   * 17.09 нашли у палисадника.
   */
  let наружу = 0;
  for (const к of город.кварталы) {
    for (const в of к.въезды) {
      const шаг = 1;
      const x = в.x + Math.cos(в.курс) * шаг, z = в.z + Math.sin(в.курс) * шаг;
      const внутри = x > к.x0 - 1e-6 && x < к.x1 + 1e-6 && z > к.z0 - 1e-6 && z < к.z1 + 1e-6;
      if (!внутри) наружу++;
    }
  }
  const въездов = город.кварталы.reduce((n, к) => n + к.въезды.length, 0);
  say('въезд ведёт внутрь квартала, а не на улицу', наружу === 0,
    `${въездов} въездов, наружу смотрят ${наружу}`);

  /**
   * Машиноместа помещаются во двор. Норма хранения требует 90% машин
   * жителей; если места физически нет, это не «поставим потеснее»,
   * а честный дефицит, и он должен быть виден числом.
   */
  let тесных = 0, худшая = 0;
  for (const к of город.кварталы) {
    if (к.двор === null || к.мест === 0) continue;
    const надо = к.мест * КВАРТАЛ.место.ширина * КВАРТАЛ.место.длина;
    // под машины отдаётся двор минус озеленение по норме
    const есть = к.двор.ширина * к.двор.глубина * (1 - КВАРТАЛ.зелени);
    if (надо > есть) { тесных++; худшая = Math.max(худшая, надо / есть); }
  }
  say('машиноместа помещаются во двор', тесных === 0,
    `${город.кварталы.length} кварталов, тесных ${тесных}`
    + (тесных > 0 ? `, худшему нужно в ${худшая.toFixed(2)} раза больше двора` : ''));
}

/**
 * ── ДОМА: вещи, а не украшения.
 *
 * Дом — объект со своим устройством: этажи, подъезды, квартиры, жители, вес.
 * Проверяется то, что обязано быть верным у КАЖДОГО дома, иначе эти числа
 * ничего не значат и на них нельзя ничего построить — ни расселение,
 * ни распорядок дня, ни вход в подъезд.
 */
{
  const дома = город.объекты.map((о) => домНаУчастке(о, 'город', город.сид, КАК_ДОМ));

  const безДвери = дома.filter((д) => д.двери.length === 0).length;
  const дверьНеНаФасаде = дома.filter((д) => д.двери.some((п) => п.грань !== 0)).length;
  say('у каждого дома есть подъезд, и он на улицу', безДвери === 0 && дверьНеНаФасаде === 0,
    `${дома.length} домов, без двери ${безДвери}, дверь не на фасаде ${дверьНеНаФасаде}`);

  /**
   * К КАЖДОМУ подъезду ведёт подход. Это не украшение улицы: дверь,
   * к которой не подойти, — такая же неправда, как дом без двери.
   * Алекс увидел это первым: «проходов к домам нет».
   */
  {
    /**
     * Меряется НА ДЕРЕВНЕ, а не на городе, и это не поблажка.
     *
     * В городском квартале фасад стоит на красной линии: дверь выходит
     * прямо на тротуар, подход имеет нулевую длину и не существует.
     * Требовать его там — требовать невыразимого, и проверка на городе
     * стала бы такой, которая не может упасть (правило 11). В деревне
     * палисадник в три метра, подход настоящий, и проверять есть что.
     */
    for (const [имя, п] of [['деревня', деревня], ['город', город]] as const) {
      const свои = п.объекты.map((о) => домНаУчастке(о, п.вид, п.сид));
      const подходы = подходыПосёлка(п, свои, безПодходов ? { подходы: 'до половины' as const } : {});
      const без = дверьБезПодхода(свои, подходы, (i) => п.улицы[п.объекты[i].улица] ?? null);
      const дверей = свои.reduce((n, д) => n + д.двери.length, 0);
      say(`к подъезду ведёт подход или он сам на тротуаре (${имя})`, без === 0,
        `${дверей} подъездов, ${подходы.length} подходов, без подхода ${без}`);
    }
  }

  /**
   * Где стоит фасад относительно красной линии.
   *
   * Этого не проверяли, и 17.09 нашлось: сдвиг шёл ПРОТИВ курса, то есть
   * дом уезжал от улицы вместо того, чтобы подходить к ней. Палисадник
   * по норме 3 м выходил 9, а витрина магазина, которой полагается стоять
   * на красной линии, оказывалась в восьми метрах от неё. Отсюда же
   * и лишняя пустая полоса газона между тротуаром и домами.
   */
  {
    const доКраснойЛинии = (о: typeof город.объекты[number], д: typeof дома[number]): number => {
      const у = город.улицы[о.улица];
      const вдольX = у.a.z === у.b.z;
      const доОси = Math.abs((вдольX ? д.z : д.x) - (вдольX ? у.a.z : у.a.x));
      return доОси - д.глубина / 2 - у.отступ;
    };
    let мимо = 0, худший = 0;
    город.объекты.forEach((о, i) => {
      // в городе фасад стоит НА красной линии — и жилой, и нежилой:
      // периметральный квартал палисадника не знает (решение 086)
      const надо = 0;
      const есть = доКраснойЛинии(о, дома[i]);
      if (Math.abs(есть - надо) > 0.01) { мимо++; худший = Math.max(худший, Math.abs(есть - надо)); }
    });
    say('фасад стоит на красной линии (город)', мимо === 0,
      `мимо ${мимо} из ${город.объекты.length}, худший промах ${худший.toFixed(2)} м`);
  }

  let вылезших = 0, худшийВылез = 0;
  город.объекты.forEach((о, i) => {
    const вылез = дома[i].ширина - о.фронт;
    if (вылез > 0.001) { вылезших++; худшийВылез = Math.max(худшийВылез, вылез); }
  });
  say('дом не шире своего участка', вылезших === 0,
    `${вылезших} шире участка, худший на ${худшийВылез.toFixed(1)} м`);

  let окноВне = 0;
  for (const д of дома) {
    for (const п of д.окна) {
      const грань = п.грань === 0 ? д.ширина : д.глубина;
      if (п.этаж < 0 || п.этаж >= д.этажей) окноВне++;
      else if (Math.abs(п.вдоль) + ОКНО.ширина / 2 > грань / 2 + 0.001) окноВне++;
      else if (п.этаж * 3 + ОКНО.отПола + ОКНО.высота > д.высота + 0.001) окноВне++;
    }
  }
  const окон = дома.reduce((n, д) => n + д.окна.length, 0);
  say('окна внутри стен, а не в воздухе', окноВне === 0, `${окон} окон, снаружи ${окноВне}`);

  let вместе = 0;
  for (const д of дома) {
    for (const о of д.окна) {
      if (о.этаж !== 0 || о.грань !== 0) continue;
      if (д.двери.some((дв) => Math.abs(дв.вдоль - о.вдоль) < (ДВЕРЬ.ширина + ОКНО.ширина) / 2 - 0.001)) вместе++;
    }
  }
  say('окно и дверь не в одном месте', вместе === 0, `${вместе} проёмов друг в друге`);

  const суммаЖителей = дома.reduce((n, д) => n + д.жителей, 0);
  say('население посёлка — это сумма жителей домов', суммаЖителей === город.людей,
    `дома дают ${суммаЖителей}, посёлок насчитал ${город.людей}`);

  const жилые = дома.filter((д) => д.что === 'жильё');
  const тонн = жилые.reduce((n, д) => n + д.тонн, 0);
  /**
   * Вес не назначен, а выведен: он обязан совпасть с объёмом на плотность
   * с точностью до округления до тонны. Если кто-нибудь однажды впишет вес
   * руками, эта проверка это поймает.
   */
  const мимо = жилые.filter((д) =>
    Math.abs(д.тонн - (д.ширина * д.глубина * д.высота * 350) / 1000) > 0.51).length;
  const кубов = жилые.reduce((n, д) => n + д.ширина * д.глубина * д.высота, 0);
  say('вес дома выведен из объёма, а не назначен', мимо === 0 && тонн > 0,
    `${жилые.length} жилых домов весят ${(тонн / 1000).toFixed(1)} тыс. тонн, `
    + `${((тонн * 1000) / кубов).toFixed(0)} кг на кубометр, мимо ${мимо}`);
}

