/**
 * План посёлка без экрана: проверяется не красота, а нормы.
 *
 * Вопрос, на который отвечает проверка: дойдёт ли ребёнок до сада за 300 метров,
 * а до школы за 500, и хватает ли мест на посчитанное население. Всё остальное
 * в городе — следствие.
 *
 * Запуск:  npm run plan
 *          npm run plan сломать   — ставить объекты куда попало, ОБЯЗАНА упасть
 *          npm run plan кварталы-от-конца — квартал шагами от конца улицы,
 *                                   как было до 15.09: ОБЯЗАНА упасть
 */

import { writeFileSync } from 'node:fs';
import {
  МЕЖДУ_ОСТАНОВКАМИ, НА_ТЫСЯЧУ, РАДИУС, УЛИЦА, ВМЕСТИМОСТЬ,
} from '../src/city/norms.ts';
import { построитьПосёлок, type Посёлок, type Участок } from '../src/city/plan.ts';

const карта = process.argv[2] === 'карта';
const сломать = process.argv[2] === 'сломать';
/** Заведомо сломанный вариант: кварталы шагами от конца улицы, как было до 15.09. */
const кварталами = process.argv[2] === 'кварталы-от-конца';
const КАК = сломать ? { покрытие: false } : кварталами ? { кварталы: false } : {};

const checks: [string, boolean, string][] = [];
const say = (имя: string, ок: boolean, что: string): void => { checks.push([имя, ок, что]); };
const дист = (a: { x: number; z: number }, b: { x: number; z: number }): number =>
  Math.hypot(a.x - b.x, a.z - b.z);

/** Самый несчастный дом: до какого объекта идти дальше всех. */
function дальшеВсего(п: Посёлок, что: Участок['что']): { метров: number; сколько: number } {
  const цели = п.участки.filter((у) => у.что === что);
  const жильё = п.участки.filter((у) => у.что === 'жильё');
  if (цели.length === 0) return { метров: Infinity, сколько: 0 };
  let худшее = 0;
  for (const дом of жильё) {
    let ближе = Infinity;
    for (const ц of цели) ближе = Math.min(ближе, дист(дом, ц));
    худшее = Math.max(худшее, ближе);
  }
  return { метров: худшее, сколько: цели.length };
}

const город = построитьПосёлок(20260913, 600, 'город', КАК);
const деревня = построитьПосёлок(20260913, 300, 'деревня', КАК);

// ── Радиусы: это и есть главная проверка города.
for (const [что, радиус] of [['сад', РАДИУС.сад], ['школа', РАДИУС.школа],
  ['магазин', РАДИУС.магазин]] as const) {
  const { метров, сколько } = дальшеВсего(город, что);
  const нужно = город.нужно[что];
  // если норма не требует объекта — и спрашивать нечего
  const ок = нужно === 0 ? true : метров <= радиус;
  say(`до «${что}» не дальше ${радиус} м`, ок,
    нужно === 0 ? 'норма не требует при таком населении'
      : `${сколько} шт., самый дальний дом в ${метров.toFixed(0)} м`);
}

// ── Остановки: тоже норматив, и тоже про ноги.
{
  const жильё = город.участки.filter((у) => у.что === 'жильё');
  let худшее = 0;
  for (const дом of жильё) {
    let ближе = Infinity;
    for (const о of город.остановки) ближе = Math.min(ближе, дист(дом, о));
    худшее = Math.max(худшее, ближе);
  }
  say(`до остановки не дальше ${РАДИУС.остановка} м`, худшее <= РАДИУС.остановка,
    `${город.остановки.length} остановок, самый дальний дом в ${худшее.toFixed(0)} м`);
}

// ── Мест хватает: арифметика от населения, а не «на глаз».
{
  const местВСаду = город.есть.сад * ВМЕСТИМОСТЬ.сад;
  const надоСад = Math.ceil((город.людей * НА_ТЫСЯЧУ.местВСаду) / 1000);
  say('мест в садах не меньше нормы', местВСаду >= надоСад,
    `${местВСаду} мест против ${надоСад} по норме на ${город.людей} жителей`);

  const местВШколе = город.есть.школа * ВМЕСТИМОСТЬ.школа;
  const надоШкола = Math.ceil((город.людей * НА_ТЫСЯЧУ.местВШколе) / 1000);
  say('мест в школах не меньше нормы', местВШколе >= надоШкола,
    `${местВШколе} мест против ${надоШкола} по норме`);

  const торговля = город.есть.магазин * ВМЕСТИМОСТЬ.магазин;
  const надоТорговли = Math.ceil(
    (город.людей * (НА_ТЫСЯЧУ.торговляЕда + НА_ТЫСЯЧУ.торговляПрочее)) / 1000,
  );
  say('торговой площади не меньше нормы', торговля >= надоТорговли,
    `${торговля} м² против ${надоТорговли} м² по норме`);
}

// ── Перестройка тоже ошибка: город, где школ вчетверо больше нужного,
//    построен не по норме, а наугад.
{
  const местВСаду = город.есть.сад * ВМЕСТИМОСТЬ.сад;
  const надоСад = Math.max(1, Math.ceil((город.людей * НА_ТЫСЯЧУ.местВСаду) / 1000));
  const местВШколе = город.есть.школа * ВМЕСТИМОСТЬ.школа;
  const надоШкола = Math.max(1, Math.ceil((город.людей * НА_ТЫСЯЧУ.местВШколе) / 1000));
  const запасСад = местВСаду / надоСад;
  const запасШкола = местВШколе / надоШкола;
  say('мест не больше, чем вдвое против нормы', запасСад <= 2.5 && запасШкола <= 2.5,
    `сады ×${запасСад.toFixed(1)}, школы ×${запасШкола.toFixed(1)} от нормы`);
}

// ── Красная линия: застройка за неё не заходит. Это устройство, не проверка,
//    но если устройство сломают — здесь будет видно.
{
  let ближе = Infinity;
  for (const у of город.участки) {
    const улица = город.улицы[у.улица];
    const вдольX = улица.a.z === улица.b.z;
    const доОси = вдольX ? Math.abs(у.z - улица.a.z) : Math.abs(у.x - улица.a.x);
    ближе = Math.min(ближе, доОси - у.глубина / 2 - улица.отступ);
  }
  say('застройка не заходит в красную линию', ближе >= -0.001,
    `самый близкий фасад на ${ближе.toFixed(2)} м от границы`);
}

/**
 * ── Перекрёсток остаётся открытым.
 *
 * Дом на углу закрывает видимость — это первое, что запрещают нормы
 * планировки. Проверяется не «красиво ли», а расстояние до ОСИ поперечной
 * улицы: ближе её красной линии застройки быть не может.
 *
 * Эта проверка нашла настоящую беду: квартал отсчитывался шагами от конца
 * улицы, и когда размер посёлка не был кратен шагу, вся раскладка съезжала
 * на полквартала. Все 180 участков стояли в углах, ближайший — ровно на оси
 * поперечной улицы. Снимок сверху это показывал, но никто не смотрел.
 */
for (const [имя, п] of [['город', город], ['деревня', деревня]] as const) {
  const оси = { вдольX: new Set<number>(), вдольZ: new Set<number>() };
  const красная = new Map<number, number>();
  for (const у of п.улицы) {
    const вдольX = у.a.z === у.b.z;
    const где = вдольX ? у.a.z : у.a.x;
    (вдольX ? оси.вдольX : оси.вдольZ).add(где);
    красная.set(где, Math.max(красная.get(где) ?? 0, у.отступ));
  }
  let ближе = Infinity;
  let виновник = '';
  for (const у of п.участки) {
    const поперёк = у.вдольX ? оси.вдольZ : оси.вдольX;
    const моя = у.вдольX ? у.x : у.z;
    for (const ось of поперёк) {
      // между фронтом участка и осью поперечной улицы должна быть её красная линия
      const зазор = Math.abs(моя - ось) - у.фронт / 2 - (красная.get(ось) ?? 0);
      if (зазор < ближе) { ближе = зазор; виновник = `участок (${у.x}, ${у.z}) против оси ${ось}`; }
    }
  }
  say(`перекрёстки не застроены (${имя})`, ближе >= -0.001,
    `самый близкий угол: ${ближе.toFixed(1)} м запаса — ${виновник}`);
}

// ── Участки не налезают друг на друга.
{
  let наложений = 0;
  const у = город.участки;
  /** Размер участка по осям мира: вдоль улицы это фронт, поперёк — глубина. */
  const поОсям = (a: Участок): { x: number; z: number } =>
    a.вдольX ? { x: a.фронт, z: a.глубина } : { x: a.глубина, z: a.фронт };
  for (let i = 0; i < у.length; i++) {
    const a = поОсям(у[i]);
    for (let j = i + 1; j < у.length; j++) {
      const b = поОсям(у[j]);
      const dx = Math.abs(у[i].x - у[j].x);
      const dz = Math.abs(у[i].z - у[j].z);
      if (dx < (a.x + b.x) / 2 - 0.01 && dz < (a.z + b.z) / 2 - 0.01) наложений++;
    }
  }
  say('участки не налезают друг на друга', наложений === 0, `${наложений} наложений`);
}

// ── Один сид — один посёлок. Иначе сохранение и мультиплеер невозможны.
{
  const ещё = построитьПосёлок(20260913, 600, 'город', КАК);
  const одинаково = ещё.участки.length === город.участки.length
    && ещё.участки.every((у, i) => у.x === город.участки[i].x
      && у.z === город.участки[i].z && у.что === город.участки[i].что);
  say('один сид — один и тот же посёлок', одинаково,
    `${город.участки.length} участков, совпали ${одинаково ? 'полностью' : 'НЕ полностью'}`);
}

// ── Деревня и город: одно устройство, разная плотность.
{
  const плотнее = город.людей / (600 * 600 * 4) > деревня.людей / (300 * 300 * 4);
  say('город плотнее деревни при одном устройстве', плотнее,
    `город ${город.людей} чел. на 1.44 км², деревня ${деревня.людей} чел. на 0.36 км²`);
}

// ── Расстояние между остановками — тоже норматив.
{
  let худшее = 0;
  for (const о of город.остановки) {
    let ближе = Infinity;
    for (const д of город.остановки) if (д !== о) ближе = Math.min(ближе, дист(о, д));
    худшее = Math.max(худшее, ближе);
  }
  say(`остановки не реже ${МЕЖДУ_ОСТАНОВКАМИ.макс} м`, худшее <= МЕЖДУ_ОСТАНОВКАМИ.макс,
    `самый большой промежуток ${худшее.toFixed(0)} м`);
}

console.log(`\nПЛАН ПОСЁЛКА${сломать ? ' — ЗАВЕДОМО СЛОМАННЫЙ: объекты куда попало' : ''}\n`);
console.log(`  город: ${город.людей} жителей, ${город.участки.length} участков, ` +
  `улиц ${город.улицы.length} (магистральных ${город.улицы.filter((у) => у.вид === 'магистральная').length})`);
console.log(`  построено: садов ${город.есть.сад}, школ ${город.есть.школа}, ` +
  `магазинов ${город.есть.магазин}, поликлиник ${город.есть.поликлиника}`);
console.log(`  норма требует: садов ${город.нужно.сад}, школ ${город.нужно.школа}, ` +
  `магазинов ${город.нужно.магазин}, поликлиник ${город.нужно.поликлиника}`);
console.log(`  деревня: ${деревня.людей} жителей, ${деревня.участки.length} участков\n`);

let упало = 0;
for (const [имя, ок, что] of checks) {
  if (!ок) упало++;
  console.log(`  ${ок ? '✓' : '✗'} ${имя.padEnd(44, '.')} ${что}`);
}
console.log(`\n${упало === 0 ? 'ПЛАН В ПОРЯДКЕ' : `ПЛАН ПРОВАЛЕН: ${упало}`}\n`);
void УЛИЦА;

/**
 * Карта плана — чтобы план можно было УВИДЕТЬ, а не только прочитать цифрами.
 * Рисуется в SVG: это тот же план, только глазами, и никакой отдельной правды
 * в нём нет — всё берётся из посёлка.
 */
if (карта) {
  const ЦВЕТ: Record<string, string> = {
    жильё: '#bfae95', сад: '#e0c060', школа: '#b06a4a',
    магазин: '#6d93b8', поликлиника: '#e6e6e0',
  };
  const п = город;
  const R = п.половина;
  const в = (v: number): number => v + R;
  const части: string[] = [];
  for (const у of п.улицы) {
    const ш = у.вид === 'магистральная' ? 14 : 7;
    части.push(`<line x1="${в(у.a.x)}" y1="${в(у.a.z)}" x2="${в(у.b.x)}" y2="${в(у.b.z)}" `
      + `stroke="#3c4046" stroke-width="${ш}" />`);
  }
  for (const у of п.участки) {
    const ш = у.вдольX ? у.фронт : у.глубина;
    const г = у.вдольX ? у.глубина : у.фронт;
    части.push(`<rect x="${в(у.x) - ш / 2}" y="${в(у.z) - г / 2}" width="${ш}" height="${г}" `
      + `fill="${ЦВЕТ[у.что]}" stroke="#00000022" stroke-width="0.6" />`);
  }
  for (const о of п.остановки) {
    части.push(`<circle cx="${в(о.x)}" cy="${в(о.z)}" r="5" fill="#2f7d32" stroke="#fff" stroke-width="1.5" />`);
  }
  const подпись = (текст: string, цвет: string, i: number): string =>
    `<rect x="12" y="${14 + i * 26}" width="18" height="18" fill="${цвет}" />`
    + `<text x="38" y="${28 + i * 26}" font-size="15" fill="#eee" font-family="system-ui">${текст}</text>`;
  const легенда = [
    подпись(`жильё — ${город.людей} жителей`, ЦВЕТ.жильё, 0),
    подпись(`сады: ${город.есть.сад} (норма ${город.нужно.сад})`, ЦВЕТ.сад, 1),
    подпись(`школы: ${город.есть.школа} (норма ${город.нужно.школа})`, ЦВЕТ.школа, 2),
    подпись(`магазины: ${город.есть.магазин} (норма ${город.нужно.магазин})`, ЦВЕТ.магазин, 3),
    подпись(`поликлиники: ${город.есть.поликлиника}`, ЦВЕТ.поликлиника, 4),
    подпись(`остановки: ${город.остановки.length}`, '#2f7d32', 5),
  ].join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${R * 2}" height="${R * 2}" `
    + `viewBox="0 0 ${R * 2} ${R * 2}"><rect width="100%" height="100%" fill="#5f8a4a" />`
    + части.join('') + `</svg>`;
  const html = `<!doctype html><meta charset="utf-8"><title>план посёлка</title>`
    + `<style>body{margin:0;background:#14181d;color:#eee;font-family:system-ui;display:flex;gap:20px;padding:20px}`
    + `svg{background:#5f8a4a;box-shadow:0 0 0 1px #0006}</style>`
    + svg
    + `<div><h2 style="margin:0 0 8px">Посёлок по нормам, ${R * 2} × ${R * 2} м</h2>`
    + `<svg width="360" height="180">${легенда}</svg>`
    + `<p style="max-width:320px;line-height:1.5;opacity:.8">Улицы, участки и назначения `
    + `выведены из сида и норм: радиусы доступности, места на тысячу жителей, `
    + `красные линии. Ничего не расставлено рукой.</p></div>`;
  writeFileSync('build/план.html', html);
  console.log('карта плана: build/план.html');
}

process.exit(упало === 0 ? 0 : 1);