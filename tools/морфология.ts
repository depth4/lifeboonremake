/**
 * Морфология: похож ли наш город на настоящий — числом, а не на глаз.
 *
 * Зачем нужен отдельный инструмент, когда есть `npm run plan`. `plan` проверяет
 * НОРМАТИВ: дошёл ли ребёнок до сада, хватает ли мест в школе. Норматив
 * выполняется и складом одинаковых ящиков — он про доступность, а не про то,
 * как улица выглядит с уровня глаз. 16 сентября посёлок ровно так и выложили
 * на сайт: нормы сходились, а с улицы оказалась стена контейнеров.
 *
 * Этот инструмент меряет ФОРМУ застройки и сверяет её с замером настоящего
 * города (`ОБРАЗЕЦ` в `norms.ts`, Прага/Бубенеч). Меры взяты те же самые
 * и считаются тем же способом, иначе сравнивать нечего.
 *
 * **Что здесь НЕ проверяется и почему.** Не проверяется «красиво». Проверяется
 * только то, что можно померить линейкой и сравнить с настоящим местом.
 *
 * **Долг — потолок, а не цель.** У каждой меры записано, насколько мы сейчас
 * расходимся с настоящим городом. Стало хуже — проверка падает и называет
 * виновного. Стало лучше — долг опускается в том же коммите, где стало лучше.
 *
 * Запуск:  npm run морфология
 *          npm run морфология одинаковые — все дома одного размера,
 *                             ОБЯЗАНА упасть на разбросе следов
 */

import { ОБРАЗЕЦ } from '../src/city/norms.ts';
import { домНаУчастке } from '../src/city/дом.ts';
import { посёлокСцены } from '../src/scenes.ts';
import type { Посёлок } from '../src/city/plan.ts';

/** Заведомо сломанный вариант: у всех домов один размер до сантиметра. */
const одинаковые = process.argv[2] === 'одинаковые';

const доля = (м: readonly number[], q: number): number => {
  const s = [...м].sort((a, b) => a - b);
  return s.length === 0 ? NaN : s[Math.min(s.length - 1, Math.floor(s.length * q))];
};
const медиана = (м: readonly number[]): number => доля(м, 0.5);

interface Мера {
  readonly имя: string;
  readonly наше: number;
  readonly настоящее: number;
  readonly единица: string;
  /**
   * Куда должно двигаться наше число, чтобы стать похожим на настоящее.
   * Долг всегда на той же стороне: проверка падает, когда стало ДАЛЬШЕ.
   */
  readonly долг: number;
  readonly сторона: 'не меньше' | 'не больше';
}

/** Все меры одного посёлка. Считается ровно так же, как считался настоящий. */
function померить(п: Посёлок): {
  следы: number[];
  подДомами: number; плотностьУлиц: number; отрезокУлицы: number; вытянутость: number;
} {
  const дома = п.объекты.map((о) => домНаУчастке(о, п.вид, п.сид));
  const следы = дома.map((д) => (одинаковые ? 20 * 14 : д.ширина * д.глубина));
  const сторона = п.половина * 2;
  const площадь = сторона * сторона;
  const улиц = п.улицы.reduce(
    (s, у) => s + Math.hypot(у.b.x - у.a.x, у.b.z - у.a.z), 0,
  );
  /**
   * Отрезок улицы между перекрёстками. Считается НЕ по шагу сетки, а по
   * настоящим пересечениям: иначе мера знала бы ответ заранее и сравнивать
   * было бы нечего.
   */
  const отрезки: number[] = [];
  for (const у of п.улицы) {
    const вдольX = у.a.z === у.b.z;
    const от = вдольX ? у.a.x : у.a.z;
    const до = вдольX ? у.b.x : у.b.z;
    const узлы = [от, до];
    for (const д of п.улицы) {
      const дВдольX = д.a.z === д.b.z;
      if (дВдольX === вдольX) continue;
      const где = дВдольX ? д.a.z : д.a.x;
      if (где > от + 1e-6 && где < до - 1e-6) узлы.push(где);
    }
    узлы.sort((a, b) => a - b);
    for (let i = 1; i < узлы.length; i++) отрезки.push(узлы[i] - узлы[i - 1]);
  }
  return {
    следы,
    подДомами: (следы.reduce((a, b) => a + b, 0) / площадь) * 100,
    плотностьУлиц: улиц / (площадь / 1e6),
    отрезокУлицы: медиана(отрезки),
    вытянутость: медиана(дома.map((д) => (одинаковые ? 20 / 14
      : Math.max(д.ширина, д.глубина) / Math.min(д.ширина, д.глубина)))),
  };
}

const обр = ОБРАЗЕЦ.чехия;
console.log(`\nМОРФОЛОГИЯ${одинаковые ? ' — ЗАВЕДОМО СЛОМАННАЯ: все дома одного размера' : ''}`);
console.log(`Линейка: ${обр.откуда}\n`);

let упало = 0;
for (const имя of ['город', 'большой город'] as const) {
  const п = посёлокСцены(имя);
  if (п === null) { console.log(`  сцены «${имя}» нет`); упало++; continue; }
  const м = померить(п);
  const низ = доля(м.следы, 0.1), верх = доля(м.следы, 0.9);

  const меры: Мера[] = [
    {
      имя: 'разброс следов домов (крупный ÷ мелкий)',
      наше: верх / низ, настоящее: обр.разбросСледов, единица: '×',
      // долг: сегодня 1.15. Настоящий город — 12.1. Это главная неправда
      // застройки: нормы сходятся, а улица читается складом одинаковых ящиков
      долг: 1.1, сторона: 'не меньше',
    },
    {
      имя: 'след дома, медиана',
      наше: медиана(м.следы), настоящее: обр.следДома.медиана, единица: 'м²',
      долг: 180, сторона: 'не меньше',
    },
    {
      имя: 'вытянутость следа',
      наше: м.вытянутость, настоящее: обр.вытянутость, единица: '',
      долг: 1.6, сторона: 'не больше',
    },
    {
      имя: 'под домами',
      наше: м.подДомами, настоящее: обр.подДомами, единица: '%',
      долг: 12, сторона: 'не меньше',
    },
    {
      имя: 'плотность улиц',
      наше: м.плотностьУлиц, настоящее: обр.плотностьУлиц, единица: 'м/км²',
      долг: 9500, сторона: 'не меньше',
    },
    {
      имя: 'отрезок улицы между перекрёстками',
      наше: м.отрезокУлицы, настоящее: обр.отрезокУлицы, единица: 'м',
      долг: 260, сторона: 'не больше',
    },
  ];

  console.log(`  ${имя} — ${п.объекты.length} домов, ${п.людей} жителей`);
  for (const м2 of меры) {
    const ок = м2.сторона === 'не меньше' ? м2.наше >= м2.долг : м2.наше <= м2.долг;
    if (!ок) упало++;
    const раз = м2.наше / м2.настоящее;
    // «больше/меньше», а не «лучше/хуже»: у разных мер хорошая сторона разная
    const разрыв = раз >= 1 ? `в ${раз.toFixed(1)} раза больше настоящего`
      : `в ${(1 / раз).toFixed(1)} раза меньше настоящего`;
    console.log(`    ${ок ? '✓' : '✗'} ${м2.имя.padEnd(42, '.')} `
      + `${м2.наше.toFixed(м2.наше < 100 ? 2 : 0)} ${м2.единица} `
      + `(настоящий ${м2.настоящее} ${м2.единица}, ${разрыв})`);
  }
  console.log('');
}

console.log(упало === 0
  ? 'МОРФОЛОГИЯ В ПОРЯДКЕ — ни одна мера не ушла дальше записанного долга\n'
  : `МОРФОЛОГИЯ ПРОВАЛЕНА: ${упало}\n`);
process.exit(упало === 0 ? 0 : 1);
