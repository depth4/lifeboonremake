/** Заведомо сломанный вариант: у всех домов один размер до сантиметра. */
const одинаковые = process.argv[2] === 'одинаковые';
/** Заведомо сломанный вариант: земля спрашивается в одной точке — как было. */
const поЦентру = process.argv[2] === 'по-центру';
/** Заведомо сломанный вариант: дерево не спрашивает мир, где газон. */
const деревоНаДороге = process.argv[2] === 'дерево-на-дороге';

const доля = (м: readonly number[], q: number): number => {
  const s = [...м].sort((a, b) => a - b);
  return s.length === 0 ? NaN : s[Math.min(s.length - 1, Math.floor(s.length * q))];
};
const медиана = (м: readonly number[]): number => доля(м, 0.5);

interface Мера {
  readonly имя: string;
  readonly наше: number;
  readonly настоящее: number;
  readonly единица: string;
  /**
   * Куда должно двигаться наше число, чтобы стать похожим на настоящее.
   * Долг всегда на той же стороне: проверка падает, когда стало ДАЛЬШЕ.
   */
  readonly долг: number;
  readonly сторона: 'не меньше' | 'не больше';
}

/** Все меры одного посёлка. Считается ровно так же, как считался настоящий. */
function померить(п: Посёлок): {
  следы: number[];
  подДомами: number; плотностьУлиц: number; отрезокУлицы: number; вытянутость: number;
} {
  const дома = п.объекты.map((о) => домНаУчастке(о, п.вид, п.сид));
  const следы = дома.map((д) => (одинаковые ? 20 * 14 : д.ширина * д.глубина));
  const сторона = п.половина * 2;
  const площадь = сторона * сторона;
  /**
   * Длина всех дорог, а не только улиц: внутриквартальный проезд — это
   * тоже дорога, по нему ездят и на нём паркуются. Настоящая плотность
   * улиц в образце тоже считана по всему, по чему можно проехать.
   */
  const улиц = п.улицы.reduce(
    (s, у) => s + Math.hypot(у.b.x - у.a.x, у.b.z - у.a.z), 0,
  ) + п.кварталы.reduce((s, к) => {
    const л = к.проезд;
    if (л === null) return s;
    let d = 0;
    for (let i = 1; i < л.length; i++) d += Math.hypot(л[i].x - л[i - 1].x, л[i].z - л[i - 1].z);
    return s + d;
  }, 0);
  /**
   * Отрезок улицы между перекрёстками. Считается НЕ по шагу сетки, а по
   * настоящим пересечениям: иначе мера знала бы ответ заранее и сравнивать
   * было бы нечего.
   */
  const отрезки: number[] = [];
  for (const у of п.улицы) {
    const вдольX = у.a.z === у.b.z;
    const от = вдольX ? у.a.x : у.a.z;
    const до = вдольX ? у.b.x : у.b.z;
    const узлы = [от, до];
    for (const д of п.улицы) {
      const дВдольX = д.a.z === д.b.z;
      if (дВдольX === вдольX) continue;
      const где = дВдольX ? д.a.z : д.a.x;
      if (где > от + 1e-6 && где < до - 1e-6) узлы.push(где);
    }
    узлы.sort((a, b) => a - b);
    for (let i = 1; i < узлы.length; i++) отрезки.push(узлы[i] - узлы[i - 1]);
  }
  return {
    следы,
    подДомами: (следы.reduce((a, b) => a + b, 0) / площадь) * 100,
    плотностьУлиц: улиц / (площадь / 1e6),
    отрезокУлицы: медиана(отрезки),
    вытянутость: медиана(дома.map((д) => (одинаковые ? 20 / 14
      : Math.max(д.ширина, д.глубина) / Math.min(д.ширина, д.глубина)))),
  };
}

const обр = ОБРАЗЕЦ.чехия;
console.log(`\nМОРФОЛОГИЯ${одинаковые ? ' — ЗАВЕДОМО СЛОМАННАЯ: все дома одного размера' : ''}`);
console.log(`Линейка: ${обр.откуда}\n`);

let упало = 0;
for (const имя of ['город', 'большой город'] as const) {
  const п = посёлокСцены(имя);
  if (п === null) { console.log(`  сцены «${имя}» нет`); упало++; continue; }
  const м = померить(п);
  const низ = доля(м.следы, 0.1), верх = доля(м.следы, 0.9);

  const меры: Мера[] = [
    {
      имя: 'разброс следов домов (крупный ÷ мелкий)',
      наше: верх / низ, настоящее: обр.разбросСледов, единица: '×',
      // долг: сегодня 1.15. Настоящий город — 12.1. Это главная неправда
      // застройки: нормы сходятся, а улица читается складом одинаковых ящиков
      долг: 1.1, сторона: 'не меньше',
    },
    {
      имя: 'след дома, медиана',
      наше: медиана(м.следы), настоящее: обр.следДома.медиана, единица: 'м²',
      долг: 180, сторона: 'не меньше',
    },
    {
      имя: 'вытянутость следа',
      наше: м.вытянутость, настоящее: обр.вытянутость, единица: '',
      долг: 1.6, сторона: 'не больше',
    },
    {
      имя: 'под домами',
      наше: м.подДомами, настоящее: обр.подДомами, единица: '%',
      /**
       * Долг ОПУЩЕН 17.09 с 12 до 11.2, и это признание, а не подгонка.
       * Внутриквартальные проезды съели по участку на каждый въезд:
       * было 12.58%, стало 11.30%. Проезд на месте дома — это правда
       * про город, и цена названа здесь числом.
       *
       * Настоящая причина разрежённости не в этом: у нас дом занимает 45%
       * своего участка, у настоящего — 66%. Это следующий шаг, и он же
       * закроет разброс следов.
       */
      долг: 11.2, сторона: 'не меньше',
    },
    {
      имя: 'плотность улиц',
      наше: м.плотностьУлиц, настоящее: обр.плотностьУлиц, единица: 'м/км²',
      долг: 9500, сторона: 'не меньше',
    },
    {
      имя: 'отрезок улицы между перекрёстками',
      наше: м.отрезокУлицы, настоящее: обр.отрезокУлицы, единица: 'м',
      долг: 260, сторона: 'не больше',
    },
  ];

  console.log(`  ${имя} — ${п.объекты.length} домов, ${п.людей} жителей`);
  for (const м2 of меры) {
    const ок = м2.сторона === 'не меньше' ? м2.наше >= м2.долг : м2.наше <= м2.долг;
    if (!ок) упало++;
    const раз = м2.наше / м2.настоящее;
    // «больше/меньше», а не «лучше/хуже»: у разных мер хорошая сторона разная
    const разрыв = раз >= 1 ? `в ${раз.toFixed(1)} раза больше настоящего`
      : `в ${(1 / раз).toFixed(1)} раза меньше настоящего`;
    console.log(`    ${ок ? '✓' : '✗'} ${м2.имя.padEnd(42, '.')} `
      + `${м2.наше.toFixed(м2.наше < 100 ? 2 : 0)} ${м2.единица} `
      + `(настоящий ${м2.настоящее} ${м2.единица}, ${разрыв})`);
  }
  console.log('');
}

/**
 * Дом и земля. Проверяются два утверждения, и оба — про то, что видно
 * с улицы: под домом нет щели, и дом не врос в землю стеной.
 *
 * Земля берётся ТА ЖЕ, по которой едет колесо, — собранная поверхность,
 * а не голый рельеф: дорога режет землю, и дом стоит рядом с этим разрезом.
 */
console.log('  ДОМ И ЗЕМЛЯ');
/** Допуск, м. Настолько разрешено промахнуться: ниже этого не видно глазом. */
const ДОПУСК = 0.02;
for (const [сцена, рельеф] of [
  ['город', 'plateau'], ['город', 'hills'], ['город', 'mountain'],
  ['большой город', 'plateau'],
] as const) {
  const п = посёлокСцены(сцена);
  if (п === null) { console.log(`    сцены «${сцена}» нет`); упало++; continue; }
  const земля = new GroundIndex(buildSurface(buildWorld(дорогиСцены(сцена), рельеф)));
  const высота = (x: number, z: number): number => земля.sample(x, z).height;

  let щель = 0, вросло = 0, худшаяЩель = 0, худшееВрастание = 0, круто = 0;
  const цоколи: number[] = [];
  for (const о of п.объекты) {
    const д = домНаУчастке(о, п.вид, п.сид);
    const след = {
      x: д.x, z: д.z, курс: д.курс, ширина: д.ширина, глубина: д.глубина,
    };
    const пл = поЦентру
      // как было до 17.09: одна точка в середине дома, цоколь постоянный
      ? { подошва: высота(д.x, д.z), пол: высота(д.x, д.z) + 0.55, цоколь: 0.55,
        перепад: 0, крутоДляДома: false }
      : площадкаПодСледом(след, высота);
    цоколи.push(пл.цоколь);
    if (пл.крутоДляДома) круто++;

    // щуп проверки вдвое мельче щупа расчёта — иначе она повторяла бы его
    const c = Math.cos(д.курс), s2 = Math.sin(д.курс);
    const пш = д.ширина / 2 + 0.2, пг = д.глубина / 2 + 0.2;
    const N = Math.max(4, Math.ceil((пш * 2) / 0.75)), M = Math.max(4, Math.ceil((пг * 2) / 0.75));
    let низ = Infinity, верх = -Infinity;
    for (let i = 0; i <= N; i++) {
      for (let j = 0; j <= M; j++) {
        const dx = -пш + (пш * 2 * i) / N, dz = -пг + (пг * 2 * j) / M;
        const y = высота(д.x + dx * c - dz * s2, д.z + dx * s2 + dz * c);
        if (y < низ) низ = y;
        if (y > верх) верх = y;
      }
    }
    const этаЩель = пл.подошва - низ;          // > 0: под домом видно дырку
    const этоВрастание = верх - пл.пол;        // > 0: стена утонула в земле
    if (этаЩель > ДОПУСК) { щель++; худшаяЩель = Math.max(худшаяЩель, этаЩель); }
    if (этоВрастание > ДОПУСК) {
      вросло++; худшееВрастание = Math.max(худшееВрастание, этоВрастание);
    }
  }

  const ок = щель === 0 && вросло === 0;
  if (!ок) упало++;
  const медЦоколь = медиана(цоколи);
  console.log(`    ${ок ? '✓' : '✗'} ${`${сцена} / ${рельеф}`.padEnd(42, '.')} `
    + `висит ${щель} (худшая щель ${худшаяЩель.toFixed(2)} м), `
    + `вросло ${вросло} (${худшееВрастание.toFixed(2)} м), `
    + `цоколь медиана ${медЦоколь.toFixed(2)} м, круче предела ${круто}`);
}

/**
 * Долг, названный числом. Место круче предела — это не дом с трёхметровым
 * цоколем, это место, где не строят. Снять их должен ПЛАН, а план пока
 * не знает рельефа: улицы у нас идут ровной сеткой через любые холмы.
 * Пока это так — число здесь потолок: станет больше, проверка упадёт.
 */
console.log('');
/**
 * ЗЕЛЕНЬ. Дерево стоит в газоне — то есть там, где не дорога и не тротуар.
 * Отступ от СВОЕЙ улицы этого не гарантирует: у развилки «наружу от своей»
 * означает «внутрь поперечной». Замерено 17.09: так стояло 20 деревьев
 * из 1360, и одно выросло посреди проезжей части перед камерой.
 */
console.log('');
console.log('  ЗЕЛЕНЬ');
for (const сцена of ['город', 'большой город'] as const) {
  const п = посёлокСцены(сцена);
  if (п === null) { console.log(`    сцены «${сцена}» нет`); упало++; continue; }
  const мир = buildWorld(дорогиСцены(сцена), 'plateau');
  const деревья = деревьяУлиц(мир, buildNetwork(мир), п.сид,
    деревоНаДороге ? { газон: false } : {});
  let наПолотне = 0, наТротуаре = 0;
  for (const д of деревья) {
    const рядом = nearestRoad(мир, д.x, д.z);
    if (рядом === null) continue;
    if (рядом.distance < рядом.halfWidth) наПолотне++;
    else if (рядом.distance < рядом.outerHalf) наТротуаре++;
  }
  const ок = наПолотне === 0 && наТротуаре === 0;
  if (!ок) упало++;
  console.log(`    ${ок ? '✓' : '✗'} ${`${сцена}: дерево стоит в газоне`.padEnd(42, '.')} `
    + `${деревья.length} деревьев, на полотне ${наПолотне}, на тротуаре ${наТротуаре}`);
}

console.log('');
console.log(упало === 0
  ? 'МОРФОЛОГИЯ В ПОРЯДКЕ — ни одна мера не ушла дальше записанного долга\n'
  : `МОРФОЛОГИЯ ПРОВАЛЕНА: ${упало}\n`);
process.exit(упало === 0 ? 0 : 1);
