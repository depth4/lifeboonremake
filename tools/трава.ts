/**
 * Трава без экрана: растёт ли она там, где можно, стоит ли на земле
 * и живёт ли примятость во времени, а не в кадрах.
 *
 *   npm run трава                 — всё
 *   npm run трава маска-по-центру — клетка травяная по одному углу: ОБЯЗАНА упасть
 *   npm run трава сквозь-дорожки  — не спрашивать, что стоит на земле: ОБЯЗАНА упасть
 *   npm run трава по-кадрам       — примятость по кадрам и точкой: ОБЯЗАНА упасть
 *
 * Травинок здесь нет, как нет их и в памяти страницы: травинка стоит
 * в любой точке травяной клетки. Поэтому проверяются не травинки, а клетки —
 * случайными точками внутри них, в тех же окнах, какие берёт страница.
 */

import { дорогиСцены, посёлокСцены } from '../src/scenes.ts';
import { buildWorld } from '../src/world/world.ts';
import { buildSurface } from '../src/surface/index.ts';
import { GroundIndex } from '../src/car/ground.ts';
import { наЗемлеПосёлка, занято } from '../src/city/двор.ts';
import { Примятость, полеТравы, растётЛи, высотаПоля } from '../src/трава/поле.ts';

const режим = process.argv[2] ?? '';
const СЦЕНА = 'город';
const посёлок = посёлокСцены(СЦЕНА);
if (посёлок === null) throw new Error(`«${СЦЕНА}» — не посёлок`);
const поверхность = buildSurface(buildWorld(дорогиСцены(СЦЕНА), 'plateau'));
const земля = new GroundIndex(поверхность);
const н = наЗемлеПосёлка(посёлок);

const checks: [string, boolean, string][] = [];
const say = (name: string, ok: boolean, note: string): void => { checks.push([name, ok, note]); };

/** Повторяемый случай: один запуск — одни точки. */
let зерно = 20260923;
const случай = (): number => { зерно = (зерно * 1664525 + 1013904223) >>> 0; return зерно / 4294967296; };

// ── Где растёт: в окнах, какие берёт страница, — 128 × 128 м.
{
  const ОКНО = 128;
  const окна = [
    { x0: -64, z0: -64 },                  // середина города
    { x0: -230, z0: -250 },                // улица из снимка «стили»
    { x0: 40, z0: 60 },
    { x0: -180, z0: 90 },
  ];
  let проверено = 0, наАсфальте = 0, подВещью = 0, травыВсего = 0, травыПокрыто = 0, худшаяВысота = 0;
  let пример = '';
  const начало = performance.now();
  for (const о of окна) {
    const поле = полеТравы(поверхность, н, { ...о, ширина: ОКНО, глубина: ОКНО }, {
      маска: режим === 'маска-по-центру' ? 'по центру' : undefined,
      занято: режим === 'сквозь-дорожки' ? false : undefined,
    });
    for (let k = 0; k < 60000; k++) {
      const x = о.x0 + случай() * ОКНО, z = о.z0 + случай() * ОКНО;
      const под = земля.sample(x, z);
      const голая = под.material === 'grass' && !занято(н, x, z, { дом: 0, подход: 0, вещь: 0 });
      if (голая) травыВсего++;
      if (!растётЛи(поле, x, z)) continue;
      if (голая) травыПокрыто++;
      проверено++;
      if (под.material !== 'grass') {
        наАсфальте++;
        if (пример === '') пример = `(${x.toFixed(2)}, ${z.toFixed(2)}) — ${под.material}`;
      } else if (!голая) подВещью++;
      else худшаяВысота = Math.max(худшаяВысота, Math.abs(высотаПоля(поле, x, z) - под.height));
    }
  }
  const мс = (performance.now() - начало) / окна.length;
  say('трава только на голой земле', проверено > 10000 && наАсфальте === 0 && подВещью === 0,
    `${проверено} точек в траве: на асфальте/тротуаре ${наАсфальте}, под домом/дорожкой/вещью ${подВещью}`
    + (пример ? `; первая: ${пример}` : ''));
  const доля = травыПокрыто / Math.max(1, травыВсего);
  say('газон покрыт, а не выщипан', доля > 0.9,
    `трава растёт на ${(доля * 100).toFixed(1)}% голой земли; остальное — полоска у края не шире клетки`);
  say('травинка стоит на той же земле, что колесо', худшаяВысота < 0.03,
    `худшее расхождение с землёй ${(худшаяВысота * 1000).toFixed(1)} мм; окно 128 м строится за ${мс.toFixed(0)} мс`);
}

// ── Примятость: один и тот же путь на 30 и на 144 кадрах в секунду.
{
  const как = режим === 'по-кадрам' ? { поКадрам: true } : {};
  /**
   * Человек идёт по дуге 1.5 м/с три секунды и стоит, машина едет прямо
   * 12 м/с две секунды и стоит. Место — функция ВРЕМЕНИ, а не номера кадра:
   * иначе на разной частоте кадров остановились бы в разных местах,
   * и проверка мерила бы саму себя.
   */
  const человек = (t: number): [number, number] => {
    const с = Math.min(t, 3) * 0.5;
    return [Math.sin(с) * 3, (1 - Math.cos(с)) * 3];
  };
  const машина = (t: number): [number, number] => [-12 + Math.min(t, 2) * 12, 6];
  const прогон = (кадров: number): Примятость => {
    const п = new Примятость(как);
    п.встать(0, 0);
    const шагов = Math.round(6 * кадров);
    for (let k = 1; k <= шагов; k++) {
      const t0 = (k - 1) / кадров, t1 = k / кадров;
      const [ax, az] = человек(t0), [bx, bz] = человек(t1);
      п.примять(ax, az, bx, bz, 0.3, false);
      const [мa, мaz] = машина(t0), [мb] = машина(t1);
      п.примять(мa, мaz - 0.8, мb, мaz - 0.8, 0.12, true);
      п.примять(мa, мaz + 0.8, мb, мaz + 0.8, 0.12, true);
      п.жить(1 / кадров);
    }
    return п;
  };
  const а = прогон(30), б = прогон(144);
  let хуже = 0, всего = 0;
  for (let n = 0; n < а.сила.length; n++) {
    хуже = Math.max(хуже, Math.abs(а.сила[n] - б.сила[n]));
    всего += б.сила[n];
  }
  /**
   * Колея: машина прошла x = −6 на 0.5 с, мерим в 6 с — через 5.5 с.
   * Распрямление — экспонента, значит должно остаться e^(−5.5/9) ≈ 54%.
   */
  let колея = 0;
  for (let dz = -0.2; dz <= 0.2; dz += 0.05) колея = Math.max(колея, б.сколько(-6, 5.2 + dz));
  say('след один на 30 и на 144 кадрах', хуже < 0.03 && всего > 50,
    `худшая разница ${(хуже * 100).toFixed(1)}% примятости; примятых клеток по сумме ${всего.toFixed(0)}`);
  say('колея держится, трава встаёт не сразу', колея > 0.45 && колея < 0.62,
    `середина колеи через 5 с после проезда примята на ${(колея * 100).toFixed(0)}%`);
  const п = прогон(60);
  for (let t = 0; t < 40; t += 1 / 60) п.жить(1 / 60);
  let осталось = 0;
  for (let n = 0; n < п.сила.length; n++) осталось = Math.max(осталось, п.сила[n]);
  say('через 40 секунд трава встала', осталось < 0.02, `осталось примятости ${(осталось * 100).toFixed(1)}%`);
}

const СЛОМАНО: Record<string, string> = {
  'маска-по-центру': 'клетка травяная по одному углу',
  'сквозь-дорожки': 'трава не спрашивает, что стоит на земле',
  'по-кадрам': 'примятость по кадрам и точкой',
};
console.log(`\nТРАВА${СЛОМАНО[режим] ? ` — ЗАВЕДОМО СЛОМАННАЯ: ${СЛОМАНО[режим]}` : ''}\n`);
let failed = 0;
for (const [name, ok, note] of checks) {
  if (!ok) failed++;
  console.log(`  ${ok ? '✓' : '✗'} ${name.padEnd(44, '.')} ${note}`);
}
console.log(`\n${failed === 0 ? 'ТРАВА В ПОРЯДКЕ' : `ТРАВА ПРОВАЛЕНА: ${failed}`}\n`);
process.exit(failed === 0 ? 0 : 1);
