/** Запустить один инструмент и вернуть, чем кончилось. */
function запустить(файл, аргументы) {
  const типы = файл.endsWith('.ts') ? ['--experimental-strip-types'] : [];
  const начало = Date.now();
  const r = spawnSync('node', [...типы, файл, ...аргументы], { encoding: 'utf8' });
  return {
    код: r.status ?? 1,
    секунды: (Date.now() - начало) / 1000,
    вывод: (r.stdout ?? '') + (r.stderr ?? ''),
  };
}

const провалы = [];

function прогнать(заголовок, список, ждём) {
  console.log(`\n${заголовок}`);
  for (const [имя, [файл, ...аргументы]] of список) {
    const { код, секунды, вывод } = запустить(файл, аргументы);
    const упал = код !== 0;
    const хорошо = ждём === 'пройти' ? !упал : упал;
    const знак = хорошо ? '✓' : '✗';
    console.log(`  ${знак} ${имя.padEnd(44, '.')} ${секунды.toFixed(0).padStart(4)} с`);
    if (!хорошо) провалы.push({ имя, ждём, вывод });
  }
}

console.log('ПРОВЕРЯЮ ВСЁ' + (быстро ? ' (без браузера)' : ''));

прогнать('Обязаны пройти:', ПРОЙТИ, 'пройти');
if (!быстро) прогнать('Обязаны пройти, через настоящий браузер:', БРАУЗЕР, 'пройти');
прогнать('Обязаны упасть — иначе проверке нельзя верить:', УПАСТЬ, 'упасть');

if (провалы.length === 0) {
  console.log('\nВСЁ В ПОРЯДКЕ' + (быстро ? ' — но браузер не проверялся\n' : '\n'));
  process.exit(0);
}

console.log(`\nПРОВАЛЕНО: ${провалы.length}\n`);
for (const { имя, ждём, вывод } of провалы) {
  console.log('─'.repeat(70));
  console.log(ждём === 'пройти'
    ? `УПАЛО: ${имя}`
    : `НЕ УПАЛО, ХОТЯ ОБЯЗАНО: ${имя} — этой проверке верить нельзя`);
  console.log(вывод.trimEnd().split('\n').slice(-12).join('\n'));
}
console.log('─'.repeat(70));
process.exit(1);
