/**
 * Одна команда «проверь всё»: гоняет каждую проверку и падает целиком,
 * если упала хоть одна.
 *
 * Зачем: проверка, которую надо не забыть запустить, однажды будет забыта.
 * Так уже случилось один раз — цифра «0 поломок» жила в памяти проекта
 * полгода после того, как поломок стало шесть.
 *
 * Запуск: npm test
 */

import { spawnSync } from 'node:child_process';

const RUNS = [
  ['поверхность, одна сцена', ['check.ts']],
  ['поверхность, 12 сцен × 3 рельефа', ['scenes.ts']],
  ['сеть движения: полосы, связи, правила', ['lanes.ts']],
  ['движение: город, 5 минут, 80 машин', ['drive.ts', 'город', '300', '80']],
];

/** Заведомо сломанные случаи: каждый ОБЯЗАН упасть, иначе проверке нельзя верить. */
const MUST_FAIL = [
  ['поверхность без бордюра', ['check.ts', 'break']],
  ['сеть без левых поворотов', ['lanes.ts', 'break']],
  ['машины, слепые дальше своего отрезка', ['drive.ts', 'город', '120', '90', 'break']],
];

const run = (args) =>
  spawnSync(process.execPath, ['--experimental-strip-types', 'tools/' + args[0], ...args.slice(1)],
    { encoding: 'utf8' });

/**
 * ИЗВЕСТНАЯ ДЫРА, а не «допустимое число».
 *
 * Обстрел случайными постройками даёт 5 поломок из 250, и все пятеро одного
 * рода: ступенька на полотне там, где дорога разворачивается почти на месте.
 * Это НЕ норма, это незаделанная дыра. Здесь она записана числом только
 * затем, чтобы стало видно, если поломок прибавится.
 *
 * Правильное значение — ноль. Пока оно не ноль, строчка стоит здесь и колет
 * глаза каждому, кто запускает проверку.
 */
const FUZZ_HOLE = 5;

let bad = 0;
console.log('ЧТО ДОЛЖНО ПРОХОДИТЬ');
for (const [name, args] of RUNS) {
  const r = run(args);
  const ok = r.status === 0;
  if (!ok) bad++;
  console.log(`  ${ok ? '✓' : '✗'} ${name}`);
  if (!ok) console.log(r.stdout.split('\n').filter((l) => l.includes('✗')).map((l) => '      ' + l.trim()).join('\n'));
}

// обстрел: считаем поломки, а не «прошло или нет» — дыра известна
const fuzz = run(['fuzz.ts', '250']);
const broke = Number(/сломалось\s+(\d+)/.exec(fuzz.stdout)?.[1] ?? -1);
if (broke < 0) {
  bad++;
  console.log('  ✗ обстрел 250 случайными постройками — не смог посчитать');
} else if (broke > FUZZ_HOLE) {
  bad++;
  console.log(`  ✗ обстрел: ${broke} поломок из 250 — БЫЛО ${FUZZ_HOLE}, стало хуже`);
} else if (broke === 0) {
  console.log('  ✓ обстрел 250 случайными постройками — дыра закрыта, убери FUZZ_HOLE');
} else {
  console.log(`  ⚠ обстрел: ${broke} поломок из 250 — ИЗВЕСТНАЯ ДЫРА, ступенька на полотне`);
  console.log('      при развороте почти на месте. Не норма, а незаделанное.');
}

console.log('\nЧТО ДОЛЖНО ПАДАТЬ (иначе проверке нельзя верить)');
for (const [name, args] of MUST_FAIL) {
  const r = run(args);
  const fell = r.status !== 0;
  if (!fell) bad++;
  console.log(`  ${fell ? '✓ падает' : '✗ НЕ ПАДАЕТ'}  ${name}`);
}

console.log(bad === 0 ? '\n✓ всё в порядке' : `\n✗ не в порядке: ${bad}`);
process.exit(bad === 0 ? 0 : 1);
