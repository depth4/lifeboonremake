/**
 * Дома без экрана: проверяется не красота, а устройство.
 *
 * Вопрос, на который отвечает проверка: **можно ли в этот дом войти, стоит ли
 * он на земле и не разъехались ли его проёмы со стенами**. Всё, что видно
 * глазом, — следствие; глазом как раз и не видно окна, наполовину уехавшего
 * за угол на дальней стене.
 *
 * Запуск:  npm run house
 *          npm run house сломать   — модуль не подгоняется, ОБЯЗАНА упасть
 */

import { ЗАСТРОЙКА, ДОМ } from '../src/city/norms.ts';
import { построитьДома, сломатьМодуль, type Дом, type Сетка } from '../src/city/house.ts';
import { построитьПосёлок, вырезать, интересноеМесто } from '../src/city/plan.ts';

const сломать = process.argv[2] === 'сломать';
if (сломать) сломатьМодуль();

const checks: [string, boolean, string][] = [];
const say = (имя: string, ок: boolean, что: string): void => { checks.push([имя, ок, что]); };

/** Земля — плоская: проверяем дома, а не рельеф. Отдельно проверим на склоне. */
const плоско = (): number => 0;
/** Наклон 6%: цоколь обязан догнать перепад, а не повиснуть в воздухе. */
const склон = (x: number, z: number): number => (x + z) * 0.06;

function собрать(вид: 'город' | 'деревня', земля: (x: number, z: number) => number): {
  дома: readonly Дом[]; стены: Сетка; стёкла: Сетка;
} {
  const посёлок = построитьПосёлок(20260913, вид === 'город' ? 400 : 300, вид);
  const кусок = вырезать(посёлок, интересноеМесто(посёлок), 110);
  return построитьДома(кусок.объекты, вид, земля, посёлок.сид);
}

const город = собрать('город', плоско);
const деревня = собрать('деревня', плоско);
const наСклоне = собрать('город', склон);
const все = [...город.дома, ...деревня.дома];

// ── В каждый дом можно войти. Это не украшение: дом без двери — это стена.
{
  const безДвери = все.filter((д) => д.дверей === 0);
  say('в каждый дом есть вход', безДвери.length === 0,
    безДвери.length === 0 ? `${все.length} домов, дверей ${все.reduce((s, д) => s + д.дверей, 0)}`
      : `${безДвери.length} домов без двери, первый — ${безДвери[0].что}`);
}

// ── Дверь начинается от пола. Дверь в воздухе — это окно, а не вход.
{
  let худшее = 0;
  let где = '';
  for (const д of все) {
    for (const п of д.проёмы) {
      if (п.вид !== 'дверь') continue;
      const зазор = Math.abs(п.низ - п.полПола);
      if (зазор > худшее) { худшее = зазор; где = `${д.что} на этаже ${п.этаж}`; }
    }
  }
  say('двери начинаются от пола', худшее < 0.01,
    худшее < 0.01 ? 'все двери на уровне пола' : `${худшее.toFixed(2)} м над полом — ${где}`);
}

// ── Проём не вылезает за стену. Ловится только так: глазом дальняя стена
//    не видна, а окно там уезжает за угол.
{
  let вылезших = 0;
  let пример = '';
  for (const д of все) {
    for (const п of д.проёмы) {
      if (п.от >= -1e-6 && п.до <= п.длинаСтены + 1e-6 && п.от < п.до) continue;
      вылезших++;
      if (!пример) {
        пример = `${д.что}: проём ${п.от.toFixed(2)}…${п.до.toFixed(2)} `
          + `на стене длиной ${п.длинаСтены.toFixed(2)}`;
      }
    }
  }
  say('проёмы не вылезают за стену', вылезших === 0,
    вылезших === 0 ? `${все.reduce((s, д) => s + д.проёмы.length, 0)} проёмов, все внутри стен`
      : `${вылезших} вылезли — ${пример}`);
}

// ── Проёмы не налезают друг на друга: два окна в одном месте — это дыра.
{
  let наложений = 0;
  for (const д of все) {
    const поСтенам = new Map<string, typeof д.проёмы[number][]>();
    for (const п of д.проёмы) {
      const ключ = `${п.стена}/${п.этаж}`;
      поСтенам.set(ключ, [...(поСтенам.get(ключ) ?? []), п]);
    }
    for (const список of поСтенам.values()) {
      for (let i = 0; i < список.length; i++) {
        for (let j = i + 1; j < список.length; j++) {
          const a = список[i], b = список[j];
          if (a.от < b.до - 1e-6 && b.от < a.до - 1e-6
            && a.низ < b.верх - 1e-6 && b.низ < a.верх - 1e-6) наложений++;
        }
      }
    }
  }
  say('проёмы не налезают друг на друга', наложений === 0, `${наложений} наложений`);
}

// ── Окно живёт внутри своего этажа. Окно поперёк перекрытия — не окно.
{
  let сквозных = 0;
  let пример = '';
  for (const д of все) {
    for (const п of д.проёмы) {
      if (п.низ >= п.полПола - 1e-6 && п.верх <= п.потолок + 1e-6) continue;
      сквозных++;
      if (!пример) {
        пример = `${д.что}: проём ${п.низ.toFixed(2)}…${п.верх.toFixed(2)} `
          + `при этаже ${п.полПола.toFixed(2)}…${п.потолок.toFixed(2)}`;
      }
    }
  }
  say('окно не режет перекрытие', сквозных === 0,
    сквозных === 0 ? 'каждый проём внутри своего этажа' : `${сквозных} сквозных — ${пример}`);
}

// ── Дом стоит на земле: цоколь уходит вниз, пол поднят. На склоне — тоже.
{
  let повисших = 0;
  for (const д of наСклоне.дома) {
    const земляПод = склон(д.x, д.z);
    if (д.низ > земляПод - 0.2) повисших++;
  }
  say('на склоне дома не висят', повисших === 0,
    `${наСклоне.дома.length} домов на уклоне 6%, повисших ${повисших}`);
}

// ── Остекление в тех пределах, в которых оно бывает у настоящего дома.
{
  const жильё = все.filter((д) => д.что === 'жильё');
  const доля = (д: Дом): number => д.стекла / Math.max(1, д.фасада);
  const мин = Math.min(...жильё.map(доля));
  const макс = Math.max(...жильё.map(доля));
  say('остекление жилья 8–30% фасада', мин >= 0.08 && макс <= 0.30,
    `от ${(мин * 100).toFixed(1)}% до ${(макс * 100).toFixed(1)}%`);

  const торговля = все.filter((д) => д.что === 'магазин' || д.что === 'супермаркет');
  const витрин = торговля.length === 0 ? 1 : Math.min(...торговля.map(доля));
  say('у магазина витрина, а не окошки', торговля.length === 0 || витрин >= 0.15,
    `${торговля.length} магазинов, самый глухой — ${(витрин * 100).toFixed(1)}% остекления`);
}

// ── Вырожденных треугольников нет: нулевая площадь — это дырка в стене.
{
  const плохих = (с: Сетка): number => {
    let счёт = 0;
    for (let i = 0; i < с.индексы.length; i += 3) {
      const [a, b, c] = [с.индексы[i], с.индексы[i + 1], с.индексы[i + 2]];
      const ux = с.позиции[b * 3] - с.позиции[a * 3];
      const uy = с.позиции[b * 3 + 1] - с.позиции[a * 3 + 1];
      const uz = с.позиции[b * 3 + 2] - с.позиции[a * 3 + 2];
      const vx = с.позиции[c * 3] - с.позиции[a * 3];
      const vy = с.позиции[c * 3 + 1] - с.позиции[a * 3 + 1];
      const vz = с.позиции[c * 3 + 2] - с.позиции[a * 3 + 2];
      const площадь = Math.hypot(
        uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx,
      ) / 2;
      if (площадь < 1e-6) счёт++;
    }
    return счёт;
  };
  // фронтоны скатной кровли — треугольники, собранные вырожденным квадом:
  // у каждого один нулевой треугольник, и это не поломка, а способ записи
  const фронтоны = все.filter((д) => д.что === 'жильё' && д.этажей <= 2).length * 2;
  const всего = плохих(город.стены) + плохих(деревня.стены);
  say('вырожденных треугольников нет, кроме фронтонов', всего <= фронтоны,
    `${всего} нулевых при ${фронтоны} фронтонах`);
}

// ── Цена показа. Не «быстро ли», а «сколько это стоит»: число здесь живёт
//    в выводе, а не переписывается руками в память.
const треугольников = (с: Сетка): number => с.индексы.length / 3;

// ── Один сид — один и тот же дом. Иначе сохранение и мультиплеер невозможны.
{
  const ещё = собрать('город', плоско);
  const совпало = ещё.стены.позиции.length === город.стены.позиции.length
    && ещё.стены.позиции.every((v, i) => v === город.стены.позиции[i]);
  say('один сид — те же дома', совпало,
    `${город.дома.length} домов, совпали ${совпало ? 'полностью' : 'НЕ полностью'}`);
}

console.log(`\nДОМА${сломать ? ' — ЗАВЕДОМО СЛОМАННЫЕ: модуль не подгоняется под стену' : ''}\n`);
console.log(`  город: ${город.дома.length} домов, `
  + `${треугольников(город.стены).toFixed(0)} треугольников стен + `
  + `${треугольников(город.стёкла).toFixed(0)} стекла, `
  + `${(треугольников(город.стены) / Math.max(1, город.дома.length)).toFixed(0)} на дом`);
console.log(`  деревня: ${деревня.дома.length} домов, `
  + `${треугольников(деревня.стены).toFixed(0)} треугольников`);
console.log(`  этажность: город ${ЗАСТРОЙКА.город.этажей.от}–${ЗАСТРОЙКА.город.этажей.до}, `
  + `деревня ${ЗАСТРОЙКА.деревня.этажей.от}–${ЗАСТРОЙКА.деревня.этажей.до}, `
  + `высота этажа ${ДОМ.этаж.жилой} м\n`);

let упало = 0;
for (const [имя, ок, что] of checks) {
  if (!ок) упало++;
  console.log(`  ${ок ? '✓' : '✗'} ${имя.padEnd(46, '.')} ${что}`);
}
console.log(`\n${упало === 0 ? 'ДОМА В ПОРЯДКЕ' : `ДОМА ПРОВАЛЕНЫ: ${упало}`}\n`);
process.exit(упало === 0 ? 0 : 1);
