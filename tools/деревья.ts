/**
 * Деревья без экрана: лист на ветке, ветка из ветки, одно число — одно дерево.
 *
 *   npm run деревья                 — всё
 *   npm run деревья на-шаре         — листья по шару кроны, как утром 23.09: ОБЯЗАНА упасть
 *   npm run деревья откуда-попало   — ветка рядом с родителем, а не на нём: ОБЯЗАНА упасть
 *   npm run деревья не-спрашивая    — кусты сажаются, не спросив, где можно: ОБЯЗАНА упасть
 */

import { ВИДЫ, type Вид, type Скелет, вырастить } from '../src/растения/дерево.ts';
import { дорогиСцены, посёлокСцены } from '../src/scenes.ts';
import { buildWorld } from '../src/world/world.ts';
import { buildSurface } from '../src/surface/index.ts';
import { GroundIndex } from '../src/car/ground.ts';
import { buildNetwork } from '../src/city/traffic.ts';
import { ЗАПАС_ДЕРЕВА, деревьяУлиц, кустыДворов } from '../src/city/зелень.ts';
import { наЗемлеПосёлка, занято } from '../src/city/двор.ts';

const режим = process.argv[2] ?? '';
const как = режим === 'на-шаре' ? { листья: 'на шаре' as const } : режим === 'откуда-попало' ? { ветки: 'откуда попало' as const } : {};

const checks: [string, boolean, string][] = [];
const say = (name: string, ok: boolean, note: string): void => { checks.push([name, ok, note]); };

/** Расстояние от точки до ближайшего отрезка веток скелета, кроме `кроме`. */
function доВеток(с: Скелет, x: number, y: number, z: number, кроме = -1): number {
  let best = Infinity;
  с.ветки.forEach((в, bi) => {
    if (bi === кроме) return;
    for (let i = 1; i < в.точки.length; i++) {
      const a = в.точки[i - 1], b = в.точки[i];
      const dx = b.x - a.x, dy = b.y - a.y, dz = b.z - a.z;
      const l2 = dx * dx + dy * dy + dz * dz;
      let t = l2 > 0 ? ((x - a.x) * dx + (y - a.y) * dy + (z - a.z) * dz) / l2 : 0;
      t = Math.max(0, Math.min(1, t));
      best = Math.min(best, Math.hypot(x - a.x - dx * t, y - a.y - dy * t, z - a.z - dz * t));
    }
  });
  return best;
}

let листьев = 0, оторвано = 0, веток = 0, висит = 0, худшийЛист = 0, худшаяВетка = 0;
const строки: string[] = [];
for (const вид of Object.keys(ВИДЫ) as Вид[]) {
  for (const вариант of [1, 2]) {
    const с = вырастить(вид, вариант, как);
    // лист: черешок на самой ветке — дальше 1 см значит «в воздухе»
    for (let k = 0; k < с.листья.length; k += 7) {
      const л = с.листья[k];
      const d = доВеток(с, л.x, л.y, л.z);
      листьев++; худшийЛист = Math.max(худшийЛист, d);
      if (d > 0.01) оторвано++;
    }
    // ветка: начало на другой ветке; стволы — у земли
    с.ветки.forEach((в, bi) => {
      const н = в.точки[0];
      веток++;
      if (в.уровень === 0) { if (н.y > 0.01) висит++; return; }
      const d = доВеток(с, н.x, н.y, н.z, bi);
      худшаяВетка = Math.max(худшаяВетка, d);
      if (d > 0.01) висит++;
    });
    if (вариант === 1) строки.push(`${вид} ${с.ветки.length}/${с.листья.length}`);
  }
}
say('лист сидит на ветке', оторвано === 0,
  `проверено ${листьев} листьев, в воздухе ${оторвано}; дальше всех от ветки ${(худшийЛист * 100).toFixed(1)} см`);
say('ветка растёт из ветки', висит === 0,
  `проверено ${веток} веток, висят в воздухе ${висит}; дальше всех ${(худшаяВетка * 100).toFixed(1)} см`);
{
  const а = JSON.stringify(вырастить('липа', 7, как)), б = JSON.stringify(вырастить('липа', 7, как));
  const в = JSON.stringify(вырастить('липа', 8, как));
  say('одно число — одно дерево', а === б && а !== в, `липа №7 дважды ${а === б ? 'одинакова' : 'РАЗНАЯ'}, №7 и №8 ${а !== в ? 'разные' : 'ОДИНАКОВЫ'}`);
}

// ── Кусты стоят на газоне: не на дорожке, не в доме, не в стволе. Те самые, что на странице.
{
  const п = посёлокСцены('город')!;
  const мир = buildWorld(дорогиСцены('город'), 'plateau');
  const земля = new GroundIndex(buildSurface(мир));
  const н = наЗемлеПосёлка(п);
  const деревья = деревьяУлиц(мир, buildNetwork(мир), п.сид, { занято: (x, z) => занято(н, x, z, ЗАПАС_ДЕРЕВА) });
  const кусты = кустыДворов(н, п.сид, (x, z) => земля.sample(x, z).material, деревья,
    режим === 'не-спрашивая' ? { где: 'не спрашивая' } : {});
  let неТам = 0, вСтволе = 0, пример = '';
  for (const к of кусты) {
    const пол = земля.sample(к.x, к.z).material;
    if (пол !== 'grass' || занято(н, к.x, к.z, { дом: 0.3, подход: 0.3, вещь: 0 })) {
      неТам++; if (!пример) пример = `(${к.x.toFixed(1)}, ${к.z.toFixed(1)}) — ${пол}`;
    }
    if (деревья.some((д) => Math.hypot(д.x - к.x, д.z - к.z) < 1)) вСтволе++;
  }
  const сирени = кусты.filter((к) => к.вид === 'сирень').length;
  say('куст на газоне, а не на дорожке', кусты.length > 100 && неТам === 0 && вСтволе === 0,
    `${сирени} сиреней, ${кусты.length - сирени} кустов изгороди; не на газоне или в занятом ${неТам}, в стволе ${вСтволе}`
    + (пример ? `; первый: ${пример}` : ''));
}

const СЛОМАНО: Record<string, string> = {
  'на-шаре': 'листья по шару кроны', 'откуда-попало': 'ветки рядом с родителем', 'не-спрашивая': 'кусты без спроса',
};
console.log(`\nДЕРЕВЬЯ${СЛОМАНО[режим] ? ` — ЗАВЕДОМО СЛОМАННЫЕ: ${СЛОМАНО[режим]}` : ''}   (ветки/листья: ${строки.join(', ')})\n`);
let failed = 0;
for (const [name, ok, note] of checks) {
  if (!ok) failed++;
  console.log(`  ${ok ? '✓' : '✗'} ${name.padEnd(30, '.')} ${note}`);
}
console.log(`\n${failed === 0 ? 'ДЕРЕВЬЯ В ПОРЯДКЕ' : `ДЕРЕВЬЯ ПРОВАЛЕНЫ: ${failed}`}\n`);
process.exit(failed === 0 ? 0 : 1);
