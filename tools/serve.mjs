/**
 * Сервер для проверок, которые открывают настоящий браузер.
 *
 * **Зачем отдельный файл.** Его просят четверо: `ride`, `play`, `shot`
 * и `inside`. Каждый заводил себе свой, и каждый наступал в одну и ту же
 * яму — поэтому здесь один сервер на всех, а не четыре похожих.
 *
 * **Яма.** Обычный `vite` следит за файлами и при любой правке перезагружает
 * страницу. Проверка, которая в этот миг держит в странице состояние — машину
 * на скорости, нажатую клавишу, отсчёт разгона, — теряет его и виснет насмерть:
 * она ждёт того, чего в новой странице уже нет. Это стоило двадцати трёх минут
 * впустую в тот раз, когда я правил ЖУРНАЛ РЕШЕНИЙ во время прогона: файл
 * к коду отношения не имел, а страницу снесло всё равно.
 *
 * В памяти проекта это лежало предупреждением «не правь файлы во время
 * проверки». Предупреждение не сработало дважды, значит оно не работает:
 * по правилу 0 плохое состояние надо не сторожить, а сделать невыразимым.
 *
 * **Как сделано невыразимым.** `watch: null` выключает слежение за файлами
 * совсем, `hmr: false` — горячую замену. Перезагружать страницу становится
 * нечему и некому. Цена: во время проверки правки в код не попадают — и это
 * ровно то, что нужно, потому что проверка и так гоняет тот код, с которого
 * началась.
 */

import { createServer } from 'vite';

/**
 * Поднять сервер на этом порту. Возвращает его же — гасить вызовом `close()`.
 *
 * @param {number} порт
 * @param {import('vite').InlineConfig} [ещё] — что добавить поверх
 */
export async function сервер(порт, ещё = {}) {
  const с = await createServer({
    ...ещё,
    logLevel: 'warn',
    server: {
      ...(ещё.server ?? {}),
      port: порт,
      strictPort: true,
      // страницу не перезагружать ни при какой правке: см. заголовок файла
      watch: null,
      hmr: false,
    },
  });
  await с.listen();
  return с;
}
