// ── Никто не теряется в течение суток: в любой час каждый ГДЕ-ТО есть.
{
  let потерянных = 0;
  const счёт: Record<string, number> = {};
  for (let ч = 0; ч < СУТКИ; ч += 0.5) {
    for (const ж of все) {
      const м = где(ж, ч);
      счёт[м.где] = (счёт[м.где] ?? 0) + 1;
      if (м.где === 'в пути' && (м.доля < 0 || м.доля > 1)) потерянных++;
    }
  }
  const всегоТочек = все.length * СУТКИ * 2;
  const сумма = Object.values(счёт).reduce((a, b) => a + b, 0);
  say('никто не теряется за сутки', потерянных === 0 && сумма === всегоТочек,
    `${(сумма / 1000).toFixed(0)} тыс. замеров, потерянных ${потерянных}; `
    + Object.entries(счёт).map(([к, n]) => `${к} ${((n / сумма) * 100).toFixed(0)}%`).join(', '));
}

// ── Ребёнок ходит в БЛИЖАЙШИЙ сад и школу, и не дальше норматива.
for (const [занятие, радиус] of [['сад', РАДИУС.сад], ['школа', РАДИУС.школа]] as const) {
  const дети = все.filter((ж) => ж.занятие === занятие && ж.дело >= 0);
  if (дети.length === 0) { say(`до «${занятие}» не дальше ${радиус} м`, true, 'таких нет'); continue; }
  let дальше = 0;
  let неБлижайший = 0;
  for (const ж of дети) {
    const дом = посёлок.объекты[ж.дом];
    const цель = посёлок.объекты[ж.дело];
    const d = дист(дом, цель);
    дальше = Math.max(дальше, d);
    let ближе = Infinity;
    for (const о of посёлок.объекты) if (о.что === занятие) ближе = Math.min(ближе, дист(дом, о));
    if (d > ближе + 0.01) неБлижайший++;
  }
  say(`ребёнок ходит в ближайший «${занятие}», не дальше ${радиус} м`,
    неБлижайший === 0 && дальше <= радиус,
    `${дети.length} детей, самый дальний в ${дальше.toFixed(0)} м, мимо ближайшего ${неБлижайший}`);
}

