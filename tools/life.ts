/**
 * ── МАШИНЫ НА ПАРКОВКЕ НЕ ДЕКОРАТИВНЫ.
 *
 * Это главная проверка шага. У каждой стоящей машины обязан быть хозяин;
 * хозяин обязан быть НЕ В МАШИНЕ, а внутри того здания, у которого она
 * стоит; и она обязана уехать в час его выхода, а не по случайному отсчёту.
 */
{
  const world = buildWorld(дорогиПосёлка(посёлок), 'plain');
  const net = buildNetwork(world);

  const снимок = (час: number): ReturnType<typeof машиныЖителей> =>
    машиныЖителей(world, net, р, час);

  const ночь = снимок(3);
  const утро = снимок(8.3);
  const день = снимок(12);

  const стоят = (п: typeof ночь): number => п.машины.filter((m) => m.park !== null).length;
  const едут = (п: typeof ночь): number => п.машины.filter((m) => m.park === null).length;

  say('у каждой стоящей машины есть хозяин',
    [ночь, утро, день].every((п) => п.машины.filter((m) => m.park !== null)
      .every((m) => m.хозяин >= 0)),
    `ночью стоит ${стоят(ночь)}, утром ${стоят(утро)}, днём ${стоят(день)}`);

  say('ничья машина не паркуется никогда',
    [ночь, утро, день].every((п) => п.машины.every((m) => m.park === null || m.хозяин >= 0)),
    'ничьих машин в посёлке нет по построению: они бывают только на голых сценах');

  /**
   * Хозяин стоящей машины — не в ней. До 25.09 проверялось «внутри того
   * здания»: тогда из дома выходили только на машине. Теперь в магазин
   * у дома идут пешком, и машина ждёт у подъезда, пока хозяин в магазине.
   */
  say('хозяин стоящей машины — не за рулём',
    ([[ночь, 3], [утро, 8.3], [день, 12]] as const).every(([п, час]) =>
      п.машины.filter((m) => m.park !== null).every((m) => {
        const м = где(кто(р, m.хозяин), час);
        return !(м.где === 'в пути' && м.наМашине);
      })),
    'проверено в 3:00, 8:18 и 12:00');

  say('ночью стоят почти все, а утром выезжают',
    стоят(ночь) > едут(ночь) * 8 && едут(утро) > едут(ночь),
    `в 3:00 стоит ${стоят(ночь)} / едет ${едут(ночь)}; `
    + `в 8:18 стоит ${стоят(утро)} / едет ${едут(утро)}; `
    + `в 12:00 стоит ${стоят(день)} / едет ${едут(день)}`);

  /**
   * Уезжает по часам хозяина. Ставим город в 7:30 и крутим два игровых часа
   * (час за минуту): машины, чьи хозяева выходят в это окно, ОБЯЗАНЫ уехать,
   * а те, чей хозяин выходит позже или сидит на работе до вечера, — ОБЯЗАНЫ
   * остаться. Проверяется и то, и другое: «уехали все» без «остались нужные»
   * ловило бы только половину.
   */
  {
    const поток = снимок(7.5);
    const стояли = поток.машины.map((m) => m.park !== null);
    const DT = 1 / 30;
    const ОТ = 7.5, ДО = 9.5;
    /**
     * Городской час идёт вшестеро быстрее настоящего: два игровых часа —
     * это двадцать минут прогона. Быстрее нельзя, и это не удобство проверки,
     * а правда: если сутки проходят за двадцать четыре минуты, то на выезд
     * из кармана у машины остаются секунды, и город физически не успевает
     * прожить свой день.
     */
    for (let к = 0; к * DT < 1200; к++) {
      moveTraffic(world, net, поток.машины, DT, к * DT,
        { час: ОТ + (к * DT) / 600 });
    }
    let должныБыли = 0, уехали = 0, ранние = 0, зависли = 0, ждут = 0;
    поток.машины.forEach((m, i) => {
      if (!стояли[i]) return;
      const пора = вОкне(m.доЧаса ?? 0, ОТ, ДО);
      if (!пора) {
        // час хозяина ещё не настал: уехать она не имела права
        if (m.park === null) ранние++;
        return;
      }
      должныБыли++;
      if (m.park === null) { уехали++; return; }
      /**
       * Не уехала — это не обязательно поломка. Выезжающий из кармана
       * УСТУПАЕТ потоку (ПДД 8.1), и пока рядом идут машины, он честно ждёт.
       * Поломка — это когда ждать нечего, а он всё равно стоит. Ответ берём
       * у того же правила, которым машина и решает, — иначе это была бы
       * вторая правда об одном.
       */
      const держат = ктоДержитВыезд(net, поток.машины, m);
      /**
       * Стоящей машине не уступают: если держат ТОЛЬКО такие — это тупик.
       * Стоящая — это именно `стоит`: та, что въезжает или выезжает, сейчас
       * в движении, и уступить ей — обычная вежливость, а не затор.
       */
      if (держат.every((o) => стоит(o))) зависли++; else ждут++;
    });
    say('никто не уехал раньше своего хозяина', ранние === 0,
      `уехавших до часа хозяина: ${ранние}`);
    say('кто не уехал — ждёт просвета, а не завис',
      зависли === 0 && уехали > 0,
      `с 7:30 до 9:30 пора было ${должныБыли}, уехало ${уехали}, `
      + `ждут просвета ${ждут}, зависло ${зависли}`);
  }

  /**
   * ── ПЕШЕХОД ИДЁТ К СВОЕМУ ДЕЛУ, а не бродит.
   *
   * Проверяется не «шевелится ли он», а СБЛИЖАЕТСЯ ЛИ С ЦЕЛЬЮ. Бродящий
   * наугад тоже шевелится и тоже проходит километр — и именно так он
   * полгода и выглядел живым, ничего при этом не делая.
   */
  {
    const пешие = пешеходыЖителей(world, net, р, 8.3);
    /**
     * Заведомо сломанный вариант: отобрать маршрут. Тогда человек ходит
     * по тротуару наугад — ровно так, как ходил до 16 сентября, — и никуда
     * не приходит. Проверка обязана это увидеть.
     */
    // цель запоминается ДО того, как её отберут: иначе в сломанном варианте
    // не с чем сравнивать — мы же именно её и убрали
    const цели = пешие.map((w) => {
      const т = along(world, w.маршрут!.цель.shape, w.маршрут!.цель.s);
      return { x: т.x, z: т.z };
    });
    if (безМаршрута) for (const w of пешие) w.маршрут = null;
    const доЦели = (w: (typeof пешие)[number], i: number): number => {
      const п = walkerPose(world, w);
      return Math.hypot(п.x - цели[i].x, п.z - цели[i].z);
    };
    const было = пешие.map(доЦели);
    const DT = 1 / 30;
    // пешеходу до дела в среднем 168 м, это две минуты ходу; восьми хватает всем
    for (let к = 0; к * DT < 480; к++) moveWalkers(world, net, пешие, DT, к * DT);
    const стало = пешие.map(доЦели);

    const пришли = пешие.filter((w) => w.state === 'пришёл').length;
    say('у каждого пешехода есть дело, а не случайный поворот',
      пешие.length > 0 && пешие.every((w) => w.житель >= 0),
      `${пешие.length} человек, у всех номер жителя и маршрут`);
    /**
     * Мерка — «ДОШЁЛ», а не «приблизился». Приблизиться может и бродящий:
     * он ходит кругами по тем же улицам и половину времени случайно
     * оказывается ближе. Дойти до своего подъезда наугад нельзя.
     */
    say('за восемь минут пешеход доходит до своего дела',
      пришли > пешие.length * 0.9,
      `дошли ${пришли} из ${пешие.length}; в среднем до дела было `
      + `${(было.reduce((a, b) => a + b, 0) / было.length).toFixed(0)} м, `
      + `стало ${(стало.reduce((a, b) => a + b, 0) / стало.length).toFixed(0)} м`);
  }

  say('мест у бордюра меньше, чем машин, и это видно',
    ночь.безМеста >= 0,
    `ночью без места у бордюра ${ночь.безМеста} машин из ${ночь.безМеста + стоят(ночь)}`
    + ` — они во дворах, которых мы не строим`);
}

/**
 * ── УЛИЦА ЖИВЁТ ПО РАСПОРЯДКУ. Город проживает 45 минут утра по НАСТОЯЩИМ
 * часам (как на странице): выходы из дома — на улицу, пришедшие — в здания.
 * Пешеходов на тротуарах столько, сколько по распорядку идёт пешком;
 * каждый выход на машине трогает машину; никто не стоит без дела.
 */
{
  const world = buildWorld(дорогиПосёлка(посёлок), 'plain');
  const net = buildNetwork(world);
  const ОТ = 7.5, DT = 0.1, МИНУТ = 45;
  const с = вывестиНаУлицу(world, net, р, ОТ);
  const пешкомПоПлану = (час: number): number => все.filter((ж) => {
    const м = где(ж, час);
    return м.где === 'в пути' && !м.наМашине && м.откуда !== м.куда && м.откуда !== -1 && м.куда !== -1;
  }).length;
  const стоитС = new Map<object, number>();
  let дольше = 0, где2 = '';
  const сверка: string[] = [];
  let хуже = 0;
  for (let к = 1; к * DT <= МИНУТ * 60; к++) {
    const время = к * DT, час = ОТ + время / 3600;
    moveWalkers(world, net, с.пешие, DT, время);
    moveTraffic(world, net, с.машины, DT, время, {
      час,
      crossing: с.пешие.filter((w) => w.crossing > 0).map((w) => ({ shape: w.shape, s: w.s })),
    });
    if (!снимокЧаса) жить(world, net, р, с, час);
    for (const m of с.машины) {
      if (m.park !== null || m.knocked !== null || m.speed > 0.5) { стоитС.delete(m); continue; }
      const с0 = стоитС.get(m) ?? время;
      стоитС.set(m, с0);
      if (время - с0 > дольше) { дольше = время - с0; где2 = `${m.reason}, дорога ${m.shape}`; }
    }
    if (к % 9000 === 0) {
      const план = пешкомПоПлану(час);
      const идут = с.пешие.filter((w) => w.state !== 'пришёл').length;
      хуже = Math.max(хуже, Math.abs(идут / Math.max(1, план) - 1));
      сверка.push(`${час.toFixed(2)}: ${идут} / ${план}`);
    }
  }
  say('на тротуарах те, кто идёт по распорядку (±20%)', хуже <= 0.2,
    `на улице / по распорядку: ${сверка.join('; ')}`);
  say('каждый выход на машине трогает машину', с.счёт.несостоялось <= с.счёт.машиной * 0.02 && с.счёт.машиной > 50,
    `тронулось ${с.счёт.машиной}, места не нашлось ${с.счёт.несостоялось}; пешком вышло ${с.счёт.пешком}`);
  say('никто не стоит без дела дольше 2 минут', дольше <= 120,
    `дольше всех стояла не в кармане ${дольше.toFixed(0)} с (${где2})`);

  /**
   * За любым можно следить: у каждого жителя в конце утра есть точка, а тех,
   * кто по распорядку сейчас идёт улицей пешком, слежка находит НА УЛИЦЕ
   * (его пешехода), а не у двери здания.
   */
  const час = ОТ + МИНУТ / 60;
  let безТочки = 0, идутУлицей = 0, найдены = 0;
  for (let n = 0; n < р.всего; n++) {
    const т = гдеЖитель(world, net, р, с, n, час);
    if (!Number.isFinite(т.x) || !Number.isFinite(т.z)) безТочки++;
    const м = где(все[n], час);
    if (м.где === 'в пути' && !м.наМашине && м.откуда !== м.куда && м.откуда !== -1 && м.куда !== -1) {
      идутУлицей++;
      if (т.как === 'идёт') найдены++;
    }
  }
  say('за любым жителем можно следить', безТочки === 0 && найдены >= идутУлицей * 0.9,
    `без точки ${безТочки} из ${р.всего}; идущих улицей по распорядку ${идутУлицей}, найдено на улице ${найдены}`);
}

/**
 * ── ДВОР ЖИВЁТ. В 16:30 кто по распорядку во дворе — тот во дворе и виден:
 * каждый в своём дворе, на лавке не больше трёх, и место не зависит от того,
 * где стоит камера (показ спрашивает о круге вокруг неё).
 */
{
  const world = buildWorld(дорогиПосёлка(посёлок), 'plain');
  const net = buildNetwork(world);
  const ЧАС = 16.5;
  const вещи = наЗемлеПосёлка(посёлок).вещи;
  const с = вывестиНаУлицу(world, net, р, ЧАС, () => вещи);
  const всеВоДворе = дворНаЧас(с, ЧАС, null);
  const поПлану = все.filter((ж) => где(ж, ЧАС).где === 'во дворе').length;
  // свой двор: не дальше 135 м от своего подъезда
  let чужой = 0;
  for (const д of всеВоДворе) {
    const дом = посёлок.объекты[все[д.номер].дом];
    if (Math.hypot(д.x - дом.x, д.z - дом.z) > 160) чужой++;
  }
  // на одной лавке — не больше трёх сидящих
  const лавки = вещи.filter((в) => в.что === 'лавка');
  const сидят = new Map<number, number>();
  for (const д of всеВоДворе.filter((о) => о.сидит)) {
    let ближе = Infinity, какая = -1;
    лавки.forEach((л, i) => { const d = Math.hypot(л.x - д.x, л.z - д.z); if (d < ближе) { ближе = d; какая = i; } });
    сидят.set(какая, (сидят.get(какая) ?? 0) + 1);
  }
  const теснее = Math.max(0, ...сидят.values());
  /**
   * Тот же двор, спрошенный МАЛЕНЬКИМ кругом вокруг одной лавки (3 м — меньше,
   * чем до подъездов сидящих), даёт ровно тех же людей на тех же местах, что
   * и весь город, — множества сверяются в обе стороны. Круг в 40 м этого
   * не ловил: он захватывал все подъезды, и отбор по кругу камеры
   * никого не терял (проверено поломкой).
   */
  let сдвинулись = 0;
  const лавка = лавки.find((л) => всеВоДворе.filter((д) => д.сидит && Math.hypot(д.x - л.x, д.z - л.z) < 2).length >= 2);
  if (лавка !== undefined) {
    const R = 3;
    const вКруге = всеВоДворе.filter((д) => Math.hypot(д.x - лавка.x, д.z - лавка.z) <= R);
    const изКруга = дворНаЧас(с, ЧАС, { x: лавка.x, z: лавка.z, r: R });
    const то = (a: typeof вКруге[number], b: typeof вКруге[number]): boolean =>
      a.номер === b.номер && Math.hypot(a.x - b.x, a.z - b.z) < 1e-6;
    сдвинулись = вКруге.filter((д) => !изКруга.some((о) => то(о, д))).length
      + изКруга.filter((о) => !вКруге.some((д) => то(о, д))).length;
  }
  say('кто по распорядку во дворе — тот во дворе и виден', всеВоДворе.length >= поПлану * 0.95 && чужой === 0,
    `во дворе по распорядку ${поПлану}, видно ${всеВоДворе.length} (сидят ${всеВоДворе.filter((д) => д.сидит).length}); в чужом дворе ${чужой}`);
  say('на лавке не больше трёх, место не зависит от камеры', теснее <= 3 && сдвинулись === 0 && лавка !== undefined,
    `теснее всего на лавке ${теснее}; пересели от сдвига камеры ${сдвинулись}`);
}

