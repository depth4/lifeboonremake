/**
 * ── ГОРОД ЖИВЁТ НЕ ОДНОЙ РАБОТОЙ. Сколько раз и зачем люди выходят из дома —
 * против обследования поездок (`ПОДВИЖНОСТЬ`). Поездка — в одну сторону;
 * дорога домой считается по цели похода, как в самом обследовании: из
 * магазина домой — это поездка за покупками.
 */
{
  let поездок = 0, заПокупками = 0, пожилых = 0, пожилыхВМагазин = 0, пожилыхКВрачу = 0;
  let неДома = 0, вразброд = 0;
  for (const ж of все) {
    поездок += ж.день.length;
    if (ж.занятие === 'дома') пожилых++;
    ж.день.forEach((д, i) => {
      const цель = д.зачем === 'дом' ? ж.день[i - 1]?.зачем : д.зачем;
      if (цель === 'магазин') заПокупками++;
      if (ж.занятие === 'дома' && цель === 'магазин') пожилыхВМагазин++;
      if (ж.занятие === 'дома' && цель === 'врач') пожилыхКВрачу++;
      const прошлая = ж.день[i - 1];
      if (д.приход < д.выход || (прошлая && (д.выход < прошлая.приход || д.откуда !== прошлая.куда))) вразброд++;
    });
    const последняя = ж.день.at(-1);
    if (последняя && (последняя.куда !== ж.дом || последняя.зачем !== 'дом' || последняя.приход >= СУТКИ)) неДома++;
  }
  const наЖителя = поездок / все.length;
  const доля = заПокупками / Math.max(1, поездок);
  const пожМаг = пожилыхВМагазин / Math.max(1, пожилых);
  const пожВр = пожилыхКВрачу / Math.max(1, пожилых);
  const П = ПОДВИЖНОСТЬ;
  say('день идёт по порядку и кончается дома до полуночи', неДома === 0 && вразброд === 0,
    `кончили не дома ${неДома}, дорог вразброд ${вразброд}`);
  say('поездок на жителя в сутки — как в обследовании (±20%)', Math.abs(наЖителя / П.поездокВСутки - 1) <= 0.2,
    `${наЖителя.toFixed(2)} при ${П.поездокВСутки} в обследовании`);
  say('за покупками — доля поездок как в обследовании (±5 п.п.)', Math.abs(доля - П.заПокупками) <= 0.05,
    `${(доля * 100).toFixed(1)}% при ${(П.заПокупками * 100).toFixed(0)}%`);
  say('пожилые ходят в магазин (±25%)', Math.abs(пожМаг / П.пожилыхЗаПокупками - 1) <= 0.25,
    `${пожМаг.toFixed(2)} поездки в сутки при ${П.пожилыхЗаПокупками.toFixed(2)}`);
  say('пожилые ходят к врачу и по делам (±30%)', Math.abs(пожВр / П.пожилыхПоДелам - 1) <= 0.3,
    `${пожВр.toFixed(2)} поездки в сутки при ${П.пожилыхПоДелам.toFixed(2)}`);
}

