/**
 * Прежний день из того же жителя: дорога к делу и прямо обратно в час,
 * когда он уходит с дела. Магазина, врача, двора и прогулки нет; у кого
 * дела нет — сидит дома.
 */
function однимДелом(ж: Житель): Дорога[] {
  const i = ж.день.findIndex((д) => д.зачем === 'работа' || д.зачем === 'школа' || д.зачем === 'сад');
  if (i < 0) return [];
  const туда = ж.день[i];
  const ушёл = ж.день[i + 1].выход;
  return [туда, {
    откуда: туда.куда, куда: ж.дом, зачем: 'дом', наМашине: туда.наМашине,
    выход: ушёл, приход: ушёл + (туда.приход - туда.выход),
  }];
}

