/**
 * Жители без экрана: проверяется не картинка, а устройство жизни.
 *
 * Вопрос, на который отвечает проверка: живёт ли город сам. Каждый ли житель
 * где-то живёт, ходит ли ребёнок в БЛИЖАЙШУЮ школу, столько ли машин, сколько
 * говорит норма, и — главное — не теряется ли кто-нибудь в течение суток.
 *
 * Запуск:  npm run life
 *          npm run life сломать   — раздать всем случайные сады и школы
 *                                   вместо ближайших: ОБЯЗАНА упасть
 *          npm run life стоянка-в-полосе — карман на полосе движения,
 *                                   как было до 18.09: ОБЯЗАНА упасть
 *          npm run life пешком-наугад — пешеход без маршрута, бродит по
 *                                   тротуару, как до 16.09: ОБЯЗАНА упасть
 */

import { дорогиПосёлка, построитьПосёлок } from '../src/city/plan.ts';
import { buildWorld } from '../src/world/world.ts';
import { buildNetwork, ктоДержитВыезд, moveTraffic, стоит } from '../src/city/traffic.ts';
import { В_ПУТИ as ДОРОГА, машиныЖителей, пешеходыЖителей } from '../src/city/жизнь.ts';
import { moveWalkers, walkerPose } from '../src/city/walkers.ts';
import { along } from '../src/city/traffic.ts';
import { МАШИН_НА_ТЫСЯЧУ, РАДИУС, ВОЗРАСТ } from '../src/city/norms.ts';
import { СУТКИ, type Житель, где, кто, расселить } from '../src/city/житель.ts';

const сломать = process.argv[2] === 'сломать';
/**
 * Заведомо сломанный вариант: карман — правая ПОЛОСА ДВИЖЕНИЯ, как было
 * до 18.09. Тогда впереди стоящей машины в той же полосе стоит следующая
 * припаркованная, и ряд запирает сам себя: выехать утром некуда.
 */
const вПолосе = process.argv[2] === 'стоянка-в-полосе';
/** Заведомо сломанный вариант: пешеход без маршрута, как было до 16 сентября. */
const безМаршрута = process.argv[2] === 'пешком-наугад';
/** Сколько часов занимает дорога. Пока одно число на всех: маршрутов ещё нет. */
const В_ПУТИ = ДОРОГА;

const checks: [string, boolean, string][] = [];
const say = (имя: string, ок: boolean, что: string): void => { checks.push([имя, ок, что]); };

const посёлок = построитьПосёлок(20260913, 300, 'город');
const р = расселить(посёлок);
const все: Житель[] = [];
for (let i = 0; i < р.всего; i++) {
  const ж = кто(р, i);
  /**
   * Заведомо сломанный вариант: ребёнок ходит в случайный сад, а не
   * в ближайший. Ровно та ошибка, ради которой город и расставлен
   * по радиусам доступности.
   */
  все.push(сломать && (ж.занятие === 'сад' || ж.занятие === 'школа')
    ? { ...ж, дело: наугад(посёлок.объекты.map((о, i) => ({ о, i }))
      .filter(({ о }) => о.что === ж.занятие).map(({ i }) => i), i) }
    : ж);
}

function наугад(из: number[], зерно: number): number {
  if (из.length === 0) return -1;
  return из[(зерно * 2654435761) % из.length];
}

const дист = (a: { x: number; z: number }, b: { x: number; z: number }): number =>
  Math.hypot(a.x - b.x, a.z - b.z);

/** Попал ли час в окно суток. Сутки кольцевые, поэтому не просто сравнение. */
const вОкне = (час: number, от: number, до: number): boolean =>
  ((час - от + СУТКИ) % СУТКИ) < ((до - от + СУТКИ) % СУТКИ);

console.log(`\nЖИТЕЛИ посёлка «${посёлок.вид}» ${посёлок.половина * 2} м`
  + `${сломать ? '   [СЛОМАНО: сад и школа наугад]' : ''}\n`);

// ── Каждый где-то живёт, и дом настоящий.
{
  const безДома = все.filter((ж) => посёлок.объекты[ж.дом]?.что !== 'жильё').length;
  say('каждый житель живёт в жилом доме', безДома === 0,
    `${все.length} жителей в ${посёлок.есть.жильё} домах, без дома ${безДома}`);
}

// ── Население совпадает с тем, что насчитал посёлок. Второй правды нет.
{
  say('жителей столько же, сколько насчитал посёлок', р.всего === посёлок.людей,
    `расселено ${р.всего}, посёлок насчитал ${посёлок.людей}`);
}

// ── Никто не теряется в течение суток: в любой час каждый ГДЕ-ТО есть.
{
  let потерянных = 0;
  const счёт: Record<string, number> = {};
  for (let ч = 0; ч < СУТКИ; ч += 0.5) {
    for (const ж of все) {
      const м = где(ж, ч, В_ПУТИ);
      счёт[м.где] = (счёт[м.где] ?? 0) + 1;
      if (м.где === 'в пути' && (м.доля < 0 || м.доля > 1)) потерянных++;
    }
  }
  const всегоТочек = все.length * СУТКИ * 2;
  const сумма = Object.values(счёт).reduce((a, b) => a + b, 0);
  say('никто не теряется за сутки', потерянных === 0 && сумма === всегоТочек,
    `${(сумма / 1000).toFixed(0)} тыс. замеров, потерянных ${потерянных}; `
    + Object.entries(счёт).map(([к, n]) => `${к} ${((n / сумма) * 100).toFixed(0)}%`).join(', '));
}

// ── Ребёнок ходит в БЛИЖАЙШИЙ сад и школу, и не дальше норматива.
for (const [занятие, радиус] of [['сад', РАДИУС.сад], ['школа', РАДИУС.школа]] as const) {
  const дети = все.filter((ж) => ж.занятие === занятие && ж.дело >= 0);
  if (дети.length === 0) { say(`до «${занятие}» не дальше ${радиус} м`, true, 'таких нет'); continue; }
  let дальше = 0;
  let неБлижайший = 0;
  for (const ж of дети) {
    const дом = посёлок.объекты[ж.дом];
    const цель = посёлок.объекты[ж.дело];
    const d = дист(дом, цель);
    дальше = Math.max(дальше, d);
    let ближе = Infinity;
    for (const о of посёлок.объекты) if (о.что === занятие) ближе = Math.min(ближе, дист(дом, о));
    if (d > ближе + 0.01) неБлижайший++;
  }
  say(`ребёнок ходит в ближайший «${занятие}», не дальше ${радиус} м`,
    неБлижайший === 0 && дальше <= радиус,
    `${дети.length} детей, самый дальний в ${дальше.toFixed(0)} м, мимо ближайшего ${неБлижайший}`);
}

// ── Занятия разложились по нормам возраста, а не как попало.
{
  const доля = (з: Житель['занятие']): number => все.filter((ж) => ж.занятие === з).length / все.length;
  const мимо = Math.max(
    Math.abs(доля('сад') - ВОЗРАСТ.дошкольник),
    Math.abs(доля('школа') - ВОЗРАСТ.школьник),
    Math.abs(доля('работа') - ВОЗРАСТ.работник),
  );
  say('возрастной состав сошёлся с нормой', мимо < 0.02,
    `сад ${(доля('сад') * 100).toFixed(1)}% (норма ${(ВОЗРАСТ.дошкольник * 100).toFixed(1)}), `
    + `школа ${(доля('школа') * 100).toFixed(1)}% (${(ВОЗРАСТ.школьник * 100).toFixed(1)}), `
    + `работа ${(доля('работа') * 100).toFixed(1)}% (${(ВОЗРАСТ.работник * 100).toFixed(1)})`);
}

// ── Машин столько, сколько говорит уровень автомобилизации.
{
  const машин = все.filter((ж) => ж.заРулём).length;
  const на1000 = (машин / все.length) * 1000;
  // за рулём только те, кому есть куда ехать, — поэтому не больше нормы
  say('машин не больше, чем по уровню автомобилизации',
    на1000 <= МАШИН_НА_ТЫСЯЧУ + 5 && на1000 > МАШИН_НА_ТЫСЯЧУ * 0.4,
    `${машин} машин, ${на1000.toFixed(0)} на тысячу при норме ${МАШИН_НА_ТЫСЯЧУ}`);
}

// ── Утром город едет ИЗ дома, вечером ДОМОЙ. Это и есть «город работает».
{
  const поток = (час: number): { изДома: number; домой: number } => {
    let изДома = 0, домой = 0;
    for (const ж of все) {
      const м = где(ж, час, В_ПУТИ);
      if (м.где !== 'в пути') continue;
      if (м.откуда === ж.дом) изДома++; else домой++;
    }
    return { изДома, домой };
  };
  const утро = поток(8.2);
  const вечер = поток(18.1);
  const ночь = поток(3);
  say('утром едут из дома, вечером домой, ночью никто',
    утро.изДома > утро.домой * 5 && вечер.домой > вечер.изДома * 5
    && ночь.изДома + ночь.домой === 0,
    `в 8:12 из дома ${утро.изДома} / домой ${утро.домой}; `
    + `в 18:06 из дома ${вечер.изДома} / домой ${вечер.домой}; в 3:00 ${ночь.изДома + ночь.домой}`);
}

// ── Один сид — один и тот же житель. Всегда и везде.
{
  const ещё = расселить(построитьПосёлок(20260913, 300, 'город'));
  let разошлись = 0;
  for (let i = 0; i < Math.min(2000, р.всего); i++) {
    const a = кто(р, i), b = кто(ещё, i);
    if (a.дом !== b.дом || a.занятие !== b.занятие || a.дело !== b.дело
      || a.заРулём !== b.заРулём || Math.abs(a.уходит - b.уходит) > 1e-9) разошлись++;
  }
  say('один сид — один и тот же житель', разошлись === 0,
    `сверено ${Math.min(2000, р.всего)} жителей, разошлись ${разошлись}`);
}

/**
 * ── МАШИНЫ НА ПАРКОВКЕ НЕ ДЕКОРАТИВНЫ.
 *
 * Это главная проверка шага. У каждой стоящей машины обязан быть хозяин;
 * хозяин обязан быть НЕ В МАШИНЕ, а внутри того здания, у которого она
 * стоит; и она обязана уехать в час его выхода, а не по случайному отсчёту.
 */
{
  const world = buildWorld(дорогиПосёлка(посёлок), 'plain');
  const net = buildNetwork(world, вПолосе ? { стоянка: 'в полосе движения' as const } : {});

  const снимок = (час: number): ReturnType<typeof машиныЖителей> =>
    машиныЖителей(world, net, р, час);

  const ночь = снимок(3);
  const утро = снимок(8.3);
  const день = снимок(12);

  const стоят = (п: typeof ночь): number => п.машины.filter((m) => m.park !== null).length;
  const едут = (п: typeof ночь): number => п.машины.filter((m) => m.park === null).length;

  say('у каждой стоящей машины есть хозяин',
    [ночь, утро, день].every((п) => п.машины.filter((m) => m.park !== null)
      .every((m) => m.хозяин >= 0)),
    `ночью стоит ${стоят(ночь)}, утром ${стоят(утро)}, днём ${стоят(день)}`);

  say('ничья машина не паркуется никогда',
    [ночь, утро, день].every((п) => п.машины.every((m) => m.park === null || m.хозяин >= 0)),
    'ничьих машин в посёлке нет по построению: они бывают только на голых сценах');

  say('хозяин стоящей машины — внутри того здания, у которого она стоит',
    [ночь, утро, день].every((п) => п.машины.filter((m) => m.park !== null).every((m) => {
      const ж = кто(р, m.хозяин);
      const м = где(ж, 12, В_ПУТИ);
      return м.где === 'дома' || м.где === 'на месте' || м.где === 'за городом';
    })),
    'проверено на трёх часах суток');

  say('ночью стоят почти все, а утром выезжают',
    стоят(ночь) > едут(ночь) * 8 && едут(утро) > едут(ночь),
    `в 3:00 стоит ${стоят(ночь)} / едет ${едут(ночь)}; `
    + `в 8:18 стоит ${стоят(утро)} / едет ${едут(утро)}; `
    + `в 12:00 стоит ${стоят(день)} / едет ${едут(день)}`);

  /**
   * Уезжает по часам хозяина. Ставим город в 7:30 и крутим два игровых часа
   * (час за минуту): машины, чьи хозяева выходят в это окно, ОБЯЗАНЫ уехать,
   * а те, чей хозяин выходит позже или сидит на работе до вечера, — ОБЯЗАНЫ
   * остаться. Проверяется и то, и другое: «уехали все» без «остались нужные»
   * ловило бы только половину.
   */
  {
    const поток = снимок(7.5);
    const стояли = поток.машины.map((m) => m.park !== null);
    const DT = 1 / 30;
    const ОТ = 7.5, ДО = 9.5;
    /**
     * Городской час идёт вшестеро быстрее настоящего: два игровых часа —
     * это двадцать минут прогона. Быстрее нельзя, и это не удобство проверки,
     * а правда: если сутки проходят за двадцать четыре минуты, то на выезд
     * из кармана у машины остаются секунды, и город физически не успевает
     * прожить свой день.
     */
    for (let к = 0; к * DT < 1200; к++) {
      moveTraffic(world, net, поток.машины, DT, к * DT,
        { час: ОТ + (к * DT) / 600 });
    }
    let должныБыли = 0, уехали = 0, ранние = 0, зависли = 0, ждут = 0;
    поток.машины.forEach((m, i) => {
      if (!стояли[i]) return;
      const пора = вОкне(m.доЧаса ?? 0, ОТ, ДО);
      if (!пора) {
        // час хозяина ещё не настал: уехать она не имела права
        if (m.park === null) ранние++;
        return;
      }
      должныБыли++;
      if (m.park === null) { уехали++; return; }
      /**
       * Не уехала — это не обязательно поломка. Выезжающий из кармана
       * УСТУПАЕТ потоку (ПДД 8.1), и пока рядом идут машины, он честно ждёт.
       * Поломка — это когда ждать нечего, а он всё равно стоит. Ответ берём
       * у того же правила, которым машина и решает, — иначе это была бы
       * вторая правда об одном.
       */
      const держат = ктоДержитВыезд(net, поток.машины, m);
      /**
       * Стоящей машине не уступают: если держат ТОЛЬКО такие — это тупик.
       * Стоящая — это именно `стоит`: та, что въезжает или выезжает, сейчас
       * в движении, и уступить ей — обычная вежливость, а не затор.
       */
      if (держат.every((o) => стоит(o))) зависли++; else ждут++;
    });
    say('никто не уехал раньше своего хозяина', ранние === 0,
      `уехавших до часа хозяина: ${ранние}`);
    say('кто не уехал — ждёт просвета, а не завис',
      зависли === 0 && уехали > 0,
      `с 7:30 до 9:30 пора было ${должныБыли}, уехало ${уехали}, `
      + `ждут просвета ${ждут}, зависло ${зависли}`);
  }

  /**
   * ── ПЕШЕХОД ИДЁТ К СВОЕМУ ДЕЛУ, а не бродит.
   *
   * Проверяется не «шевелится ли он», а СБЛИЖАЕТСЯ ЛИ С ЦЕЛЬЮ. Бродящий
   * наугад тоже шевелится и тоже проходит километр — и именно так он
   * полгода и выглядел живым, ничего при этом не делая.
   */
  {
    const пешие = пешеходыЖителей(world, net, р, 8.3);
    /**
     * Заведомо сломанный вариант: отобрать маршрут. Тогда человек ходит
     * по тротуару наугад — ровно так, как ходил до 16 сентября, — и никуда
     * не приходит. Проверка обязана это увидеть.
     */
    // цель запоминается ДО того, как её отберут: иначе в сломанном варианте
    // не с чем сравнивать — мы же именно её и убрали
    const цели = пешие.map((w) => {
      const т = along(world, w.маршрут!.цель.shape, w.маршрут!.цель.s);
      return { x: т.x, z: т.z };
    });
    if (безМаршрута) for (const w of пешие) w.маршрут = null;
    const доЦели = (w: (typeof пешие)[number], i: number): number => {
      const п = walkerPose(world, w);
      return Math.hypot(п.x - цели[i].x, п.z - цели[i].z);
    };
    const было = пешие.map(доЦели);
    const DT = 1 / 30;
    // пешеходу до дела в среднем 168 м, это две минуты ходу; восьми хватает всем
    for (let к = 0; к * DT < 480; к++) moveWalkers(world, net, пешие, DT, к * DT);
    const стало = пешие.map(доЦели);

    const пришли = пешие.filter((w) => w.state === 'пришёл').length;
    say('у каждого пешехода есть дело, а не случайный поворот',
      пешие.length > 0 && пешие.every((w) => w.житель >= 0),
      `${пешие.length} человек, у всех номер жителя и маршрут`);
    /**
     * Мерка — «ДОШЁЛ», а не «приблизился». Приблизиться может и бродящий:
     * он ходит кругами по тем же улицам и половину времени случайно
     * оказывается ближе. Дойти до своего подъезда наугад нельзя.
     */
    say('за восемь минут пешеход доходит до своего дела',
      пришли > пешие.length * 0.9,
      `дошли ${пришли} из ${пешие.length}; в среднем до дела было `
      + `${(было.reduce((a, b) => a + b, 0) / было.length).toFixed(0)} м, `
      + `стало ${(стало.reduce((a, b) => a + b, 0) / стало.length).toFixed(0)} м`);
  }

  say('мест у бордюра меньше, чем машин, и это видно',
    ночь.безМеста >= 0,
    `ночью без места у бордюра ${ночь.безМеста} машин из ${ночь.безМеста + стоят(ночь)}`
    + ` — они во дворах, которых мы не строим`);
}

let провалов = 0;
for (const [имя, ок, что] of checks) {
  if (!ок) провалов++;
  console.log(`  ${ок ? '✓' : '✗'} ${имя.padEnd(52, '.')} ${что}`);
}
console.log(`\n${провалов === 0 ? 'ЖИТЕЛИ В ПОРЯДКЕ' : `ЖИТЕЛИ ПРОВАЛЕНЫ: ${провалов}`}\n`);
process.exit(провалов === 0 ? 0 : 1);
