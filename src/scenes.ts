/**
 * Посёлки — единственные сцены, которые не нарисованы рукой, а посчитаны
 * по нормам: улицы, участки, назначения и население выводятся из сида.
 *
 * **Размер больше не упирается ни во что.** Три дня здесь стояло «110 метров
 * по потолку мира: плита 240 на 240, планаризация квадратична». Замерено
 * 15 сентября — неправда по обоим пунктам. Мир больше не постоянная, он
 * выводится из того, что в нём построено. Планаризация на мире 2 × 2 км
 * стоит 0.9 с из двадцати, то есть ни при чём. Настоящий потолок сидел
 * в самом плане: жадная расстановка пересчитывала покрытие внутри сравнения
 * при сортировке, и посёлок в 2 км строился две с половиной минуты. После
 * правки — четыре секунды, и посёлок получается ТОТ ЖЕ, отпечаток в отпечаток.
 *
 * Считаются они ПО ТРЕБОВАНИЮ: инструмент, которому посёлок не нужен, не
 * должен платить за него при запуске.
 */
export const ПОСЁЛКИ_ЗАКАЗ = {
  деревня: { сид: 20260913, половина: 300, вид: 'деревня' },
  город: { сид: 20260913, половина: 300, вид: 'город' },
  'большой город': { сид: 20260913, половина: 600, вид: 'город' },
} as const satisfies Record<string, { сид: number; половина: number; вид: 'город' | 'деревня' }>;

const посчитанные = new Map<string, Посёлок>();

/** Посёлок по имени сцены. Не посёлок — `null`, и это не ошибка. */
export function посёлокСцены(имя: string): Посёлок | null {
  if (!(имя in ПОСЁЛКИ_ЗАКАЗ)) return null;
  const готов = посчитанные.get(имя);
  if (готов !== undefined) return готов;
  const з = ПОСЁЛКИ_ЗАКАЗ[имя as keyof typeof ПОСЁЛКИ_ЗАКАЗ];
  const п = построитьПосёлок(з.сид, з.половина, з.вид);
  посчитанные.set(имя, п);
  return п;
}

const road = (lanes: number, ...centerline: Point2[]): Road => ({
  type: roadTypeForLanes(lanes),
  centerline,
});

/** Луч из центра под углом (градусы), длиной `len`. */
const ray = (deg: number, len: number, lanes = 1): Road => {
  const a = (deg * Math.PI) / 180;
  return road(lanes, { x: 0, z: 0 }, { x: Math.cos(a) * len, z: Math.sin(a) * len });
};

