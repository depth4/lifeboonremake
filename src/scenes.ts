/**
 * Посёлок считается В ПОЛНЫЙ РОСТ, а на плиту мира вырезается окно.
 *
 * Так было не всегда, и разница принципиальная. Раньше посёлок строили сразу
 * размером с плиту — 220 метров. В такой клочок норма умещает ровно один
 * перекрёсток и ни одного квартала: квартал — это то, что окружено улицами,
 * а при шаге 200 м в 220 метров влезает всего одна линия сетки. Получался
 * не город, а огрызок, и застройка в нём разваливалась на отдельные ящики.
 *
 * Теперь город 800 × 800 м и деревня 600 × 600 м считаются целиком — со всеми
 * радиусами, нормами и населением, — а сцена показывает окно 220 м вокруг
 * ИНТЕРЕСНОГО места: перекрёстка рядом с магазином. Своей правды у окна нет:
 * это те же дома, сдвинутые в его координаты.
 *
 * Считается лениво, по первому обращению: инструменты, которым посёлок
 * не нужен (а таких большинство), за него не платят.
 */
const РАЗМЕР_ПОСЁЛКА = { город: 400, деревня: 300 } as const;
/** Полуразмер окна: столько же, сколько у рукотворных сцен. */
const ОКНО = 110;
const СИД = 20260913;

const кэш = new Map<string, Кусок>();

export function кусок(имя: 'город' | 'деревня'): Кусок {
  const готовый = кэш.get(имя);
  if (готовый) return готовый;
  const посёлок = построитьПосёлок(СИД, РАЗМЕР_ПОСЁЛКА[имя], имя);
  const свежий = вырезать(посёлок, интересноеМесто(посёлок), ОКНО);
  кэш.set(имя, свежий);
  return свежий;
}

const road = (lanes: number, ...centerline: Point2[]): Road => ({
  type: roadTypeForLanes(lanes),
  centerline,
});

/** Луч из центра под углом (градусы), длиной `len`. */
const ray = (deg: number, len: number, lanes = 1): Road => {
  const a = (deg * Math.PI) / 180;
  return road(lanes, { x: 0, z: 0 }, { x: Math.cos(a) * len, z: Math.sin(a) * len });
};

