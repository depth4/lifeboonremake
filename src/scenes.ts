/**
 * Сложные случаи, на которых сеть дорог обязана не ломаться.
 *
 * Это ДАННЫЕ, а не проверка. Каждая сцена — постройка, которую живой человек
 * действительно может нарисовать: острый угол, звезда из пяти лучей, дорога,
 * пересекающая сама себя. Смотреть на одну красивую сцену бессмысленно —
 * ломается всегда на некрасивых.
 */

import type { Point2, Road } from './world/road.ts';
import { roadTypeForLanes } from './world/road.ts';
import { type Посёлок, построитьПосёлок } from './city/plan.ts';

/**
 * Посёлки — единственные сцены, которые не нарисованы рукой, а посчитаны
 * по нормам: улицы, участки, назначения и население выводятся из сида.
 * Рядом с рукотворными они лежат нарочно: проверки гоняются по всем сразу,
 * и город обязан не ломаться там же, где не ломается «каша».
 *
 * **Размер здесь 110 м не по смыслу, а по потолку мира.** Плита земли —
 * 240 на 240 метров, и настоящий квартал (200 м по нормам) влезает в неё
 * ровно один. Замерено: расширить мир до 600 м можно, но проверка всех сцен
 * замедляется в четырнадцать раз — 2 мин 24 с против 10 с, потому что
 * планаризация квадратична (дыра 10 в STATE.md). Настоящий город появится
 * не раньше, чем мир начнёт строиться плитками. План при этом считается
 * в полный рост: `npm run plan` проверяет нормы на посёлке 1.2 × 1.2 км.
 */
export const ПОСЁЛКИ: Record<string, Посёлок> = {
  город: построитьПосёлок(20260913, 110, 'город'),
  деревня: построитьПосёлок(20260913, 110, 'деревня'),
};

const road = (lanes: number, ...centerline: Point2[]): Road => ({
  type: roadTypeForLanes(lanes),
  centerline,
});

/** Луч из центра под углом (градусы), длиной `len`. */
const ray = (deg: number, len: number, lanes = 1): Road => {
  const a = (deg * Math.PI) / 180;
  return road(lanes, { x: 0, z: 0 }, { x: Math.cos(a) * len, z: Math.sin(a) * len });
};

