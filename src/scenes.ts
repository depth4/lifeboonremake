/**
 * Посёлок попадает в список сцен ЛЕНИВО: считать город ради инструмента,
 * который его не открывает, — платить за то, чего не смотрят. Свойство
 * с геттером ведёт себя как обычный ключ: и `Object.keys`, и `SCENES['город']`
 * работают, не зная про это ничего.
 */
for (const имя of ['город', 'деревня'] as const) {
  Object.defineProperty(SCENES, имя, {
    enumerable: true,
    configurable: true,
    get: (): Road[] => дорогиКуска(кусок(имя)),
  });
}

