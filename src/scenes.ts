/** Все имена сцен: рукотворные и посёлки. */
export const ИМЕНА_СЦЕН: string[] = [...Object.keys(SCENES), ...Object.keys(ПОСЁЛКИ_ЗАКАЗ)];

/**
 * Дороги сцены по имени. Неизвестное имя — ОШИБКА, а не «возьмём решётку».
 *
 * Молчаливая подстановка стоила дорого: `npm run traffic город` полгода
 * гонял «решётку», потому что сцены с таким именем в списке не было,
 * и `?? SCENES['решётка']` подставлял её молча. В памяти при этом стояло
 * «трафик падает на сгенерированном городе» — а он там ни разу не запускался.
 */
export function дорогиСцены(имя: string): Road[] {
  const рука = SCENES[имя];
  if (рука !== undefined) return рука;
  const п = посёлокСцены(имя);
  if (п !== null) return дорогиПосёлка(п);
  throw new Error(`сцены «${имя}» нет. Есть: ${ИМЕНА_СЦЕН.join(', ')}`);
}
