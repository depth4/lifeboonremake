/**
 * Копилка треугольников: из неё собирают всё, что стоит в городе.
 *
 * Отдельный модуль, потому что копилка нужна двоим — домам и уличной
 * обстановке, — а третьей копилки заводить нельзя: две копилки это два
 * способа посчитать нормаль и два способа ошибиться.
 *
 * Про Three.js здесь не знают ничего: наружу отдаются массивы чисел.
 */

/** Готовая к загрузке сетка треугольников. Ничего, кроме чисел. */
export interface Сетка {
  readonly позиции: Float32Array;
  readonly нормали: Float32Array;
  readonly цвета: Float32Array;
  readonly индексы: Uint32Array;
}

export type Точка = readonly [number, number, number];
export type Угол = { x: number; z: number };

export interface Куча {
  поз: number[];
  нор: number[];
  цв: number[];
  инд: number[];
}

export const куча = (): Куча => ({ поз: [], нор: [], цв: [], инд: [] });

export const собрать = (к: Куча): Сетка => ({
  позиции: new Float32Array(к.поз),
  нормали: new Float32Array(к.нор),
  цвета: new Float32Array(к.цв),
  индексы: new Uint32Array(к.инд),
});


/**
 * Четырёхугольник по углам против часовой стрелки снаружи.
 * Нормаль считается из самих углов: «нормаль, не совпадающая с гранью»
 * записать нельзя.
 */
export function квад(к: Куча, a: Точка, b: Точка, c: Точка, d: Точка, цвет: number): void {
  const ux = b[0] - a[0], uy = b[1] - a[1], uz = b[2] - a[2];
  const vx = d[0] - a[0], vy = d[1] - a[1], vz = d[2] - a[2];
  let nx = uy * vz - uz * vy;
  let ny = uz * vx - ux * vz;
  let nz = ux * vy - uy * vx;
  const длина = Math.hypot(nx, ny, nz) || 1;
  nx /= длина; ny /= длина; nz /= длина;
  const r = ((цвет >> 16) & 255) / 255;
  const g = ((цвет >> 8) & 255) / 255;
  const b2 = (цвет & 255) / 255;
  const начало = к.поз.length / 3;
  for (const т of [a, b, c, d]) {
    к.поз.push(т[0], т[1], т[2]);
    к.нор.push(nx, ny, nz);
    к.цв.push(r, g, b2);
  }
  к.инд.push(начало, начало + 1, начало + 2, начало, начало + 2, начало + 3);
}

/** Коробка по середине, размерам и осям. Нужна для мелочи: козырьки, полки. */
export function коробка(
  к: Куча, cx: number, cy: number, cz: number,
  вдоль: number, вверх: number, поперёк: number,
  fx: number, fz: number, цвет: number,
): void {
  // ось «вдоль» — (fx, fz), ось «поперёк» — перпендикуляр к ней
  const px = -fz, pz = fx;
  const т = (a: number, b: number, c: number): Точка => [
    cx + fx * a + px * c, cy + b, cz + fz * a + pz * c,
  ];
  const A = вдоль / 2, B = вверх / 2, C = поперёк / 2;
  квад(к, т(-A, -B, C), т(A, -B, C), т(A, B, C), т(-A, B, C), цвет);
  квад(к, т(A, -B, -C), т(-A, -B, -C), т(-A, B, -C), т(A, B, -C), цвет);
  квад(к, т(A, -B, C), т(A, -B, -C), т(A, B, -C), т(A, B, C), цвет);
  квад(к, т(-A, -B, -C), т(-A, -B, C), т(-A, B, C), т(-A, B, -C), цвет);
  квад(к, т(-A, B, C), т(A, B, C), т(A, B, -C), т(-A, B, -C), цвет);
  квад(к, т(-A, -B, -C), т(A, -B, -C), т(A, -B, C), т(-A, -B, C), цвет);
}


/**
 * Треугольник. Нужен там, где четвёртого угла нет: фронтон крыши, конус кроны.
 *
 * Раньше треугольник записывали вырожденным квадом — четвёртый угол совпадал
 * с первым. У такого квада нормаль считается из (b−a)×(d−a), а d−a при этом
 * ноль: нормаль выходит нулевая, и грань становится ЧЁРНОЙ. Кроны деревьев
 * были чёрными снизу ровно поэтому. Отдельная функция убирает целый класс:
 * треугольник, записанный треугольником, нулевой нормали не даёт.
 */
export function треуг(к: Куча, a: Точка, b: Точка, c: Точка, цвет: number): void {
  const ux = b[0] - a[0], uy = b[1] - a[1], uz = b[2] - a[2];
  const vx = c[0] - a[0], vy = c[1] - a[1], vz = c[2] - a[2];
  let nx = uy * vz - uz * vy;
  let ny = uz * vx - ux * vz;
  let nz = ux * vy - uy * vx;
  const длина = Math.hypot(nx, ny, nz) || 1;
  nx /= длина; ny /= длина; nz /= длина;
  const r = ((цвет >> 16) & 255) / 255;
  const g = ((цвет >> 8) & 255) / 255;
  const b2 = (цвет & 255) / 255;
  const начало = к.поз.length / 3;
  for (const т of [a, b, c]) {
    к.поз.push(т[0], т[1], т[2]);
    к.нор.push(nx, ny, nz);
    к.цв.push(r, g, b2);
  }
  к.инд.push(начало, начало + 1, начало + 2);
}

/** Затемнить цвет: тень откоса, парапет, ограждение. */
export function затемнить(цвет: number, во: number): number {
  const r = Math.round(((цвет >> 16) & 255) * во);
  const g = Math.round(((цвет >> 8) & 255) * во);
  const b = Math.round((цвет & 255) * во);
  return (r << 16) | (g << 8) | b;
}

/**
 * Столб: шестигранная призма. Фонарь, ствол дерева, стойка знака, опора
 * навеса — всё это столбы, и круглым им быть незачем: с трёх метров
 * шестигранник от круга не отличить, а стоит втрое дешевле.
 */
export function столб(
  к: Куча, x: number, z: number, низ: number, верх: number,
  радиус: number, цвет: number, граней = 6,
): void {
  for (let i = 0; i < граней; i++) {
    const a = (i / граней) * Math.PI * 2;
    const b = ((i + 1) / граней) * Math.PI * 2;
    const ax = x + Math.cos(a) * радиус, az = z + Math.sin(a) * радиус;
    const bx = x + Math.cos(b) * радиус, bz = z + Math.sin(b) * радиус;
    квад(к, [ax, низ, az], [bx, низ, bz], [bx, верх, bz], [ax, верх, az], цвет);
  }
}

/**
 * Крона: восьмигранная «капля» — нижний конус к стволу, верхний к макушке.
 * Дерево без неё — палка, а с шаром вместо неё — леденец.
 */
export function крона(
  к: Куча, x: number, z: number, низ: number, высота: number,
  радиус: number, цвет: number,
): void {
  const верх = низ + высота;
  const пояс = низ + высота * 0.34;
  const граней = 8;
  const тёмный = затемнить(цвет, 0.72);
  for (let i = 0; i < граней; i++) {
    const a = (i / граней) * Math.PI * 2;
    const b = ((i + 1) / граней) * Math.PI * 2;
    const ax = x + Math.cos(a) * радиус, az = z + Math.sin(a) * радиус;
    const bx = x + Math.cos(b) * радиус, bz = z + Math.sin(b) * радиус;
    треуг(к, [ax, пояс, az], [bx, пояс, bz], [x, низ, z], тёмный);
    треуг(к, [ax, пояс, az], [bx, пояс, bz], [x, верх, z], цвет);
  }
}

/** Слить несколько сеток в одну: город рисуется одним вызовом, а не сотней. */
export function слить(сетки: readonly Сетка[]): Сетка {
  const живые = сетки.filter((с) => с.индексы.length > 0);
  if (живые.length === 0) return собрать(куча());
  if (живые.length === 1) return живые[0];
  const вершин = живые.reduce((s, с) => s + с.позиции.length / 3, 0);
  const индексов = живые.reduce((s, с) => s + с.индексы.length, 0);
  const позиции = new Float32Array(вершин * 3);
  const нормали = new Float32Array(вершин * 3);
  const цвета = new Float32Array(вершин * 3);
  const индексы = new Uint32Array(индексов);
  let вершина = 0;
  let индекс = 0;
  for (const с of живые) {
    позиции.set(с.позиции, вершина * 3);
    нормали.set(с.нормали, вершина * 3);
    цвета.set(с.цвета, вершина * 3);
    for (let i = 0; i < с.индексы.length; i++) индексы[индекс + i] = с.индексы[i] + вершина;
    вершина += с.позиции.length / 3;
    индекс += с.индексы.length;
  }
  return { позиции, нормали, цвета, индексы };
}
