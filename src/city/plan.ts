/**
 * План посёлка: из сида — улицы, участки, назначения, население.
 *
 * Устройство одно и то же для деревни и для города: разница только в размере
 * площадки и, как следствие, в населении. Всё остальное выводится:
 *
 *   улицы → кварталы → участки → сколько людей помещается →
 *   → сколько нужно садов, школ, магазинов → где они обязаны стоять.
 *
 * **Ни одно число здесь не выдумано.** Все нормы — в `src/city/norms.ts`,
 * их источники — в `docs/how-cities-work.md`. Если генератору нужно новое
 * число, оно сначала появляется там.
 *
 * Что сделано невыразимым, а не поймано проверкой:
 *
 * - **дом без улицы.** Участок не существует сам по себе: он нарезается ВДОЛЬ
 *   улицы, от её красной линии вглубь квартала. Участка, до которого не
 *   доехать, здесь нельзя записать;
 * - **дом в красной линии.** Отступ от оси улицы не «проверяется», а является
 *   тем, из чего считается положение участка;
 * - **население, назначенное числом.** Людей не задают: они получаются из
 *   жилой площади, а площадь — из участков.
 *
 * Про экран этот файл не знает ничего.
 */

