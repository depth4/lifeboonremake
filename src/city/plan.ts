export interface Улица {
  readonly a: Point2;
  readonly b: Point2;
  readonly вид: 'магистральная' | 'местная';
  readonly полосВСторону: number;
  /** Половина красной линии: ближе к оси застройки не бывает. */
  readonly отступ: number;
}

export interface Участок {
  /** Середина участка. */
  readonly x: number;
  readonly z: number;
  /** Размер по фронту улицы и вглубь квартала, м. */
  readonly фронт: number;
  readonly глубина: number;
  /** Куда смотрит фасад, радианы: на улицу. */
  readonly курс: number;
  /** Какой улице принадлежит фронт. */
  readonly улица: number;
  /** Улица идёт вдоль X: тогда фронт участка меряется по X, глубина по Z. */
  readonly вдольX: boolean;
  что: Назначение;
  /**
   * Номер объекта, которому принадлежит участок.
   *
   * Школа занимает четыре участка подряд, но школа при этом ОДНА. Раньше
   * это нигде не записывалось, и вопрос «какие участки составляют один
   * объект» переспрашивался в трёх местах и отвечался по-разному: `есть`
   * делил число участков на расчётное, `занять` искал соседей по расстоянию,
   * а проверка брала подряд идущие в массиве. Три ответа на один вопрос —
   * и они расходились. Теперь ответ один и записан здесь.
   */
  объект: number;
}

/**
 * Объект посёлка: то, что станет ОДНИМ зданием.
 *
 * Жилой дом — это один участок. Школа — несколько подряд. Отсюда «половина
 * школы» невыразима, и показ рисует школу одним домом, а не четырьмя
 * коробками в ряд.
 */
export interface Объект {
  readonly что: Назначение;
  /** Середина всего объекта и куда смотрит фасад. */
  readonly x: number;
  readonly z: number;
  readonly курс: number;
  /** Фронт всех своих участков вместе и глубина участка. */
  readonly фронт: number;
  readonly глубина: number;
  readonly вдольX: boolean;
  readonly улица: number;
  readonly участков: number;
}

/**
 * Въезд во двор: разрыв в периметре застройки, выходящий на улицу.
 *
 * Двор без въезда — это не двор, а колодец. Поэтому въезд не «ставится
 * во дворе», а ВЫРЕЗАЕТСЯ ИЗ ПЕРИМЕТРА: там, где он есть, участка нет.
 * Записать двор, в который нельзя заехать, здесь негде.
 */
export interface Въезд {
  /** Середина разрыва на красной линии. */
  readonly x: number;
  readonly z: number;
  /** Куда ведёт — внутрь квартала, радианы. */
  readonly курс: number;
  readonly ширина: number;
  readonly улица: number;
}

/**
 * Квартал: то, что улицы отрезали от земли, вместе со всем, что внутри.
 *
 * Квартал — не «шаг сетки улиц», а ОБЛАСТЬ. У области есть внутренность,
 * и именно в ней живёт всё, чего у нас не было: двор, проезд, машины
 * жителей, площадки, зелень.
 *
 * Двор ВЫЧИСЛЯЕТСЯ: это квартал минус глубина участков со всех сторон,
 * где они есть. Его нельзя задать отдельно и нельзя рассогласовать
 * с застройкой — двух правд об одном месте здесь не получится.
 */
export interface Квартал {
  /** Границы по красным линиям, м. */
  readonly x0: number;
  readonly x1: number;
  readonly z0: number;
  readonly z1: number;
  /** Двор: середина и размеры. `null` — квартал слишком мал, двора нет. */
  readonly двор: {
    readonly x: number; readonly z: number;
    readonly ширина: number; readonly глубина: number;
  } | null;
  readonly въезды: readonly Въезд[];
  /** Какие участки этого квартала — номера в `Посёлок.участки`. */
  readonly участки: readonly number[];
  /** Машиномест во дворе по норме хранения. Считается по жителям квартала. */
  readonly мест: number;
}

export interface Остановка { readonly x: number; readonly z: number }

