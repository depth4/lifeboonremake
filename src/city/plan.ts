/** Одно и то же зерно даёт один и тот же посёлок. Всегда. */
function зерно(сид: number): () => number {
  let s = (сид ^ 0x9e3779b9) >>> 0;
  return () => {
    s = (Math.imul(s ^ (s >>> 15), 0x2c1b3c6d) + 0x9e3779b9) >>> 0;
    return ((s ^ (s >>> 16)) >>> 0) / 4294967296;
  };
}

const дистанция = (a: { x: number; z: number }, b: { x: number; z: number }): number =>
  Math.hypot(a.x - b.x, a.z - b.z);

/** Сетка улиц: магистральные реже, местные чаще. Обе — по нормам шага. */
function улицы(половина: number): Улица[] {
  const из: Улица[] = [];
  const шаг = УЛИЦА.местная.шаг;
  const линии: number[] = [];
  for (let c = -Math.floor(половина / шаг) * шаг; c <= половина; c += шаг) линии.push(c);

  /**
   * КРАСНАЯ ЛИНИЯ — ЭТО КРАЙ САМОЙ УЛИЦЫ, а не число из таблицы.
   *
   * Красная линия по определению отделяет общую землю от частной, и общая
   * земля улицы — это её проезжая часть с тротуарами, ровно она и ничего
   * сверх. Пока здесь стояло «местная 20 м», а сама улица была 11.96 —
   * между тротуаром и домами оставалось четыре метра ничьего газона, и ещё
   * три съедал палисадник. Семь метров пустоты с уровня глаз и превращали
   * городскую улицу в загородное шоссе: дома стояли не вдоль неё, а где-то
   * за деревьями. Теперь отступ ВЫВОДИТСЯ из типа дороги, и «красная линия,
   * разошедшаяся с шириной улицы» записать негде.
   */
  const отступУлицы = (полосВСторону: number): number => {
    const тип = roadTypeForLanes(полосВСторону);
    return roadWidth(тип) / 2 + тип.sidewalk;
  };
  for (const c of линии) {
    // магистральная там, где сетка совпадает с её шагом; остальные местные
    const главная = Math.abs(c % УЛИЦА.магистральная.шаг) < 1e-6;
    const вид = главная ? 'магистральная' : 'местная';
    const правила = главная ? УЛИЦА.магистральная : УЛИЦА.местная;
    из.push({
      a: { x: -половина, z: c }, b: { x: половина, z: c },
      вид, полосВСторону: правила.полосВСторону, отступ: отступУлицы(правила.полосВСторону),
    });
    из.push({
      a: { x: c, z: -половина }, b: { x: c, z: половина },
      вид, полосВСторону: правила.полосВСторону, отступ: отступУлицы(правила.полосВСторону),
    });
  }
  return из;
}

/**
 * Кварталы и участки в них.
 *
 * **Квартал — это область, отрезанная улицами, а не шаг сетки.** Участки
 * нарезаются ИЗ квартала, по его периметру, от красной линии внутрь.
 * То, что осталось в середине, — двор, и он вычисляется, а не задаётся.
 *
 * Что стало невыразимым:
 *
 * - **участок, не принадлежащий никакому кварталу.** Он нарезается из
 *   квартала, и другого способа его получить нет;
 * - **двор, рассогласованный с застройкой.** Двор — это квартал минус
 *   глубина участков; отдельного числа, которое могло бы разойтись, нет;
 * - **двор без въезда.** Въезд не ставится во двор, а ВЫРЕЗАЕТСЯ из
 *   периметра: там, где он есть, участка нет. Двор, в который нельзя
 *   заехать, записать негде;
 * - **застройка на перекрёстке.** Углы квартала остаются пустыми: от края
 *   квартала внутрь отступается глубина участка поперечной стороны.
 *
 * Раньше квартал отсчитывался шагами от КОНЦА улицы, и когда размер посёлка
 * не был кратен шагу, вся раскладка съезжала на полквартала (решение от
 * 15.09). Теперь границы берутся у самих улиц: `границы()` ниже.
 */

/**
 * Нарезать сторону квартала на участки РАЗНОЙ ширины.
 *
 * Зачем: до 17.09 фронт участка был одной постоянной, и все дома выходили
 * одинаковыми — разброс следов 1.13 при настоящих 12.1 (`npm run морфология`).
 * Нормы при этом выполнялись целиком: норматив не знает, склад перед ним
 * или улица.
 *
 * Что сделано невыразимым:
 *
 * - **щель между участками и наложение.** Ширины считаются, а потом РОВНО
 *   домащиваются до длины стороны: сумма равна длине по построению.
 *   Ни зазора, ни нахлёста записать нельзя;
 * - **зависимость от порядка.** Ширины выводятся из зерна стороны, а не
 *   из последовательного датчика: посчитай стороны в другом порядке —
 *   получится то же самое.
 */
function фронты(
  длина: number, вилка: { мин: number; макс: number }, зерно: number,
): number[] {
  if (длина < вилка.мин) return [];
  let s = (зерно ^ 0x9e3779b9) >>> 0;
  const дальше = (): number => {
    s = (Math.imul(s ^ (s >>> 15), 0x2c1b3c6d) + 0x9e3779b9) >>> 0;
    return ((s ^ (s >>> 16)) >>> 0) / 4294967296;
  };
  /**
   * Ширина берётся не ровно, а с уклоном к узкому: в настоящем квартале
   * мелких участков больше, чем крупных. Замер Праги: медиана участка
   * 394 м² при вилке 79…1218 — медиана сидит примерно на трети вилки,
   * а не посередине. Степень 1.6 и даёт такой перекос: медиана на 0.33,
   * среднее на 1/2.6.
   */
  const СТЕПЕНЬ = 1.6;
  const среднее = вилка.мин + (вилка.макс - вилка.мин) / (СТЕПЕНЬ + 1);

  /**
   * Сколько участков — решается СРАЗУ, а потом ширины домащиваются
   * растяжением до длины стороны.
   *
   * Первая редакция набирала участки, пока влезают, и раздавала остаток
   * поровну. Остаток в среднем — получастка, и он систематически раздувал
   * каждый участок процентов на восемнадцать: замеренная медиана следа
   * выходила 347 м² там, где вилка обещала 226. Подкручивать вилку под
   * этот перекос значило бы лечить симптом. Растяжение перекоса не вносит:
   * все ширины умножаются на один множитель, и распределение остаётся тем,
   * каким его задали.
   */
  /**
   * Число участков выбирается так, чтобы средняя ширина ПОСЛЕ растяжения
   * осталась внутри вилки. Без этих границ одно и то же деление на короткой
   * стороне прыгало: сдвинешь вилку на полтора метра — число участков
   * перескочит на единицу, и все они разом станут шире на треть. Замерено:
   * медиана следа скакала со 157 до 351 м² от такой мелочи.
   */
  const нМин = Math.max(1, Math.ceil(длина / вилка.макс));
  const нМакс = Math.max(1, Math.floor(длина / вилка.мин));
  /**
   * Вилка держит КАЖДЫЙ участок, а не только средний.
   *
   * Раньше границы проверялись у среднего, а растяжение до длины стороны
   * шло потом — и отдельный участок вылетал за вилку сколько угодно далеко.
   * Замерено 21.09: магазин на трёх участках вышел 137 метров по фронту
   * при норме сорок, и с улицы это была одноэтажная стена в полтора
   * квартала. Теперь число участков растёт, пока самый широкий не влезет
   * в вилку; «участок шире, чем бывает» записать негде.
   */
  let сколько = Math.min(нМакс, Math.max(нМин, Math.round(длина / среднее)));
  let из: number[] = [];
  for (let попытка = 0; попытка < 12; попытка++) {
    из = [];
    for (let i = 0; i < сколько; i++) из.push(вилка.мин + (вилка.макс - вилка.мин) * дальше() ** СТЕПЕНЬ);
    const сумма = из.reduce((a, b) => a + b, 0);
    // сумма ширин равна длине стороны ТОЧНО: ни щели, ни нахлёста
    из = из.map((ш) => (ш * длина) / сумма);
    if (Math.max(...из) <= вилка.макс || сколько >= нМакс) break;
    сколько++;
  }
  return из;
}

/**
 * Скруглить ВСЕ внутренние углы ломаной дугами.
 *
 * У дороги есть предел по радиусу — не меньше трёх полуширин полотна;
 * прямой угол его нарушает, и поверхность в том месте не собирается
 * (замерено 17.09: 53 точки без земли под ними и повисший дом). Пока
 * скругление было написано прямо в ветке углового квартала, ломаную
 * из четырёх поворотов записать было нельзя. Теперь можно любую.
 *
 * Радиус берётся с запасом над пределом и урезается по обоим соседним
 * отрезкам, чтобы две соседние дуги не съели один и тот же кусок.
 */
function скруглить(точки: readonly Point2[], R: number): Point2[] {
  if (точки.length < 3) return [...точки];
  const из: Point2[] = [точки[0]];
  for (let i = 1; i + 1 < точки.length; i++) {
    const угол = точки[i], пред = точки[i - 1], след = точки[i + 1];
    const ед = (от: Point2): Point2 => {
      const d = Math.hypot(от.x - угол.x, от.z - угол.z) || 1;
      return { x: (от.x - угол.x) / d, z: (от.z - угол.z) / d };
    };
    const е1 = ед(пред), е2 = ед(след);
    // почти прямая: скруглять нечего
    if (е1.x * е2.x + е1.z * е2.z < -0.98) { из.push(угол); continue; }
    const r = Math.min(R,
      Math.hypot(пред.x - угол.x, пред.z - угол.z) * 0.45,
      Math.hypot(след.x - угол.x, след.z - угол.z) * 0.45);
    if (r < 1) { из.push(угол); continue; }
    const центр = { x: угол.x + (е1.x + е2.x) * r, z: угол.z + (е1.z + е2.z) * r };
    const н = { x: угол.x + е1.x * r, z: угол.z + е1.z * r };
    const к = { x: угол.x + е2.x * r, z: угол.z + е2.z * r };
    const a1 = Math.atan2(н.z - центр.z, н.x - центр.x);
    let a2 = Math.atan2(к.z - центр.z, к.x - центр.x);
    // короткая сторона дуги: длинная обошла бы двор кругом
    while (a2 - a1 > Math.PI) a2 -= 2 * Math.PI;
    while (a1 - a2 > Math.PI) a2 += 2 * Math.PI;
    из.push(н);
    for (let ш = 1; ш <= 3; ш++) {
      const t = a1 + (a2 - a1) * (ш / 4);
      из.push({ x: центр.x + Math.cos(t) * r, z: центр.z + Math.sin(t) * r });
    }
    из.push(к);
  }
  из.push(точки[точки.length - 1]);
  return из;
}

/** Граница квартала: где проходит и чем задана. */
interface Граница {
  readonly где: number;
  /** Половина красной линии улицы. У края мира — ноль. */
  readonly отступ: number;
  /** Номер улицы в сети. `null` — это край мира, а не улица. */
  readonly улица: number | null;
}

/**
 * Границы кварталов по одной оси: все поперечные улицы плюс края посёлка.
 *
 * `как.кварталы === false` — заведомо сломанный вариант: границы ровным
 * шагом от края, как было до 15.09. Дома встают на перекрёстки.
 */
function границы(
  сеть: readonly Улица[], половина: number, поX: boolean,
  как: { кварталы?: boolean },
): Граница[] {
  if (как.кварталы === false) {
    const из: Граница[] = [];
    const шаг = УЛИЦА.местная.шаг;
    for (let c = -половина; c <= половина + 1e-6; c += шаг) {
      из.push({ где: c, отступ: УЛИЦА.магистральная.красная / 2, улица: null });
    }
    return из;
  }
  const из: Граница[] = [];
  сеть.forEach((у, индекс) => {
    // улица, идущая вдоль Z, делит ось X, и наоборот
    const вдольX = у.a.z === у.b.z;
    if (вдольX === поX) return;
    из.push({ где: вдольX ? у.a.z : у.a.x, отступ: у.отступ, улица: индекс });
  });
  из.sort((a, b) => a.где - b.где);
  /**
   * Края посёлка — границы без отступа: там просто кончается земля.
   * Если улица стоит ровно на краю, второй границы там быть не должно,
   * иначе застройка подойдёт к перекрёстку вплотную.
   */
  if (из.length === 0 || из[0].где > -половина + 1e-6) {
    из.unshift({ где: -половина, отступ: 0, улица: null });
  }
  if (из[из.length - 1].где < половина - 1e-6) {
    из.push({ где: половина, отступ: 0, улица: null });
  }
  return из;
}

/**
 * Нарезать кварталы и участки в них.
 *
 * Возвращает и то и другое сразу: участок не существует без своего квартала,
 * и собирать их порознь значило бы завести две правды об одном.
 */
function кварталы(
  сеть: readonly Улица[], половина: number, вид: Вид, сид: number,
  как: { кварталы?: boolean; въезды?: boolean; устье?: boolean } = {},
): { кварталы: Квартал[]; участки: Участок[] } {
  const УЗКИЙ = самыйУзкийУчасток(вид);
  const поX = границы(сеть, половина, true, как);
  const поZ = границы(сеть, половина, false, как);
  const все: Участок[] = [];
  const список: Квартал[] = [];
  /** Сквозная нумерация сплошных кусков застройки по всему посёлку. */
  let кусков = 0;

  for (let i = 0; i + 1 < поX.length; i++) {
    for (let j = 0; j + 1 < поZ.length; j++) {
      const x0 = поX[i].где + поX[i].отступ, x1 = поX[i + 1].где - поX[i + 1].отступ;
      const z0 = поZ[j].где + поZ[j].отступ, z1 = поZ[j + 1].где - поZ[j + 1].отступ;
      if (x1 - x0 < УЗКИЙ || z1 - z0 < УЗКИЙ) continue;

      /**
       * Четыре стороны квартала. Сторона застраивается только если её
       * граница — улица: к краю мира фасадом не выходят, туда некуда выйти.
       * `наружу` — куда от стороны идёт улица, то есть куда смотрит фасад.
       */
      const сторона = (
        гр: Граница, вдольX: boolean, поперёк: number, наружу: -1 | 1,
      ): {
        гр: Граница; вдольX: boolean; поперёк: number; наружу: -1 | 1; курсНаружу: number;
      } => ({
        гр,
        вдольX,
        поперёк,
        наружу,
        /**
         * Куда от этой стороны улица — ОДНА формула на всё.
         *
         * Фасад смотрит туда же, въезд — ровно против. Пока это было двумя
         * табличками, они разошлись: 17.09 проверка нашла, что все 36 въездов
         * ведут из двора на проезжую часть, потому что въезду достался курс
         * фасада. Теперь развернуть можно только прибавлением π, и разойтись
         * им не с чем.
         */
        курсНаружу: вдольX
          ? (наружу > 0 ? Math.PI / 2 : -Math.PI / 2)
          : (наружу > 0 ? 0 : Math.PI),
      });
      const стороны = [
        сторона(поX[i], false, x0, -1),
        сторона(поX[i + 1], false, x1, 1),
        сторона(поZ[j], true, z0, -1),
        сторона(поZ[j + 1], true, z1, 1),
      ];

      /**
       * Проезд во дворе — СКВОЗНОЙ, и въезды это два его конца.
       *
       * Почему не один въезд с тупиком. Тупик пришлось бы разворачивать:
       * машине нужно четырнадцать чистых метров, и двор превратился бы
       * в место, где все застревают. Сквозной проезд — это к тому же то,
       * как устроен настоящий двор: в него заезжают с одной улицы, а
       * выезжают на другую.
       *
       * Ось выбирается та, у которой ОБЕ границы — улицы. С магистрали
       * во двор не заезжают: там сплошной поток, и разрыв в застройке
       * на ней был бы опасным съездом. Поэтому пара местных предпочтительнее.
       */
      const ВСЕ_ПАРЫ = [
        [0, 1], [2, 3],                    // насквозь
        [0, 2], [0, 3], [1, 2], [1, 3],    // с поворотом, в угловых кварталах
      ] as const;
      const пары = ВСЕ_ПАРЫ
        .filter((ось) => ось.every((к) => стороны[к].гр.улица !== null))
        .map((ось) => ({
          ось,
          /**
           * С ПОВОРОТОМ ЛУЧШЕ, ЧЕМ НАСКВОЗЬ, — и это не про удобство езды.
           *
           * Проезд соединяет два въезда. Когда они на противоположных
           * сторонах, он идёт ПО ПРЯМОЙ через середину двора — по пустырю,
           * где нет ни одного дома, и машины жителей стоят в девяноста
           * метрах от подъездов. Когда на соседних, он огибает двор буквой
           * «Г»: вдоль северного ряда домов, потом вдоль западного. Стоянка
           * от этого оказывается у подъездов, а двор перестаёт быть полем
           * с дорогой посередине.
           *
           * Поворот у него ровно один, и он уже проверен: угловые кварталы
           * ездят так с 17.09. Изломы посерьёзнее пробовали 21.09 — четыре
           * поворота ломают четыре проверки сразу.
           *
           * По местным улицам по-прежнему лучше, чем по магистрали: с неё
           * во двор не заезжают.
           */
          вес: (ось[0] + 1 === ось[1] && ось[0] % 2 === 0 ? 0 : 10)
            + ось.filter((к) => сеть[стороны[к].гр.улица as number].вид === 'местная').length,
        }))
        .sort((a, b) => b.вес - a.вес);
      /** `въезды: false` — заведомо сломанный вариант: двор без въезда. */
      const лучшие = пары.filter((п) => пары.length > 0 && п.вес === пары[0].вес);
      const сквозь = (пары.length === 0 || как.въезды === false) ? null
        : лучшие[Math.abs(Math.imul(Math.round(x0) | 0, 374761393)
          ^ Math.imul(Math.round(z0) | 0, 668265263) ^ Math.imul(сид | 0, 2246822519))
          % лучшие.length].ось;

      /**
       * Отступ от конца стороны. Он нужен затем, чтобы не застроить УГОЛ:
       * там стоят участки поперечной стороны, и дом в углу закрывает
       * видимость на перекрёстке. Значит отступать надо ровно там, где
       * поперечная сторона застроена, — у края мира перекрёстка нет,
       * и отступать не от чего.
       */
      /**
       * УГОЛ КВАРТАЛА ЗАСТРОЕН, и принадлежит он стороне ВДОЛЬ X.
       *
       * Раньше от каждого конца каждой стороны отступалась глубина участка —
       * чтобы участки двух перпендикулярных сторон не налезли друг на друга
       * в углу. Цена этому была замерена 18.09: на квартале в 200 м пустовало
       * 52 метра из 200 на каждой стороне, то есть четверть всего периметра,
       * и застройка держалась на 16% при настоящих 26%. С улицы это читалось
       * прямо: каждый перекрёсток окружён газоном, а не домами.
       *
       * Налезание убирается не пустотой, а ПРАВОМ НА УГОЛ. Стороны вдоль X
       * берут свои углы целиком; стороны вдоль Z начинаются там, где кончается
       * глубина участков поперечной стороны. Две полосы смыкаются встык
       * и пересечься не могут по построению — проверять нечего.
       */
      const уголОт = (гр: Граница, вдольX: boolean): number =>
        (вдольX || гр.улица === null ? 0 : ГЛУБИНА_УЧАСТКА);
      const мои: number[] = [];
      const въезды: Въезд[] = [];
      for (const [к, сторона] of стороны.entries()) {
        if (сторона.гр.улица === null) continue;
        const концы = сторона.вдольX ? [поX[i], поX[i + 1]] : [поZ[j], поZ[j + 1]];
        const от = (сторона.вдольX ? x0 : z0) + уголОт(концы[0], сторона.вдольX);
        const до = (сторона.вдольX ? x1 : z1) - уголОт(концы[1], сторона.вдольX);
        if (до - от < УЗКИЙ) continue;

        /** Где на этой стороне разрыв под въезд. Нет въезда — пустой список. */
        /**
         * ВЪЕЗД НЕ ПОСЕРЕДИНЕ СТОРОНЫ, А БЛИЖЕ К КРАЮ КВАРТАЛА.
         *
         * Отсюда всё остальное: проезд соединяет два въезда, и пока они
         * стояли в серединах противоположных сторон, он шёл ровно через
         * середину двора — по пустырю, где нет ни одного дома. Машины
         * жителей стояли в девяноста метрах от своих подъездов. 21.09
         * Алекс сказал про выложенный город: «никаких проездов к домам,
         * придомовой территории — только дома и дороги», и это было правдой.
         *
         * Сдвиг к краю ставит проезд вдоль задней линии участков, то есть
         * вдоль домов, — и остаётся ПРЯМЫМ. Добиваться того же изломом
         * посреди двора пробовали в тот же день: четыре поворота радиуса 22
         * сломали четыре проверки сразу (походка на тротуаре дуги, поворотники,
         * слепая езда), потому что двор превратился в извилистую дорогу.
         * Прямой проезд у края делает то же самое и не платит ничем.
         */
        /**
         * ПОКА 0.5 — СЕРЕДИНА СТОРОНЫ, и это не то, чего хочется.
         *
         * Хочется трети: тогда проезд идёт вдоль задней линии участков,
         * то есть вдоль домов, и стоянка оказывается у подъездов, а не
         * посреди газона. Замерено 21.09 — с третью пешеходы перестают
         * доходить до своих дел: 319 из 400 вместо 360 по проверке.
         * Улица режется узлом не пополам, а на треть и две трети, и маршрут
         * пешехода через этот узел где-то теряется. Причина не найдена,
         * число названо, задача записана в `STATE.md`.
         */
        const К_КРАЮ = 0.5;
        const разрыв = сквозь !== null && (сквозь[0] === к || сквозь[1] === к)
          ? { от: от + (до - от) * К_КРАЮ - ШИРИНА_ВЪЕЗДА / 2,
            до: от + (до - от) * К_КРАЮ + ШИРИНА_ВЪЕЗДА / 2 }
          : null;
        if (разрыв !== null) {
          const вдоль = от + (до - от) * К_КРАЮ;
          въезды.push({
            x: сторона.вдольX ? вдоль : сторона.поперёк,
            z: сторона.вдольX ? сторона.поперёк : вдоль,
            // въезд ведёт внутрь — это ровно против того, куда смотрит фасад
            курс: сторона.курсНаружу + Math.PI,
            ширина: ШИРИНА_ВЪЕЗДА,
            улица: сторона.гр.улица,
          });
        }

        /** Куски стороны, свободные от въезда. Без въезда — вся сторона. */
        const куски = разрыв === null ? [{ от, до }]
          : [{ от, до: разрыв.от }, { от: разрыв.до, до }];

        for (const [номерКуска, кусок] of куски.entries()) {
          // сквозной номер куска по всему посёлку: он и есть ответ на вопрос
          // «смежны ли эти два участка», и другого ответа нет
          const номерКускаВПосёлке = кусков++;
          const вилка = ЗАСТРОЙКА[вид].фронт[сеть[сторона.гр.улица].вид];
          const ширины = фронты(кусок.до - кусок.от, вилка,
            Math.imul(сид | 0, 2654435761) ^ Math.imul(Math.round(x0) | 0, 374761393)
            ^ Math.imul(Math.round(z0) | 0, 668265263) ^ Math.imul(к * 4 + номерКуска, 2246822519));
          let вдольОт = кусок.от;
          for (const фронт of ширины) {
            const вдоль = вдольОт + фронт / 2;
            вдольОт += фронт;
            const вглубь = сторона.поперёк + сторона.наружу * -1 * (ГЛУБИНА_УЧАСТКА / 2);
            const x = сторона.вдольX ? вдоль : вглубь;
            const z = сторона.вдольX ? вглубь : вдоль;
            мои.push(все.length);
            все.push({
              x, z,
              фронт, глубина: ГЛУБИНА_УЧАСТКА,
              // фасад смотрит НА улицу: наружу от квартала
              курс: сторона.курсНаружу,
              улица: сторона.гр.улица,
              вдольX: сторона.вдольX,
              кусок: номерКускаВПосёлке,
              что: 'жильё',
              объект: -1,
            });
          }
        }
      }

      /**
       * Двор — это то, что осталось. Отступается глубина участка с тех
       * сторон, где участки есть; где их нет (край мира), двор доходит
       * до самой границы квартала.
       */
      const застроена = (с: typeof стороны[number]): number =>
        (с.гр.улица === null ? 0 : ГЛУБИНА_УЧАСТКА);
      const дx0 = x0 + застроена(стороны[0]), дx1 = x1 - застроена(стороны[1]);
      const дz0 = z0 + застроена(стороны[2]), дz1 = z1 - застроена(стороны[3]);
      const двор = (дx1 - дx0 >= МИНИМАЛЬНЫЙ_ДВОР && дz1 - дz0 >= МИНИМАЛЬНЫЙ_ДВОР)
        ? {
          x: (дx0 + дx1) / 2, z: (дz0 + дz1) / 2,
          ширина: дx1 - дx0, глубина: дz1 - дz0,
        }
        : null;

      /**
       * Проезд: от одного въезда внутрь до края двора, при надобности
       * с поворотом, и наружу вторым въездом. Точки берутся из самих
       * въездов и границ двора, поэтому проезд не может разойтись
       * ни с разрывом в застройке, ни со двором.
       */
      let проезд: Point2[] | null = null;
      if (въезды.length === 2 && двор !== null) {
        const край = (в: Въезд): Point2 => ({
          x: в.x + Math.cos(в.курс) * ГЛУБИНА_УЧАСТКА,
          z: в.z + Math.sin(в.курс) * ГЛУБИНА_УЧАСТКА,
        });
        const [a, b] = въезды;
        /**
         * Проезд начинается НА ОСИ УЛИЦЫ, а не на красной линии.
         *
         * Две дороги становятся связанными, только когда их осевые линии
         * встречаются (`network.ts`: примыкание торцом, полтора метра).
         * Красная линия отстоит от оси, и пока проезд начинался там,
         * он не примыкал ни к чему: замерено 18.09 — НИ ОДИН из дворов
         * не был соединён с сетью, машины во дворе стояли, но заехать
         * туда и выехать было нельзя вовсе.
         */
        const наОси = (в: Въезд): Point2 => {
          const у = сеть[в.улица];
          const dx = у.b.x - у.a.x, dz = у.b.z - у.a.z;
          const len2 = dx * dx + dz * dz;
          if (len2 < 1e-9) return { x: в.x, z: в.z };
          const t = ((в.x - у.a.x) * dx + (в.z - у.a.z) * dz) / len2;
          return { x: у.a.x + dx * t, z: у.a.z + dz * t };
        };
        /**
         * `устье: false` — заведомо сломанный вариант: проезд начинается
         * на красной линии, как было до 18.09. Двор становится островом.
         */
        const устье = (в: Въезд): Point2[] => {
          if (как.устье === false) return [{ x: в.x, z: в.z }];
          const о = наОси(в);
          return Math.hypot(о.x - в.x, о.z - в.z) < 1 ? [{ x: в.x, z: в.z }] : [о, { x: в.x, z: в.z }];
        };
        const ка = край(a), кб = край(b);
        /** Радиус сопряжения: с запасом над пределом в три полуширины полотна. */
        const R = 4 * (КВАРТАЛ.въезд / 2);
        /**
         * ПРОЕЗД ИДЁТ ВДОЛЬ ДОМОВ, А НЕ ЧЕРЕЗ СЕРЕДИНУ ПОЛЯ.
         *
         * Первая редакция вела его напрямую от въезда к въезду — то есть
         * ровно через середину двора, где нет ничего и никого. С улицы
         * и сверху это читалось как ещё одна дорога через пустырь, а не
         * как двор: 21.09 Алекс сказал про выложенный город «никаких
         * проездов к домам, придомовой территории — только дома и дороги»,
         * и это было правдой. Машины стояли в девяноста метрах от подъездов.
         *
         * Теперь проезд уходит к ближнему краю двора и идёт ВДОЛЬ НЕГО —
         * вплотную к задней линии участков, то есть вдоль домов. Отсюда
         * и стоянка оказывается у домов, а не посреди газона.
         */
        const насквозь = Math.abs(Math.cos(a.курс)) > 0.5 === (Math.abs(Math.cos(b.курс)) > 0.5);
        if (насквозь) {
          проезд = скруглить([...устье(a), ка, кб, ...устье(b).reverse()], R);
        } else {
          /**
           * Проезд с поворотом — в угловом квартале, где насквозь не выйдет.
           */
          /**
           * УГОЛ «Г» — В УГЛУ ДВОРА, а не в его середине.
           *
           * Две диагонали дают разные повороты, и разница видна только
           * на картинке. При въездах в серединах сторон точка {кб.x, ка.z}
           * приходится РОВНО на середину двора: проезд снова режет пустырь,
           * только буквой «Г». Замерено 22.09: середина двора оказалась
           * в пяти метрах от полотна. Другая диагональ ведёт проезд по двум
           * краям двора — вдоль домов, ради чего всё и затевалось.
           */
          const угол = Math.abs(Math.cos(a.курс)) > 0.5
            ? { x: ка.x, z: кб.z } : { x: кб.x, z: ка.z };
          проезд = скруглить([...устье(a), ка, угол, кб, ...устье(b).reverse()], R);
        }
      }

      список.push({ x0, x1, z0, z1, двор, въезды, проезд, участки: мои, мест: 0 });
    }
  }
  return { кварталы: список, участки: все };
}

/**
 * Людей — из КВАРТИР, а не из площади участков.
 *
 * Раньше население считалось по «фронт × глубина × этажей нормы»: то есть
 * по дому, которого нет. Настоящий дом на этом участке может оказаться в два
 * этажа или в четыре, уже участка на пару метров, — и тогда в памяти живёт
 * одно число жителей, а в домах помещается другое. Две правды об одном.
 * Теперь считает сам дом, а посёлок только складывает.
 */
function население(участки: readonly Участок[], вид: Вид, сид: number): number {
  let людей = 0;
  for (const у of участки) {
    if (у.что !== 'жильё') continue;
    людей += домНаУчастке({
      что: 'жильё', x: у.x, z: у.z, курс: у.курс, фронт: у.фронт,
      глубина: у.глубина, вдольX: у.вдольX, улица: у.улица, участков: 1,
      вход: { куда: 'улица' }, квартал: -1,
    }, вид, сид).жителей;
  }
  return людей;
}

/**
 * Сетка для вопроса «сколько точек не дальше R отсюда».
 *
 * Без неё ответ стоит перебора всех точек, а спрашивают его при КАЖДОМ
 * сравнении в сортировке — то есть n·log n раз за круг. Замерено: посёлок
 * в 2 км строился 2.5 минуты, и 99% времени уходило сюда. Сетка отвечает
 * тем же числом, только смотрит в девять клеток вместо всего посёлка.
 *
 * Клетка ровно радиуса: тогда всё, что ближе R, лежит в своей клетке или
 * в соседней, и «пропустили дальний дом» невыразимо.
 */
class Сетка {
  private readonly клетки = new Map<string, { x: number; z: number }[]>();
  private readonly шаг: number;

  constructor(точки: readonly { x: number; z: number }[], радиус: number) {
    this.шаг = Math.max(1, радиус);
    for (const т of точки) {
      const ключ = this.ключ(т.x, т.z);
      const было = this.клетки.get(ключ);
      if (было === undefined) this.клетки.set(ключ, [т]); else было.push(т);
    }
  }

  private ключ(x: number, z: number): string {
    return `${Math.floor(x / this.шаг)}:${Math.floor(z / this.шаг)}`;
  }

  /** Сколько точек не дальше `радиус` от места. Ответ ТОЧНЫЙ, не приблизительный. */
  сколькоРядом(x: number, z: number, радиус: number): number {
    const i = Math.floor(x / this.шаг), j = Math.floor(z / this.шаг);
    let сколько = 0;
    for (let di = -1; di <= 1; di++) {
      for (let dj = -1; dj <= 1; dj++) {
        const список = this.клетки.get(`${i + di}:${j + dj}`);
        if (список === undefined) continue;
        for (const т of список) if (Math.hypot(т.x - x, т.z - z) <= радиус) сколько++;
      }
    }
    return сколько;
  }
}

/**
 * Занять под объект столько соседних участков, сколько он требует по фронту.
 *
 * Участки теперь РАЗНОЙ ширины, поэтому «сколько штук» посчитать заранее
 * нельзя: складываются настоящие фронты, пока не наберётся нужный. Прежняя
 * редакция делила требуемый фронт на постоянную ширину участка — с вилкой
 * вместо постоянной она брала бы то вдвое меньше места, то вдвое больше.
 */
function занять(
  участки: Участок[], середина: Участок, что: Назначение, номер: number,
  /**
   * `смежность: 'по расстоянию'` — искать соседей как до 18.09: по всей
   * стороне улицы, проверяя смежность расстоянием. Заведомо сломанный
   * вариант: здание перешагивает разрыв под въезд во двор.
   */
  как: { смежность?: 'по расстоянию' } = {},
): boolean {
  const нужноФронта = РАЗМЕР[что].фронт;
  /**
   * Соседи — только из ТОГО ЖЕ СПЛОШНОГО КУСКА застройки, по возрастанию
   * расстояния. Внутри куска ближайшие к середине образуют непрерывный
   * ряд по построению, поэтому отдельная проверка смежности не нужна:
   * до 18.09 она меряла расстояние и пропускала разрыв под въезд —
   * школа в 49 метров вставала поперёк въезда во двор.
   */
  const поРасстоянию = как.смежность === 'по расстоянию';
  const соседи = участки
    .filter((у) => у.что === 'жильё' && (поРасстоянию
      ? у.улица === середина.улица && (у.вдольX
        ? Math.abs(у.z - середина.z) < 1 : Math.abs(у.x - середина.x) < 1)
      : у.кусок === середина.кусок))
    .sort((a, b) => дистанция(a, середина) - дистанция(b, середина));

  const взять: Участок[] = [];
  let набрано = 0;
  for (const у of соседи) {
    if (набрано >= нужноФронта) break;
    if (поРасстоянию && взять.length > 0
      && дистанция(у, середина) > набрано + у.фронт) break;
    взять.push(у);
    набрано += у.фронт;
  }
  if (набрано < нужноФронта) return false;
  // объект занимает все нужные участки: половины здания не бывает
  for (const у of взять) { у.что = что; у.объект = номер; }
  return true;
}

/**
 * Расставить объекты одного вида.
 *
 * **Требований два, и они разные.** Норма на тысячу жителей говорит, сколько
 * нужно МЕСТ; радиус доступности говорит, как далеко может стоять ближайший.
 * Город обязан выполнить оба, поэтому строится не «сколько по норме мест»,
 * а столько, чтобы не нарушалось ни то, ни другое. На больших площадках
 * главным оказывается радиус: мест хватает, а дойти нельзя.
 */
function расставить(
  дома: Участок[], что: Назначение, минимум: number, радиус: number,
  людей: number,
  как: { покрытие?: boolean; смежность?: 'по расстоянию' }, случайно: () => number,
  /** Откуда брать номера объектов: у объекта должен быть свой, ни с кем не общий. */
  счётчик: { следующий: number },
): void {
  if (минимум === 0) return;
  /**
   * Где стоят уже построенные — СЕРЕДИНЫ ЗДАНИЙ, а не опорные участки.
   *
   * Школа занимает четыре участка подряд, и её середина отстоит от опорного
   * участка на тридцать метров. Пока жадный обход мерил до опорного, а
   * проверка до середины, это были две разные правды об одном месте, и
   * они расходились: две школы из семи оказывались лишними.
   */
  const стоят: { x: number; z: number; номер: number }[] = [];
  /** Предел на всякий случай: город конечен, и вечный цикл тут невозможен. */
  const предел = 400;

  while (стоят.length < предел) {
    const жильё = дома.filter((у) => у.что === 'жильё');
    if (жильё.length === 0) break;

    /**
     * Заведомо сломанный вариант считает, что хватит нормы по местам, и про
     * радиус не спрашивает. Это ровно та ошибка, ради которой проверка и
     * написана: мест достаточно, а дойти нельзя.
     */
    /** До ближайшей уже построенной службы от каждого дома. Считается ОДИН раз. */
    const доСлужбы = жильё.map((дом) => ближайшее(дом, стоят));
    // далеко ли сейчас идти самому несчастному дому
    const дальше = доСлужбы.reduce((худо, d) => Math.max(худо, d), 0);
    const хватает = как.покрытие === false
      ? стоят.length >= минимум
      : стоят.length >= минимум && дальше <= радиус;
    if (хватает) break;

    const наУчасток = людей / Math.max(1, жильё.length);
    /**
     * Куда ставить. Не «где сейчас хуже всего» — так объект встаёт на самый
     * край непокрытого пятна и накрывает половину круга впустую. Ставим туда,
     * откуда НАКРОЕТСЯ БОЛЬШЕ ВСЕГО непокрытых домов: это обычная жадная
     * расстановка по покрытию, и она втрое экономнее. Первая редакция
     * строила 56 магазинов там, где хватает дюжины.
     *
     * Всё, по чему сортируем, считается ОДИН РАЗ ЗА КРУГ и кладётся рядом
     * с участком. Раньше это считалось внутри сравнения — то есть заново
     * на каждую пару, n·log n раз, — и посёлок в 2 км строился 2.5 минуты.
     * Порядок от этого не изменился ни на один участок: числа те же самые,
     * просто посчитаны раньше.
     */
    const непокрытые = жильё.filter((_, i) => доСлужбы[i] > радиус);
    const сеткаНепокрытых = new Сетка(непокрытые, радиус);
    const накроет = жильё.map((где) => сеткаНепокрытых.сколькоРядом(где.x, где.z, радиус));
    // поток мимо участка: сколько жителей живёт в радиусе доступности магазина
    const сеткаЖилья = что === 'магазин' ? new Сетка(жильё, РАДИУС.магазин) : null;
    const поток = сеткаЖилья === null ? null
      : жильё.map((где) => сеткаЖилья.сколькоРядом(где.x, где.z, РАДИУС.магазин) * наУчасток);

    const порядок = жильё.map((_, i) => i);
    const очередь = (как.покрытие === false
      ? порядок.sort(() => случайно() - 0.5)
      : порядок.sort((a, b) => {
        const разница = накроет[b] - накроет[a];
        if (разница !== 0) return разница;
        // при равном покрытии магазин выбирает поток: так решает торговля
        return поток !== null ? поток[b] - поток[a] : доСлужбы[b] - доСлужбы[a];
      })).map((i) => жильё[i]);

    let встал = false;
    for (const цель of очередь.slice(0, 40)) {
      if (занять(дома, цель, что, счётчик.следующий, как)) {
        стоят.push({ ...середина(дома, счётчик.следующий), номер: счётчик.следующий });
        счётчик.следующий++;
        встал = true;
        break;
      }
    }
    // некуда ставить — город застроен, дальше ничего не выжмешь
    if (!встал) break;
  }
}

/**
 * Убрать лишнее.
 *
 * Жадная расстановка по покрытию даёт хороший, но не наименьший набор: ранний
 * объект может оказаться целиком накрыт теми, что поставили после него.
 * Замерено проверкой «ни один объект не лишний»: на посёлке 1.2 км лишними
 * были 3 сада из 13 и 2 школы из 7. Это не мелочь — лишний сад занимает
 * жилые участки, а значит уменьшает население ни за что.
 *
 * Разбор идёт с конца к началу и снимает объект, БЕЗ КОТОРОГО НИЧЕГО НЕ
 * ЛОМАЕТСЯ: и мест хватает, и дойти можно. Участки возвращаются под жильё,
 * а вернувшиеся дома тут же начинают требовать покрытия наравне со всеми —
 * иначе мы бы снимали объект, ради которого он и стоял.
 */
/** Середина объекта: по всем его участкам, а не по опорному. */
function середина(дома: readonly Участок[], номер: number): { x: number; z: number } {
  const его = дома.filter((у) => у.объект === номер);
  if (его.length === 0) return { x: 0, z: 0 };
  return {
    x: его.reduce((s, у) => s + у.x, 0) / его.length,
    z: его.reduce((s, у) => s + у.z, 0) / его.length,
  };
}

function разобрать(
  дома: Участок[], что: Назначение, минимум: number, радиус: number,
  как: { покрытие?: boolean },
): void {
  const номера = [...new Set(дома.filter((у) => у.что === что).map((у) => у.объект))];
  const стоят = номера.map((номер) => ({ ...середина(дома, номер), номер }));

  for (let i = стоят.length - 1; i >= 0; i--) {
    if (стоят.length - 1 < минимум) break;
    const номер = стоят[i].номер;
    const его = дома.filter((у) => у.объект === номер);
    for (const у of его) { у.что = 'жильё'; у.объект = -1; }

    const остались = стоят.filter((_, k) => k !== i);
    /**
     * Снимать можно, только если после этого КАЖДЫЙ жилой дом — включая
     * те, что сейчас освободились, — по-прежнему в радиусе. Иначе мы
     * снимали бы объект, ради которого он и стоял.
     */
    const хватает = как.покрытие === false
      ? true
      : дома.filter((у) => у.что === 'жильё')
        .every((дом) => ближайшее(дом, остались) <= радиус);
    if (хватает) стоят.splice(i, 1);
    // нужен — вернуть на место вместе с его номером
    else for (const у of его) { у.что = что; у.объект = номер; }
  }
}

/** Насколько далеко до ближайшего уже поставленного. Пусто — бесконечность. */
function ближайшее(
  где: { x: number; z: number }, стоят: readonly { x: number; z: number }[],
): number {
  if (стоят.length === 0) return 1e6;
  let ближе = Infinity;
  for (const с of стоят) ближе = Math.min(ближе, дистанция(где, с));
  return ближе;
}

export function построитьПосёлок(
  сид: number, половина: number, вид: Вид = 'город',
  /**
   * Заведомо сломанные варианты: `покрытие: false` — ставить объекты куда
   * попало; `кварталы: false` — считать кварталы шагами от конца улицы.
   */
  как: {
    покрытие?: boolean; кварталы?: boolean; разбор?: boolean; въезды?: boolean;
    устье?: boolean; смежность?: 'по расстоянию';
  } = {},
): Посёлок {
  const случайно = зерно(сид);
  const сеть = улицы(половина);
  const нарезка = кварталы(сеть, половина, вид, сид, как);
  const дома = нарезка.участки;

  /**
   * Население и потребность считаются дважды: объекты обслуживания съедают
   * жилые участки, людей становится меньше, и потребность падает. Две
   * итерации сходятся — проверено на посёлках от 200 до 20 000 человек.
   */
  let людей = население(дома, вид, сид);
  const счётчик = { следующий: 0 };
  for (let подход = 0; подход < 2; подход++) {
    for (const у of дома) if (у.что !== 'жильё') { у.что = 'жильё'; у.объект = -1; }
    людей = население(дома, вид, сид);
    const нужно = сколькоНужно(людей);

    for (const что of ['школа', 'сад', 'поликлиника', 'магазин'] as const) {
      const радиус = что === 'школа' ? РАДИУС.школа
        : что === 'сад' ? РАДИУС.сад
          : что === 'магазин' ? РАДИУС.магазин : РАДИУС.поликлиника;
      расставить(дома, что, нужно[что], радиус, людей, как, случайно, счётчик);
    }
  }

  // остановки: вдоль магистральных улиц, шагом по норме
  const остановки: Остановка[] = [];
  const шагОстановок = (МЕЖДУ_ОСТАНОВКАМИ.мин + МЕЖДУ_ОСТАНОВКАМИ.макс) / 2;
  for (const улица of сеть) {
    if (улица.вид !== 'магистральная') continue;
    const вдольX = улица.a.z === улица.b.z;
    const длина = вдольX ? улица.b.x - улица.a.x : улица.b.z - улица.a.z;
    const сколько = Math.max(1, Math.round(длина / шагОстановок));
    for (let i = 0; i < сколько; i++) {
      const t = (i + 0.5) / сколько;
      остановки.push({
        x: улица.a.x + (улица.b.x - улица.a.x) * t,
        z: улица.a.z + (улица.b.z - улица.a.z) * t,
      });
    }
  }

  /**
   * РАЗБОР — общий и в самом конце, а не внутри каждой расстановки.
   *
   * Жадная расстановка даёт хороший набор, но не наименьший: ранний объект
   * может оказаться целиком накрыт поздними. Разбирать сразу после своей
   * расстановки нельзя — следующие виды заберут жилые участки под себя,
   * дома исчезнут, и объект станет лишним уже после разбора. Поэтому разбор
   * идёт последним и по всем видам сразу, дважды: снятый объект возвращает
   * участки под жильё, население растёт, и норма может снова потребовать
   * то, что только что сняли.
   *
   * `разбор: false` — заведомо сломанный вариант: не снимать ничего.
   */
  for (let круг = 0; круг < 6 && как.разбор !== false; круг++) {
    const было = дома.filter((у) => у.что !== 'жильё').length;
    const надо = сколькоНужно(население(дома, вид, сид));
    for (const что of ['школа', 'сад', 'поликлиника', 'магазин'] as const) {
      const радиус = что === 'школа' ? РАДИУС.школа
        : что === 'сад' ? РАДИУС.сад
          : что === 'магазин' ? РАДИУС.магазин : РАДИУС.поликлиника;
      разобрать(дома, что, надо[что], радиус, как);
    }
    // снятый объект возвращает участки под жильё, а это меняет и население,
    // и покрытие соседей. Значит крутим, пока что-то снимается
    if (дома.filter((у) => у.что !== 'жильё').length === было) break;
  }

  /**
   * Население считается ЗАНОВО по тому, что в итоге построено.
   *
   * Внутри круга подбора `людей` берётся, когда все участки ещё жилые, —
   * иначе не с чего считать потребность в садах и школах. Но это число
   * нельзя отдавать наружу: в нём живут люди, «поселённые» в школе и
   * магазине. Проверка «население посёлка — это сумма жителей домов»
   * нашла разницу в 1316 человек на посёлке 1.2 км.
   */
  людей = население(дома, вид, сид);

  /**
   * Объекты: что на самом деле построено. Жилой дом — один участок,
   * школа — несколько подряд, но здание ОДНО. Номер объекта у участков
   * уже проставлен, поэтому склеивать по расстоянию больше не надо.
   */
  const объекты: Объект[] = [];
  /** Чей участок: номер участка → номер квартала. */
  const кварталУчастка = new Map<number, number>();
  нарезка.кварталы.forEach((к, i) => { for (const у of к.участки) кварталУчастка.set(у, i); });
  /**
   * Вход жилого дома. Со двора — только в городе, только у квартала с двором
   * и проездом и только если хотя бы три метра фронта участка смотрят во двор.
   * Угловой участок, целиком стоящий спиной в бок соседнего крыла, входит
   * с улицы: двери во двор ему ставить некуда.
   */
  const входЖилья = (у: Участок, квартал: number): Объект['вход'] => {
    const к = нарезка.кварталы[квартал];
    if (вид !== 'город' || к === undefined || к.двор === null || к.проезд === null) return { куда: 'улица' };
    const д = к.двор;
    const x0 = д.x - д.ширина / 2, x1 = д.x + д.ширина / 2, z0 = д.z - д.глубина / 2, z1 = д.z + д.глубина / 2;
    const середина = у.вдольX ? у.x : у.z;
    const от = Math.max(у.вдольX ? x0 : z0, середина - у.фронт / 2);
    const до = Math.min(у.вдольX ? x1 : z1, середина + у.фронт / 2);
    return до - от >= 3 ? { куда: 'двор', x0, x1, z0, z1 } : { куда: 'улица' };
  };
  const жилой = дома.filter((у) => у.что === 'жильё');
  дома.forEach((у, i) => {
    if (у.что !== 'жильё') return;
    const квартал = кварталУчастка.get(i) ?? -1;
    объекты.push({
      что: 'жильё', x: у.x, z: у.z, курс: у.курс,
      фронт: у.фронт, глубина: у.глубина, вдольX: у.вдольX, улица: у.улица, участков: 1,
      вход: входЖилья(у, квартал), квартал,
    });
  });
  const поНомеру = new Map<number, Участок[]>();
  const кварталОбъекта = new Map<number, number>();
  дома.forEach((у, i) => {
    if (у.что === 'жильё' || у.объект < 0) return;
    const был = поНомеру.get(у.объект);
    if (был === undefined) поНомеру.set(у.объект, [у]); else был.push(у);
    кварталОбъекта.set(у.объект, кварталУчастка.get(i) ?? -1);
  });
  for (const [номер, группа] of поНомеру) {
    const вдольX = группа[0].вдольX;
    /**
     * Середина объекта — СЕРЕДИНА ЗАНЯТОГО ОТРЕЗКА, а не среднее серединами
     * участков, и фронт берётся оттуда же.
     *
     * Пока участки были одной ширины, среднее совпадало с серединой, и разницы
     * никто не видел. С разной шириной (17.09) они разошлись: у пары участков
     * в 10 и 30 метров среднее серединами даёт 15, а настоящая середина 20, —
     * и здание в 40 метров вылезает на пять метров за свой край. Замерено
     * 18.09: детский сад в 50 метров залез на 2.25 м в разрыв под въезд
     * во двор. Теперь и середина, и фронт выведены из одних и тех же краёв,
     * поэтому разойтись им не с чем.
     */
    const вдоль = (у: Участок): number => (вдольX ? у.x : у.z);
    const от = Math.min(...группа.map((у) => вдоль(у) - у.фронт / 2));
    const до = Math.max(...группа.map((у) => вдоль(у) + у.фронт / 2));
    const середина = (от + до) / 2;
    объекты.push({
      что: группа[0].что,
      x: вдольX ? середина : группа[0].x,
      z: вдольX ? группа[0].z : середина,
      курс: группа[0].курс,
      фронт: до - от,
      глубина: группа[0].глубина,
      вдольX,
      улица: группа[0].улица,
      участков: группа.length,
      // магазин, школа, сад, поликлиника — вход с улицы: к ним идут не жильцы двора
      вход: { куда: 'улица' },
      квартал: кварталОбъекта.get(номер) ?? -1,
    });
  }

  const есть: Record<Назначение, number> = {
    жильё: жилой.length, сад: 0, школа: 0, магазин: 0, поликлиника: 0,
  };
  for (const о of объекты) if (о.что !== 'жильё') есть[о.что]++;

  /**
   * Машиноместа во дворе — по норме хранения и по жителям СВОЕГО квартала.
   * Не «столько-то мест на двор», а столько, сколько нужно тем, кто здесь
   * живёт: машину ставят у своего дома, а не у ближайшего свободного места.
   */
  const жителейУчастка = new Map<number, number>();
  дома.forEach((у, i) => {
    if (у.что !== 'жильё') return;
    жителейУчастка.set(i, домНаУчастке({
      что: 'жильё', x: у.x, z: у.z, курс: у.курс, фронт: у.фронт,
      глубина: у.глубина, вдольX: у.вдольX, улица: у.улица, участков: 1,
      вход: { куда: 'улица' }, квартал: -1,
    }, вид, сид).жителей);
  });
  const кварталыСМестами: Квартал[] = нарезка.кварталы.map((к) => {
    const жителей = к.участки.reduce((s2, i) => s2 + (жителейУчастка.get(i) ?? 0), 0);
    return { ...к, мест: Math.round((жителей * МЕСТ_ХРАНЕНИЯ_НА_ТЫСЯЧУ) / 1000) };
  });

  return {
    сид, вид, половина, улицы: сеть, кварталы: кварталыСМестами,
    участки: дома, объекты, остановки,
    людей, нужно: сколькоНужно(людей), есть,
  };
}

/**
 * Улицы посёлка — теми же дорогами, какими их рисует рука.
 *
 * Это главное решение стыковки: генератор не заводит свой формат дорог,
 * он выдаёт ровно то, что уже умеют поверхность, трафик, знаки и светофоры.
 * Поэтому город не потребовал ни одной правки в них.
 */
export function дорогиПосёлка(посёлок: Посёлок): Road[] {
  return [
    ...посёлок.улицы.map((у) => ({
      type: roadTypeForLanes(у.полосВСторону),
      centerline: [у.a, у.b],
    })),
    ...посёлок.кварталы
      .filter((к) => к.проезд !== null)
      .map((к) => ({ type: ПРОЕЗД, centerline: к.проезд as readonly Point2[] })),
  ];
}

/**
 * Тип внутриквартального проезда.
 *
 * Строится здесь, а не в `world/road.ts`, по двум причинам. Тип дороги —
 * это ДАННЫЕ, так и написано в самом `road.ts`; и проезд во дворе —
 * принадлежность города, а не дорожной геометрии, которая заморожена.
 *
 * Шесть метров проезжей части без разметки: СП требует для проезда
 * к группе домов не менее 5.5 м. Бордюр берётся у обычной улицы, чтобы
 * высота бордюра в городе была одна на всех.
 *
 * **По краям — СТОЯНКА, и это не украшение.** Пока стоянки не было,
 * машина вставала в полосу движения, и её приходилось объезжать
 * по встречной; механизм объезда был написан, заработал и был откачен,
 * потому что приносил столкновения (решение 079). Отдельная полоса
 * в полтора раза дешевле и убивает весь класс: стоящей машине негде
 * оказаться на пути у едущей. Ширина — само машиноместо, другого
 * числа тут быть не может.
 *
 * **Тротуар у проезда УЗКИЙ, но он есть, и ноль тут ставить нельзя.**
 * В `road.ts` написано «0 — тротуара нет», но этим путём никто не ходил:
 * `roadTypeForLanes` нуля не выдаёт никогда. Проверено 17.09: с нулём
 * поверхность рвётся — на «городе» появляется под сотню точек, под
 * которыми нет земли вообще, и дом над одной из них повисает.
 * Лента нулевой ширины вырождается, и раскрой её не сшивает.
 * Починить это в `surface/` нельзя — папка заморожена, — поэтому здесь
 * стоит метр, а сама дыра записана в `STATE.md`.
 */
export const ПРОЕЗД: RoadType = {
  name: 'внутриквартальный проезд',
  lanes: [
    { kind: 'parking', width: КВАРТАЛ.место.ширина, direction: 0, rise: 0 },
    { kind: 'travel', width: КВАРТАЛ.въезд / 2, direction: -1, rise: 0 },
    { kind: 'travel', width: КВАРТАЛ.въезд / 2, direction: 1, rise: 0 },
    { kind: 'parking', width: КВАРТАЛ.место.ширина, direction: 0, rise: 0 },
  ],
  sidewalk: 1,
  curb: roadTypeForLanes(1).curb,
};

/**
 * Насколько широк разрыв в застройке под въезд.
 *
 * Не отдельное число, а ШИРИНА САМОГО ПРОЕЗДА вместе с тротуарами:
 * «разрыв уже дороги, которая в него проходит» этим записать негде.
 */
const ШИРИНА_ВЪЕЗДА = roadWidth(ПРОЕЗД) + 2 * ПРОЕЗД.sidewalk;

/**
 * Насколько узким двор быть не может.
 *
 * Не число из норм, а МАКСИМУМ из двух причин, и обе настоящие: норма
 * по инсоляции (6 м от окон до соседней стены, то есть 12 на двор)
 * и то, что в этот двор должен пройти сам проезд со стоянками.
 * Пока это было одним числом 12, а проезд подрос до тринадцати,
 * «двор, в который не влезает собственный проезд» записывался молча.
 */
const МИНИМАЛЬНЫЙ_ДВОР = Math.max(КВАРТАЛ.минимальныйДвор, ШИРИНА_ВЪЕЗДА);

/** Сколько мест даёт то, что построено. Для проверки норм. */
export function мест(посёлок: Посёлок, что: 'сад' | 'школа' | 'магазин'): number {
  return посёлок.есть[что] * ВМЕСТИМОСТЬ[что];
}
