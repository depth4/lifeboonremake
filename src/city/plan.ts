/**
 * Этажность дома по его МЕСТУ, а не по порядку в списке.
 *
 * Считается из координат: дом на своём месте всегда получает ту же высоту,
 * сколько бы раз его ни пересчитывали и в каком бы порядке ни строили
 * участки. Порядок обхода на вид города не влияет — этого и добиваемся.
 */
function этажность(сид: number, x: number, z: number, от: number, до: number): number {
  let h = (сид ^ 0x27d4eb2f) >>> 0;
  h = Math.imul(h ^ Math.round(x * 8), 0x9e3779b1) >>> 0;
  h = Math.imul(h ^ Math.round(z * 8), 0x85ebca6b) >>> 0;
  h = (h ^ (h >>> 15)) >>> 0;
  return от + (h % (до - от + 1));
}

/** Одно и то же зерно даёт один и тот же посёлок. Всегда. */
function зерно(сид: number): () => number {
  let s = (сид ^ 0x9e3779b9) >>> 0;
  return () => {
    s = (Math.imul(s ^ (s >>> 15), 0x2c1b3c6d) + 0x9e3779b9) >>> 0;
    return ((s ^ (s >>> 16)) >>> 0) / 4294967296;
  };
}

const дистанция = (a: { x: number; z: number }, b: { x: number; z: number }): number =>
  Math.hypot(a.x - b.x, a.z - b.z);

/**
 * Сетка улиц: магистральные реже, местные чаще. Обе — по нормам шага.
 *
 * Возвращает и линии сетки: из них строятся кварталы. Одна и та же линия
 * знает свою улицу вдоль X и вдоль Z, поэтому «квартал, у которого сосед
 * не та улица» записать нельзя.
 */
interface Линия {
  readonly c: number;
  readonly отступ: number;
  /** Индексы в списке улиц: улица вдоль X на z = c и улица вдоль Z на x = c. */
  readonly вдольX: number;
  readonly вдольZ: number;
}

function сетка(половина: number): { улицы: Улица[]; линии: Линия[] } {
  const улицы: Улица[] = [];
  const линии: Линия[] = [];
  const шаг = УЛИЦА.местная.шаг;

  for (let c = -Math.floor(половина / шаг) * шаг; c <= половина; c += шаг) {
    // магистральная там, где сетка совпадает с её шагом; остальные местные
    const главная = Math.abs(c % УЛИЦА.магистральная.шаг) < 1e-6;
    const вид = главная ? 'магистральная' : 'местная';
    const правила = главная ? УЛИЦА.магистральная : УЛИЦА.местная;
    const отступ = правила.красная / 2;
    const вдольX = улицы.length;
    улицы.push({
      a: { x: -половина, z: c }, b: { x: половина, z: c },
      вид, полосВСторону: правила.полосВСторону, отступ,
    });
    const вдольZ = улицы.length;
    улицы.push({
      a: { x: c, z: -половина }, b: { x: c, z: половина },
      вид, полосВСторону: правила.полосВСторону, отступ,
    });
    линии.push({ c, отступ, вдольX, вдольZ });
  }
  return { улицы, линии };
}

/** Кварталы: то, что осталось между красными линиями соседних улиц. */
function кварталы(линии: readonly Линия[]): Квартал[] {
  const из: Квартал[] = [];
  for (let i = 0; i + 1 < линии.length; i++) {
    for (let j = 0; j + 1 < линии.length; j++) {
      из.push({
        x0: линии[j].c + линии[j].отступ,
        x1: линии[j + 1].c - линии[j + 1].отступ,
        z0: линии[i].c + линии[i].отступ,
        z1: линии[i + 1].c - линии[i + 1].отступ,
        север: линии[i].вдольX,
        юг: линии[i + 1].вдольX,
        запад: линии[j].вдольZ,
        восток: линии[j + 1].вдольZ,
      });
    }
  }
  return из;
}

/**
 * Участки: кусок ПЕРИМЕТРА квартала, а не отрезок вдоль улицы.
 *
 * Из-за этого исчезают сразу три беды прежнего устройства:
 *
 * - **наложение участков двух улиц** — делить нечего, периметр делится один
 *   раз. Раньше это ловилось пустым углом в 46 м и проверкой на 900 наложений;
 * - **дыра в уличном фронте** — сторона делится НАЦЕЛО: фронт участка равен
 *   длине стороны, делённой на число участков. Остатка, из которого получалась
 *   дыра, просто нет;
 * - **двор уже бытового разрыва** — глубина участка ужимается так, чтобы между
 *   спинами двух рядов осталось не меньше 15 м (СП 42.13330 п. 7.1).
 */
function участки(кварталы: readonly Квартал[], вид: Вид, сид: number): Участок[] {
  const из: Участок[] = [];
  const ФРОНТ = ЗАСТРОЙКА[вид].фронт;
  const ГЛУБИНА = ЗАСТРОЙКА[вид].глубинаУчастка;
  /** Мельче этого участок не участок: дом туда не встанет. */
  const МИН_ГЛУБИНА = 12;

  кварталы.forEach((к, номер) => {
    const ширина = к.x1 - к.x0;
    const высота = к.z1 - к.z0;
    // двор между спинами двух рядов — не меньше бытового разрыва
    const Гx = Math.min(ГЛУБИНА, (ширина - РАЗРЫВ.до3этажей) / 2);
    const Гz = Math.min(ГЛУБИНА, (высота - РАЗРЫВ.до3этажей) / 2);
    if (Гx < МИН_ГЛУБИНА || Гz < МИН_ГЛУБИНА) return;

    /**
     * Одна сторона периметра. `вдоль` — по какой оси идёт фронт, `наружу` —
     * куда смотрит фасад. Углы по вертушке: сторона забирает угол, с которого
     * начинается, и не доходит на глубину соседней стороны до следующего.
     */
    const сторона = (
      от: number, до: number, поперёк: number, глубина: number,
      нx: number, нz: number, улица: number, вдольX: boolean,
    ): void => {
      const длина = до - от;
      const сколько = Math.floor(длина / ФРОНТ);
      if (сколько < 1) return;
      const фронт = длина / сколько;
      const предел = ЗАСТРОЙКА[вид].этажей;
      for (let i = 0; i < сколько; i++) {
        const вдоль = от + фронт * (i + 0.5);
        // внутрь квартала — это «против наружу» по той оси, где наружу не ноль
        const внутрь = -(нx !== 0 ? нx : нz);
        const центр = поперёк + внутрь * глубина / 2;
        из.push({
          x: вдольX ? вдоль : центр,
          z: вдольX ? центр : вдоль,
          фронт, глубина,
          нx, нz, улица, вдольX, квартал: номер,
          этажей: этажность(сид, вдольX ? вдоль : центр, вдольX ? центр : вдоль,
            предел.от, предел.до),
          что: 'жильё',
        });
      }
    };

    // север: фасады смотрят в −z; восток: в +x; юг: в +z; запад: в −x
    сторона(к.x0, к.x1 - Гx, к.z0, Гz, 0, -1, к.север, true);
    сторона(к.z0, к.z1 - Гz, к.x1, Гx, 1, 0, к.восток, false);
    сторона(к.x0 + Гx, к.x1, к.z1, Гz, 0, 1, к.юг, true);
    сторона(к.z0 + Гz, к.z1, к.x0, Гx, -1, 0, к.запад, false);
  });
  return из;
}

/**
 * Сколько человек помещается в доме. Одна формула на весь проект.
 *
 * Полезная площадь квартир — около трёх четвертей площади этажей, дальше
 * жилищная обеспеченность из норм. Людей нигде не НАЗНАЧАЮТ: они получаются
 * из дома, а дом — из участка.
 */
export function сколькоЖивёт(фронт: number, глубина: number, этажей: number): number {
  return Math.round((фронт * глубина * этажей * 0.75) / МЕТРОВ_НА_ЧЕЛОВЕКА);
}

/**
 * Людей — сумма по жилым участкам, ТОЙ ЖЕ формулой, что и по домам.
 *
 * Одна формула, а не две: пока их было две, «сколько людей в посёлке»
 * и «сколько людей в доме» отвечали по-разному, и разница была не в округлении,
 * а в шести тысячах человек.
 */
function население(участки: readonly Участок[], вид: Вид): number {
  const дом = ЗАСТРОЙКА[вид];
  let людей = 0;
  for (const у of участки) {
    if (у.что !== 'жильё') continue;
    людей += сколькоЖивёт(дом.фронтДома ?? (у.фронт - ШОВ), дом.глубинаДома, у.этажей);
  }
  return людей;
}

/**
 * Занять под объект столько соседних участков, сколько он требует по фронту.
 *
 * Берутся соседи по ОДНОЙ стороне одного квартала: объект, разорванный
 * перекрёстком, здесь записать нельзя. Набираем, пока набранного фронта
 * хватает под норму размера, — половины здания не бывает.
 */
function занять(
  участки: Участок[], середина: Участок, что: Назначение, объекты: Объект[],
): boolean {
  const надо = РАЗМЕР[что].фронт;
  const свои = участки
    .filter((у) => у.улица === середина.улица && у.квартал === середина.квартал
      && у.что === 'жильё')
    .sort((a, b) => дистанция(a, середина) - дистанция(b, середина));

  const взято: Участок[] = [];
  let фронт = 0;
  for (const у of свои) {
    взято.push(у);
    фронт += у.фронт;
    if (фронт >= надо) break;
  }
  if (фронт < надо) return false;

  for (const у of взято) у.что = что;
  объекты.push(пятно(взято, что));
  return true;
}

/** Пятно застройки: что получилось из набранных участков. */
function пятно(взято: readonly Участок[], что: Назначение): Объект {
  const первый = взято[0];
  const вдоль = (у: Участок): number => (первый.вдольX ? у.x : у.z);
  const края = взято.map(вдоль);
  const от = Math.min(...края) - первый.фронт / 2;
  const до = Math.max(...края) + первый.фронт / 2;
  const серединаВдоль = (от + до) / 2;
  const поперёк = первый.вдольX ? первый.z : первый.x;
  // здание не шире того, что требует норма: остаток пятна — двор и подъезды
  const фронт = Math.min(до - от, РАЗМЕР[что].фронт) || (до - от);
  const глубина = Math.min(РАЗМЕР[что].глубина, первый.глубина);
  return {
    что, жителей: 0,
    x: первый.вдольX ? серединаВдоль : поперёк,
    z: первый.вдольX ? поперёк : серединаВдоль,
    фронт, глубина,
    нx: первый.нx, нz: первый.нz,
    улица: первый.улица, квартал: первый.квартал,
    участокГлубина: первый.глубина,
    этажей: РАЗМЕР[что].этажей,
  };
}

/**
 * Расставить объекты одного вида.
 *
 * **Требований два, и они разные.** Норма на тысячу жителей говорит, сколько
 * нужно МЕСТ; радиус доступности говорит, как далеко может стоять ближайший.
 * Город обязан выполнить оба, поэтому строится не «сколько по норме мест»,
 * а столько, чтобы не нарушалось ни то, ни другое. На больших площадках
 * главным оказывается радиус: мест хватает, а дойти нельзя.
 */
function расставить(
  дома: Участок[], что: Назначение, минимум: number, радиус: number,
  людей: number, объекты: Объект[],
  как: { покрытие?: boolean }, случайно: () => number,
  /** Где такому объекту вообще место. Супермаркет — только на магистральной. */
  годится: (у: Участок) => boolean = () => true,
): number {
  if (минимум === 0) return 0;
  const стоят: Участок[] = [];
  /** Предел на всякий случай: город конечен, и вечный цикл тут невозможен. */
  const предел = 400;

  while (стоят.length < предел) {
    const жильё = дома.filter((у) => у.что === 'жильё');
    if (жильё.length === 0) break;
    const можно = жильё.filter(годится);
    if (можно.length === 0) break;

    // далеко ли сейчас идти самому несчастному дому
    let дальше = 0;
    for (const дом of жильё) {
      let ближе = Infinity;
      for (const с of стоят) ближе = Math.min(ближе, дистанция(дом, с));
      дальше = Math.max(дальше, ближе === Infinity ? Infinity : ближе);
    }
    /**
     * Заведомо сломанный вариант считает, что хватит нормы по местам, и про
     * радиус не спрашивает. Это ровно та ошибка, ради которой проверка и
     * написана: мест достаточно, а дойти нельзя.
     */
    const хватает = как.покрытие === false
      ? стоят.length >= минимум
      : стоят.length >= минимум && дальше <= радиус;
    if (хватает) break;

    const наУчасток = людей / Math.max(1, жильё.length);
    /**
     * Куда ставить. Не «где сейчас хуже всего» — так объект встаёт на самый
     * край непокрытого пятна и накрывает половину круга впустую. Ставим туда,
     * откуда НАКРОЕТСЯ БОЛЬШЕ ВСЕГО непокрытых домов: это обычная жадная
     * расстановка по покрытию, и она втрое экономнее. Первая редакция
     * строила 56 магазинов там, где хватает дюжины.
     *
     * Покрытие и поток считаются ОДИН раз на круг, а не внутри сравнения:
     * внутри сравнения то же самое считалось по сорок раз на каждый участок,
     * и расстановка посёлка занимала 28 секунд вместо трёх.
     */
    const непокрытые = жильё.filter((дом) => ближайшее(дом, стоят) > радиус);
    const накроет = new Map<Участок, number>();
    const вес = new Map<Участок, number>();
    for (const где of можно) {
      let сколько = 0;
      let людно = 0;
      for (const дом of непокрытые) if (дистанция(где, дом) <= радиус) сколько++;
      накроет.set(где, сколько);
      if (что === 'магазин') {
        for (const дом of жильё) if (дистанция(где, дом) <= РАДИУС.магазин) людно += наУчасток;
        вес.set(где, людно);
      } else {
        вес.set(где, ближайшее(где, стоят));
      }
    }
    const очередь = как.покрытие === false
      ? [...можно].sort(() => случайно() - 0.5)
      : [...можно].sort((a, b) => {
        const разница = (накроет.get(b) ?? 0) - (накроет.get(a) ?? 0);
        if (разница !== 0) return разница;
        // при равном покрытии магазин выбирает поток: так решает торговля
        return (вес.get(b) ?? 0) - (вес.get(a) ?? 0);
      });

    let встал = false;
    for (const цель of очередь.slice(0, 40)) {
      if (занять(дома, цель, что, объекты)) { стоят.push(цель); встал = true; break; }
    }
    // некуда ставить — город застроен, дальше ничего не выжмешь
    if (!встал) break;
  }
  return стоят.length;
}

/**
 * Убрать лишнее: объект, без которого покрытие не ломается, не нужен.
 *
 * Жадная расстановка ставит по одному «где накроется больше всего», и почти
 * всегда среди поставленных заводится один-два лишних: то, что они покрывали,
 * к концу уже покрыто соседями. Раньше такие оставались стоять, и рядом
 * оказывались два магазина в двухстах метрах.
 *
 * Убирается ТОЛЬКО то, без чего и покрытие держится, и минимум по числу
 * соблюдён. Поэтому «убрали нужный» невыразимо: условие проверяется до
 * снятия, а не после.
 */
function подчистить(
  дома: Участок[], объекты: Объект[], что: Назначение, радиус: number, минимум: number,
): void {
  const свои = (): Объект[] => объекты.filter((о) => о.что === что);
  let менялось = true;
  while (менялось) {
    менялось = false;
    const список = свои();
    if (список.length <= минимум) break;
    for (const кандидат of список) {
      const без = список.filter((о) => о !== кандидат);
      const жильё = дома.filter((у) => у.что === 'жильё');
      const держится = жильё.every((дом) => без.some((о) => дистанция(дом, о) <= радиус));
      if (!держится) continue;
      // участки лишнего объекта возвращаются жилью, и людей снова становится больше
      for (const у of дома) {
        if (у.что === что && дистанция(у, кандидат) <= кандидат.фронт) у.что = 'жильё';
      }
      объекты.splice(объекты.indexOf(кандидат), 1);
      менялось = true;
      break;
    }
  }
}

/**
 * Хватает ли построенного тем, кто в посёлке остался.
 *
 * Это и есть условие выхода из подбора: не «прошло два круга», а «норма
 * выполнена для настоящего населения». Проверяются те же три нормы, что
 * потом спрашивает `npm run plan`, — и спрашиваются они здесь ПО ТОЙ ЖЕ
 * формуле: если бы формул было две, генератор и проверка разошлись бы.
 */
function хватает(людей: number, объекты: readonly Объект[]): boolean {
  const штук = (что: Назначение): number => объекты.filter((о) => о.что === что).length;
  const мест = (на1000: number): number => Math.ceil((людей * на1000) / 1000);
  if (штук('сад') * ВМЕСТИМОСТЬ.сад < мест(НА_ТЫСЯЧУ.местВСаду)) return false;
  if (штук('школа') * ВМЕСТИМОСТЬ.школа < мест(НА_ТЫСЯЧУ.местВШколе)) return false;
  const торговля = штук('магазин') * ВМЕСТИМОСТЬ.магазин
    + штук('супермаркет') * ВМЕСТИМОСТЬ.супермаркет;
  return торговля >= надоТорговли(людей);
}

/** Насколько далеко до ближайшего уже поставленного. Пусто — бесконечность. */
function ближайшее(где: Участок, стоят: readonly Участок[]): number {
  if (стоят.length === 0) return 1e6;
  let ближе = Infinity;
  for (const с of стоят) ближе = Math.min(ближе, дистанция(где, с));
  return ближе;
}

export function построитьПосёлок(
  сид: number, половина: number, вид: Вид = 'город',
  /** `покрытие: false` — ставить объекты куда попало. Заведомо сломанный вариант. */
  как: { покрытие?: boolean } = {},
): Посёлок {
  const случайно = зерно(сид);
  const { улицы: сеть, линии } = сетка(половина);
  const кварталыПосёлка = кварталы(линии);
  const дома = участки(кварталыПосёлка, вид, сид);
  let объекты: Объект[] = [];

  /**
   * Сколько строить — зависит от того, сколько людей; сколько людей —
   * зависит от того, сколько построили. Это неподвижная точка, и решается
   * она повторением, а не «двумя проходами на всякий случай».
   *
   * **Что было не так.** Проходов было ровно два, и каждый начинался со
   * сброса участков в жильё и пересчёта населения ПО НИМ — то есть снова
   * получал число «если бы весь посёлок был жилым». Посёлок на 1152 участка
   * строился под 35 612 человек, а жило в нём 29 871: садов и школ выходило
   * на четверть больше нормы. Цифра врала и выглядела правдой, потому что
   * норма сходилась сама с собой.
   *
   * **Критерий выхода теперь настоящий:** цикл кончается, когда построенного
   * ХВАТАЕТ ТЕМ, КТО ОСТАЛСЯ. Не хватает — строим под новое число и повторяем.
   * Больше построек — меньше жилья — меньше потребность, поэтому это сходится;
   * предел стоит от бесконечного цикла, а не вместо условия.
   */
  const ПРОХОДОВ = 8;
  let людей = население(дома, вид);
  for (let подход = 0; подход < ПРОХОДОВ; подход++) {
    for (const у of дома) if (у.что !== 'жильё') у.что = 'жильё';
    объекты = [];
    const нужно = сколькоНужно(людей);

    for (const что of ['школа', 'сад', 'поликлиника', 'магазин'] as const) {
      const радиус = что === 'школа' ? РАДИУС.школа
        : что === 'сад' ? РАДИУС.сад
          : что === 'магазин' ? РАДИУС.магазин : РАДИУС.поликлиника;
      расставить(дома, что, нужно[что], радиус, людей, объекты, как, случайно);
      // заведомо сломанный вариант не подчищает: ему и покрытие не нужно
      if (как.покрытие !== false) подчистить(дома, объекты, что, радиус, нужно[что]);
    }
    /**
     * Супермаркет — последним и по другому правилу. Он не покрывает шаговую
     * доступность (её уже закрыли магазины у дома), а добирает норму по
     * торговой площади и стоит ТОЛЬКО на магистральной улице: так это и
     * происходит в жизни — поток, подъезд, парковка.
     */
    const магазинов = объекты.filter((о) => о.что === 'магазин').length;
    расставить(
      дома, 'супермаркет', сколькоСупермаркетов(людей, магазинов),
      РАДИУС_СУПЕРМАРКЕТА, людей, объекты, как, случайно,
      (у) => сеть[у.улица].вид === 'магистральная',
    );

    /**
     * Подчистка ещё раз, и уже по ОКОНЧАТЕЛЬНОМУ жилью.
     *
     * Первая подчистка идёт сразу после своего вида и видит жильё, которого
     * позже не станет: супермаркет съедает участки последним. Дом, ради
     * которого стоял крайний магазин, к этому моменту может перестать быть
     * домом — и магазин оказывается лишним. Поэтому проход повторяется, когда
     * все объекты уже на местах.
     */
    if (как.покрытие !== false) {
      /**
       * Минимум для подчистки берётся от ТЕПЕРЕШНЕГО населения, а не от того,
       * под которое строили. Строили под прикидку, она заведомо больше; если
       * чистить по ней, лишние объекты остаются стоять — проверка «лишних
       * объектов нет» ловила ровно это, две школы подряд.
       */
      const поФакту = сколькоНужно(население(дома, вид));
      for (const что of ['школа', 'сад', 'магазин'] as const) {
        const радиус = что === 'школа' ? РАДИУС.школа
          : что === 'сад' ? РАДИУС.сад : РАДИУС.магазин;
        подчистить(дома, объекты, что, радиус, поФакту[что]);
      }
    }

    const стало = население(дома, вид);
    // заведомо сломанному варианту сходиться незачем: он и строит куда попало
    if (как.покрытие === false) { людей = стало; break; }
    if (хватает(стало, объекты)) { людей = стало; break; }
    // не хватает — значит людей оказалось больше, чем закладывали: повторяем
    людей = Math.max(людей + 1, стало);
  }

  /**
   * Жилой дом — тоже объект, просто на одном участке. После этой строки
   * «здание» в посёлке ровно одно понятие: список `объекты`. Дом, которого
   * нет в списке, невыразим — рисовать больше нечего.
   */
  for (const у of дома) {
    if (у.что !== 'жильё') continue;
    объекты.push({
      что: 'жильё',
      x: у.x, z: у.z,
      // в городе дом занимает фронт участка (минус шов), в деревне — свою
      // ширину: усадьба это дом ПЛЮС палисадник, въезд и огород
      фронт: ЗАСТРОЙКА[вид].фронтДома ?? (у.фронт - ШОВ),
      глубина: Math.min(ЗАСТРОЙКА[вид].глубинаДома, у.глубина - ЗАСТРОЙКА[вид].отступДома),
      нx: у.нx, нz: у.нz,
      улица: у.улица, квартал: у.квартал,
      участокГлубина: у.глубина,
      этажей: у.этажей,
      жителей: сколькоЖивёт(
        ЗАСТРОЙКА[вид].фронтДома ?? (у.фронт - ШОВ),
        ЗАСТРОЙКА[вид].глубинаДома, у.этажей,
      ),
    });
  }

  // остановки: вдоль магистральных улиц, шагом по норме
  const остановки: Остановка[] = [];
  const шагОстановок = (МЕЖДУ_ОСТАНОВКАМИ.мин + МЕЖДУ_ОСТАНОВКАМИ.макс) / 2;
  for (const улица of сеть) {
    if (улица.вид !== 'магистральная') continue;
    const вдольX = улица.a.z === улица.b.z;
    const длина = вдольX ? улица.b.x - улица.a.x : улица.b.z - улица.a.z;
    const сколько = Math.max(1, Math.round(длина / шагОстановок));
    for (let i = 0; i < сколько; i++) {
      const t = (i + 0.5) / сколько;
      остановки.push({
        x: улица.a.x + (улица.b.x - улица.a.x) * t,
        z: улица.a.z + (улица.b.z - улица.a.z) * t,
      });
    }
  }

  /** Считается по списку зданий, а не по участкам: здание — одно, участков много. */
  const есть: Record<Назначение, number> = {
    жильё: 0, сад: 0, школа: 0, магазин: 0, супермаркет: 0, поликлиника: 0,
  };
  for (const о of объекты) есть[о.что]++;

  /**
   * Окончательное население — СУММА ПО ДОМАМ, а не прикидка по участкам.
   * Прикидка нужна была раньше, чтобы решить, сколько строить школ; теперь
   * дома есть, и правда живёт в них. Двух чисел «сколько людей» не остаётся.
   */
  const вДомах = объекты.reduce((s, о) => s + о.жителей, 0);

  return {
    сид, половина, улицы: сеть, кварталы: кварталыПосёлка, участки: дома, объекты, остановки,
    людей: вДомах, нужно: сколькоНужно(вДомах), есть,
  };
}

/**
 * Улицы посёлка — теми же дорогами, какими их рисует рука.
 *
 * Это главное решение стыковки: генератор не заводит свой формат дорог,
 * он выдаёт ровно то, что уже умеют поверхность, трафик, знаки и светофоры.
 * Поэтому город не потребовал ни одной правки в них.
 */
export function дорогиПосёлка(посёлок: Посёлок): Road[] {
  return посёлок.улицы.map((у) => ({
    type: roadTypeForLanes(у.полосВСторону),
    centerline: [у.a, у.b],
  }));
}

/** Сколько мест даёт то, что построено. Для проверки норм. */
export function мест(посёлок: Посёлок, что: 'сад' | 'школа' | 'магазин'): number {
  return посёлок.есть[что] * ВМЕСТИМОСТЬ[что];
}

/**
 * Кусок посёлка — то, что влезает на плиту мира.
 *
 * **Это не отдельный маленький посёлок, а окно в большой.** Разница
 * принципиальная: посёлок на 220 метров — это один перекрёсток, в котором
 * норма не может разместить ни школу, ни магазин, и получается не город,
 * а огрызок. Посёлок считается в полный рост, со всеми радиусами и нормами,
 * а на плиту вырезается окно вокруг интересного места.
 *
 * Своей правды у куска нет: улицы, здания и остановки — те же самые объекты,
 * только сдвинутые в координаты окна. Поэтому «в куске магазин есть, а в
 * посёлке его нет» невыразимо.
 */
export interface Кусок {
  readonly посёлок: Посёлок;
  readonly центр: Point2;
  readonly полуразмер: number;
  readonly улицы: readonly Улица[];
  /** Кварталы окна: двор — это середина квартала, без него его негде найти. */
  readonly кварталы: readonly Квартал[];
  readonly объекты: readonly Объект[];
  readonly остановки: readonly Остановка[];
}

/**
 * Где резать окно: СЕРЕДИНА квартала, в котором стоит магазин.
 *
 * Не середина посёлка — там может не оказаться ничего, кроме жилья, и кусок
 * снова выйдет безликим. И не перекрёсток: окно вокруг перекрёстка ловит
 * только четыре угла соседних кварталов, дальние стороны улиц остаются
 * пустыми, и получается четыре обрубка вместо улицы.
 *
 * Середина квартала при окне 220 м и квартале 150 м даёт ровно то, что нужно:
 * свой квартал целиком, четыре улицы вокруг него и ближние ряды четырёх
 * соседей — то есть улицу, застроенную с ОБЕИХ сторон, и четыре перекрёстка
 * по углам. Магазин при этом в кадре по построению.
 */
export function интересноеМесто(посёлок: Посёлок): Point2 {
  const магазин = посёлок.объекты.find((о) => о.что === 'магазин')
    ?? посёлок.объекты.find((о) => о.что === 'супермаркет')
    ?? посёлок.объекты[0];
  if (!магазин) return { x: 0, z: 0 };
  const к = посёлок.кварталы[магазин.квартал];
  return { x: (к.x0 + к.x1) / 2, z: (к.z0 + к.z1) / 2 };
}

/**
 * Вырезать окно вокруг точки. Всё возвращается в координатах окна.
 *
 * **Номера улиц ПЕРЕСЧИТЫВАЮТСЯ.** Здание помнит свою улицу номером, а список
 * улиц в окне другой — короче. Пока номер оставался прежним, «улица дома»
 * указывала в чужой список: проверка камеры на первом же запуске получила
 * `undefined`. Теперь номер переводится вместе со списком, а здание, чья
 * улица в окно не попала, в окно не попадает тоже — здания без своей улицы
 * здесь нет.
 */
export function вырезать(посёлок: Посёлок, центр: Point2, полуразмер: number): Кусок {
  const R = полуразмер;
  const улицы: Улица[] = [];
  /** Из номера в посёлке — в номер в окне. Нет в карте — улица не попала. */
  const перевод = new Map<number, number>();
  посёлок.улицы.forEach((у, номер) => {
    const вдольX = у.a.z === у.b.z;
    const поперёк = (вдольX ? у.a.z : у.a.x) - (вдольX ? центр.z : центр.x);
    if (Math.abs(поперёк) > R) return;
    const от = Math.max(вдольX ? у.a.x : у.a.z, (вдольX ? центр.x : центр.z) - R);
    const до = Math.min(вдольX ? у.b.x : у.b.z, (вдольX ? центр.x : центр.z) + R);
    if (до - от < 1) return;
    const сдвиг = вдольX ? центр.x : центр.z;
    перевод.set(номер, улицы.length);
    улицы.push({
      ...у,
      a: вдольX ? { x: от - сдвиг, z: поперёк } : { x: поперёк, z: от - сдвиг },
      b: вдольX ? { x: до - сдвиг, z: поперёк } : { x: поперёк, z: до - сдвиг },
    });
  });
  /** Здание попадает в окно, если его СЕРЕДИНА внутри: половинок домов не бывает. */
  const внутри = (x: number, z: number): boolean =>
    Math.abs(x - центр.x) <= R && Math.abs(z - центр.z) <= R;
  /** Кварталы окна: те, чья середина внутри. Номера тоже переводятся. */
  const кварталы: Квартал[] = [];
  const кварталПеревод = new Map<number, number>();
  посёлок.кварталы.forEach((к, номер) => {
    const сx = (к.x0 + к.x1) / 2, сz = (к.z0 + к.z1) / 2;
    if (Math.abs(сx - центр.x) > R + 40 || Math.abs(сz - центр.z) > R + 40) return;
    кварталПеревод.set(номер, кварталы.length);
    кварталы.push({
      ...к,
      x0: к.x0 - центр.x, x1: к.x1 - центр.x,
      z0: к.z0 - центр.z, z1: к.z1 - центр.z,
      север: перевод.get(к.север) ?? -1, юг: перевод.get(к.юг) ?? -1,
      запад: перевод.get(к.запад) ?? -1, восток: перевод.get(к.восток) ?? -1,
    });
  });
  const объекты = посёлок.объекты
    .filter((о) => внутри(о.x, о.z) && перевод.has(о.улица))
    .map((о) => ({
      ...о, x: о.x - центр.x, z: о.z - центр.z,
      улица: перевод.get(о.улица) as number,
      квартал: кварталПеревод.get(о.квартал) ?? -1,
    }));
  const остановки = посёлок.остановки
    .filter((о) => внутри(о.x, о.z))
    .map((о) => ({ x: о.x - центр.x, z: о.z - центр.z }));
  return { посёлок, центр, полуразмер: R, улицы, кварталы, объекты, остановки };
}

/** Улицы куска — теми же дорогами, какими их рисует рука. */
export function дорогиКуска(кусок: Кусок): Road[] {
  return кусок.улицы.map((у) => ({
    type: roadTypeForLanes(у.полосВСторону),
    centerline: [у.a, у.b],
  }));
}
