/**
 * Жизнь города: кто сейчас едет и кто стоит у своего подъезда.
 *
 * Зачем отдельный файл. `житель.ts` знает, кто человек и где он должен быть,
 * но про дороги не знает ничего. `traffic.ts` знает дороги и правила, но про
 * жителей ничего. Связь между ними — третье дело, и класть его в любой
 * из двух значило бы смешать «кто живёт в городе» с «как ездят машины».
 *
 * ЧТО ЭТО МЕНЯЕТ. Раньше трафик рождался числом: «поставь восемнадцать машин
 * куда попало». Теперь машина существует потому, что её хозяину надо ехать,
 * и стоит потому, что хозяин внутри. «Машина на парковке просто так»
 * записать негде: у неё некуда девать хозяина.
 *
 * Про экран этот файл не знает ничего.
 */

