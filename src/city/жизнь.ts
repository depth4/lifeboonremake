/**
 * Жизнь города: кто сейчас едет и кто стоит у своего подъезда.
 *
 * Зачем отдельный файл. `житель.ts` знает, кто человек и где он должен быть,
 * но про дороги не знает ничего. `traffic.ts` знает дороги и правила, но про
 * жителей ничего. Связь между ними — третье дело, и класть его в любой
 * из двух значило бы смешать «кто живёт в городе» с «как ездят машины».
 *
 * ЧТО ЭТО МЕНЯЕТ. Раньше трафик рождался числом: «поставь восемнадцать машин
 * куда попало». Теперь машина существует потому, что её хозяину надо ехать,
 * и стоит потому, что хозяин внутри. «Машина на парковке просто так»
 * записать негде: у неё некуда девать хозяина.
 *
 * Про экран этот файл не знает ничего.
 */

import type { World } from '../world/world.ts';
import { COLOURS, CRUISE, type Mover, type Network, along, locate, retune } from './traffic.ts';
import { laneAcross, laneCount } from './lanes.ts';
import type { Посёлок } from './plan.ts';
import { домНаУчастке } from './дом.ts';
import { type Житель, type Расселение, где, кто } from './житель.ts';
import { type Маршрут, путь } from './путь.ts';

/** Сколько часов занимает дорога через город. Позже придёт из маршрута. */
export const В_ПУТИ = 0.4;

/** Куда смотрит здание на дороге: его место в дорожной сети. */
interface УЗдания {
  readonly shape: number;
  readonly s: number;
  readonly across: number;
}

/** Где дом выходит на дорогу. Спрашивается у сети, а не хранится в доме. */
function уДома(world: World, посёлок: Посёлок, объект: number): УЗдания | null {
  const о = посёлок.объекты[объект];
  if (о === undefined) return null;
  const дом = домНаУчастке(о, посёлок.вид, посёлок.сид);
  // подъезд, а не середина дома: машина встаёт у входа
  const cos = Math.cos(дом.курс), sin = Math.sin(дом.курс);
  const п = дом.двери[0];
  const x = дом.x + (дом.глубина / 2) * cos - п.вдоль * sin;
  const z = дом.z + (дом.глубина / 2) * sin + п.вдоль * cos;
  const на = locate(world, x, z);
  return на === null ? null : { shape: на.shape, s: на.s, across: на.across };
}

export interface Поток {
  readonly машины: Mover[];
  /** Кого не удалось поставить: мест у бордюра меньше, чем машин. */
  readonly безМеста: number;
}

/**
 * Машины жителей на этот час.
 *
 * Тот, кто в пути и за рулём, — едет: он поставлен на дорогу у своего дома
 * и направлен дальше. Тот, кто дома или на месте и за рулём, — стоит
 * в кармане у того здания, где он сейчас, до часа своего выхода.
 *
 * Мест у бордюра меньше, чем машин, и это не ошибка, а правда: кому места
 * не хватило, того на улице просто нет — он во дворе, которого мы не строим.
 */
export function машиныЖителей(
  world: World, net: Network, р: Расселение, час: number, предел = 400,
): Поток {
  const посёлок = р.посёлок;
  for (const b of net.bays) b.taken = -1;
  const машины: Mover[] = [];
  let безМеста = 0;

  /** Место здания в сети считается один раз на здание, а не на жителя. */
  const место = new Map<number, УЗдания | null>();
  const узнать = (объект: number): УЗдания | null => {
    if (!место.has(объект)) место.set(объект, уДома(world, посёлок, объект));
    return место.get(объект) ?? null;
  };

  for (let номер = 0; номер < р.всего && машины.length < предел; номер++) {
    const ж: Житель = кто(р, номер);
    if (!ж.заРулём) continue;
    const м = где(ж, час, В_ПУТИ);
    if (м.где === 'за городом') continue;

    if (м.где === 'в пути') {
      const откуда = узнать(м.откуда === -1 ? ж.дом : м.откуда);
      const куда = узнать(м.куда === -1 ? ж.дом : м.куда);
      if (откуда === null || куда === null) continue;
      const total = net.length[откуда.shape];
      if (total < 40) continue;
      /**
       * Машина ставится не «где-то», а НА СВОЙ МАРШРУТ, и направление берётся
       * из него же: первый поворот маршрута говорит, в какую сторону ехать.
       * Иначе половина города с утра едет от своей работы.
       */
      const маршрут = путь(net, откуда, куда);
      const dir = маршрут === null ? (номер % 2 === 0 ? 1 : -1) as 1 | -1
        : напрвление(net, маршрут, откуда);
      /**
       * Машина ставится МЕЖДУ домом и целью, а не «где-то по дороге».
       * Если цель на той же улице, проехать её при рождении нельзя: тогда
       * машина уедет от своей цели и не вернётся — маршрут кончился, а
       * приехать некуда. Поймано на живом городе: две машины упёрлись
       * в край посёлка и встали навсегда.
       */
      const предел = маршрут !== null && маршрут.дороги.length === 1
        ? маршрут.цель.s : откуда.s + dir * 60;
      const s = Math.max(12, Math.min(total - 12,
        откуда.s + (предел - откуда.s) * Math.min(0.9, м.доля)));
      const м3 = новая(world, net, номер, откуда.shape, s, dir,
        часПрибытия(ж, м.куда), маршрут);
      /**
       * Машину нельзя поставить в ту же точку, где уже стоит другая.
       * Кузов не свойство места: два кузова в одном месте — это не «тесно»,
       * а невозможно, и физика такого не разгребёт. Первая редакция этого
       * не проверяла, и город рождался с наложенными машинами.
       */
      if (тесно(машины, м3)) continue;
      машины.push(м3);
      continue;
    }

    // дома или на месте — машина стоит у того здания, где хозяин
    const объект = м.объект;
    const у = узнать(объект);
    if (у === null) continue;
    const bay = net.bays.findIndex((b) => b.taken < 0 && b.shape === у.shape
      && Math.abs(b.s - у.s) < 40);
    if (bay < 0) { безМеста++; continue; }
    net.bays[bay].taken = машины.length;
    const dir = (Math.sign(net.bays[bay].across) || 1) as 1 | -1;
    const м2 = новая(world, net, номер, net.bays[bay].shape, net.bays[bay].s, dir,
      объект === ж.дом ? ж.уходит : ж.возвращается, null);
    м2.speed = 0;
    м2.across = net.bays[bay].across;
    м2.park = { bay, phase: 'стоит', доЧаса: м2.доЧаса ?? 0 };
    м2.reason = 'стоит в кармане';
    if (тесно(машины, м2)) { net.bays[bay].taken = -1; безМеста++; continue; }
    машины.push(м2);
  }
  return { машины, безМеста };
}

/**
 * В какую сторону ехать по своей дороге, чтобы попасть на следующую в маршруте.
 * Спрашивается у сети: сторона — это то, в каком конце дороги нужный узел.
 */
function напрвление(net: Network, м: Маршрут, откуда: УЗдания): 1 | -1 {
  const следующая = м.дороги.length > 1 ? м.дороги[1] : null;
  if (следующая === null) return (м.цель.s > откуда.s ? 1 : -1) as 1 | -1;
  for (const конец of [0, 1] as const) {
    const e = net.ends[откуда.shape][конец];
    if (e === null) continue;
    if (net.atJunction[e.junction].some((l) => l.shape === следующая)) {
      return (конец === 1 ? 1 : -1) as 1 | -1;
    }
  }
  return 1;
}

/** Нет ли уже машины в этом месте: кузова не накладываются. */
function тесно(машины: readonly Mover[], м: Mover): boolean {
  return машины.some((o) => o.shape === м.shape
    && Math.abs(o.across - м.across) < 2.2
    && Math.abs(o.s - м.s) < 9);
}

/** До какого часа хозяин будет внутри, когда доедет. */
function часПрибытия(ж: Житель, куда: number): number {
  return куда === ж.дом ? ж.уходит : ж.возвращается;
}

/**
 * Машина жителя. Всё, что в ней есть личного, выведено из НОМЕРА ХОЗЯИНА:
 * цвет, торопливость, зерно случайности. Поэтому у одного и того же человека
 * машина всегда одна и та же, и «вчера была синяя, сегодня красная»
 * записать негде.
 */
function новая(
  world: World, net: Network, хозяин: number,
  shape: number, s: number, dir: 1 | -1, доЧаса: number, маршрут: Маршрут | null,
): Mover {
  const spot = along(world, shape, s);
  const сид = (Math.imul(хозяин + 1, 2654435761) >>> 0) % 2147483647;
  const haste = ((сид >>> 8) % 1000) / 1000;
  const lane = Math.max(0, laneCount(net.lanes, shape, dir) - 1) === 0
    ? 0 : (сид >>> 3) % laneCount(net.lanes, shape, dir);
  const m: Mover = {
    shape, s, dir,
    speed: 9, wait: 0, reason: 'едет', accel: 0,
    seed: сид,
    lane,
    across: laneAcross(net.lanes, shape, dir, lane),
    хозяин, доЧаса, маршрут,
    park: null, route: null, knocked: null,
    haste,
    cruise: CRUISE,
    yaw: Math.atan2(spot.fz * dir, spot.fx * dir),
    colour: COLOURS[сид % COLOURS.length],
  };
  retune(net, m);
  return m;
}
