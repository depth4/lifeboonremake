export const ЧАС_УТРА = 7.8;

/**
 * СКОЛЬКО ЖИЗНИ НА УЛИЦЕ — одна плотность на весь проект.
 *
 * Было четыре числа в двух файлах: страница ставила 18 машин на любой сцене
 * и 180 на городской, проверка считала по своей формуле и получала 329.
 * Одна и та же величина, записанная четырьмя разными числами, обязана была
 * разойтись — и разошлась: проверка гоняла густой город, а страница
 * показывала вдвое более пустой. Спорить, который из них настоящий,
 * было не с чем.
 *
 * Мера — МЕТРЫ УЛИЦЫ, а не число: на «решётке» с её километром улиц
 * восемнадцать машин это плотный поток, а на семи километрах те же
 * восемнадцать расползаются так, что за две минуты никто никого
 * не встречает. Плотность подобрана так, чтобы на «решётке» вышли ровно
 * прежние 18 и 26 — старые замеры остаются сравнимыми.
 */
export const МЕТРОВ_НА_МАШИНУ = 51;
export const МЕТРОВ_НА_ПЕШЕХОДА = 35;

/** Длина всех улиц сети, м. */
const улиц = (net: Network): number => net.length.reduce((s, l) => s + l, 0);

/** Сколько машин уместно на этой сети в утренний час. */
export const сколькоМашин = (net: Network): number =>
  Math.max(18, Math.round(улиц(net) / МЕТРОВ_НА_МАШИНУ));

/** Сколько пешеходов уместно на этой сети в утренний час. */
export const сколькоПешеходов = (net: Network): number =>
  Math.max(26, Math.round(улиц(net) / МЕТРОВ_НА_ПЕШЕХОДА));


/** Куда смотрит здание на дороге: его место в дорожной сети. */
interface УЗдания {
  readonly shape: number;
  readonly s: number;
  readonly across: number;
  /** Сам подъезд: точка, от которой человек идёт к своей машине. */
  readonly x: number;
  readonly z: number;
}

/**
 * Насколько далеко от подъезда человек согласен оставить машину, м.
 *
 * Не «сколько метров по дороге», а по земле: своё место может оказаться
 * во дворе, то есть на совсем другой дороге. Сотня метров — это минута
 * пешком; дальше человек не пошёл бы, а искал бы другое место.
 */
const РАДИУС_СВОЕГО_МЕСТА = 100;

/** Ближайший к подъезду свободный карман. −1 — свободных рядом нет. */
function ближнийКарман(world: World, net: Network, у: УЗдания, радиус: number): number {
  let лучший = -1, ближе = радиус;
  net.bays.forEach((b, i) => {
    if (b.taken >= 0) return;
    const т = along(world, b.shape, b.s);
    const d = Math.hypot(т.x - b.across * т.fz - у.x, т.z + b.across * т.fx - у.z);
    if (d < ближе) { ближе = d; лучший = i; }
  });
  return лучший;
}

/** Где дом выходит на дорогу. Спрашивается у сети, а не хранится в доме. */
function уДома(world: World, посёлок: Посёлок, объект: number): УЗдания | null {
  const о = посёлок.объекты[объект];
  if (о === undefined) return null;
  const дом = домНаУчастке(о, посёлок.вид, посёлок.сид);
  // подъезд, а не середина дома: машина встаёт у входа
  const cos = Math.cos(дом.курс), sin = Math.sin(дом.курс);
  const п = дом.двери[0];
  const x = дом.x + (дом.глубина / 2) * cos - п.вдоль * sin;
  const z = дом.z + (дом.глубина / 2) * sin + п.вдоль * cos;
  const на = locate(world, x, z);
  return на === null ? null : { shape: на.shape, s: на.s, across: на.across, x, z };
}

/**
 * ПО ВСЕМУ ГОРОДУ, А НЕ ПО ПЕРВЫМ ПО СПИСКУ.
 *
 * Показать можно не всех: в «большом городе» одиннадцать тысяч жителей,
 * а на улицах помещается триста машин. Весь вопрос в том, КАКИЕ триста.
 *
 * Перебор подряд брал первых по номеру. Номер жителя идёт от его дома, дом
 * от участка, участок от плана — и получался город, живой кусками: пешеходы
 * нашлись на 29 улицах из 84, а на остальных 55 тротуары были пусты. Это
 * видно с уровня глаз: улица с домами, окнами и подъездами и ни одного
 * человека на ней.
 *
 * Обход идёт ШАГОМ, ВЗАИМНО ПРОСТЫМ С ЧИСЛОМ ЖИТЕЛЕЙ. Такой шаг обходит всех
 * ровно по разу и никого не повторяет — обычное свойство часов: если шаг
 * и циферблат не имеют общего делителя, стрелка встанет на каждое деление.
 * Соседние взятые жители при этом далеко друг от друга по номеру, значит
 * и по городу, — выборка размазана по всей карте.
 *
 * Ничего не хранится и ничего не случайно: один город — один и тот же обход.
 * Обрыв на пределе больше не значит «показали только начало списка».
 */
function обход(всего: number): (i: number) => number {
  if (всего <= 2) return (i) => i % Math.max(1, всего);
  const нод = (a: number, b: number): number => (b === 0 ? a : нод(b, a % b));
  // золотое сечение — самый «рассыпающий» шаг из всех возможных
  let шаг = Math.max(1, Math.round(всего * 0.6180339887));
  while (нод(шаг, всего) !== 1) шаг++;
  return (i: number) => (i * шаг) % всего;
}

export interface Поток {
  readonly машины: Mover[];
  /** Кого не удалось поставить: мест у бордюра меньше, чем машин. */
  readonly безМеста: number;
}

/**
 * Пешеходы жителей на этот час.
 *
 * Тот же отбор, что и у машин, только наоборот: идут те, кто В ПУТИ и НЕ
 * за рулём. Каждый поставлен на свой маршрут от дома к делу и по нему же
 * сворачивает на перекрёстках. «Пешеход, идущий ниоткуда в никуда» тут
 * записать негде — у него есть откуда и куда.
 */
export function пешеходыЖителей(
  world: World, net: Network, р: Расселение, час: number, предел = 400,
): Walker[] {
  const посёлок = р.посёлок;
  const идут: Walker[] = [];
  const место = new Map<number, УЗдания | null>();
  const узнать = (объект: number): УЗдания | null => {
    if (!место.has(объект)) место.set(объект, уДома(world, посёлок, объект));
    return место.get(объект) ?? null;
  };

  const порядок = обход(р.всего);
  for (let i = 0; i < р.всего && идут.length < предел; i++) {
    const номер = порядок(i);
    const ж = кто(р, номер);
    if (ж.заРулём) continue;                       // этот за рулём, не пешком
    const м = где(ж, час, В_ПУТИ);
    if (м.где !== 'в пути') continue;
    const откуда = узнать(м.откуда === -1 ? ж.дом : м.откуда);
    const куда = узнать(м.куда === -1 ? ж.дом : м.куда);
    if (откуда === null || куда === null) continue;
    const маршрут = путь(net, откуда, куда);
    if (маршрут === null) continue;

    const хвост = net.length[откуда.shape];
    if (хвост < 25) continue;
    const dir = напрвление(net, маршрут, откуда);
    const предел2 = маршрут.дороги.length === 1 ? маршрут.цель.s : откуда.s + dir * 80;
    const s = Math.max(4, Math.min(хвост - 4,
      откуда.s + (предел2 - откуда.s) * Math.min(0.9, м.доля)));
    идут.push(пеший(номер, посёлок.сид, откуда.shape, s, dir, маршрут));
  }
  return идут;
}

/** Одежда и шаг выводятся из номера жителя: у одного человека они одни и те же. */
function пеший(
  житель: number, сид: number, shape: number, s: number, dir: number, маршрут: Маршрут,
): Walker {
  const зерно = (Math.imul(житель + 1, 0x9e3779b1) ^ Math.imul(сид, 0x85ebca77)) >>> 0;
  const доля = (сдвиг: number): number => ((зерно >>> сдвиг) & 0xffff) / 65536;
  return {
    shape, s, dir,
    side: доля(0) < 0.5 ? 1 : -1,
    speed: 1.35 * (0.65 + доля(4) * 0.5),
    crossing: 0,
    colour: ОДЕЖДА[(зерно >>> 8) % ОДЕЖДА.length],
    штаны: ШТАНЫ[(зерно >>> 12) % ШТАНЫ.length],
    кожа: КОЖА[(зерно >>> 16) % КОЖА.length],
    путь: доля(20) * 4,
    seed: (зерно % 2147483646) + 1,
    житель,
    маршрут,
    state: 'идёт',
  };
}

/**
 * Машины жителей на этот час.
 *
 * Тот, кто в пути и за рулём, — едет: он поставлен на дорогу у своего дома
 * и направлен дальше. Тот, кто дома или на месте и за рулём, — стоит
 * в кармане у того здания, где он сейчас, до часа своего выхода.
 *
 * Мест у бордюра меньше, чем машин, и это не ошибка, а правда: кому места
 * не хватило, того на улице просто нет — он во дворе, которого мы не строим.
 */
export function машиныЖителей(
  world: World, net: Network, р: Расселение, час: number, предел = 400,
): Поток {
  const посёлок = р.посёлок;
  for (const b of net.bays) b.taken = -1;
  const машины: Mover[] = [];
  let безМеста = 0;

  /** Место здания в сети считается один раз на здание, а не на жителя. */
  const место = new Map<number, УЗдания | null>();
  const узнать = (объект: number): УЗдания | null => {
    if (!место.has(объект)) место.set(объект, уДома(world, посёлок, объект));
    return место.get(объект) ?? null;
  };

  const порядок = обход(р.всего);
  for (let i = 0; i < р.всего && машины.length < предел; i++) {
    const номер = порядок(i);
    const ж: Житель = кто(р, номер);
    if (!ж.заРулём) continue;
    const м = где(ж, час, В_ПУТИ);
    if (м.где === 'за городом') continue;

    if (м.где === 'в пути') {
      const откуда = узнать(м.откуда === -1 ? ж.дом : м.откуда);
      const куда = узнать(м.куда === -1 ? ж.дом : м.куда);
      if (откуда === null || куда === null) continue;
      const total = net.length[откуда.shape];
      if (total < 40) continue;
      /**
       * Машина ставится не «где-то», а НА СВОЙ МАРШРУТ, и направление берётся
       * из него же: первый поворот маршрута говорит, в какую сторону ехать.
       * Иначе половина города с утра едет от своей работы.
       */
      const маршрут = путь(net, откуда, куда);
      const dir = маршрут === null ? (номер % 2 === 0 ? 1 : -1) as 1 | -1
        : напрвление(net, маршрут, откуда);
      /**
       * Машина ставится МЕЖДУ домом и целью, а не «где-то по дороге».
       * Если цель на той же улице, проехать её при рождении нельзя: тогда
       * машина уедет от своей цели и не вернётся — маршрут кончился, а
       * приехать некуда. Поймано на живом городе: две машины упёрлись
       * в край посёлка и встали навсегда.
       */
      const предел = маршрут !== null && маршрут.дороги.length === 1
        ? маршрут.цель.s : откуда.s + dir * 60;
      const s = Math.max(12, Math.min(total - 12,
        откуда.s + (предел - откуда.s) * Math.min(0.9, м.доля)));
      const м3 = новая(world, net, номер, откуда.shape, s, dir,
        часПрибытия(ж, м.куда), маршрут);
      /**
       * Машину нельзя поставить в ту же точку, где уже стоит другая.
       * Кузов не свойство места: два кузова в одном месте — это не «тесно»,
       * а невозможно, и физика такого не разгребёт. Первая редакция этого
       * не проверяла, и город рождался с наложенными машинами.
       */
      if (нельзяСюда(world, net, машины, м3, true)) continue;
      машины.push(м3);
      continue;
    }

    // дома или на месте — машина стоит у того здания, где хозяин
    const объект = м.объект;
    const у = узнать(объект);
    if (у === null) continue;
    /**
     * Своё место ищется ПО РАССТОЯНИЮ ДО ПОДЪЕЗДА, а не «на той же дороге
     * в сорока метрах по s».
     *
     * Так было, пока стоянка была правой полосой улицы: тогда «та же дорога»
     * и «рядом с домом» совпадали. Со стоянкой во дворе совпадать перестали —
     * подъезд выходит на улицу, а место у него во дворе, и это ДРУГАЯ дорога.
     * Прежним правилом ни один двор не был бы занят вовсе.
     */
    const bay = ближнийКарман(world, net, у, РАДИУС_СВОЕГО_МЕСТА);
    if (bay < 0) { безМеста++; continue; }
    net.bays[bay].taken = машины.length;
    const dir = (Math.sign(net.bays[bay].across) || 1) as 1 | -1;
    const м2 = новая(world, net, номер, net.bays[bay].shape, net.bays[bay].s, dir,
      объект === ж.дом ? ж.уходит : ж.возвращается, null);
    м2.speed = 0;
    м2.across = net.bays[bay].across;
    м2.park = { bay, phase: 'стоит', доЧаса: м2.доЧаса ?? 0 };
    м2.reason = 'стоит в кармане';
    /**
     * Стоящей у перекрёстка стоять можно — карман там и нарезан. А вот
     * появиться вплотную перед едущей нельзя: та не успеет затормозить.
     */
    if (нельзяСюда(world, net, машины, м2, false)) {
      net.bays[bay].taken = -1; безМеста++; continue;
    }
    машины.push(м2);
  }
  return { машины, безМеста };
}

/**
 * В какую сторону ехать по своей дороге, чтобы попасть на следующую в маршруте.
 * Спрашивается у сети: сторона — это то, в каком конце дороги нужный узел.
 */
function напрвление(net: Network, м: Маршрут, откуда: УЗдания): 1 | -1 {
  const следующая = м.дороги.length > 1 ? м.дороги[1] : null;
  if (следующая === null) return (м.цель.s > откуда.s ? 1 : -1) as 1 | -1;
  for (const конец of [0, 1] as const) {
    const e = net.ends[откуда.shape][конец];
    if (e === null) continue;
    if (net.atJunction[e.junction].some((l) => l.shape === следующая)) {
      return (конец === 1 ? 1 : -1) as 1 | -1;
    }
  }
  return 1;
}

/**
 * Можно ли поставить машину сюда.
 *
 * Два условия, и оба — про то, что машина РОЖДАЕТСЯ, а не подъезжает:
 *
 * 1. Кузова не накладываются. Меряется тем же `touching`, которым город
 *    решает «столкнулись ли» (решение 028), а не своей меркой по `s`:
 *    на перекрёстке две машины с РАЗНЫХ дорог стоят в одном месте, и мерка
 *    по одной дороге их не видит. Так и вышло — 62% от касания.
 * 2. Не у самой стоп-линии. Машина, рождённая на ходу в двух метрах
 *    за стоп-линией на красный, проезжает на красный, не сделав ни одного
 *    решения, — и это записывается ей в нарушения. `placeTraffic` это
 *    правило знал, а моя расстановка жителей его потеряла: три проезда
 *    на красный случились на первой секунде прогона.
 */
const ОТ_ПЕРЕКРЁСТКА = 26;

function нельзяСюда(
  world: World, net: Network, машины: readonly Mover[], м: Mover,
  /** Машина рождается на ходу: ей ещё нельзя вставать у самой стоп-линии. */
  наХоду: boolean,
): boolean {
  if (наХоду && net.nodes[м.shape].some((n) => Math.abs(n.s - м.s) < ОТ_ПЕРЕКРЁСТКА)) return true;
  const моя = poseOf(world, net, м);
  /**
   * Дистанция при рождении — ТА, КОТОРУЮ МАШИНА САМА ДЕРЖИТ на своей
   * скорости, а не длина кузова. Машина, появившаяся на тридцати километрах
   * в восьми метрах за припаркованной, затормозить уже не успевает: ей нужно
   * почти двадцать. Первая редакция проверяла только касание кузовов, и
   * наложение случалось на седьмой десятой секунды — то есть прямо при
   * рождении, только чуть позже.
   */
  for (const o of машины) {
    /**
     * Нужная дистанция берётся по БЫСТРЕЙШЕЙ из двух: неважно, кто из них
     * появился раньше. Припаркованная, поставленная в восьми метрах перед
     * едущей, ломает ровно так же, как едущая, поставленная за ней, — и
     * первая редакция проверяла только вторую.
     */
    const быстрее = Math.max(м.speed, o.speed);
    const нужно = LENGTH + GAP0 + быстрее * HEADWAY;
    if (o.shape === м.shape && o.dir === м.dir
      && Math.abs(o.across - м.across) < 2.2
      && Math.abs(o.s - м.s) < нужно) return true;
    if (touching(моя, poseOf(world, net, o)) < 1.4) return true;
  }
  return false;
}

/** До какого часа хозяин будет внутри, когда доедет. */
function часПрибытия(ж: Житель, куда: number): number {
  return куда === ж.дом ? ж.уходит : ж.возвращается;
}

/**
 * Машина жителя. Всё, что в ней есть личного, выведено из НОМЕРА ХОЗЯИНА:
 * цвет, торопливость, зерно случайности. Поэтому у одного и того же человека
 * машина всегда одна и та же, и «вчера была синяя, сегодня красная»
 * записать негде.
 */
function новая(
  world: World, net: Network, хозяин: number,
  shape: number, s: number, dir: 1 | -1, доЧаса: number, маршрут: Маршрут | null,
): Mover {
  const spot = along(world, shape, s);
  const сид = (Math.imul(хозяин + 1, 2654435761) >>> 0) % 2147483647;
  const haste = ((сид >>> 8) % 1000) / 1000;
  const lane = Math.max(0, laneCount(net.lanes, shape, dir) - 1) === 0
    ? 0 : (сид >>> 3) % laneCount(net.lanes, shape, dir);
  const m: Mover = {
    shape, s, dir,
    speed: 9, wait: 0, reason: 'едет', accel: 0,
    seed: сид,
    lane,
    across: laneAcross(net.lanes, shape, dir, lane),
    хозяин, доЧаса, маршрут,
    park: null, route: null, knocked: null,
    haste,
    cruise: CRUISE,
    yaw: Math.atan2(spot.fz * dir, spot.fx * dir),
    colour: COLOURS[сид % COLOURS.length],
  };
  retune(net, m);
  return m;
}
