/**
 * Житель: кто живёт в городе и чем занят.
 *
 * ГЛАВНОЕ УСТРОЙСТВО: житель НЕ ХРАНИТСЯ. Он вычисляется из своего номера
 * и сида посёлка — всегда одинаково, на любой машине и в любом порядке.
 * Поэтому «житель потерялся» и «у двух игроков разные жители» невыразимы:
 * забыть можно только то, что где-то лежит (решение 044).
 *
 * Отсюда же берётся ответ на «машины на парковке не должны быть
 * декоративными». Декоративность — не свойство машины, а следствие того,
 * что у стоянки нет причины. У жителя причина есть: он дома, он на работе,
 * он идёт в магазин. Машина стоит, пока хозяин не вышел, и уезжает, когда
 * он вышел. «Машина, стоящая просто так» записать негде — некуда девать
 * хозяина.
 *
 * Про экран этот файл не знает ничего.
 */

import type { Посёлок } from './plan.ts';
import { домНаУчастке } from './дом.ts';
import { МАШИН_НА_ТЫСЯЧУ, РАБОТАЕТ_В_ПОСЁЛКЕ, ВОЗРАСТ } from './norms.ts';

/** Чем человек занят днём. Пустого занятия не бывает. */
export type Занятие = 'сад' | 'школа' | 'работа' | 'дома';

/** Зачем житель идёт. «дом» — возвращается домой. */
export type Зачем = 'сад' | 'школа' | 'работа' | 'магазин' | 'врач' | 'двор' | 'прогулка' | 'дом';

/**
 * Одна дорога дня. Откуда и куда — номера объектов посёлка, −1 — за город.
 * Во двор и на прогулку идут от своего дома к нему же: двор — за домом.
 */
export interface Дорога {
  readonly откуда: number;
  readonly куда: number;
  readonly зачем: Зачем;
  /** Когда вышел и когда пришёл, часы суток. Приход ВЫЧИСЛЕН из пути. */
  readonly выход: number;
  readonly приход: number;
  /** На машине или пешком. Выход из дома решает за весь круг до возвращения. */
  readonly наМашине: boolean;
}

/** Где житель должен быть прямо сейчас. */
export type Место =
  | { где: 'дома'; объект: number }
  | { где: 'в пути'; откуда: number; куда: number; доля: number; зачем: Зачем; наМашине: boolean; i: number }
  | { где: 'на месте'; объект: number }
  | { где: 'во дворе'; дом: number }
  | { где: 'за городом' };

export interface Житель {
  readonly номер: number;
  /** Номер объекта посёлка, в котором живёт. */
  readonly дом: number;
  readonly занятие: Занятие;
  /**
   * Куда ходит днём: номер объекта посёлка, или −1 — за город.
   * У занятия «дома» это его собственный дом.
   */
  readonly дело: number;
  /** Есть ли машина. Есть — ездит на ней далеко, близко всё равно ходит пешком. */
  readonly заРулём: boolean;
  /**
   * ДЕНЬ — дороги подряд, от дома до дома. Между дорогами человек там,
   * куда пришёл. Сутки начинаются и кончаются дома, и каждый выход —
   * не раньше прихода: «в двух местах сразу» и «нигде» записать нельзя,
   * потому что места нет — есть только дороги и то, что между ними.
   */
  readonly день: readonly Дорога[];
}

/** Сутки — 24 часа. Городские часы идут в секундах, здесь только перевод. */
export const СУТКИ = 24;
/**
 * Сколько секунд длится городской час — НАСТОЯЩИЙ ЧАС.
 *
 * До 25.09 час шёл за минуту. Пока люди на улице были снимком одного часа,
 * это ничего не ломало. Теперь улица живёт по распорядку, а человек идёт
 * со своей настоящей скоростью: при часе за минуту дорога в 200 м по плану
 * длилась бы 2.6 секунды, а по тротуару — 150, и на улице оказалось бы
 * в 58 раз больше людей, чем в пути по распорядку. Скорость часов и скорость
 * шага — одна мера, иначе улица врёт. Другой час смотрят адресом `?час=18`.
 */
export const СЕКУНД_В_ЧАСЕ = 3600;

/** Часы суток из городских секунд. */
export const часСуток = (секунд: number): number =>
  ((секунд / СЕКУНД_В_ЧАСЕ) % СУТКИ + СУТКИ) % СУТКИ;

/** Одно и то же зерно даёт одного и того же жителя. Всегда. */
function зерно(a: number, b: number): () => number {
  let s = (Math.imul(a, 0x9e3779b1) ^ Math.imul(b, 0x85ebca77)) >>> 0;
  return () => {
    s = (Math.imul(s ^ (s >>> 16), 0x21f0aaad) + 0x9e3779b9) >>> 0;
    return ((s ^ (s >>> 15)) >>> 0) / 4294967296;
  };
}

/**
 * Разложение по объектам одного назначения: кто из них ближе к дому.
 * Ребёнок ходит в БЛИЖАЙШИЙ сад, а не в случайный — это и есть смысл
 * радиуса доступности, ради которого город так и расставлен.
 */
function ближайший(посёлок: Посёлок, дом: number, что: 'сад' | 'школа' | 'магазин' | 'поликлиника'): number {
  const мой = посёлок.объекты[дом];
  let лучший = -1;
  let ближе = Infinity;
  посёлок.объекты.forEach((о, i) => {
    if (о.что !== что) return;
    const d = Math.hypot(о.x - мой.x, о.z - мой.z);
    if (d < ближе) { ближе = d; лучший = i; }
  });
  return лучший;
}

/**
 * Сколько всего жителей в посёлке и в каком доме живёт каждый.
 *
 * Номера идут подряд по домам: жители дома 0 первые, потом дома 1 и так
 * далее. Поэтому «в каком доме живёт житель N» — это поиск по возрастающему
 * ряду, а не хранимая ссылка, и разойтись им не с чем.
 */
export interface Расселение {
  readonly посёлок: Посёлок;
  /** Номер первого жителя каждого объекта; у нежилых — тот же, что у следующего. */
  readonly первый: readonly number[];
  readonly всего: number;
}

export function расселить(посёлок: Посёлок): Расселение {
  const первый: number[] = [];
  let всего = 0;
  for (const о of посёлок.объекты) {
    первый.push(всего);
    // сколько человек помещается — спрашивается у САМОГО дома, а не считается тут
    всего += о.что === 'жильё' ? домНаУчастке(о, посёлок.вид, посёлок.сид).жителей : 0;
  }
  первый.push(всего);
  return { посёлок, первый, всего };
}

/** В каком доме живёт житель с этим номером. */
export function домЖителя(р: Расселение, номер: number): number {
  let низ = 0, верх = р.посёлок.объекты.length - 1;
  while (низ < верх) {
    const середина = (низ + верх + 1) >> 1;
    if (р.первый[середина] <= номер) низ = середина; else верх = середина - 1;
  }
  return низ;
}

/**
 * Кто этот житель. Вычисляется, а не хранится.
 *
 * Возраст, занятие, машина и распорядок берутся из одного зерна — номера
 * жителя и сида посёлка. Значит один и тот же номер даёт одного и того же
 * человека всегда: и на сервере, и у каждого игрока, и через год.
 */
export function кто(р: Расселение, номер: number): Житель {
  const о = чем(р, номер);
  return { номер, дом: о.дом, занятие: о.занятие, дело: о.дело, заРулём: о.заРулём, день: распорядок(р.посёлок, о, о.сдвиг) };
}

/**
 * Житель без распорядка: где живёт, чем занят, куда ходит, есть ли машина.
 * Это та же половина `кто`, а не второй расчёт: `кто` её и зовёт. Нужна,
 * когда вопрос не про день, — «знакомы ли двое» спрашивается десятки раз
 * за кадр, а распорядок дороже всего остального вместе.
 */
export function чем(р: Расселение, номер: number): Omit<Житель, 'день'> & { readonly сдвиг: number } {
  const дом = домЖителя(р, номер);
  const случайно = зерно(номер + 1, р.посёлок.сид);

  const бросок = случайно();
  const занятие: Занятие =
    бросок < ВОЗРАСТ.дошкольник ? 'сад'
      : бросок < ВОЗРАСТ.дошкольник + ВОЗРАСТ.школьник ? 'школа'
        : бросок < ВОЗРАСТ.дошкольник + ВОЗРАСТ.школьник + ВОЗРАСТ.работник ? 'работа'
          : 'дома';

  /**
   * Куда ходит. Ребёнок — в ближайший сад или школу: ради этого город
   * и расставлен по радиусам. Работник — либо на место в самом посёлке,
   * либо за город, и доля берётся из норм, а не из головы.
   */
  let дело = дом;
  if (занятие === 'сад') дело = ближайший(р.посёлок, дом, 'сад');
  else if (занятие === 'школа') дело = ближайший(р.посёлок, дом, 'школа');
  else if (занятие === 'работа') {
    дело = случайно() < РАБОТАЕТ_В_ПОСЁЛКЕ ? рабочееМесто(р, номер) : -1;
  }
  // сада или школы в посёлке может не быть вовсе — тогда сидит дома
  if (дело === -1 && занятие !== 'работа') дело = дом;

  /**
   * Машина. Уровень автомобилизации считается на ВСЁ население, но за рулём
   * бывают только взрослые: дети и старики ездят пассажирами или пешком.
   * Поэтому доля среди взрослых выше, чем норма на тысячу, ровно во столько
   * раз, во сколько взрослых меньше, чем всех.
   */
  const взрослый = занятие === 'работа' || занятие === 'дома';
  const долиВзрослых = ВОЗРАСТ.работник + ВОЗРАСТ.пожилой;
  const доляЗаРулём = Math.min(0.95, МАШИН_НА_ТЫСЯЧУ / 1000 / долиВзрослых);
  const заРулём = взрослый && дело !== дом && случайно() < доляЗаРулём;

  /** Утренние часы разведены, иначе весь город выходит в одну минуту. */
  const сдвиг = (случайно() - 0.5) * 1.5;
  return { номер, дом, занятие, дело, заРулём, сдвиг };
}

/**
 * ПОВЕДЕНИЕ — сколько раз и куда люди выходят сверх работы и учёбы.
 * Подобрано под обследование поездок (`ПОДВИЖНОСТЬ` в `norms.ts`), и
 * `tools/life.ts` сверяет итог: поездок в сутки, доля за покупками,
 * сколько раз пожилые ходят в магазин и к врачу.
 */
const ВЫХОДЫ = {
  /** Работник заходит в магазин по дороге с работы. */
  магазинПослеРаботы: 0.25,
  /** Вечером выходит погулять — с собакой, вокруг дома. */
  прогулкаВечером: 0.2,
  /** Ребёнок из сада — вечером на площадку во дворе. */
  дошкольникВоДвор: 0.55,
  /** Школьник после уроков — во двор, в коробку. */
  школьникВоДвор: 0.5,
  школьникВМагазин: 0.1,
  /** Пожилой: утром в магазин, к врачу, днём на лавку во дворе, вечером пройтись. */
  пожилойВМагазин: 0.37,
  пожилойКВрачу: 0.16,
  пожилойВоДвор: 0.4,
  пожилойПрогулка: 0.12,
} as const;

/** Скорости дороги: пешком, на машине по городу, и время на парковку, м/с и часы. */
const ПЕШКОМ = 1.3;
const НА_МАШИНЕ = 8.3;
const ПАРКОВКА = 0.05;
/** Улица не прямая: путь по улицам длиннее прямой во столько раз. */
const ИЗВИЛИСТОСТЬ = 1.3;
/** Ближе этого на машине не ездят, м. */
const ПЕШКОМ_БЛИЖЕ = 600;
/** Дорога за город и обратно, часы. Маршрута туда нет: город кончается. */
export const ЗА_ГОРОД = 0.4;
/** Из подъезда во двор, часы: две минуты. */
const ВО_ДВОР = 0.035;

/**
 * День жителя. Строится ПО ПОРЯДКУ: каждая дорога начинается не раньше,
 * чем кончилась прошлая, и последняя приводит домой. Приход считается из
 * расстояния и способа — не одно число на всех, как было до 25.09.
 */
function распорядок(
  посёлок: Посёлок,
  ж: { номер: number; дом: number; занятие: Занятие; дело: number; заРулём: boolean },
  сдвиг: number,
): Дорога[] {
  // своё зерно: добавить в день новое дело не значит поменять человеку профессию
  const с = зерно(ж.номер + 104729, посёлок.сид ^ 0x3c6ef372);
  const о = посёлок.объекты;
  const далеко = (a: number, b: number): number =>
    (a === -1 || b === -1 ? Infinity : Math.hypot(о[a].x - о[b].x, о[a].z - о[b].z) * ИЗВИЛИСТОСТЬ);
  const путь = (откуда: number, куда: number, зачем: Зачем, машина: boolean): number => {
    if (зачем === 'двор' || зачем === 'прогулка' || (зачем === 'дом' && откуда === куда)) return ВО_ДВОР;
    if (откуда === -1 || куда === -1) return ЗА_ГОРОД;
    const м = далеко(откуда, куда);
    return машина ? м / НА_МАШИНЕ / 3600 + ПАРКОВКА : м / ПЕШКОМ / 3600;
  };

  const дороги: Дорога[] = [];
  let здесь = ж.дом, час = 0, машина = false;
  /** Пойти туда не раньше `когда`; дома — решить, на машине ли весь круг. */
  const пойти = (куда: number, зачем: Зачем, когда: number): void => {
    if (здесь === ж.дом) {
      машина = ж.заРулём && зачем !== 'двор' && зачем !== 'прогулка' && далеко(здесь, куда) > ПЕШКОМ_БЛИЖЕ;
    }
    const выход = Math.max(когда, час);
    const приход = выход + путь(здесь, куда, зачем, машина);
    дороги.push({ откуда: здесь, куда, зачем, выход, приход, наМашине: машина });
    здесь = куда;
    час = приход;
  };
  /** Домой — если не дома: во дворе и на прогулке человек ещё не дома. */
  const домой = (когда: number): void => {
    const последняя = дороги.at(-1);
    const дома = здесь === ж.дом && (последняя === undefined || последняя.зачем === 'дом');
    if (!дома) пойти(ж.дом, 'дом', когда);
  };
  const побыть = (часов: number): void => { час += часов; };
  const магазин = ближайший(посёлок, ж.дом, 'магазин');
  const врач = ближайший(посёлок, ж.дом, 'поликлиника');
  const бросок = (p: number): boolean => с() < p;

  switch (ж.занятие) {
    case 'работа': {
      пойти(ж.дело, 'работа', 8 + сдвиг);
      const сРаботы = 17.6 + сдвиг * 0.6;
      if (магазин >= 0 && бросок(ВЫХОДЫ.магазинПослеРаботы)) {
        пойти(магазин, 'магазин', сРаботы);
        побыть(0.15 + с() * 0.25);
      }
      домой(сРаботы);
      if (бросок(ВЫХОДЫ.прогулкаВечером)) {
        пойти(ж.дом, 'прогулка', 19.5 + с() * 1.5);
        побыть(0.4 + с() * 0.6);
        домой(0);
      }
      break;
    }
    case 'сад': {
      if (ж.дело !== ж.дом) {
        пойти(ж.дело, 'сад', 8 + сдвиг * 0.4);
        домой(17.2 + с() * 0.8);
      }
      if (бросок(ВЫХОДЫ.дошкольникВоДвор)) {
        пойти(ж.дом, 'двор', Math.max(час + 0.2, 17.8 + с() * 0.7));
        побыть(0.7 + с() * 0.8);
        домой(0);
      }
      break;
    }
    case 'школа': {
      if (ж.дело !== ж.дом) {
        пойти(ж.дело, 'школа', 8.1 + сдвиг * 0.3);
        домой(13.5 + с() * 1.5);
      }
      if (бросок(ВЫХОДЫ.школьникВоДвор)) {
        пойти(ж.дом, 'двор', Math.max(час + 0.5, 15.5 + с() * 1.5));
        побыть(1 + с());
        домой(0);
      }
      if (магазин >= 0 && бросок(ВЫХОДЫ.школьникВМагазин)) {
        пойти(магазин, 'магазин', Math.max(час + 0.3, 16 + с() * 3));
        побыть(0.1 + с() * 0.15);
        домой(0);
      }
      break;
    }
    case 'дома': {
      // пожилой: утро — к врачу и в магазин, день — лавка во дворе, вечер — пройтись
      if (врач >= 0 && бросок(ВЫХОДЫ.пожилойКВрачу)) {
        пойти(врач, 'врач', 8.5 + с() * 2.5);
        побыть(0.8 + с() * 0.7);
        домой(0);
      }
      if (магазин >= 0 && бросок(ВЫХОДЫ.пожилойВМагазин)) {
        пойти(магазин, 'магазин', Math.max(час + 0.2, 9 + с() * 2.5));
        побыть(0.2 + с() * 0.3);
        домой(0);
      }
      if (бросок(ВЫХОДЫ.пожилойВоДвор)) {
        пойти(ж.дом, 'двор', Math.max(час + 0.5, 15 + с() * 2.5));
        побыть(1 + с());
        домой(0);
      }
      if (бросок(ВЫХОДЫ.пожилойПрогулка)) {
        пойти(ж.дом, 'прогулка', Math.max(час + 0.3, 18.5 + с() * 1.5));
        побыть(0.5 + с() * 0.5);
        домой(0);
      }
      break;
    }
  }
  return дороги;
}

/**
 * Рабочее место в посёлке: сад, школа, магазин или поликлиника.
 *
 * Не «любой объект наугад»: чем больше объект, тем больше в нём работает
 * народу, и выбор идёт с весом по числу мест. Иначе в магазине у дома
 * работало бы столько же людей, сколько в школе на пятьсот учеников.
 */
function рабочееМесто(р: Расселение, номер: number): number {
  const служебные = р.посёлок.объекты
    .map((о, i) => ({ о, i }))
    .filter(({ о }) => о.что !== 'жильё');
  if (служебные.length === 0) return -1;
  const случайно = зерно(номер + 7919, р.посёлок.сид ^ 0x5bf03635);
  const вес = ({ о }: { о: Посёлок['объекты'][number] }): number => о.участков;
  const всего = служебные.reduce((s, x) => s + вес(x), 0);
  let бросок = случайно() * всего;
  for (const x of служебные) {
    бросок -= вес(x);
    if (бросок <= 0) return x.i;
  }
  return служебные[служебные.length - 1].i;
}

/**
 * Где житель в этот час. Считается, а не хранится.
 *
 * День — дороги подряд. До первой — дома; в дороге — в пути, с долей
 * пройденного; между дорогами — там, куда пришёл. Отсюда и берётся, кого
 * видно на улице: не «поставим двадцать шесть пешеходов», а «вот эти
 * сейчас идут».
 */
export function где(ж: Житель, час: number): Место {
  let здесь = ж.дом;
  let зачем: Зачем = 'дом';
  for (let i = 0; i < ж.день.length; i++) {
    const д = ж.день[i];
    if (час < д.выход) break;
    if (час < д.приход) {
      return {
        где: 'в пути', откуда: д.откуда, куда: д.куда, зачем: д.зачем, наМашине: д.наМашине, i,
        доля: (час - д.выход) / (д.приход - д.выход),
      };
    }
    здесь = д.куда;
    зачем = д.зачем;
  }
  if (здесь === -1) return { где: 'за городом' };
  if (зачем === 'двор' || зачем === 'прогулка') return { где: 'во дворе', дом: ж.дом };
  if (здесь === ж.дом) return { где: 'дома', объект: ж.дом };
  return { где: 'на месте', объект: здесь };
}

/**
 * Где машина жителя в этот час: едет по дороге дня, стоит у объекта до
 * часа, когда хозяин на ней уедет, или её нет (нет машины, уехала за город).
 * Машина стоит там, куда хозяин на ней приехал: ушёл пешком в магазин —
 * она ждёт у дома.
 */
export function гдеМашина(ж: Житель, час: number):
  { едет: Дорога } | { стоит: number; доЧаса: number } | null {
  // доЧаса — час суток сегодня; завтрашний — плюс сутки; не едет вовсе — никогда
  if (!ж.заРулём) return null;
  let стоит = ж.дом;
  const наМашине = ж.день.filter((д) => д.наМашине);
  for (const д of наМашине) {
    if (час < д.выход) return стоит === -1 ? null : { стоит, доЧаса: д.выход };
    if (час < д.приход) return { едет: д };
    стоит = д.куда;
  }
  if (стоит === -1) return null;
  return { стоит, доЧаса: наМашине.length === 0 ? Infinity : наМашине[0].выход + СУТКИ };
}
