/**
 * Житель: кто живёт в городе и чем занят.
 *
 * ГЛАВНОЕ УСТРОЙСТВО: житель НЕ ХРАНИТСЯ. Он вычисляется из своего номера
 * и сида посёлка — всегда одинаково, на любой машине и в любом порядке.
 * Поэтому «житель потерялся» и «у двух игроков разные жители» невыразимы:
 * забыть можно только то, что где-то лежит (решение 044).
 *
 * Отсюда же берётся ответ на «машины на парковке не должны быть
 * декоративными». Декоративность — не свойство машины, а следствие того,
 * что у стоянки нет причины. У жителя причина есть: он дома, он на работе,
 * он идёт в магазин. Машина стоит, пока хозяин не вышел, и уезжает, когда
 * он вышел. «Машина, стоящая просто так» записать негде — некуда девать
 * хозяина.
 *
 * Про экран этот файл не знает ничего.
 */

import type { Посёлок } from './plan.ts';
import { домНаУчастке } from './дом.ts';
import { МАШИН_НА_ТЫСЯЧУ, РАБОТАЕТ_В_ПОСЁЛКЕ, ВОЗРАСТ, ДОМОХОЗЯЙСТВА } from './norms.ts';

/** Чем человек занят днём. Пустого занятия не бывает. */
export type Занятие = 'сад' | 'школа' | 'работа' | 'дома';

/** Зачем житель идёт. «дом» — возвращается домой. */
export type Зачем = 'сад' | 'школа' | 'работа' | 'магазин' | 'врач' | 'двор' | 'прогулка' | 'гости' | 'дача' | 'дом';

/**
 * Одна дорога дня. Откуда и куда — номера объектов посёлка, −1 — за город.
 * Во двор и на прогулку идут от своего дома к нему же: двор — за домом.
 */
export interface Дорога {
  readonly откуда: number;
  readonly куда: number;
  readonly зачем: Зачем;
  /** Когда вышел и когда пришёл, часы суток. Приход ВЫЧИСЛЕН из пути. */
  readonly выход: number;
  readonly приход: number;
  /** На машине или пешком. Выход из дома решает за весь круг до возвращения. */
  readonly наМашине: boolean;
  /**
   * Кого ведёт за руку — номера дошкольников. Дорога с ребёнком ОДНА: та же
   * запись лежит и в дне взрослого, и в дне ребёнка, поэтому «пришли в сад
   * порознь» записать нечем.
   */
  readonly ведёт: readonly number[];
}

/** Где житель должен быть прямо сейчас. */
export type Место =
  | { где: 'дома'; объект: number }
  | { где: 'в пути'; откуда: number; куда: number; доля: number; зачем: Зачем; наМашине: boolean; i: number }
  | { где: 'на месте'; объект: number }
  | { где: 'во дворе'; дом: number }
  | { где: 'за городом' };

export interface Житель {
  readonly номер: number;
  /**
   * Которые это сутки жизни города (0 — первые). Кто он — от суток не
   * зависит (`чем`); от суток зависит только его день: привычки те же,
   * а зайдёт ли сегодня в магазин — сегодняшнее дело.
   */
  readonly сутки: number;
  /** Номер объекта посёлка, в котором живёт. */
  readonly дом: number;
  /** Его квартира: с кем живёт. Ребёнок без взрослого в ней не пишется (`Квартира`). */
  readonly квартира: Квартира;
  readonly занятие: Занятие;
  /**
   * Куда ходит днём: номер объекта посёлка, или −1 — за город.
   * У занятия «дома» это его собственный дом.
   */
  readonly дело: number;
  /** Есть ли машина. Есть — ездит на ней далеко, близко всё равно ходит пешком. */
  readonly заРулём: boolean;
  /**
   * ДЕНЬ — дороги подряд, от дома до дома. Между дорогами человек там,
   * куда пришёл. Сутки начинаются и кончаются дома, и каждый выход —
   * не раньше прихода: «в двух местах сразу» и «нигде» записать нельзя,
   * потому что места нет — есть только дороги и то, что между ними.
   */
  readonly день: readonly Дорога[];
}

/** Сутки — 24 часа. Городские часы идут в секундах, здесь только перевод. */
export const СУТКИ = 24;
/**
 * Сколько секунд длится городской час — НАСТОЯЩИЙ ЧАС.
 *
 * До 25.09 час шёл за минуту. Пока люди на улице были снимком одного часа,
 * это ничего не ломало. Теперь улица живёт по распорядку, а человек идёт
 * со своей настоящей скоростью: при часе за минуту дорога в 200 м по плану
 * длилась бы 2.6 секунды, а по тротуару — 150, и на улице оказалось бы
 * в 58 раз больше людей, чем в пути по распорядку. Скорость часов и скорость
 * шага — одна мера, иначе улица врёт. Другой час смотрят адресом `?час=18`.
 */
export const СЕКУНД_В_ЧАСЕ = 3600;

/** Часы суток из городских секунд. */
export const часСуток = (секунд: number): number =>
  ((секунд / СЕКУНД_В_ЧАСЕ) % СУТКИ + СУТКИ) % СУТКИ;

/** Одно и то же зерно даёт одного и того же жителя. Всегда. */
function зерно(a: number, b: number): () => number {
  let s = (Math.imul(a, 0x9e3779b1) ^ Math.imul(b, 0x85ebca77)) >>> 0;
  return () => {
    s = (Math.imul(s ^ (s >>> 16), 0x21f0aaad) + 0x9e3779b9) >>> 0;
    return ((s ^ (s >>> 15)) >>> 0) / 4294967296;
  };
}

/**
 * Разложение по объектам одного назначения: кто из них ближе к дому.
 * Ребёнок ходит в БЛИЖАЙШИЙ сад, а не в случайный — это и есть смысл
 * радиуса доступности, ради которого город так и расставлен.
 */
function ближайший(посёлок: Посёлок, дом: number, что: 'сад' | 'школа' | 'магазин' | 'поликлиника'): number {
  const мой = посёлок.объекты[дом];
  let лучший = -1;
  let ближе = Infinity;
  посёлок.объекты.forEach((о, i) => {
    if (о.что !== что) return;
    const d = Math.hypot(о.x - мой.x, о.z - мой.z);
    if (d < ближе) { ближе = d; лучший = i; }
  });
  return лучший;
}

/**
 * Сколько всего жителей в посёлке и в каком доме живёт каждый.
 *
 * Номера идут подряд по домам: жители дома 0 первые, потом дома 1 и так
 * далее. Поэтому «в каком доме живёт житель N» — это поиск по возрастающему
 * ряду, а не хранимая ссылка, и разойтись им не с чем.
 */
export interface Расселение {
  readonly посёлок: Посёлок;
  /** Номер первого жителя каждого объекта; у нежилых — тот же, что у следующего. */
  readonly первый: readonly number[];
  readonly всего: number;
}

export function расселить(посёлок: Посёлок): Расселение {
  const первый: number[] = [];
  let всего = 0;
  for (const о of посёлок.объекты) {
    первый.push(всего);
    // сколько человек помещается — спрашивается у САМОГО дома, а не считается тут
    всего += о.что === 'жильё' ? домНаУчастке(о, посёлок.вид, посёлок.сид).жителей : 0;
  }
  первый.push(всего);
  return { посёлок, первый, всего };
}

/** В каком доме живёт житель с этим номером. */
export function домЖителя(р: Расселение, номер: number): number {
  let низ = 0, верх = р.посёлок.объекты.length - 1;
  while (низ < верх) {
    const середина = (низ + верх + 1) >> 1;
    if (р.первый[середина] <= номер) низ = середина; else верх = середина - 1;
  }
  return низ;
}

/**
 * Кто этот житель. Вычисляется, а не хранится.
 *
 * Возраст, занятие, машина и распорядок берутся из одного зерна — номера
 * жителя и сида посёлка. Значит один и тот же номер даёт одного и того же
 * человека всегда: и на сервере, и у каждого игрока, и через год.
 */
export function кто(р: Расселение, номер: number, сутки: number): Житель {
  const о = чем(р, номер);
  /**
   * Дошкольника ведёт в сад взрослый из его квартиры, и дни их связаны:
   * день ребёнка — те же дороги, что у провожающего с ним за руку, а не
   * копии. Провожающий своего дня от ребёнка не берёт — только номера
   * тех, кого ведёт, — поэтому и круга в вычислении нет.
   */
  const провожатый = провожатыйКвартиры(о.квартира);
  const сад = ближайший(р.посёлок, о.дом, 'сад');
  /**
   * Болезнь меняет день и его самого, и того, кто его водит: больной
   * дошкольник дома — провожающий с ним (в будни не на работе), а здоровых
   * братьев и сестёр всё равно ведёт в сад. Больного провожающего нет
   * на улице — и дети в этот день дома: вести их некому.
   */
  const больна = болеет(р, номер, о.занятие, сутки);
  const дети = провожатый === номер && сад >= 0 ? дошкольники(о.квартира) : [];
  const ведёт = дети.filter((n) => болеет(р, n, 'сад', сутки) === null);
  const поУходу = ведёт.length < дети.length;
  const ведут = о.занятие === 'сад' && сад >= 0 && больна === null
    ? кто(р, провожатый, сутки).день.filter((д) => д.ведёт.includes(номер)) : null;
  return {
    номер, сутки, дом: о.дом, квартира: о.квартира, занятие: о.занятие, дело: о.дело, заРулём: о.заРулём,
    день: распорядок(р.посёлок, о, о.сдвиг, ведёт, ведут, сутки, родня(р, о.дом, о.квартира), { больна, поУходу }),
  };
}

/**
 * Кто в квартире водит детей в сад: пожилой, если он есть (бабушка
 * с внуком), иначе первый работающий по пути на работу. Взрослый в квартире
 * есть всегда — первым по типу (`Квартира`), — так что «некому вести»
 * не бывает.
 */
export function провожатыйКвартиры(к: Квартира): number {
  // нет пожилого — первый: он взрослый по типу, и раз не пожилой — работает
  return к.первый + Math.max(0, к.кто.indexOf('дома'));
}

/**
 * РОДНЯ — у каждой семьи есть родная семья в другой квартире города: туда
 * ездят в гости по выходным. Пары квартир — из перестановки всех квартир
 * города по сиду, соседние в ней — родня друг другу. Поэтому родство
 * ВЗАИМНО по устройству: «я к ним езжу, а они меня не знают» не пишется.
 * Считается раз на город. Возвращает дом родни; −1 — родни в городе нет
 * (нечётная последняя квартира) или она в том же доме.
 */
const роднёйПо = new WeakMap<Расселение, Map<Квартира, number>>();
export function родня(р: Расселение, дом: number, квартира: Квартира): number {
  let пары = роднёйПо.get(р);
  if (пары === undefined) {
    const все: { дом: number; к: Квартира }[] = [];
    р.посёлок.объекты.forEach((_, д) => { for (const к of квартиры(р, д)) все.push({ дом: д, к }); });
    const случайно = зерно(р.посёлок.сид, 0x2545f491);
    for (let i = все.length - 1; i > 0; i--) {
      const j = Math.floor(случайно() * (i + 1));
      [все[i], все[j]] = [все[j], все[i]];
    }
    пары = new Map();
    for (let i = 0; i + 1 < все.length; i += 2) {
      пары.set(все[i].к, все[i + 1].дом);
      пары.set(все[i + 1].к, все[i].дом);
    }
    роднёйПо.set(р, пары);
  }
  const их = пары.get(квартира);
  return их === undefined || их === дом ? -1 : их;
}

/**
 * ─── БОЛЕЗНЬ — первое событие жизни из календаря (основа + журнал, 25.09) ───
 *
 * Ничего не хранится: заболел ли человек в сутки d — бросок по его номеру
 * и d; сколько проболеет — тоже. Болеет в сутки N, если начал в одни из
 * прошлых суток (не дальше самого долгого эпизода) и ещё не выздоровел.
 * Поэтому «заболел вчера, а сегодня про это никто не помнит» невыразимо:
 * спросить можно про любые сутки, и ответ один.
 *
 * Эпизодов в год, когда человек остаётся дома, и дней на эпизод.
 * Дошкольник в саду — Союз педиатров России: 6–8 эпизодов ОРВИ в год,
 * эпизод 7–10 дней, дома из них 5–9. Остальное ПРЕДПОЛАГАЮ: школьник реже,
 * взрослый лёгкое переносит на ногах (ВОЗ: 2–4 ОРВИ в год, дома — одна).
 */
const БОЛЕЗНЬ: Record<Занятие, { вГод: number; дней: readonly [number, number] }> = {
  сад: { вГод: 7, дней: [5, 9] },
  школа: { вГод: 3, дней: [4, 7] },
  работа: { вГод: 1, дней: [5, 9] },
  дома: { вГод: 1.5, дней: [5, 10] },
};
/** Эпизод болезни: с каких суток и до каких (не включая) — дома. */
export interface Болезнь { readonly с: number; readonly до: number }
export function болеет(р: Расселение, номер: number, занятие: Занятие, сутки: number): Болезнь | null {
  const { вГод, дней } = БОЛЕЗНЬ[занятие];
  for (let d = сутки - дней[1] + 1; d <= сутки; d++) {
    const с = зерно(номер + 1, р.посёлок.сид ^ Math.imul(d + 7, 0x2c1b3c6d));
    if (с() >= вГод / 365) continue;
    const длина = дней[0] + Math.floor(с() * (дней[1] - дней[0] + 1));
    if (d + длина > сутки) return { с: d, до: d + длина };
  }
  return null;
}

/** Номера дошкольников квартиры. */
function дошкольники(к: Квартира): number[] {
  const номера: number[] = [];
  к.кто.forEach((з, i) => { if (з === 'сад') номера.push(к.первый + i); });
  return номера;
}

/**
 * ─── КВАРТИРА И СЕМЬЯ ───
 *
 * Жители дома делятся на квартиры: номера подряд, квартира за квартирой.
 * СКОЛЬКО квартир и людей, решает дом (`домНаУчастке`), второго счёта нет.
 * КТО в квартире — состав по её размеру: взрослые и дети.
 *
 * Первым в составе всегда взрослый — это ТИП (`Состав`), а не проверка:
 * «квартира из одних детей» не пишется, и у ребёнка всегда есть, с кем жить
 * и кому вести его в сад. До 25.09 занятие бросалось каждому отдельно,
 * и в квартире мог оказаться один трёхлетний.
 */
type Взрослый = 'работа' | 'дома';
export interface Квартира {
  /** Номер первого жильца; жильцы — подряд. */
  readonly первый: number;
  /** Занятия жильцов по порядку номеров. Первый — взрослый. */
  readonly кто: readonly [Взрослый, ...Занятие[]];
}

const Р = 'работа' as const, П = 'дома' as const, Д = 'ребёнок' as const;
type Состав = readonly [Взрослый, ...(Взрослый | typeof Д)[]];
const с = (...члены: Состав): Состав => члены;
/**
 * Составы по размеру квартиры и их доли. Подобраны так, чтобы по городу
 * вышел возрастной состав (`ВОЗРАСТ`) при тех размерах квартир, что
 * получаются у домов (одиночек 23%, пар 30%, троих 24%, четверых 15%,
 * пятерых и больше 7%): одинокие — чаще пожилые, пара — часто
 * пожилые или взрослые без детей, в трёх-четырёх — родители с детьми или
 * со взрослым ребёнком, в пяти-шести — три поколения.
 */
const СОСТАВЫ: Record<number, readonly (readonly [Состав, number])[]> = {
  1: [[с(П), 0.6], [с(Р), 0.4]],
  2: [[с(П, П), 0.45], [с(Р, Р), 0.33], [с(П, Р), 0.12], [с(Р, Д), 0.1]],
  3: [[с(Р, Р, Р), 0.4], [с(Р, Р, Д), 0.35], [с(П, Р, Р), 0.12], [с(П, П, Р), 0.08], [с(Р, Д, Д), 0.05]],
  4: [[с(Р, Р, Д, Д), 0.5], [с(П, Р, Р, Д), 0.2], [с(П, П, Р, Р), 0.15], [с(Р, Р, Р, Д), 0.15]],
  5: [[с(П, Р, Р, Д, Д), 0.45], [с(П, П, Р, Р, Д), 0.3], [с(Р, Р, Д, Д, Д), 0.25]],
  6: [[с(П, П, Р, Р, Д, Д), 1]],
};
/** Больше шести в квартире не живут: таблица составов кончается на шести. */
const БОЛЬШЕ_НЕКУДА = 6;
/** Кто из детей дошкольник: доля дошкольников среди всех детей. */
const ДОШКОЛЬНИКИ = ВОЗРАСТ.дошкольник / (ВОЗРАСТ.дошкольник + ВОЗРАСТ.школьник);

/** Выбрать по долям: бросок 0..1 против накопленных долей. */
function поДолям<T>(варианты: readonly (readonly [T, number])[], бросок: number): T {
  const всего = варианты.reduce((s2, [, д]) => s2 + д, 0);
  let x = бросок * всего;
  for (const [в, д] of варианты) { x -= д; if (x <= 0) return в; }
  return варианты[варианты.length - 1][0];
}

const квартирыПо = new WeakMap<Расселение, Map<number, readonly Квартира[]>>();
/**
 * Квартиры дома. Вычисляются из дома и сида — раз на дом, и устареть им
 * нечему: у одного расселения один и тот же дом всегда делится одинаково.
 */
export function квартиры(р: Расселение, дом: number): readonly Квартира[] {
  let дома = квартирыПо.get(р);
  if (дома === undefined) { дома = new Map(); квартирыПо.set(р, дома); }
  const есть = дома.get(дом);
  if (есть !== undefined) return есть;

  const первый = р.первый[дом], людей = р.первый[дом + 1] - первый;
  const итог: Квартира[] = [];
  if (людей > 0) {
    const о = р.посёлок.объекты[дом];
    // квартир столько, сколько у дома, но не меньше, чем нужно, чтобы все поместились
    const сколько = Math.max(Math.ceil(людей / БОЛЬШЕ_НЕКУДА),
      Math.min(людей, домНаУчастке(о, р.посёлок.вид, р.посёлок.сид).квартир));
    const случайно = зерно(дом + 7717, р.посёлок.сид ^ 0x1b873593);
    const размеры = Array.from({ length: сколько }, () =>
      поДолям(ДОМОХОЗЯЙСТВА.map((д, i) => [i + 1, д] as const), случайно()));
    // подогнать к числу жителей дома: по одному человеку по кругу
    let всего = размеры.reduce((a, b) => a + b, 0);
    let i = Math.floor(случайно() * сколько);
    while (всего > людей) { if (размеры[i] > 1) { размеры[i]--; всего--; } i = (i + 1) % сколько; }
    while (всего < людей) { if (размеры[i] < БОЛЬШЕ_НЕКУДА) { размеры[i]++; всего++; } i = (i + 1) % сколько; }
    let n = первый;
    for (const размер of размеры) {
      const [глава, ...прочие] = поДолям(СОСТАВЫ[размер], случайно());
      const ребёнок = (): Занятие => (случайно() < ДОШКОЛЬНИКИ ? 'сад' : 'школа');
      итог.push({ первый: n, кто: [глава, ...прочие.map((ч) => (ч === Д ? ребёнок() : ч))] });
      n += размер;
    }
  }
  дома.set(дом, итог);
  return итог;
}

/** Квартира жителя: последняя, чей первый номер не больше его номера. */
function квартираЖителя(р: Расселение, дом: number, номер: number): Квартира {
  const все = квартиры(р, дом);
  let низ = 0, верх = все.length - 1;
  while (низ < верх) {
    const середина = (низ + верх + 1) >> 1;
    if (все[середина].первый <= номер) низ = середина; else верх = середина - 1;
  }
  return все[низ];
}

/**
 * Житель без распорядка: где живёт, чем занят, куда ходит, есть ли машина.
 * Это та же половина `кто`, а не второй расчёт: `кто` её и зовёт. Нужна,
 * когда вопрос не про день, — «знакомы ли двое» спрашивается десятки раз
 * за кадр, а распорядок дороже всего остального вместе.
 */
export function чем(р: Расселение, номер: number): Omit<Житель, 'день' | 'сутки'> & { readonly сдвиг: number } {
  const дом = домЖителя(р, номер);
  const случайно = зерно(номер + 1, р.посёлок.сид);
  // занятие — из состава квартиры: кто он в своей семье
  const квартира = квартираЖителя(р, дом, номер);
  const занятие = квартира.кто[номер - квартира.первый];

  /**
   * Куда ходит. Ребёнок — в ближайший сад или школу: ради этого город
   * и расставлен по радиусам. Работник — либо на место в самом посёлке,
   * либо за город, и доля берётся из норм, а не из головы.
   */
  let дело = дом;
  if (занятие === 'сад') дело = ближайший(р.посёлок, дом, 'сад');
  else if (занятие === 'школа') дело = ближайший(р.посёлок, дом, 'школа');
  else if (занятие === 'работа') {
    дело = случайно() < РАБОТАЕТ_В_ПОСЁЛКЕ ? рабочееМесто(р, номер) : -1;
  }
  // сада или школы в посёлке может не быть вовсе — тогда сидит дома
  if (дело === -1 && занятие !== 'работа') дело = дом;

  /**
   * Машина. Уровень автомобилизации считается на ВСЁ население, но за рулём
   * бывают только взрослые: дети и старики ездят пассажирами или пешком.
   * Поэтому доля среди взрослых выше, чем норма на тысячу, ровно во столько
   * раз, во сколько взрослых меньше, чем всех.
   */
  const взрослый = занятие === 'работа' || занятие === 'дома';
  const долиВзрослых = ВОЗРАСТ.работник + ВОЗРАСТ.пожилой;
  const доляЗаРулём = Math.min(0.95, МАШИН_НА_ТЫСЯЧУ / 1000 / долиВзрослых);
  const заРулём = взрослый && дело !== дом && случайно() < доляЗаРулём;

  /** Утренние часы разведены, иначе весь город выходит в одну минуту. */
  const сдвиг = (случайно() - 0.5) * 1.5;
  return { номер, дом, квартира, занятие, дело, заРулём, сдвиг };
}

/**
 * ПОВЕДЕНИЕ — сколько раз и куда люди выходят сверх работы и учёбы.
 * Подобрано под обследование поездок (`ПОДВИЖНОСТЬ` в `norms.ts`), и
 * `tools/life.ts` сверяет итог: поездок в сутки, доля за покупками,
 * сколько раз пожилые ходят в магазин и к врачу.
 */
const ВЫХОДЫ = {
  /** Работник заходит в магазин по дороге с работы. */
  магазинПослеРаботы: 0.25,
  /** Вечером выходит погулять — с собакой, вокруг дома. */
  прогулкаВечером: 0.2,
  /** Ребёнок из сада — вечером на площадку во дворе. */
  дошкольникВоДвор: 0.55,
  /** Школьник после уроков — во двор, в коробку. */
  школьникВоДвор: 0.5,
  школьникВМагазин: 0.1,
  /** Пожилой: утром в магазин, к врачу, днём на лавку во дворе, вечером пройтись. */
  пожилойВМагазин: 0.37,
  пожилойКВрачу: 0.16,
  пожилойВоДвор: 0.4,
  пожилойПрогулка: 0.12,
} as const;

/**
 * ВЫХОДНЫЕ — суббота и воскресенье. Сад и школа закрыты, у большинства
 * работы нет; работники магазинов работают сменами. Взрослые — за покупками
 * побольше, в гости к родне, на дачу, гулять; дошкольника к родне ведут за
 * руку. Доли ПРЕДПОЛАГАЮ: таблицы обследования по дням недели из контейнера
 * закрыты; сверяется только итог — поездок в сутки в допуске обследования.
 */
const ВЫХОДНЫЕ = {
  сменаМагазина: 0.5,
  дача: { суббота: 0.12, воскресенье: 0.06 },
  магазин: { суббота: 0.45, воскресенье: 0.3 },
  гости: { суббота: 0.2, воскресенье: 0.3 },
  прогулка: 0.3,
  дошкольникВоДворУтром: 0.6,
  школьникВоДвор: 0.6,
  школьникВМагазин: 0.15,
  пожилойВМагазин: { суббота: 0.35, воскресенье: 0.25 },
  пожилойВоДвор: 0.5,
  пожилойПрогулка: 0.15,
} as const;

/** Скорости дороги: пешком, на машине по городу, и время на парковку, м/с и часы. */
const ПЕШКОМ = 1.3;
const НА_МАШИНЕ = 8.3;
const ПАРКОВКА = 0.05;
/** Улица не прямая: путь по улицам длиннее прямой во столько раз. */
const ИЗВИЛИСТОСТЬ = 1.3;
/** Ближе этого на машине не ездят, м. */
const ПЕШКОМ_БЛИЖЕ = 600;
/** Дорога за город и обратно, часы. Маршрута туда нет: город кончается. */
export const ЗА_ГОРОД = 0.4;
/** Из подъезда во двор, часы: две минуты. */
const ВО_ДВОР = 0.035;
/** Отдать ребёнка воспитателю или забрать и одеть — пять минут, часов. */
const СДАТЬ_РЕБЁНКА = 0.08;

/**
 * День жителя. Строится ПО ПОРЯДКУ: каждая дорога начинается не раньше,
 * чем кончилась прошлая, и последняя приводит домой. Приход считается из
 * расстояния и способа — не одно число на всех, как было до 25.09.
 */
function распорядок(
  посёлок: Посёлок,
  ж: { номер: number; дом: number; занятие: Занятие; дело: number; заРулём: boolean },
  сдвиг: number,
  /** Кого из дошкольников квартиры он водит в сад. */
  ведёт: readonly number[],
  /** Дошкольнику — дороги провожающего, на которых тот ведёт его за руку. */
  ведут: readonly Дорога[] | null,
  /** Которые сутки: у каждых свои броски — сегодня в магазин, завтра нет. */
  сутки: number,
  /** Дом родни, куда ездят в гости; −1 — нет. */
  кРодне: number,
  /** Болеет ли сам; дома ли по уходу за больным дошкольником. */
  здоровье: { больна: Болезнь | null; поУходу: boolean },
): Дорога[] {
  // своё зерно: добавить в день новое дело не значит поменять человеку профессию;
  // и своё на каждые сутки — привычки (час выхода) при этом в `чем` и не меняются
  const с = зерно(ж.номер + 104729 + сутки * 1000003, посёлок.сид ^ 0x3c6ef372);
  const о = посёлок.объекты;
  const далеко = (a: number, b: number): number =>
    (a === -1 || b === -1 ? Infinity : Math.hypot(о[a].x - о[b].x, о[a].z - о[b].z) * ИЗВИЛИСТОСТЬ);
  const путь = (откуда: number, куда: number, зачем: Зачем, машина: boolean): number => {
    if (зачем === 'двор' || зачем === 'прогулка' || (зачем === 'дом' && откуда === куда)) return ВО_ДВОР;
    if (откуда === -1 || куда === -1) return ЗА_ГОРОД;
    const м = далеко(откуда, куда);
    return машина ? м / НА_МАШИНЕ / 3600 + ПАРКОВКА : м / ПЕШКОМ / 3600;
  };

  const дороги: Дорога[] = [];
  let здесь = ж.дом, час = 0, машина = false;
  /**
   * Пойти туда не раньше `когда`, ведя за руку `с`; дома — решить, на машине
   * ли весь круг: по самой дальней его цели `круг` (в сад по дороге на
   * работу едут, если далеко работа, а не сад).
   */
  const пойти = (куда: number, зачем: Зачем, когда: number, с: readonly number[] = [], круг = куда): void => {
    if (здесь === ж.дом) {
      машина = ж.заРулём && зачем !== 'двор' && зачем !== 'прогулка' && далеко(здесь, круг) > ПЕШКОМ_БЛИЖЕ;
    }
    const выход = Math.max(когда, час);
    const приход = выход + путь(здесь, куда, зачем, машина);
    дороги.push({ откуда: здесь, куда, зачем, выход, приход, наМашине: машина, ведёт: с });
    здесь = куда;
    час = приход;
  };
  /** Домой — если не дома: во дворе и на прогулке человек ещё не дома. */
  const домой = (когда: number, с: readonly number[] = []): void => {
    const последняя = дороги.at(-1);
    const дома = здесь === ж.дом && (последняя === undefined || последняя.зачем === 'дом');
    if (!дома) пойти(ж.дом, 'дом', когда, с);
  };
  const побыть = (часов: number): void => { час += часов; };
  const магазин = ближайший(посёлок, ж.дом, 'магазин');
  const врач = ближайший(посёлок, ж.дом, 'поликлиника');
  const бросок = (p: number): boolean => с() < p;

  /** Выходной: без работы, школы и сада. */
  function выходнойДень(день: 'суббота' | 'воскресенье'): void {
    const В = ВЫХОДНЫЕ;
    switch (ж.занятие) {
      case 'работа': {
        // на дачу — на весь день, за город; машину решает дорога за город
        if (бросок(В.дача[день])) {
          пойти(-1, 'дача', 9.5 + с() * 1.5);
          побыть(5 + с() * 3);
          домой(0);
          break;
        }
        if (магазин >= 0 && бросок(В.магазин[день])) {
          пойти(магазин, 'магазин', 10.5 + с() * 2.5);
          побыть(0.3 + с() * 0.4);
          домой(0);
        }
        // к родне — с дошкольниками за руку, если водит их он
        if (кРодне >= 0 && бросок(В.гости[день])) {
          пойти(кРодне, 'гости', Math.max(час + 0.5, 14 + с() * 2), ведёт);
          побыть(2 + с() * 2);
          домой(0, ведёт);
        }
        if (бросок(В.прогулка)) {
          пойти(ж.дом, 'прогулка', Math.max(час + 0.3, 19 + с() * 1.5));
          побыть(0.5 + с() * 0.6);
          домой(0);
        }
        break;
      }
      case 'сад': {
        // утром — площадка; днём — к родне за руку, если его туда ведут; вечером — снова двор
        if (бросок(В.дошкольникВоДворУтром)) {
          пойти(ж.дом, 'двор', 10.5 + с());
          побыть(1 + с() * 0.5);
          домой(0);
        }
        for (const д of ведут ?? []) {
          дороги.push(д);
          здесь = д.куда;
          час = д.приход;
        }
        if (бросок(ВЫХОДЫ.дошкольникВоДвор)) {
          пойти(ж.дом, 'двор', Math.max(час + 0.2, 17.5 + с()));
          побыть(0.7 + с() * 0.8);
          домой(0);
        }
        break;
      }
      case 'школа': {
        if (бросок(В.школьникВоДвор)) {
          пойти(ж.дом, 'двор', 11 + с() * 2);
          побыть(1 + с() * 1.5);
          домой(0);
        }
        if (магазин >= 0 && бросок(В.школьникВМагазин)) {
          пойти(магазин, 'магазин', Math.max(час + 0.3, 15 + с() * 3));
          побыть(0.1 + с() * 0.15);
          домой(0);
        }
        break;
      }
      case 'дома': {
        // поликлиника в выходные закрыта; к родне — бабушка с внуком, если водит его она
        if (магазин >= 0 && бросок(В.пожилойВМагазин[день])) {
          пойти(магазин, 'магазин', 9.5 + с() * 2.5);
          побыть(0.2 + с() * 0.3);
          домой(0);
        }
        if (кРодне >= 0 && ведёт.length > 0 && бросок(В.гости[день])) {
          пойти(кРодне, 'гости', Math.max(час + 0.5, 14 + с() * 2), ведёт);
          побыть(2 + с() * 2);
          домой(0, ведёт);
        }
        if (бросок(В.пожилойВоДвор)) {
          пойти(ж.дом, 'двор', Math.max(час + 0.5, 15 + с() * 2.5));
          побыть(1 + с());
          домой(0);
        }
        if (бросок(В.пожилойПрогулка)) {
          пойти(ж.дом, 'прогулка', Math.max(час + 0.3, 18.5 + с() * 1.5));
          побыть(0.5 + с() * 0.5);
          домой(0);
        }
        break;
      }
    }
  }
  const день = деньНедели(сутки);
  const выходной = день === 'суббота' || день === 'воскресенье';
  // сад, куда он водит детей; −1 — никого не водит или сад сегодня закрыт
  const сад = ведёт.length > 0 && !выходной ? ближайший(посёлок, ж.дом, 'сад') : -1;
  // в выходные работник магазина работает сменой — через раз
  const наСмене = ж.занятие === 'работа' && ж.дело >= 0 && посёлок.объекты[ж.дело].что === 'магазин'
    && бросок(ВЫХОДНЫЕ.сменаМагазина);
  // больной — дома; в первый день взрослый идёт к врачу (поликлиника в воскресенье закрыта)
  if (здоровье.больна !== null) {
    const взрослый = ж.занятие === 'работа' || ж.занятие === 'дома';
    if (взрослый && врач >= 0 && здоровье.больна.с === сутки && день !== 'воскресенье') {
      пойти(врач, 'врач', 9 + с() * 2);
      побыть(0.6 + с() * 0.6);
      домой(0);
    }
    return дороги;
  }
  if (выходной && !наСмене) {
    выходнойДень(день as 'суббота' | 'воскресенье');
    return дороги;
  }
  // дома по уходу за больным дошкольником: здоровых — в сад и из сада, на работу — нет
  if (здоровье.поУходу && ж.занятие === 'работа') {
    const садДетей = ближайший(посёлок, ж.дом, 'сад');
    if (ведёт.length > 0 && садДетей >= 0) {
      пойти(садДетей, 'сад', 8 + сдвиг - 0.3, ведёт);
      побыть(СДАТЬ_РЕБЁНКА);
      домой(0);
    }
    if (магазин >= 0 && бросок(0.5)) {
      пойти(магазин, 'магазин', Math.max(час + 0.5, 11 + с() * 2));
      побыть(0.15 + с() * 0.2);
      домой(0);
    }
    if (ведёт.length > 0 && садДетей >= 0) {
      пойти(садДетей, 'сад', Math.max(час + 0.3, 17 + с() * 0.6));
      побыть(СДАТЬ_РЕБЁНКА);
      домой(0, ведёт);
    }
    return дороги;
  }

  switch (ж.занятие) {
    case 'работа': {
      // отвести детей в сад — по дороге на работу, чуть раньше обычного
      if (сад >= 0) {
        пойти(сад, 'сад', 8 + сдвиг - 0.3, ведёт, ж.дело);
        побыть(СДАТЬ_РЕБЁНКА);
      }
      пойти(ж.дело, 'работа', 8 + сдвиг);
      const сРаботы = 17.6 + сдвиг * 0.6;
      // забрать — с работы в сад, дальше с детьми
      if (сад >= 0) {
        пойти(сад, 'сад', сРаботы);
        побыть(СДАТЬ_РЕБЁНКА);
      }
      if (магазин >= 0 && бросок(ВЫХОДЫ.магазинПослеРаботы)) {
        пойти(магазин, 'магазин', сРаботы, ведёт);
        побыть(0.15 + с() * 0.25);
      }
      домой(сРаботы, ведёт);
      if (бросок(ВЫХОДЫ.прогулкаВечером)) {
        пойти(ж.дом, 'прогулка', 19.5 + с() * 1.5);
        побыть(0.4 + с() * 0.6);
        домой(0);
      }
      break;
    }
    case 'сад': {
      // в сад и из сада — за руку со взрослым: те же дороги, что у него
      for (const д of ведут ?? []) {
        дороги.push(д);
        здесь = д.куда;
        час = д.приход;
      }
      if (бросок(ВЫХОДЫ.дошкольникВоДвор)) {
        пойти(ж.дом, 'двор', Math.max(час + 0.2, 17.8 + с() * 0.7));
        побыть(0.7 + с() * 0.8);
        домой(0);
      }
      break;
    }
    case 'школа': {
      if (ж.дело !== ж.дом) {
        пойти(ж.дело, 'школа', 8.1 + сдвиг * 0.3);
        домой(13.5 + с() * 1.5);
      }
      if (бросок(ВЫХОДЫ.школьникВоДвор)) {
        пойти(ж.дом, 'двор', Math.max(час + 0.5, 15.5 + с() * 1.5));
        побыть(1 + с());
        домой(0);
      }
      if (магазин >= 0 && бросок(ВЫХОДЫ.школьникВМагазин)) {
        пойти(магазин, 'магазин', Math.max(час + 0.3, 16 + с() * 3));
        побыть(0.1 + с() * 0.15);
        домой(0);
      }
      break;
    }
    case 'дома': {
      // пожилой: утро — внука в сад, к врачу и в магазин; день — лавка во дворе,
      // до вечера — забрать внука, вечер — пройтись
      if (сад >= 0) {
        пойти(сад, 'сад', 7.6 + с() * 0.8, ведёт);
        побыть(СДАТЬ_РЕБЁНКА);
        домой(0);
      }
      if (врач >= 0 && бросок(ВЫХОДЫ.пожилойКВрачу)) {
        пойти(врач, 'врач', 8.5 + с() * 2.5);
        побыть(0.8 + с() * 0.7);
        домой(0);
      }
      if (магазин >= 0 && бросок(ВЫХОДЫ.пожилойВМагазин)) {
        пойти(магазин, 'магазин', Math.max(час + 0.2, 9 + с() * 2.5));
        побыть(0.2 + с() * 0.3);
        домой(0);
      }
      if (сад >= 0) {
        пойти(сад, 'сад', Math.max(час + 0.3, 16.6 + с() * 0.9));
        побыть(СДАТЬ_РЕБЁНКА);
        домой(0, ведёт);
      }
      if (бросок(ВЫХОДЫ.пожилойВоДвор)) {
        пойти(ж.дом, 'двор', Math.max(час + 0.5, 15 + с() * 2.5));
        побыть(1 + с());
        домой(0);
      }
      if (бросок(ВЫХОДЫ.пожилойПрогулка)) {
        пойти(ж.дом, 'прогулка', Math.max(час + 0.3, 18.5 + с() * 1.5));
        побыть(0.5 + с() * 0.5);
        домой(0);
      }
      break;
    }
  }
  return дороги;
}

/**
 * Рабочее место в посёлке: сад, школа, магазин или поликлиника.
 *
 * Не «любой объект наугад»: чем больше объект, тем больше в нём работает
 * народу, и выбор идёт с весом по числу мест. Иначе в магазине у дома
 * работало бы столько же людей, сколько в школе на пятьсот учеников.
 */
function рабочееМесто(р: Расселение, номер: number): number {
  const служебные = р.посёлок.объекты
    .map((о, i) => ({ о, i }))
    .filter(({ о }) => о.что !== 'жильё');
  if (служебные.length === 0) return -1;
  const случайно = зерно(номер + 7919, р.посёлок.сид ^ 0x5bf03635);
  const вес = ({ о }: { о: Посёлок['объекты'][number] }): number => о.участков;
  const всего = служебные.reduce((s, x) => s + вес(x), 0);
  let бросок = случайно() * всего;
  for (const x of служебные) {
    бросок -= вес(x);
    if (бросок <= 0) return x.i;
  }
  return служебные[служебные.length - 1].i;
}

/**
 * Где житель в этот час. Считается, а не хранится.
 *
 * День — дороги подряд. До первой — дома; в дороге — в пути, с долей
 * пройденного; между дорогами — там, куда пришёл. Отсюда и берётся, кого
 * видно на улице: не «поставим двадцать шесть пешеходов», а «вот эти
 * сейчас идут».
 */
export function где(ж: Житель, час: number): Место {
  let здесь = ж.дом;
  let зачем: Зачем = 'дом';
  for (let i = 0; i < ж.день.length; i++) {
    const д = ж.день[i];
    if (час < д.выход) break;
    if (час < д.приход) {
      return {
        где: 'в пути', откуда: д.откуда, куда: д.куда, зачем: д.зачем, наМашине: д.наМашине, i,
        доля: (час - д.выход) / (д.приход - д.выход),
      };
    }
    здесь = д.куда;
    зачем = д.зачем;
  }
  if (здесь === -1) return { где: 'за городом' };
  if (зачем === 'двор' || зачем === 'прогулка') return { где: 'во дворе', дом: ж.дом };
  if (здесь === ж.дом) return { где: 'дома', объект: ж.дом };
  return { где: 'на месте', объект: здесь };
}

/**
 * Где машина жителя в этот час: едет по дороге дня, стоит у объекта до
 * часа, когда хозяин на ней уедет, или её нет (нет машины, уехала за город).
 * Машина стоит там, куда хозяин на ней приехал: ушёл пешком в магазин —
 * она ждёт у дома.
 */
export function гдеМашина(р: Расселение, ж: Житель, час: number):
  { едет: Дорога } | { стоит: number; доЧаса: number } | null {
  // доЧаса — час суток сегодня; после последней поездки — первый выезд
  // ЗАВТРАШНЕГО дня (плюс сутки), спрошенный у завтрашнего дня, а не
  // «сегодняшний плюс сутки»: завтра у него может быть другой день
  if (!ж.заРулём) return null;
  let стоит = ж.дом;
  for (const д of ж.день) {
    if (!д.наМашине) continue;
    if (час < д.выход) return стоит === -1 ? null : { стоит, доЧаса: д.выход };
    if (час < д.приход) return { едет: д };
    стоит = д.куда;
  }
  if (стоит === -1) return null;
  return { стоит, доЧаса: первыйВыезд(р, ж.номер, ж.сутки + 1, 1) };
}

/** Первый выезд на машине начиная с этих суток, в часах от их начала; не ближе недели — никогда. */
function первыйВыезд(р: Расселение, номер: number, сутки: number, глубина: number): number {
  const д = кто(р, номер, сутки).день.find((x) => x.наМашине);
  if (д !== undefined) return д.выход + СУТКИ;
  return глубина >= 7 ? Infinity : первыйВыезд(р, номер, сутки + 1, глубина + 1) + СУТКИ;
}

/** Дни недели. Город начинается в понедельник: первые сутки — понедельник. */
export const ДНИ = ['понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота', 'воскресенье'] as const;
export const деньНедели = (сутки: number): (typeof ДНИ)[number] => ДНИ[((сутки % 7) + 7) % 7];
