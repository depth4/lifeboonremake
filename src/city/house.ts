interface Стена {
  /** Начало и конец стены на земле. */
  readonly ax: number;
  readonly az: number;
  readonly bx: number;
  readonly bz: number;
  readonly низ: number;
  readonly верх: number;
  readonly проёмы: readonly Проём[];
  readonly цвет: number;
  /** До какой высоты стена считается цоколем и красится в его цвет. */
  readonly цокольДо?: number;
}

/**
 * Стена строится СЕТКОЙ ЯЧЕЕК: границы проёмов режут стену по вертикали
 * и по горизонтали, и каждая получившаяся клетка либо кирпич, либо дырка.
 *
 * Почему так, а не «вырезать дырку из прямоугольника»: вырезание — это
 * отдельный алгоритм с вырожденными случаями (проём на краю, два проёма
 * впритык, проём выше стены). Сетка их не знает: клетка либо внутри проёма,
 * либо нет, третьего нет. Считать чуть дороже, ошибиться нечем.
 */
function стена(
  к: Куча, стекло: Куча, окна: Куча, свет: Куча, с: Стена, откос: number,
): void {
  const dx = с.bx - с.ax;
  const dz = с.bz - с.az;
  const длина = Math.hypot(dx, dz);
  if (длина < 1e-6) return;
  const ux = dx / длина, uz = dz / длина;
  // наружу — вправо от направления стены: стена идёт против часовой снаружи
  const nx = uz, nz = -ux;

  const т = (s: number, y: number, вглубь = 0): Точка => [
    с.ax + ux * s - nx * вглубь, y, с.az + uz * s - nz * вглубь,
  ];

  const рез = (значения: number[], от: number, до: number): number[] => {
    const все = [от, до, ...значения.filter((v) => v > от + 1e-6 && v < до - 1e-6)];
    return [...new Set(все.map((v) => Math.round(v * 1e4) / 1e4))].sort((a, b) => a - b);
  };
  const xs = рез(с.проёмы.flatMap((п) => [п.от, п.до]), 0, длина);
  const ys = рез([
    ...с.проёмы.flatMap((п) => [п.низ, п.верх]),
    ...(с.цокольДо === undefined ? [] : [с.цокольДо]),
  ], с.низ, с.верх);

  const дырка = (s: number, y: number): Проём | undefined =>
    с.проёмы.find((п) => s > п.от && s < п.до && y > п.низ && y < п.верх);

  // ряд за рядом; соседние кирпичные клетки склеиваются в один прямоугольник
  for (let j = 0; j + 1 < ys.length; j++) {
    const y0 = ys[j], y1 = ys[j + 1];
    const yc = (y0 + y1) / 2;
    let от = -1;
    for (let i = 0; i < xs.length; i++) {
      const кирпич = i + 1 < xs.length
        && дыркиНет(дырка((xs[i] + xs[i + 1]) / 2, yc));
      if (кирпич && от < 0) от = xs[i];
      if (!кирпич && от >= 0) {
        // цоколь — не отдельная вещь, а нижние ячейки той же стены: тогда
        // «цоколь поперёк двери» записать нечем, дверь там просто дырка
        const цоколь = с.цокольДо !== undefined && yc < с.цокольДо;
        квад(к, т(от, y0), т(xs[i], y0), т(xs[i], y1), т(от, y1),
          цоколь ? ДОМ.цвет.цоколь : с.цвет);
        от = -1;
      }
    }
  }

  // откосы и стекло: проём — это дырка, у которой есть толщина
  for (const п of с.проёмы) {
    const тень = затемнить(с.цвет, 0.72);
    // верхний и нижний откос
    квад(к, т(п.от, п.верх), т(п.до, п.верх), т(п.до, п.верх, откос), т(п.от, п.верх, откос), тень);
    квад(к, т(п.до, п.низ), т(п.от, п.низ), т(п.от, п.низ, откос), т(п.до, п.низ, откос), тень);
    // боковые
    квад(к, т(п.от, п.низ), т(п.от, п.верх), т(п.от, п.верх, откос), т(п.от, п.низ, откос), тень);
    квад(к, т(п.до, п.верх), т(п.до, п.низ), т(п.до, п.низ, откос), т(п.до, п.верх, откос), тень);

    if (п.вид === 'дверь') {
      // дверь — это вход, и она открыта: сквозь неё входят
      continue;
    }
    if (п.вид === 'витрина') {
      квад(стекло,
        т(п.от, п.низ, откос), т(п.до, п.низ, откос),
        т(п.до, п.верх, откос), т(п.от, п.верх, откос), ДОМ.цвет.витрина);
      continue;
    }
    /**
     * Окно квартиры: обратный обход углов, чтобы лицевой стороной плоскость
     * смотрела НАРУЖУ. Материал односторонний — значит снаружи это зеркало,
     * а изнутри плоскости просто нет и видно улицу.
     *
     * Цвет — отражение неба, и оно тем светлее, чем выше этаж: снизу в стекле
     * отражается противоположный дом, сверху небо. Это не украшение, а то,
     * по чему живой дом отличается от дома с одинаковыми серыми дырками.
     */
    /**
     * В части окон ГОРИТ СВЕТ. Их видно с улицы, и это единственное, что
     * с улицы видно внутри дома: не комнату, а то, что в ней кто-то есть.
     *
     * Стекло при этом такое же одностороннее: изнутри его нет, улицу видно
     * насквозь. Разница только в том, из какой сетки оно взято — из обычной
     * или из светящейся.
     */
    const горит = окнаНаружу && светитЛи(п.от, с.низ);
    const куда = горит ? свет : окна;
    const ц = горит ? ДОМ.цвет.окноГорит : отражение(п.от, с.низ);
    if (окнаНаружу) {
      квад(куда,
        т(п.до, п.низ, откос), т(п.от, п.низ, откос),
        т(п.от, п.верх, откос), т(п.до, п.верх, откос), ц);
    } else {
      квад(куда,
        т(п.от, п.низ, откос), т(п.до, п.низ, откос),
        т(п.до, п.верх, откос), т(п.от, п.верх, откос), ц);
    }
  }
}

const дыркиНет = (п: Проём | undefined): boolean => п === undefined;

/**
 * Цвет оконного стекла: чем выше, тем больше в нём неба.
 *
 * `надПолом` тут не при чём — важна высота НАД ЗЕМЛЁЙ: на первом этаже
 * в окне отражается дом напротив, на пятом — небо. Смешиваем два цвета
 * по высоте и добавляем малую рябь от самой высоты, чтобы соседние окна
 * не были одинаковыми до последнего разряда.
 */
/**
 * Горит ли свет в этом окне. Доля — из норм, место — из сида.
 *
 * Днём свет горит не во всех окнах и не в одном: примерно в каждом
 * десятом. Это единственное, что с улицы видно ВНУТРИ дома, — и видно
 * не комнату, а то, что в ней кто-то есть.
 */
function светитЛи(вдоль: number, низСтены: number): boolean {
  let h = ((Math.round(вдоль * 31) * 374761393) ^ Math.round(низСтены * 71)) >>> 0;
  h = Math.imul(h ^ (h >>> 15), 0x2c1b3c6d) >>> 0;
  return ((h >>> 8) % 100) < ДОМ.горитОкон;
}

function отражение(вдоль: number, низСтены: number): number {
  const доля = Math.min(1, Math.max(0, низСтены / 14));
  const смесь = (a: number, b: number): number => Math.round(a + (b - a) * доля);
  const тёмн = ДОМ.цвет.стекло, свет = ДОМ.цвет.стеклоВверху;
  /**
   * Рябь — от МЕСТА окна, а не от одной высоты: иначе весь ряд на этаже
   * получается одного оттенка и фасад читается полосами. За окнами живут
   * разные люди: где-то шторы, где-то нет.
   */
  let h = ((Math.round(вдоль * 13) * 2654435761) ^ Math.round(низСтены * 29)) >>> 0;
  h = (h ^ (h >>> 13)) >>> 0;
  const рябь = ((h % 9) - 4) * 7;
  const r = Math.min(255, Math.max(0, смесь((тёмн >> 16) & 255, (свет >> 16) & 255) + рябь));
  const g = Math.min(255, Math.max(0, смесь((тёмн >> 8) & 255, (свет >> 8) & 255) + рябь));
  const b = Math.min(255, Math.max(0, смесь(тёмн & 255, свет & 255) + рябь));
  return (r << 16) | (g << 8) | b;
}

