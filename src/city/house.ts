/** Проём в стене: от-до вдоль стены, низ-верх по высоте. Метры. */
export interface Проём {
  readonly вид: 'окно' | 'дверь' | 'витрина';
  readonly от: number;
  readonly до: number;
  readonly низ: number;
  readonly верх: number;
}

/** Что получилось. Числа отсюда читает проверка, а не переписывает человек. */
export interface Застройка {
  readonly стены: Сетка;
  readonly стёкла: Сетка;
  /**
   * То, что светится само: потолочные панели магазина, подсветка витрины.
   *
   * Отдельной сеткой, потому что внутри дома солнца нет, а свет есть.
   * Считать настоящий свет в каждом торговом зале — это десятки источников
   * на квартал и цена, которой мы платить не собираемся. Светящаяся
   * поверхность стоит ноль и делает ровно то, что нужно: изнутри и с улицы
   * видно, что в магазине горит свет.
   */
  readonly свет: Сетка;
  readonly дома: readonly Дом[];
}

/** Проём вместе с тем, где он стоит: по этой записи его и проверяют. */
export interface ПроёмВДоме extends Проём {
  /** Номер стены: 0 фасад, 1 правый торец, 2 двор, 3 левый торец. */
  readonly стена: number;
  readonly длинаСтены: number;
  readonly этаж: number;
  readonly полПола: number;
  readonly потолок: number;
}

/** Один дом — то, что о нём знает проверка. */
export interface Дом {
  readonly что: Назначение;
  readonly x: number;
  readonly z: number;
  /** Единичный вектор наружу, к улице: обстановка ставится по нему. */
  readonly нx: number;
  readonly нz: number;
  /** Номер улицы в куске, которому дом показывает фасад. */
  readonly улица: number;
  readonly низ: number;
  readonly верх: number;
  readonly фронт: number;
  readonly глубина: number;
  readonly этажей: number;
  readonly проёмы: readonly ПроёмВДоме[];
  readonly дверей: number;
  /** Площадь остекления фасада, м². */
  readonly стекла: number;
  /** Площадь фасада, м². */
  readonly фасада: number;
}

