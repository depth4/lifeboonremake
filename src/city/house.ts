/**
 * Дом как геометрия: стены с проёмами, этажи, крыша.
 *
 * **Главное решение: стена — это плоскость с ДЫРКАМИ, а не картинка окон.**
 * Разница не в красоте. Пока окно нарисовано на стене, «войти в дом» —
 * отдельная задача, «видно ли улицу из окна» — вторая, «видно ли витрину
 * с улицы» — третья, и все три решаются по-своему и расходятся. Когда окно
 * это дырка, ни одной из трёх задач нет: сквозь дырку видно в обе стороны,
 * потому что она дырка.
 *
 * Что стало невыразимым, а не поймано проверкой:
 *
 * - **окно посреди перекрытия** — проём стоит в ячейке «этаж × модуль»,
 *   других мест нет;
 * - **окно, наполовину уехавшее за угол** — модуль нарезается по длине
 *   стены, за её пределы выйти нечем;
 * - **дом без крыши и без входа** — крыша и вход не «добавляются», а входят
 *   в сборку дома наравне со стенами;
 * - **дом, висящий над землёй или утонувший в ней** — цоколь тянется от
 *   САМОЙ НИЗКОЙ точки под пятном до самой высокой, то есть ровно настолько,
 *   насколько нужно;
 * - **разная правда внутри и снаружи** — геометрия одна, стены двусторонние.
 *   То, что видно с улицы через витрину, и то, что видно изнутри, — один
 *   и тот же треугольник.
 *
 * Про Three.js этот файл не знает ничего: наружу отдаются массивы чисел.
 * Поэтому дом можно проверить из терминала — `npm run house`.
 */

