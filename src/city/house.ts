export type { Сетка } from './mesh.ts';

/** Проём в стене: от-до вдоль стены, низ-верх по высоте. Метры. */
export interface Проём {
  readonly вид: 'окно' | 'дверь' | 'витрина';
  readonly от: number;
  readonly до: number;
  readonly низ: number;
  readonly верх: number;
}

/** Что получилось. Числа отсюда читает проверка, а не переписывает человек. */
export interface Застройка {
  readonly стены: Сетка;
  /**
   * ПРОЗРАЧНОЕ стекло: витрины магазинов, и только они.
   *
   * Сквозь витрину видно в обе стороны, потому что в зале горит свет:
   * видно всегда туда, где светлее. Днём это магазин, а не квартира.
   */
  readonly стёкла: Сетка;
  /**
   * НЕПРОЗРАЧНОЕ стекло жилых окон — односторонняя плоскость наружу.
   *
   * Днём с улицы в квартиру не видно: оконное стекло отражает небо, и это
   * не приём, а то, как оно работает. Изнанка этой плоскости отсекается,
   * поэтому ИЗ КВАРТИРЫ улицу видно насквозь — ровно как в жизни.
   *
   * Заодно это даром решает то, ради чего обычно пишут отдельный «уровень
   * подробности»: внутренность жилого дома снаружи не видна никогда, и
   * показывать её незачем.
   */
  readonly окна: Сетка;
  /**
   * То, что светится само: потолочные панели магазина, подсветка витрины.
   *
   * Отдельной сеткой, потому что внутри дома солнца нет, а свет есть.
   * Считать настоящий свет в каждом торговом зале — это десятки источников
   * на квартал и цена, которой мы платить не собираемся. Светящаяся
   * поверхность стоит ноль и делает ровно то, что нужно: изнутри и с улицы
   * видно, что в магазине горит свет.
   */
  readonly свет: Сетка;
  readonly дома: readonly Дом[];
}

/**
 * Зона за проёмом — коробка, которую с улицы видно сквозь дырку в стене.
 *
 * Это единственное место, где у дома есть постоянная внутренняя геометрия.
 * Всё, что не попало в зону, снаружи не существует и появляется только
 * когда в дом вошли. Коробка не выбирается, а СЧИТАЕТСЯ от проёма —
 * поэтому «нарисовали комнату там, где в стене нет дырки» невыразимо.
 */
export interface Зона {
  /** Середина зоны на плоскости фасада. */
  readonly x: number;
  readonly z: number;
  /** Сдвиг середины вдоль фасада от его центра, м: по нему ищется проём. */
  readonly вдоль: number;
  /** Полуширина вдоль фасада и глубина внутрь, м. */
  readonly полуширина: number;
  readonly глубина: number;
  readonly низ: number;
  readonly верх: number;
}

/** Проём вместе с тем, где он стоит: по этой записи его и проверяют. */
export interface ПроёмВДоме extends Проём {
  /** Номер стены: 0 фасад, 1 правый торец, 2 двор, 3 левый торец. */
  readonly стена: number;
  readonly длинаСтены: number;
  readonly этаж: number;
  readonly полПола: number;
  readonly потолок: number;
}

/** Один дом — то, что о нём знает проверка. */
export interface Дом {
  readonly что: Назначение;
  readonly x: number;
  readonly z: number;
  /** Единичный вектор наружу, к улице: обстановка ставится по нему. */
  readonly нx: number;
  readonly нz: number;
  /** Номер улицы в куске, которому дом показывает фасад. */
  readonly улица: number;
  readonly низ: number;
  readonly верх: number;
  readonly фронт: number;
  readonly глубина: number;
  readonly этажей: number;
  /** Уровень пола первого этажа и высоты этажей — по ним строится внутренность. */
  readonly пол: number;
  readonly высоты: readonly number[];
  readonly проёмы: readonly ПроёмВДоме[];
  /** Коробки за проёмами: ровно то, что у дома нарисовано всегда. */
  readonly зоны: readonly Зона[];
  readonly дверей: number;
  /** Площадь остекления фасада, м². */
  readonly стекла: number;
  /** Площадь фасада, м². */
  readonly фасада: number;
}

