interface Место {
  /** Середина пятна застройки. */
  readonly x: number;
  readonly z: number;
  /** Единичный вектор наружу, к улице. */
  readonly нx: number;
  readonly нz: number;
  readonly фронт: number;
  readonly глубина: number;
  readonly улица: number;
}

/** Высоты этажей: первый бывает выше остальных — там магазин или вестибюль. */
function этажи(что: Назначение, сколько: number): number[] {
  const первый = что === 'магазин' || что === 'супермаркет' ? ДОМ.этаж.торговый
    : что === 'жильё' ? ДОМ.этаж.жилой : ДОМ.этаж.общественный;
  const прочие = что === 'жильё' ? ДОМ.этаж.жилой : ДОМ.этаж.общественный;
  return Array.from({ length: сколько }, (_, i) => (i === 0 ? первый : прочие));
}

function цветДома(что: Назначение, случайно: () => number): number {
  const набор = ДОМ.цвет.стены[что];
  return набор[Math.floor(случайно() * набор.length) % набор.length];
}

/**
 * Собрать один дом.
 *
 * Порядок сборки — это и есть определение дома: цоколь, этажи с фасадами,
 * крыша. Пропустить звено нельзя: следующее считается от предыдущего.
 */
function дом(
  к: Куча, стекло: Куча, свет: Куча, м: Место, что: Назначение, сколькоЭтажей: number,
  землиНиз: number, землиВерх: number, случайно: () => number,
): Дом {
  const fx = -м.нz, fz = м.нx;          // вдоль фронта
  const nx = м.нx, nz = м.нz;           // наружу
  const A = м.фронт / 2, B = м.глубина / 2;
  const угол = (a: number, b: number): { x: number; z: number } => ({
    x: м.x + fx * a + nx * b,
    z: м.z + fz * a + nz * b,
  });
  // против часовой стрелки при взгляде сверху, если смотреть снаружи
  const п1 = угол(-A, B);   // левый передний
  const п2 = угол(A, B);    // правый передний
  const п3 = угол(A, -B);   // правый задний
  const п4 = угол(-A, -B);  // левый задний

  const цокольНиз = землиНиз - ДОМ.цоколь.вЗемлю;
  const пол = землиВерх + ДОМ.цоколь.надЗемлёй;
  const высоты = этажи(что, сколькоЭтажей);
  const верхСтен = пол + высоты.reduce((a, b) => a + b, 0);

  const цвет = цветДома(что, случайно);
  const цокольЦвет = ДОМ.цвет.цоколь;

  // ── цоколь: от самой низкой точки земли под пятном до уровня пола
  const цоколь = (a: { x: number; z: number }, b: { x: number; z: number }): void => {
    квад(к, [a.x, цокольНиз, a.z], [b.x, цокольНиз, b.z],
      [b.x, пол, b.z], [a.x, пол, a.z], цокольЦвет);
  };
  цоколь(п1, п2); цоколь(п2, п3); цоколь(п3, п4); цоколь(п4, п1);

  // ── проёмы по этажам
  const всеПроёмы: ПроёмВДоме[] = [];
  let дверей = 0;
  let стекла = 0;
  let фасада = 0;

  const шагФасад = что === 'жильё' ? ДОМ.модуль.жильё : ДОМ.модуль.общественный;
  const ширинаОкна = что === 'жильё' ? ДОМ.окно.ширина : ДОМ.окно.ширинаОбщественная;

  /**
   * Стены четырёх сторон: фасад, правый торец, зад (дворовый фасад), левый торец.
   *
   * **Торец жилого дома — глухой.** Это не экономия треугольников, а то, как
   * в России стоит панельный и кирпичный дом: окна выходят на улицу и во двор,
   * торцы слепые. Стоит поставить окна по кругу — и дом перестаёт читаться
   * как дом, становится коробкой с дырками.
   */
  const стороны: { a: typeof п1; b: typeof п1; длина: number; фасад: boolean; торец: boolean }[] = [
    { a: п1, b: п2, длина: м.фронт, фасад: true, торец: false },
    { a: п2, b: п3, длина: м.глубина, фасад: false, торец: true },
    { a: п3, b: п4, длина: м.фронт, фасад: false, торец: false },
    { a: п4, b: п1, длина: м.глубина, фасад: false, торец: true },
  ];

  let полПола = пол;
  for (let этаж = 0; этаж < высоты.length; этаж++) {
    const h = высоты[этаж];
    const первый = этаж === 0;

    for (let номерСтены = 0; номерСтены < стороны.length; номерСтены++) {
      const с = стороны[номерСтены];
      const торговый = (что === 'магазин' || что === 'супермаркет');
      /**
       * Что кладём на эту стену — по старшинству: сначала входы, потом окна.
       * Складывает всегда `сложить`, поэтому наложение невыразимо.
       */
      const группы: Проём[][] = [];
      if (первый && с.фасад && торговый) {
        // витрина во всю ширину фасада: за ней торговый зал, и его видно
        группы.push(входы(с.длина, полПола, 1));
        группы.push(окнаЭтажа(с.длина, полПола, h, ДОМ.модуль.витрина,
          ДОМ.модуль.витрина - ДОМ.простенок, 'витрина'));
      } else if (первый && с.фасад) {
        // подъезды: один на секцию, остальное — обычные окна
        группы.push(входы(с.длина, полПола, Math.max(1, Math.round(с.длина / ДОМ.секция))));
        группы.push(окнаЭтажа(с.длина, полПола, h, шагФасад, ширинаОкна, 'окно'));
      } else if (!(с.торец && что === 'жильё')) {
        группы.push(окнаЭтажа(с.длина, полПола, h, шагФасад, ширинаОкна, 'окно'));
      }
      const проёмы = сложить(группы);

      стена(к, стекло, {
        ax: с.a.x, az: с.a.z, bx: с.b.x, bz: с.b.z,
        низ: полПола, верх: полПола + h, проёмы, цвет,
      }, ДОМ.откос);

      /**
       * Балконы — со второго этажа и не у всех окон. Балкон стоит тридцать
       * треугольников и делает с домом больше, чем всё остальное вместе:
       * это первое, по чему жилой дом отличают от конторы.
       */
      if (что === 'жильё' && !первый && !с.торец) {
        for (const о of проёмы) {
          if (о.вид !== 'окно' || случайно() > ДОМ.балкон.доля) continue;
          балкон(к, с.a, с.b, с.длина, (о.от + о.до) / 2, полПола, цвет);
        }
      }

      for (const п of проёмы) {
        всеПроёмы.push({
          ...п, стена: номерСтены, длинаСтены: с.длина,
          этаж, полПола, потолок: полПола + h,
        });
      }
      дверей += проёмы.filter((п) => п.вид === 'дверь').length;
      стекла += проёмы
        .filter((п) => п.вид !== 'дверь')
        .reduce((s, п) => s + (п.до - п.от) * (п.верх - п.низ), 0);
      фасада += с.длина * h;
    }

    /**
     * ── Внутренность этажа.
     *
     * Отдельной «модели интерьера» не существует: то, что видно с улицы
     * через витрину, и то, что видно, когда вошёл, — одни и те же
     * треугольники. Разойтись им негде, потому что они одни.
     */
    if (первый && (что === 'магазин' || что === 'супермаркет')) {
      торговыйЗал(к, свет, п1, п2, п3, п4, полПола, h, м.фронт, м.глубина, fx, fz, nx, nz);
    } else if (что === 'жильё') {
      квартиры(к, п1, п2, п4, полПола, h, м.фронт, м.глубина, fx, fz, nx, nz, первый);
    }

    // ── перекрытие: пол следующего этажа, он же потолок этого.
    //    Из-за него дом не «полый ящик», а этажи: изнутри видно потолок.
    перекрытие(к, п1, п2, п3, п4, полПола, ДОМ.цвет.перекрытие);
    полПола += h;
  }

  // ── крыша
  const скатная = что === 'жильё' && сколькоЭтажей <= 2;
  const конёк = скатная
    ? крышаСкатная(к, п1, п2, п3, п4, верхСтен, м.фронт, м.глубина, цвет)
    : крышаПлоская(к, п1, п2, п3, п4, верхСтен, цвет);

  // ── козырёк над входом виден с улицы и стоит десять треугольников
  if (!скатная) {
    const середина = угол(0, B);
    коробка(к, середина.x + nx * 0.6, пол + ДОМ.дверь.высота + 0.25, середина.z + nz * 0.6,
      ДОМ.дверь.ширина + 1.0, 0.18, 1.4, fx, fz, ДОМ.цвет.козырёк);
  }

  // ── вывеска над витриной: по ней магазин узнают с другой стороны улицы
  if (что === 'магазин' || что === 'супермаркет') {
    const перед = угол(0, B);
    коробка(к, перед.x + nx * 0.12, пол + высоты[0] - ДОМ.витрина.надВитриной / 2, перед.z + nz * 0.12,
      м.фронт * 0.8, ДОМ.витрина.надВитриной * 0.7, 0.24, fx, fz,
      что === 'супермаркет' ? ДОМ.цвет.вывескаСупер : ДОМ.цвет.вывеска);
  }

  return {
    что, x: м.x, z: м.z, нx: м.нx, нz: м.нz, улица: м.улица,
    низ: цокольНиз, верх: конёк,
    фронт: м.фронт, глубина: м.глубина, этажей: сколькоЭтажей,
    проёмы: всеПроёмы, дверей, стекла, фасада,
  };
}

/**
 * Балкон: плита и ограждение. Держится на стене, а не висит рядом с ней, —
 * положение берётся из той же стены, у которой он растёт.
 */
function балкон(
  к: Куча, a: Угол, b: Угол, длина: number, s: number, пол: number, цвет: number,
): void {
  const ux = (b.x - a.x) / длина, uz = (b.z - a.z) / длина;
  const nx = uz, nz = -ux;                        // наружу от стены
  const x = a.x + ux * s, z = a.z + uz * s;
  const В = ДОМ.балкон.вынос, Ш = ДОМ.балкон.ширина;
  const плита = пол + 0.02;
  // плита
  коробка(к, x + nx * (В / 2), плита, z + nz * (В / 2), Ш, 0.16, В, ux, uz, ДОМ.цвет.перекрытие);
  // ограждение: три щита по краю плиты
  const h = ДОМ.балкон.ограждение;
  коробка(к, x + nx * В, плита + h / 2, z + nz * В, Ш, h, 0.08, ux, uz, затемнить(цвет, 0.82));
  for (const сторона of [-1, 1]) {
    коробка(к,
      x + nx * (В / 2) + ux * сторона * (Ш / 2), плита + h / 2,
      z + nz * (В / 2) + uz * сторона * (Ш / 2),
      0.08, h, В, ux, uz, затемнить(цвет, 0.82));
  }
}

/**
 * Сложить проёмы одной стены так, чтобы они не налезали друг на друга.
 *
 * Группы идут по старшинству: дверь важнее окна, её не двигают. Окно, попавшее
 * на уже занятое место, просто не появляется — вместо него остаётся стена.
 *
 * Раньше этим занимался каждый случай отдельно: у жилого дома окна фильтровались
 * по дверям, у магазина — нет, и витрина налезала на вход. Проверка нашла это
 * с первого запуска. Теперь случая нет: класть проёмы можно только через эту
 * функцию, и «два проёма в одном месте» записать нечем.
 */
function сложить(группы: Проём[][]): Проём[] {
  const легло: Проём[] = [];
  const мешает = (a: Проём, b: Проём): boolean =>
    a.от < b.до - 1e-6 && b.от < a.до - 1e-6
    && a.низ < b.верх - 1e-6 && b.низ < a.верх - 1e-6;
  for (const группа of группы) {
    for (const п of группа) {
      if (легло.some((у) => мешает(у, п))) continue;
      легло.push(п);
    }
  }
  return легло;
}

/** Входные двери, расставленные по длине стены. */
function входы(длина: number, полПола: number, сколько: number): Проём[] {
  const из: Проём[] = [];
  for (let i = 0; i < сколько; i++) {
    const центр = (длина * (i + 0.5)) / сколько;
    из.push({
      вид: 'дверь',
      от: центр - ДОМ.дверь.ширина / 2,
      до: центр + ДОМ.дверь.ширина / 2,
      низ: полПола,
      верх: полПола + ДОМ.дверь.высота,
    });
  }
  return из;
}

/** Перекрытие между этажами. Двустороннее: снизу потолок, сверху пол. */
function перекрытие(
  к: Куча, п1: Угол, п2: Угол, п3: Угол, п4: Угол, y: number, цвет: number,
): void {
  квад(к, [п1.x, y, п1.z], [п2.x, y, п2.z], [п3.x, y, п3.z], [п4.x, y, п4.z], цвет);
}

/** Плоская кровля с парапетом. Ограждение кровли — требование, а не украшение. */
function крышаПлоская(
  к: Куча, п1: Угол, п2: Угол, п3: Угол, п4: Угол, y: number, цвет: number,
): number {
  квад(к, [п1.x, y, п1.z], [п2.x, y, п2.z], [п3.x, y, п3.z], [п4.x, y, п4.z], ДОМ.цвет.кровля);
  const верх = y + ДОМ.парапет;
  const стенка = (a: Угол, b: Угол): void => {
    квад(к, [a.x, y, a.z], [b.x, y, b.z], [b.x, верх, b.z], [a.x, верх, a.z], затемнить(цвет, 0.9));
  };
  стенка(п1, п2); стенка(п2, п3); стенка(п3, п4); стенка(п4, п1);
  return верх;
}

/**
 * Скатная кровля: конёк идёт ВДОЛЬ фронта улицы, свес нависает над стеной.
 * Уклон берётся из норм, а высота конька считается из него — «крыша круче,
 * чем бывает» здесь не записывается.
 */
function крышаСкатная(
  к: Куча, п1: Угол, п2: Угол, п3: Угол, п4: Угол,
  y: number, фронт: number, глубина: number, цвет: number,
): number {
  const подъём = (глубина / 2) * Math.tan((ДОМ.скат * Math.PI) / 180);
  const конёк = y + подъём;
  const св = ДОМ.свес;
  // направления: вдоль фронта и наружу
  const fx = (п2.x - п1.x) / фронт, fz = (п2.z - п1.z) / фронт;
  const nx = (п1.x - п4.x) / глубина, nz = (п1.z - п4.z) / глубина;

  const т = (a: number, b: number, h: number): Точка => [
    (п1.x + п3.x) / 2 + fx * a + nx * b, h, (п1.z + п3.z) / 2 + fz * a + nz * b,
  ];
  const A = фронт / 2 + св, B = глубина / 2 + св;
  const цк = ДОМ.цвет.кровля;
  // два ската
  квад(к, т(-A, B, y), т(A, B, y), т(A, 0, конёк), т(-A, 0, конёк), цк);
  квад(к, т(A, -B, y), т(-A, -B, y), т(-A, 0, конёк), т(A, 0, конёк), цк);
  // два фронтона — настоящими треугольниками: у вырожденного квада нормаль
  // нулевая, и грань чернеет (так почернели кроны деревьев)
  треуг(к, т(-A, -B, y), т(-A, B, y), т(-A, 0, конёк), затемнить(цвет, 0.95));
  треуг(к, т(A, B, y), т(A, -B, y), т(A, 0, конёк), затемнить(цвет, 0.95));
  return конёк;
}

