/**
 * Вестибюль подъезда. Ширина 3.4 м и глубина 4.5 м — практика входной группы
 * жилого дома; норматив снизу: СП 59.13330 требует тамбур не менее 1.5 м
 * в глубину и ширину двери не менее 1.2 м.
 */
const ВЕСТИБЮЛЬ = { ширина: 3.4, глубина: 4.5 } as const;

/** Одно и то же зерно — один и тот же дом. Всегда. */
function зерно(сид: number): () => number {
  let s = (сид ^ 0x85ebca6b) >>> 0;
  return () => {
    s = (Math.imul(s ^ (s >>> 15), 0x2c1b3c6d) + 0x9e3779b9) >>> 0;
    return ((s ^ (s >>> 16)) >>> 0) / 4294967296;
  };
}

/**
 * Разбивка стены на модули.
 *
 * Модуль — это шаг простенков: расстояние от оси окна до оси соседнего.
 * В панельном доме это шаг несущих стен, 3.0–3.3 м; в школе и магазине
 * шаг крупнее. Число модулей округляется, а ширина модуля подгоняется —
 * поэтому окно, не влезшее в стену, невыразимо: их ровно столько, сколько
 * влезло.
 */
let подгонятьМодуль = true;
let окнаНаружу = true;

/**
 * Заведомо сломанный вариант: окна развёрнуты лицом ВНУТРЬ. Тогда снаружи
 * плоскость отсекается, и с улицы становится видно квартиру — то самое,
 * ради чего окна и сделали односторонними.
 */
export function сломатьОкна(): void { окнаНаружу = false; }

let нутроСразу = false;

/**
 * Заведомо сломанный вариант: внутренность строится ВМЕСТЕ с оболочкой, как
 * было до того, как окна стали зеркалами. Тогда квартиры рисуются всегда,
 * даже когда их никто не видит, — и проверка «снаружи квартиры не существует»
 * обязана это поймать.
 */
export function сломатьНутро(): void { нутроСразу = true; }

let зонаБезПроёма = false;

/**
 * Заведомо сломанный вариант: вестибюль ставится не за дверью, а в углу
 * фасада — за глухой стеной. Снаружи его не видно ни с какой точки, значит
 * он существует зря. Проверка «снаружи есть только то, что видно сквозь
 * проём» обязана это поймать: зона есть, дырки перед ней нет.
 */
export function сломатьЗону(): void { зонаБезПроёма = true; }

/**
 * Заведомо сломанный вариант: модуль НЕ подгоняется под длину стены, а берётся
 * как есть. Тогда последнее окно вылезает за угол, а на коротких стенах окна
 * налезают друг на друга. Это ровно та ошибка, ради которой проверка и нужна.
 */
export function сломатьМодуль(): void { подгонятьМодуль = false; }

function модули(длина: number, шаг: number): { сколько: number; ширина: number } {
  const сколько = Math.max(1, Math.round(длина / шаг));
  return { сколько, ширина: подгонятьМодуль ? длина / сколько : шаг };
}

/** Окна одного этажа по всей длине стены. */
function окнаЭтажа(
  длина: number, полПола: number, высотаЭтажа: number, шаг: number,
  ширинаОкна: number, вид: 'окно' | 'витрина',
): Проём[] {
  const { сколько, ширина } = модули(длина, шаг);
  const проёмы: Проём[] = [];
  const w = Math.min(ширинаОкна, ширина - ДОМ.простенок);
  if (w <= 0.4) return проёмы;
  for (let i = 0; i < сколько; i++) {
    const центр = ширина * (i + 0.5);
    const низ = вид === 'витрина' ? полПола + ДОМ.витрина.низ : полПола + ДОМ.окно.подоконник;
    const верх = вид === 'витрина'
      ? полПола + высотаЭтажа - ДОМ.витрина.надВитриной
      : низ + ДОМ.окно.высота;
    проёмы.push({ вид, от: центр - w / 2, до: центр + w / 2, низ, верх });
  }
  return проёмы;
}

