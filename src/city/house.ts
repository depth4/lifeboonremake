/**
 * Собрать все дома посёлка в ДВЕ сетки: стены и стёкла.
 *
 * Две, а не тысяча, — потому что цена показа меряется вызовами отрисовки,
 * а не треугольниками (решение 053, замер `npm run inside`). Стёкла отдельно
 * не по красоте: прозрачное рисуется другим материалом, иначе сквозь него
 * ничего не видно.
 */
export function построитьДома(
  объекты: readonly {
    что: Назначение; x: number; z: number; фронт: number; глубина: number;
    нx: number; нz: number; этажей: number; участокГлубина: number; улица: number;
  }[],
  вид: Вид,
  земля: (x: number, z: number) => number,
  сид: number,
): Застройка {
  const к = куча();
  const стекло = куча();
  const свет = куча();
  const дома: Дом[] = [];
  const случайно = зерно(сид);
  const отступ = ЗАСТРОЙКА[вид].отступДома;

  for (const о of объекты) {
    // фасад отодвинут от красной линии на отступ, остальное участка — двор
    const вглубь = о.участокГлубина / 2 - о.глубина / 2 - отступ;
    const x = о.x + о.нx * вглубь;
    const z = о.z + о.нz * вглубь;
    const место: Место = {
      x, z, нx: о.нx, нz: о.нz, фронт: о.фронт, глубина: о.глубина, улица: о.улица,
    };
    // земля под пятном: цоколь тянется от самой низкой точки до самой высокой
    const fx = -о.нz, fz = о.нx;
    const пробы: number[] = [];
    for (const a of [-0.5, 0, 0.5]) {
      for (const b of [-0.5, 0, 0.5]) {
        пробы.push(земля(
          x + fx * a * о.фронт + о.нx * b * о.глубина,
          z + fz * a * о.фронт + о.нz * b * о.глубина,
        ));
      }
    }
    дома.push(дом(
      к, стекло, свет, место, о.что, о.этажей,
      Math.min(...пробы), Math.max(...пробы), случайно,
    ));
  }

  return { стены: собрать(к), стёкла: собрать(стекло), свет: собрать(свет), дома };
}
