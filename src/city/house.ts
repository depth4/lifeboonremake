/**
 * Торговый зал: пол, светящийся потолок, стеллажи и кассовая стойка.
 *
 * Стеллажи стоят ПОПЕРЁК витрины, а не вдоль: так их видно с улицы рядами,
 * уходящими вглубь, — и это ровно то, как выглядит продуктовый с тротуара.
 * Проходы между ними по норме торгового зала — не уже 1.4 м.
 */
function торговыйЗал(
  к: Куча, свет: Куча, п1: Угол, п2: Угол, п3: Угол, п4: Угол,
  пол: number, высота: number, фронт: number, глубина: number,
  fx: number, fz: number, nx: number, nz: number,
): void {
  const cx = (п1.x + п3.x) / 2, cz = (п1.z + п3.z) / 2;
  const т = (a: number, b: number): Угол => ({ x: cx + fx * a + nx * b, z: cz + fz * a + nz * b });

  /**
   * Весь зал идёт в сетку СВЕТА, а не стен. Причина не в красоте: снаружи
   * светит солнце и полусфера, а внутри дома от полусферы приходит НИЖНЯЯ
   * половина — цвет земли, тёмно-зелёный. Зал от этого чёрный, и витрина,
   * ради которой всё затевалось, показывает темноту. Настоящие лампы в каждом
   * магазине — это десятки источников на квартал; светящаяся поверхность
   * стоит ноль и делает ровно то, что нужно.
   */
  const A = фронт / 2 - 0.2, B = глубина / 2 - 0.2;
  перекрытие(свет, т(-A, B), т(A, B), т(A, -B), т(-A, -B), пол + 0.02, ДОМ.цвет.полЗала);
  перекрытие(свет, т(-A, -B), т(A, -B), т(A, B), т(-A, B), пол + высота - 0.12, ДОМ.цвет.потолокЗала);
  /**
   * Светильники — ПОЛОСАМИ поперёк витрины, а не ровным свечением всего
   * потолка. Ровный потолок читается как белая заливка над головой; полосы
   * читаются как лампы, и по ним же видно, что зал уходит вглубь.
   */
  const полос = Math.max(2, Math.round(фронт / 6));
  for (let i = 0; i < полос; i++) {
    const a = -фронт / 2 + (фронт * (i + 0.5)) / полос;
    const л1 = т(a - 0.25, B - 1.0), л2 = т(a + 0.25, B - 1.0);
    const л3 = т(a + 0.25, -B + 1.0), л4 = т(a - 0.25, -B + 1.0);
    перекрытие(свет, л1, л2, л3, л4, пол + высота - 0.16, ДОМ.цвет.лампа);
  }
  // задняя стена зала: без неё сквозь витрину видно улицу за домом
  const зад = ДОМ.цвет.стенаЗала;
  квад(свет, [т(-A, -B).x, пол, т(-A, -B).z], [т(A, -B).x, пол, т(A, -B).z],
    [т(A, -B).x, пол + высота, т(A, -B).z], [т(-A, -B).x, пол + высота, т(-A, -B).z], зад);

  /**
   * Кассы стоят СБОКУ от входа, а не напротив него: напротив входа в магазине
   * проход, иначе в дверь упирается стойка. Первая редакция ставила её по
   * середине фасада, и с улицы дверь была заткнута белым ящиком.
   */
  const касса = т(-фронт * 0.28, B - 2.4);
  коробка(свет, касса.x, пол + 0.55, касса.z,
    фронт * 0.34, 1.1, 0.7, fx, fz, ДОМ.цвет.касса);

  /**
   * Стеллажи поперёк витрины — и ПО ОБЕ СТОРОНЫ от середины, а не подряд
   * от края. Середина фасада — это вход, и напротив входа в магазине проход,
   * а не полка. Первая редакция считала ряды от края, при нечётном числе
   * ряд вставал ровно в дверях, и человек, войдя, упирался в стеллаж носом.
   */
  const шагСтеллажа = ДОМ.зал.стеллаж + ДОМ.зал.проход;
  const половин = Math.max(1, Math.floor((фронт / 2 - 1.2) / шагСтеллажа));
  const места: number[] = [];
  for (let k = 0; k < половин; k++) {
    места.push(шагСтеллажа / 2 + k * шагСтеллажа, -(шагСтеллажа / 2 + k * шагСтеллажа));
  }
  const рядов = места.length;
  const глубинаРяда = глубина - 6;
  if (глубинаРяда < 2) return;
  for (let i = 0; i < рядов; i++) {
    const a = места[i];
    const центр = т(a, -0.6);
    коробка(свет, центр.x, пол + ДОМ.зал.высотаСтеллажа / 2, центр.z,
      ДОМ.зал.стеллаж, ДОМ.зал.высотаСтеллажа, глубинаРяда, fx, fz, ДОМ.цвет.стеллаж);
    // товар сверху: пёстрая полоса, по которой стеллаж и читается как стеллаж
    коробка(свет, центр.x, пол + ДОМ.зал.высотаСтеллажа + 0.12, центр.z,
      ДОМ.зал.стеллаж - 0.1, 0.24, глубинаРяда - 0.2, fx, fz,
      ДОМ.цвет.товар[i % ДОМ.цвет.товар.length]);
  }
}

/**
 * ВНУТРЕННОСТЬ ОДНОГО ДОМА — строится, когда в него вошли.
 *
 * **Почему не вместе со всем остальным.** Днём с улицы в квартиру не видно:
 * стекло отражает небо. Значит всё, что за стеклом, снаружи не показывается
 * никогда — и держать его собранным незачем. Здесь это не приём ради
 * скорости, а следствие того, как работает стекло: снаружи квартиры просто
 * не существует.
 *
 * Что это даёт на будущее: мебель, двери, лестницы и живущий в квартире
 * человек стоят столько же, сколько сама квартира, — то есть нисколько,
 * пока в неё не вошли. Сегодня экономия невелика (замер — в `npm run house`),
 * потому что вся цена сидит в фасадах; но как только квартиру обставят,
 * считать её для всего квартала стало бы нельзя.
 *
 * Собирается ЗАНОВО при каждом входе и выбрасывается при выходе. Хранить
 * нечего: всё выводится из дома, а дом — из сида.
 */
export function внутренность(д: Дом): { стены: Сетка; свет: Сетка } {
  const к = куча();
  const свет = куча();
  const fx = -д.нz, fz = д.нx;
  const nx = д.нx, nz = д.нz;
  const A = д.фронт / 2, B = д.глубина / 2;
  const угол = (a: number, b: number): Угол => ({
    x: д.x + fx * a + nx * b, z: д.z + fz * a + nz * b,
  });
  const п1 = угол(-A, B), п2 = угол(A, B), п3 = угол(A, -B), п4 = угол(-A, -B);

  let полПола = д.пол;
  for (let этаж = 0; этаж < д.высоты.length; этаж++) {
    const h = д.высоты[этаж];
    const первый = этаж === 0;
    // торговый зал уже стоит снаружи: его видно с улицы, он строится сразу
    if (!(первый && (д.что === 'магазин' || д.что === 'супермаркет'))) {
      квартиры(к, п1, п2, п4, полПола, h, д.фронт, д.глубина, fx, fz, nx, nz, первый);
    }
    перекрытие(к, п1, п2, п3, п4, полПола + (первый ? 0.01 : 0), ДОМ.цвет.перекрытие);
    полПола += h;
  }
  // потолок последнего этажа: без него сверху видно небо сквозь крышу
  перекрытие(к, п4, п3, п2, п1, полПола, ДОМ.цвет.перекрытие);

  // подъезд не строится здесь: он виден с улицы сквозь дверь и стоит всегда
  return { стены: собрать(к), свет: собрать(свет) };
}

/**
 * Жилой этаж изнутри: перегородки поперёк корпуса.
 *
 * Не мебель и не планировка — ровно столько, чтобы в окно было видно
 * комнату, а не ангар. Перегородка ставится через секцию: дом 20 м по фронту
 * при корпусе 14 м даёт комнаты примерно 6 × 6, то есть квартиру.
 */
function квартиры(
  к: Куча, п1: Угол, п2: Угол, п4: Угол,
  пол: number, высота: number, фронт: number, глубина: number,
  fx: number, fz: number, nx: number, nz: number, первый: boolean,
): void {
  const cx = (п1.x + п2.x) / 2 + (п4.x - п1.x) / 2;
  const cz = (п1.z + п2.z) / 2 + (п4.z - п1.z) / 2;
  const т = (a: number, b: number, y: number): Точка =>
    [cx + fx * a + nx * b, y, cz + fz * a + nz * b];

  const шаг = ДОМ.комната;
  const сколько = Math.max(0, Math.round(фронт / шаг) - 1);
  const B = глубина / 2 - 0.15;
  for (let i = 1; i <= сколько; i++) {
    const a = -фронт / 2 + (фронт * i) / (сколько + 1);
    квад(к, т(a, -B, пол), т(a, B, пол), т(a, B, пол + высота), т(a, -B, пол + высота),
      ДОМ.цвет.перегородка);
  }
  // продольная перегородка: коридор вдоль корпуса, комнаты по обе стороны
  if (!первый) {
    const A = фронт / 2 - 0.15;
    квад(к, т(-A, 0, пол), т(A, 0, пол), т(A, 0, пол + высота), т(-A, 0, пол + высота),
      ДОМ.цвет.перегородка);
  }
}

/**
 * ЕДИНСТВЕННОЕ место, где у дома появляется постоянная внутренняя геометрия.
 *
 * Правило одно на всех: **что видно с улицы сквозь дырку в стене — то есть
 * всегда; чего не видно — того снаружи не существует.** Витрина и входная
 * дверь это две дырки, за ними торговый зал и подъезд. Окно квартиры дыркой
 * не является: его стекло одностороннее и снаружи оно зеркало, — значит
 * квартиры снаружи нет, и «уровень подробности» писать не надо, он получился
 * сам из того, как устроено стекло.
 *
 * Коробка зоны не выбирается руками, а считается ОТ ПРОЁМА и возвращается
 * наружу. Поэтому нарисовать комнату там, куда не смотрит ни одна дырка,
 * здесь просто нечем: заполнитель получает готовую зону и не знает координат.
 */
function заПроёмом(
  к: Куча, свет: Куча, п1: Угол, п2: Угол,
  вдоль: number, полуширина: number, глубина: number,
  пол: number, высота: number, fx: number, fz: number,
  заполнить: (з: Зона) => void,
): Зона {
  const з: Зона = {
    x: (п1.x + п2.x) / 2 + fx * вдоль,
    z: (п1.z + п2.z) / 2 + fz * вдоль,
    вдоль, полуширина, глубина, низ: пол, верх: пол + высота,
  };
  заполнить(з);
  return з;
}

/**
 * Вестибюль подъезда — коробка сразу за входной дверью.
 *
 * Пол, потолок, задняя стена и две боковых. Открыт только в сторону двери:
 * с улицы видно подъезд, а не сквозной дом и не газон под ним.
 */
function вестибюль(
  к: Куча, свет: Куча, з: Зона, пол: number, высота: number,
  fx: number, fz: number, nx: number, nz: number,
): void {
  const Ш = з.полуширина;
  const Г = з.глубина;
  const т = (a: number, b: number): Угол => ({
    x: з.x + fx * a - nx * b, z: з.z + fz * a - nz * b,
  });
  const угол1 = т(-Ш, 0), угол2 = т(Ш, 0), угол3 = т(Ш, Г), угол4 = т(-Ш, Г);
  // пол и потолок
  перекрытие(к, угол1, угол2, угол3, угол4, пол + 0.02, ДОМ.цвет.плитка);
  перекрытие(к, угол4, угол3, угол2, угол1, пол + высота - 0.1, ДОМ.цвет.перекрытие);
  // задняя стена и две боковых
  const стенка = (a: Угол, b: Угол): void => {
    квад(к, [a.x, пол, a.z], [b.x, пол, b.z],
      [b.x, пол + высота, b.z], [a.x, пол + высота, a.z], ДОМ.цвет.перегородка);
  };
  стенка(угол4, угол3);
  стенка(угол1, угол4);
  стенка(угол3, угол2);
  подъезд(к, свет, з, fx, fz, nx, nz, пол, высота);
}

/**
 * Подъезд: площадка, почтовые ящики и первый марш лестницы.
 *
 * Это то, что человек видит, войдя в дверь. Без него вход ведёт в пустую
 * коробку, и «войти» перестаёт что-либо значить.
 */
function подъезд(
  к: Куча, свет: Куча, з: Зона,
  fx: number, fz: number, nx: number, nz: number, пол: number, высота: number,
): void {
  const вглубь = (d: number): Угол => ({ x: з.x - nx * d, z: з.z - nz * d });
  /**
   * Все глубины отсчитываются ОТ ЗАДНЕЙ СТЕНЫ зоны, а не от двери.
   *
   * Отсчёт от двери уже стоил ошибки: марш из пяти ступеней начинался на
   * 3.4 м и заканчивался на 4.75, а вестибюль кончается на 4.5 — лестница
   * торчала сквозь заднюю стену внутрь квартир. Проверка это поймала. От
   * задней стены такое не выражается: последняя ступень упирается в неё
   * по построению, куда бы ни уехала глубина зоны.
   */
  const ступеней = 5;
  const ступень = { глубина: 0.3, высота: 0.17 };
  const марш = ступеней * ступень.глубина;
  /**
   * Площадки здесь нет, и это не экономия. Пол у вестибюля уже есть, один
   * на всю зону; вторая плита поверх него — второй источник правды о том,
   * где пол. Она у меня и соврала: её передняя грань легла ровно в
   * плоскость фасада, и с улицы у дома по низу стены светилась полоса
   * шириной три метра. Пол один.
   */
  const марж = Math.max(0.6, з.глубина - марш);
  const п = вглубь(марж / 2);
  // почтовые ящики на боковой стене
  const я = { x: п.x + fx * (з.полуширина - 0.2), z: п.z + fz * (з.полуширина - 0.2) };
  коробка(к, я.x, пол + 1.3, я.z, 0.2, 0.9, 1.4, fx, fz, ДОМ.цвет.ящики);
  // марш лестницы: последняя ступень упирается в заднюю стену вестибюля
  for (let i = 0; i < ступеней; i++) {
    const глубже = з.глубина - марш + ступень.глубина * (i + 0.5);
    const с = вглубь(глубже);
    коробка(к, с.x, пол + ступень.высота * (i + 0.5) / 2, с.z,
      1.4, ступень.высота * (i + 0.5), ступень.глубина, fx, fz, ДОМ.цвет.перекрытие);
  }
  // лампочка на площадке: в подъезде всегда горит свет, даже днём
  коробка(свет, п.x, пол + высота - 0.3, п.z, 0.5, 0.1, 0.5, fx, fz, ДОМ.цвет.лампа);
}

