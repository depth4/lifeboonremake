/**
 * Площадка: как дом встречается с землёй.
 *
 * До этого файла у дома была одна связь с землёй — высота в его СЕРЕДИНЕ
 * (`main.ts`: `низ = ground.sample(дом.x, дом.z).height`). Дом 17 × 14 метров
 * на уклоне в восемь процентов расходится с землёй больше чем на метр,
 * и это не ошибка расчёта: ровно это и было записано. Замерено 17.09.2026:
 * на «холмах» у 635 домов из 676 угол висел выше 30 см, худший разрыв 6.31 м.
 *
 * **Как это устроено в жизни.** Померено по настоящим данным (Прага, Бубенеч,
 * `docs/how-cities-work.md` §6): у 37% настоящих домов земля под следом гуляет
 * больше метра, у 15% — больше двух. И дом при этом не кривой.
 * **Ровный у дома пол, а не земля.** Разницу берёт на себя цоколь: с низкой
 * стороны он высокий, с высокой почти исчезает. Цоколь — это не украшение
 * и не постоянная величина, это и есть ответ на вопрос «как ровное стоит
 * на неровном».
 *
 * ЧТО СДЕЛАНО НЕВЫРАЗИМЫМ (а не поймано проверкой):
 *
 * - **угол дома висит над землёй.** Подошва цоколя — это минимум земли под
 *   следом минус запас. Ниже самой низкой земли по определению; выше быть
 *   не может, потому что она из неё и посчитана;
 * - **стена вросла в землю.** Пол — это максимум земли под следом плюс порог.
 *   Выше самой высокой земли по определению;
 * - **пол с уклоном.** Пол — одно число на весь дом, а не функция от места.
 *   Наклонного пола здесь негде записать;
 * - **зависимость от порядка.** Площадка — чистая функция следа и земли.
 *   Кого посчитали раньше, тот ни на кого не влияет.
 *
 * Что НЕВОЗМОЖНО сделать невыразимым и потому осталось проверкой: **цоколь
 * не бывает выше предела**. Это зависит от рельефа, а рельеф мы не выбираем.
 * Слишком крутое место — не «дом с трёхметровым цоколем», а место, где
 * не строят. Само решение не строить принимает план, а не этот файл:
 * здесь только считается, сколько бы потребовалось.
 *
 * Про экран этот файл не знает ничего.
 */

/**
 * Насколько пол первого этажа поднят над самой высокой землёй у стены, м.
 * Практика российского жилья: пол выше отмостки на две ступени с порогом,
 * иначе талая вода идёт в подъезд.
 */
export const ПОРОГ = 0.45;

/**
 * Насколько подошва цоколя уходит ниже самой низкой земли под следом, м.
 * Нужен не «на всякий случай», а по счёту: землю мы щупаем решёткой,
 * а нарисована она треугольниками, и настоящая низшая точка может оказаться
 * между узлами щупа. Шаг щупа 1.5 м при предельном уклоне полотна 8% даёт
 * промах до 12 см; 25 см перекрывают его вдвое.
 */
export const ЗАПАС = 0.25;

/**
 * Предел высоты цоколя, м. Выше — это уже не цоколь, а подпорная стена
 * с домом наверху: такое место в жизни либо террасируют, либо не застраивают.
 * Высота взята как этаж (3 м) минус порог: цоколь ростом с этаж ещё читается
 * цоколем-полуподвалом, выше — нет.
 */
export const ПРЕДЕЛ_ЦОКОЛЯ = 2.55;

/** Шаг щупа по следу дома, м. Мельче — дороже и ничего не меняет. */
const ШАГ_ЩУПА = 1.5;

export interface След {
  /** Середина следа по земле и куда смотрит фасад, радианы. */
  readonly x: number;
  readonly z: number;
  readonly курс: number;
  /** По фронту и вглубь, м. */
  readonly ширина: number;
  readonly глубина: number;
}

export interface Площадка {
  /** Отметка чистого пола первого этажа, м. Ровная — она и есть пол. */
  readonly пол: number;
  /** Низ цоколя, м. Ниже самой низкой земли под следом. */
  readonly подошва: number;
  /** Высота цоколя, м. Вычисляется из земли, а не задаётся. */
  readonly цоколь: number;
  /** Перепад земли под следом, м: сколько именно берёт на себя цоколь. */
  readonly перепад: number;
  /** Место слишком крутое: цоколь потребовался бы выше предела. */
  readonly крутоДляДома: boolean;
}

/**
 * Площадка под следом дома.
 *
 * `земля` — та же самая земля, по которой едет колесо и ходит человек.
 * Второй земли не существует (инвариант мира), поэтому сюда передаётся
 * именно она, а не отдельный «рельеф для домов».
 *
 * `запас` — насколько щупать шире стен. Цоколь рисуется чуть шире дома,
 * и земля прямо у его грани тоже обязана быть накрыта.
 */
export function площадкаПодСледом(
  след: След,
  земля: (x: number, z: number) => number,
  запасПоБокам = 0.2,
): Площадка {
  const c = Math.cos(след.курс), s = Math.sin(след.курс);
  const пол_ш = след.ширина / 2 + запасПоБокам;
  const пол_г = след.глубина / 2 + запасПоБокам;
  // щуп всегда попадает В УГЛЫ: иначе самая низкая точка следа может
  // оказаться между узлами, и цоколь не достанет до земли именно там,
  // где это виднее всего
  const пош = Math.max(2, Math.ceil((пол_ш * 2) / ШАГ_ЩУПА));
  const пог = Math.max(2, Math.ceil((пол_г * 2) / ШАГ_ЩУПА));

  let низ = Infinity, верх = -Infinity;
  for (let i = 0; i <= пош; i++) {
    const dx = -пол_ш + (пол_ш * 2 * i) / пош;
    for (let j = 0; j <= пог; j++) {
      const dz = -пол_г + (пол_г * 2 * j) / пог;
      const y = земля(след.x + dx * c - dz * s, след.z + dx * s + dz * c);
      if (y < низ) низ = y;
      if (y > верх) верх = y;
    }
  }

  const пол = верх + ПОРОГ;
  const подошва = низ - ЗАПАС;
  return {
    пол,
    подошва,
    цоколь: пол - подошва,
    перепад: верх - низ,
    крутоДляДома: пол - подошва > ПРЕДЕЛ_ЦОКОЛЯ,
  };
}

/** Ступень уличной лестницы, м. СП 54.13330 / 59.13330: подъём не выше 0.15, проступь не уже 0.30. */
export const СТУПЕНЬ = { подъём: 0.15, проступь: 0.3 };
/** Площадка крыльца перед дверью, м: глубже козырька (1.1) и шире двери на полметра с каждой стороны. */
export const КРЫЛЬЦО = { глубина: 1.4, ширина: 2.5 };

/** Плита крыльца: площадка или ступень. Середина по земле, курс длины, верх и низ. */
export interface Плита {
  readonly x: number;
  readonly z: number;
  readonly курс: number;
  readonly длина: number;
  readonly ширина: number;
  readonly верх: number;
  readonly низ: number;
}

/**
 * КРЫЛЬЦО — как дверь встречается с землёй.
 *
 * Пол дома ровный и стоит на пороге выше САМОЙ ВЫСОКОЙ земли под домом,
 * а у двери земля бывает ниже пола и на два с половиной метра. До 24.09
 * дверь так и висела над газоном: Алекс — «дверь подъезда тупо висит
 * в воздухе». Крыльцо выводится из двух чисел — пола и земли у двери, —
 * поэтому «дверь, до которой не дойти» невыразима: ступеней ровно столько,
 * сколько нужно, чтобы с пола сойти на землю, и последняя ступень кончается
 * у самой земли, где бы та ни оказалась.
 *
 * Лестница идёт прямо от двери, если вся она ложится на газон (`можно`);
 * иначе — вдоль стены, в ту сторону, где земля ниже. Прямая лестница у двери
 * на тротуар улицы перегородила бы тротуар, а у подъезда рядом с проездом
 * при перепаде в два метра дошла бы до асфальта: 24.09 таких было 66 из 1333.
 */
export function крыльцо(
  дверь: { x: number; z: number; nx: number; nz: number },
  пол: number,
  земля: (x: number, z: number) => number,
  можно: (x: number, z: number) => boolean,
): Плита[] {
  const прямо = лестница(дверь, пол, земля, false);
  const легла = прямо.every((п) => {
    const ux = Math.cos(п.курс), uz = Math.sin(п.курс);
    return можно(п.x, п.z) && можно(п.x + ux * п.длина / 2, п.z + uz * п.длина / 2);
  });
  return легла ? прямо : лестница(дверь, пол, земля, true);
}

function лестница(
  дверь: { x: number; z: number; nx: number; nz: number },
  пол: number,
  земля: (x: number, z: number) => number,
  вдольСтены: boolean,
): Плита[] {
  const nx = дверь.nx, nz = дверь.nz;
  const курсНаружу = Math.atan2(nz, nx);
  const верхПлощадки = пол - 0.02;
  const глубина = вдольСтены ? 1.2 : КРЫЛЬЦО.глубина;
  const низПод = (x: number, z: number, ах: number, аз: number, пх: number, пз: number): number => Math.min(
    земля(x + ах + пх, z + аз + пз), земля(x + ах - пх, z + аз - пз),
    земля(x - ах + пх, z - аз + пз), земля(x - ах - пх, z - аз - пз)) - 0.15;
  const плиты: Плита[] = [];
  const сx = дверь.x + nx * глубина / 2, сz = дверь.z + nz * глубина / 2;
  плиты.push({
    x: сx, z: сz, курс: курсНаружу, длина: глубина, ширина: КРЫЛЬЦО.ширина,
    верх: верхПлощадки,
    низ: низПод(сx, сz, nx * глубина / 2, nz * глубина / 2, -nz * КРЫЛЬЦО.ширина / 2, nx * КРЫЛЬЦО.ширина / 2),
  });
  // куда сходят ступени: наружу или вдоль стены — туда, где земля ниже
  let ux = nx, uz = nz, отX = дверь.x + nx * глубина, отZ = дверь.z + nz * глубина, поперёк = КРЫЛЬЦО.ширина;
  if (вдольСтены) {
    const лx = -nz, лz = nx;
    const слева = земля(сx + лx * 3, сz + лz * 3), справа = земля(сx - лx * 3, сz - лz * 3);
    const знак = слева <= справа ? 1 : -1;
    ux = лx * знак; uz = лz * знак;
    отX = сx + ux * КРЫЛЬЦО.ширина / 2; отZ = сz + uz * КРЫЛЬЦО.ширина / 2;
    поперёк = глубина;
  }
  // потолок — предел цоколя с запасом: дальше земли ниже пола не бывает (ПРЕДЕЛ_ЦОКОЛЯ)
  for (let i = 1; i <= Math.ceil((ПРЕДЕЛ_ЦОКОЛЯ * 2) / СТУПЕНЬ.подъём); i++) {
    const верх = верхПлощадки - i * СТУПЕНЬ.подъём;
    const d = (i - 0.5) * СТУПЕНЬ.проступь;
    const x = отX + ux * d, z = отZ + uz * d;
    // ступень, ушедшая под землю, не нужна: сошли раньше
    if (верх < земля(x, z) + 0.03) break;
    плиты.push({
      x, z, курс: Math.atan2(uz, ux), длина: СТУПЕНЬ.проступь, ширина: поперёк, верх,
      низ: низПод(x, z, ux * СТУПЕНЬ.проступь / 2, uz * СТУПЕНЬ.проступь / 2, -uz * поперёк / 2, ux * поперёк / 2),
    });
    // с этой ступени на землю — не выше одного подъёма: сошли
    const край = земля(x + ux * СТУПЕНЬ.проступь / 2, z + uz * СТУПЕНЬ.проступь / 2);
    if (верх - край <= СТУПЕНЬ.подъём) break;
  }
  return плиты;
}
