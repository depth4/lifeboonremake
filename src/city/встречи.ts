/**
 * Встречи: двое знакомых сходятся на тротуаре — останавливаются, говорят,
 * расходятся.
 *
 * Алекс: «проследить за типом и увидеть, как он… встречает знакомого на
 * улице». Для этого нужны две вещи: кто кого знает и что бывает, когда
 * знакомые сходятся. Отдельный файл, а не `жизнь.ts`: там — кто на улице
 * по распорядку; здесь — отклонения от распорядка между людьми, и сюда же
 * ляжет следующий слой (потребности, знакомства, ссоры).
 *
 * ЗНАКОМСТВО НЕ ХРАНИТСЯ. Знакомы ли двое — вычисляется из пары номеров,
 * их домов и дел и сида посёлка, как и сам житель (решение 044). Пара
 * упорядочивается ДО броска, поэтому «A знает B, а B не знает A» записать
 * нечем, и «список знакомых разошёлся с другим списком» — тоже: списка нет.
 *
 * РАЗГОВОР — ОДНА ЗАПИСЬ НА ДВОИХ. Оба пешехода смотрят на неё; кончается
 * она для обоих одним сравнением часов с одним `до`. «Один договорил,
 * другой всё говорит» невыразимо. Куда смотрит говорящий, вычисляется из
 * места собеседника (`walkerPose`), а стоит он потому, что шаг говорящих
 * не двигает (`moveWalkers`).
 *
 * ВСТРЕЧА НЕ ЗАВИСИТ ОТ ПОРЯДКА. Пары-кандидаты сначала собираются все,
 * потом сортируются по расстоянию и номерам, и только потом разбираются:
 * кто с кем заговорит, решает расстановка людей, а не их место в списке.
 *
 * Про экран этот файл не знает ничего.
 */

import type { World } from '../world/world.ts';
import { type Walker, walkerPose } from './walkers.ts';
import { type Житель, type Зачем, type Расселение, СЕКУНД_В_ЧАСЕ, СУТКИ, кто, чем } from './житель.ts';

/** Откуда двое знают друг друга. */
export type Круг = 'семья' | 'сосед' | 'коллега' | 'одноклассник' | 'по саду' | 'приятель';

/**
 * Какая доля пар одного круга знакома.
 *
 * Семья — живущие в одной квартире: знакомы всегда.
 * Сосед: ВЦИОМ «Мы и наши соседи» — в многоквартирном доме 37% знают всех
 * или большинство соседей по дому, 46% — почти всех по подъезду, 75% —
 * соседей по площадке. Подъездов мы не строим; «знаешь соседа по дому
 * с долей 0.4» — середина этих цифр. Коллеги: мест работы в «городе» 13,
 * по 75–180 человек; знают по имени свой отдел и ещё немного — около
 * четверти (при 0.7 каждый знал бы сотню коллег). Класс — около 25 из
 * трёхсот с лишним учеников школы, плюс друзья из других классов. Группа
 * сада — около 20 из сотни. Приятели по городу — родня, бывшие
 * одноклассники, знакомые знакомых: 0.004 даёт двадцать с лишним на город
 * в пять тысяч. Кроме соседей — ПРЕДПОЛАГАЮ, источника нет.
 */
const ЗНАКОМЫ: Record<Круг, number> = {
  семья: 1, сосед: 0.4, коллега: 0.2, одноклассник: 0.12, 'по саду': 0.25, приятель: 0.004,
};
/** Свой бросок на каждый круг: сосед-одноклассник знаком по одной из двух причин. */
const СОЛЬ: Record<Круг, number> = { семья: 10, сосед: 11, коллега: 12, одноклассник: 13, 'по саду': 14, приятель: 15 };
const КРУГ_ДЕЛА = { работа: 'коллега', школа: 'одноклассник', сад: 'по саду' } as const;

/** Число 0..1 из пары номеров: одна пара — одно число, в любом порядке вызова. */
function доляПары(младший: number, старший: number, сид: number, соль: number): number {
  let s = (Math.imul(младший + 1, 0x9e3779b1) ^ Math.imul(старший + 1, 0x85ebca77)
    ^ Math.imul(сид + соль * 0x632be5ab, 0xc2b2ae35)) >>> 0;
  s = Math.imul(s ^ (s >>> 16), 0x21f0aaad) >>> 0;
  s = Math.imul(s ^ (s >>> 15), 0x735a2d97) >>> 0;
  return ((s ^ (s >>> 15)) >>> 0) / 4294967296;
}

/** Знакомы ли двое и откуда. null — чужие. */
type Кто = Pick<Житель, 'номер' | 'дом' | 'квартира' | 'занятие' | 'дело'>;
export function знакомы(сид: number, a: Кто, b: Кто): Круг | null {
  if (a.номер === b.номер) return null;
  const [x, y] = a.номер < b.номер ? [a, b] : [b, a];
  const круги: Круг[] = [];
  if (x.дом === y.дом && x.квартира.первый === y.квартира.первый) круги.push('семья');
  if (x.дом === y.дом) круги.push('сосед');
  // одно дело — не дом и не «за городом»: за городом у каждого своя работа
  if (x.занятие === y.занятие && x.занятие !== 'дома' && x.дело === y.дело && x.дело !== -1 && x.дело !== x.дом) {
    круги.push(КРУГ_ДЕЛА[x.занятие]);
  }
  круги.push('приятель');
  for (const к of круги) if (доляПары(x.номер, y.номер, сид, СОЛЬ[к]) < ЗНАКОМЫ[к]) return к;
  return null;
}

/**
 * Основа жителя (дом, занятие, дело) — раз на жителя. Это не вторая правда:
 * основа вычисляется из номера и сида, и у одного расселения устареть ей
 * нечему. Пока пара идёт сквозь кольцо встречи, о ней спрашивают каждый кадр.
 */
const основы = new WeakMap<Расселение, Map<number, Кто>>();
function основа(р: Расселение, номер: number): Кто {
  let все = основы.get(р);
  if (все === undefined) { все = new Map(); основы.set(р, все); }
  let о = все.get(номер);
  if (о === undefined) { о = чем(р, номер); все.set(номер, о); }
  return о;
}

/** Один разговор двоих — тот самый, на который смотрят оба пешехода. */
export interface Разговор {
  readonly a: Walker;
  readonly b: Walker;
  readonly круг: Круг;
  /** Часы жизни города: когда заговорили и когда разойдутся. */
  readonly от: number;
  readonly до: number;
}

/**
 * Кольцо встречи, м: знакомые, идущие навстречу, останавливаются, когда
 * между ними от ВПЛОТНУЮ до СХОДЯТСЯ, — это и есть расстояние разговора,
 * на вытянутую руку. Идущие навстречу проходят кольцо (0.6 м) за четверть
 * секунды, и шаг жизни (не больше 0.1 с, 0.26 м сближения) его не
 * перескакивает. Ближе ВПЛОТНУЮ бывают только те, кто вышел на улицу
 * прямо у другого: они уже разминулись, и говорить «сквозь» друг друга
 * им нечем — 25.09 без нижнего края нашлась пара в 0.4 м.
 */
export const СХОДЯТСЯ = 1.6;
export const ВПЛОТНУЮ = 1.0;
/**
 * Окно поиска по метке вдоль улицы, м осевой. Тротуар на повороте бывает
 * до четырёх раз короче осевой (`растяжение` в `walkers.ts`), и кольцо
 * встречи в метрах тротуара — до четырёх колец по осевой.
 */
const ОКНО = 4 * СХОДЯТСЯ;

/**
 * Сколько говорят, секунд. Кто идёт на работу, в школу или в сад, —
 * спешит: «привет, как дела, ну давай» — десять-тридцать секунд. Остальные
 * стоят от минуты до четырёх (ПРЕДПОЛАГАЮ, замера нет).
 */
const СПЕШАТ = new Set<Зачем>(['работа', 'школа', 'сад']);
const НАСПЕХ = [8, 30] as const;
const ПОГОВОРИТЬ = [40, 240] as const;

/**
 * Встречи этого часа: кончившиеся разговоры — расходятся, сошедшиеся
 * знакомые — заговаривают. Звать каждый шаг после движения пешеходов.
 *
 * `разговоры` — разговоры суток, по ним же: «эти двое сегодня уже
 * говорили» — второй раз за день пара не останавливается.
 * `безКонца` — заведомо сломанный вариант: разговор не кончается никогда.
 */
export function встречи(
  world: World, р: Расселение, пешие: readonly Walker[], разговоры: Разговор[], часЖизни: number,
  безКонца = false,
): void {
  if (!безКонца) for (const w of пешие) if (w.разговор !== null && часЖизни >= w.разговор.до) w.разговор = null;

  /**
   * Встречаются идущие по ОДНОМУ ТРОТУАРУ — одна улица, одна сторона: через
   * дорогу машут рукой, а не останавливаются. Поэтому соседей ищут не по
   * всему миру, а в ряду тротуара по метке вдоль улицы, и место в мире
   * считается только для редких кандидатов. Первая редакция считала место
   * каждого пешехода каждый кадр: на «большом городе» в час пик 2.7 мс.
   */
  const тротуары = new Map<number, Walker[]>();
  for (const w of пешие) {
    if (w.житель < 0 || w.разговор !== null || w.state !== 'идёт' || w.crossing > 0) continue;
    const к = w.shape * 2 + (w.side > 0 ? 1 : 0);
    const ряд = тротуары.get(к);
    if (ряд === undefined) тротуары.set(к, [w]); else ряд.push(w);
  }

  // все пары, сошедшиеся навстречу друг другу в кольце встречи; место — раз на пешехода
  const пары: { a: Walker; b: Walker; d: number }[] = [];
  const места = new Map<Walker, { x: number; z: number }>();
  const где = (w: Walker): { x: number; z: number } => {
    let п = места.get(w);
    if (п === undefined) { п = walkerPose(world, w); места.set(w, п); }
    return п;
  };
  for (const [, ряд] of тротуары) {
    if (ряд.length < 2) continue;
    ряд.sort((p, q) => p.s - q.s || p.житель - q.житель);
    for (let i = 0; i < ряд.length; i++) {
      const зад = ряд[i];
      for (let j = i + 1; j < ряд.length && ряд[j].s - зад.s <= ОКНО; j++) {
        const перёд = ряд[j];
        // навстречу — разрыв сокращается; расходящимся после разговора сойтись нечем
        if (перёд.dir * перёд.speed - зад.dir * зад.speed >= 0) continue;
        const pa = где(зад), pb = где(перёд);
        const d = Math.hypot(pb.x - pa.x, pb.z - pa.z);
        if (d > СХОДЯТСЯ || d < ВПЛОТНУЮ) continue;
        const [a, b] = зад.житель < перёд.житель ? [зад, перёд] : [перёд, зад];
        пары.push({ a, b, d });
      }
    }
  }
  if (пары.length === 0) return;

  /**
   * Разбор НЕ зависит от порядка списка: ближайшие пары первыми, при
   * равенстве — по номерам. Тот, кому встретились двое знакомых сразу,
   * заговорит с ближним, в каком бы порядке их ни держал список.
   */
  пары.sort((p, q) => p.d - q.d || p.a.житель - q.a.житель || p.b.житель - q.b.житель);
  const день = Math.floor(часЖизни / СУТКИ);
  const заняты = new Set<Walker>();
  for (const { a, b } of пары) {
    if (заняты.has(a) || заняты.has(b)) continue;
    // в записи пара всегда младшим номером вперёд — так её и ищем
    if (разговоры.some((р2) => р2.a.житель === a.житель && р2.b.житель === b.житель)) continue;
    // знакомство — по дому и делу; распорядок (дорогой) — только у знакомых
    const круг = знакомы(р.посёлок.сид, основа(р, a.житель), основа(р, b.житель));
    if (круг === null) continue;
    const жа = кто(р, a.житель), жб = кто(р, b.житель);
    const спешат = СПЕШАТ.has(жа.день[a.дорога]?.зачем ?? 'дом') || СПЕШАТ.has(жб.день[b.дорога]?.зачем ?? 'дом');
    const [от, до] = спешат ? НАСПЕХ : ПОГОВОРИТЬ;
    const секунд = от + (до - от) * доляПары(a.житель, b.житель, р.посёлок.сид, 100 + день);
    const разговор: Разговор = { a, b, круг, от: часЖизни, до: часЖизни + секунд / СЕКУНД_В_ЧАСЕ };
    a.разговор = b.разговор = разговор;
    разговоры.push(разговор);
    заняты.add(a);
    заняты.add(b);
  }
}
