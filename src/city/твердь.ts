/**
 * ТВЕРДЬ — то, сквозь что не проходят: дома, крыльца, стволы, столбы,
 * вещи двора.
 *
 * До 25.09 всё это было только нарисовано: машина проезжала дом насквозь,
 * пешеход — ствол и лавку (Алекс: «какого хуя у домов нет физики»).
 *
 * Что сделано невыразимым:
 *
 * - **нарисовано, но не твёрдо.** Твердь собирается из ТЕХ ЖЕ записей, что
 *   уходят на экран: дом — из того же `Дом`, вещь двора — из тех же частей
 *   модели (`частиВещи`), ствол — из той же породы и масштаба. Отдельного
 *   списка преград нет, и разойтись ему не с чем;
 * - **пролёт сквозь тонкое.** Машина упирается на каждом шаге физики
 *   (1/300 с — 9 см на 100 км/ч), а не раз в кадр, и сторону выталкивания
 *   решает середина тела, которая за шаг сквозь преграду не проходит.
 *
 * Мягкое не твёрдо, и это правда, а не исключение: куст машина продавливает,
 * пешеход проходит сквозь ветки. Низкое — тоже: резиновое покрытие площадки
 * и бортик ниже ступени под ногами, а не на пути.
 *
 * Про экран этот файл не знает ничего.
 */

/** Прямоугольник в плане: середина, куда смотрит «вдоль», полуразмеры. */
export interface Коробка {
  readonly вид: 'коробка';
  readonly x: number; readonly z: number;
  /** Направление «вдоль»: (cos, sin) курса. «Поперёк» — (−sin, cos). */
  readonly cos: number; readonly sin: number;
  readonly вдоль: number; readonly поперёк: number;
}
/** Круг в плане: ствол, столб, стойка. */
export interface Круг {
  readonly вид: 'круг';
  readonly x: number; readonly z: number; readonly r: number;
}
export type Форма = Коробка | Круг;

/** Коробка по середине, курсу и ПОЛНЫМ размерам: длина вдоль курса, ширина поперёк. */
export const коробка = (x: number, z: number, курс: number, длина: number, ширина: number): Коробка => ({
  вид: 'коробка', x, z, cos: Math.cos(курс), sin: Math.sin(курс), вдоль: длина / 2, поперёк: ширина / 2,
});
export const круг = (x: number, z: number, r: number): Круг => ({ вид: 'круг', x, z, r });

/**
 * Выше этого над землёй — на пути, ниже — под ногами, м. Ступень крыльца
 * 0.15, бордюр 0.15: их перешагивают. Колено поднимается до 0.3.
 */
export const СТУПЕНЬ = 0.3;
/** Выше этого — над головой и над крышей машины: перекладина качелей не преграда. */
export const РОСТ = 1.9;
/**
 * Отскок удара — один на все удары кузова: о чужую машину (`traffic.ts`)
 * и о твердь. Смятое железо почти не пружинит.
 */
export const ОТСКОК = 0.12;
/** Трение кузова о стену при ударе: железо по штукатурке и бетону. */
const ТРЕНИЕ = 0.4;
/** Сторона клетки поиска, м. */
const КЛЕТКА = 8;

/**
 * Часть вещи — как в `модели.ts`: коробка или цилиндр, середина, размеры,
 * наклоны вокруг поперечной (z) и продольной (x) осей.
 */
export interface ЧастьВещи {
  readonly форма: 'коробка' | 'цилиндр';
  readonly x: number; readonly y: number; readonly z: number;
  readonly sx: number; readonly sy: number; readonly sz: number;
  readonly наклонZ?: number; readonly наклонX?: number;
}

/**
 * Твердь вещи двора — из её же частей: каждая часть, что поднимается выше
 * ступени и начинается ниже роста, — преграда размером со свой след на земле.
 * Ноги качелей и борта коробки твёрдые, покрытие площадки — под ногами,
 * перекладина качелей — над головой.
 */
export function формыВещи(
  части: readonly ЧастьВещи[], место: { x: number; z: number; курс: number },
): Форма[] {
  const c = Math.cos(место.курс), s = Math.sin(место.курс);
  const вМир = (a: number, b: number): { x: number; z: number } =>
    ({ x: место.x + a * c - b * s, z: место.z + a * s + b * c });
  const формы: Форма[] = [];
  for (const ч of части) {
    if (ч.форма === 'цилиндр') {
      if (ч.y + ч.sy / 2 <= СТУПЕНЬ || ч.y - ч.sy / 2 >= РОСТ) continue;
      const м = вМир(ч.x, ч.z);
      формы.push(круг(м.x, м.z, ч.sx / 2));
      continue;
    }
    // восемь углов коробки с наклоном — тем же, что у сетки (Эйлер XYZ: сперва z, потом x)
    const cz = Math.cos(ч.наклонZ ?? 0), sz = Math.sin(ч.наклонZ ?? 0);
    const cx = Math.cos(ч.наклонX ?? 0), sx = Math.sin(ч.наклонX ?? 0);
    let a0 = Infinity, a1 = -Infinity, b0 = Infinity, b1 = -Infinity, y0 = Infinity, y1 = -Infinity;
    for (const i of [-1, 1]) for (const j of [-1, 1]) for (const k of [-1, 1]) {
      const px = (i * ч.sx) / 2, py = (j * ч.sy) / 2, pz = (k * ч.sz) / 2;
      const x1 = px * cz - py * sz, y1v = px * sz + py * cz;
      const y2 = y1v * cx - pz * sx, z2 = y1v * sx + pz * cx;
      a0 = Math.min(a0, x1); a1 = Math.max(a1, x1);
      b0 = Math.min(b0, z2); b1 = Math.max(b1, z2);
      y0 = Math.min(y0, y2); y1 = Math.max(y1, y2);
    }
    if (ч.y + y1 <= СТУПЕНЬ || ч.y + y0 >= РОСТ) continue;
    const м = вМир(ч.x + (a0 + a1) / 2, ч.z + (b0 + b1) / 2);
    формы.push(коробка(м.x, м.z, место.курс, a1 - a0, b1 - b0));
  }
  return формы;
}

/** Твердь, разложенная по клеткам: спрашивают всегда о малом месте. */
export interface Твердь {
  readonly формы: readonly Форма[];
  readonly клетки: ReadonlyMap<number, readonly number[]>;
}

const ключ = (i: number, j: number): number => (i + 32768) * 65536 + (j + 32768);
const охват = (ф: Форма): number => (ф.вид === 'круг' ? ф.r : Math.hypot(ф.вдоль, ф.поперёк));

export function собратьТвердь(формы: readonly Форма[]): Твердь {
  const клетки = new Map<number, number[]>();
  формы.forEach((ф, n) => {
    const r = охват(ф);
    for (let i = Math.floor((ф.x - r) / КЛЕТКА); i <= Math.floor((ф.x + r) / КЛЕТКА); i++) {
      for (let j = Math.floor((ф.z - r) / КЛЕТКА); j <= Math.floor((ф.z + r) / КЛЕТКА); j++) {
        const к = ключ(i, j);
        const в = клетки.get(к);
        if (в) в.push(n); else клетки.set(к, [n]);
      }
    }
  });
  return { формы, клетки };
}

export const ПУСТО: Твердь = собратьТвердь([]);

/** Формы, чьи клетки задевает круг (x, z, r). Каждая — один раз. */
function рядом(т: Твердь, x: number, z: number, r: number, куда: Форма[]): void {
  куда.length = 0;
  const видели = new Set<number>();
  for (let i = Math.floor((x - r) / КЛЕТКА); i <= Math.floor((x + r) / КЛЕТКА); i++) {
    for (let j = Math.floor((z - r) / КЛЕТКА); j <= Math.floor((z + r) / КЛЕТКА); j++) {
      for (const n of т.клетки.get(ключ(i, j)) ?? []) {
        if (видели.has(n)) continue;
        видели.add(n);
        куда.push(т.формы[n]);
      }
    }
  }
}

/**
 * Касание круга (x, z, R) с формой: нормаль ОТ формы к кругу и глубина.
 * null — не касаются.
 */
function кругО(ф: Форма, x: number, z: number, R: number): { nx: number; nz: number; глубина: number } | null {
  if (ф.вид === 'круг') {
    const dx = x - ф.x, dz = z - ф.z, d = Math.hypot(dx, dz);
    if (d >= R + ф.r) return null;
    return d > 1e-9 ? { nx: dx / d, nz: dz / d, глубина: R + ф.r - d } : { nx: 1, nz: 0, глубина: R + ф.r };
  }
  // в осях коробки
  const dx = x - ф.x, dz = z - ф.z;
  const a = dx * ф.cos + dz * ф.sin, b = -dx * ф.sin + dz * ф.cos;
  const ca = Math.max(-ф.вдоль, Math.min(ф.вдоль, a)), cb = Math.max(-ф.поперёк, Math.min(ф.поперёк, b));
  const da = a - ca, db = b - cb, d = Math.hypot(da, db);
  if (d > 1e-9) {
    if (d >= R) return null;
    return { nx: (da * ф.cos - db * ф.sin) / d, nz: (da * ф.sin + db * ф.cos) / d, глубина: R - d };
  }
  // середина круга внутри коробки: наружу через ближнюю грань
  const доA = ф.вдоль - Math.abs(a), доB = ф.поперёк - Math.abs(b);
  if (доA < доB) {
    const k = a >= 0 ? 1 : -1;
    return { nx: k * ф.cos, nz: k * ф.sin, глубина: доA + R };
  }
  const k = b >= 0 ? 1 : -1;
  return { nx: -k * ф.sin, nz: k * ф.cos, глубина: доB + R };
}

const найденные: Форма[] = [];

/**
 * ПЕШЕХОД: пройти из точки в точку кругом радиуса R, не заходя в твердь.
 *
 * Упёрся — остаётся у преграды и СКОЛЬЗИТ вдоль неё остатком шага:
 * выталкивается только по нормали, вдоль стены движение сохраняется.
 * Без скольжения человек прилипает к дому: задел плечом фасад — и встал.
 * Длинный шаг режется на куски не длиннее полурадиуса: сквозь борт
 * хоккейной коробки не проскочить даже в долгом кадре.
 *
 * `ещё` — подвижная твердь этого мгновения (машины): её не раскладывают
 * по клеткам, она каждый кадр своя.
 */
export function пройти(
  т: Твердь, x0: number, z0: number, x1: number, z1: number, R: number,
  ещё: readonly Форма[] = [],
): { x: number; z: number } {
  const путь = Math.hypot(x1 - x0, z1 - z0);
  const кусков = Math.max(1, Math.ceil(путь / (R * 0.5)));
  let x = x0, z = z0;
  for (let к = 1; к <= кусков; к++) {
    x += (x1 - x0) / кусков;
    z += (z1 - z0) / кусков;
    рядом(т, x, z, R + 1, найденные);
    for (let проход = 0; проход < 4; проход++) {
      let сдвинули = false;
      for (const ф of найденные.length ? [...найденные, ...ещё] : ещё) {
        const к2 = кругО(ф, x, z, R);
        if (к2 === null) continue;
        x += к2.nx * к2.глубина;
        z += к2.nz * к2.глубина;
        сдвинули = true;
      }
      if (!сдвинули) break;
    }
  }
  return { x, z };
}

/** Тело машины для удара: где, куда смотрит и как движется. Меняется на месте. */
export interface Кузов {
  x: number; z: number; yaw: number;
  vx: number; vz: number; yawRate: number;
}

/** Углы прямоугольника в мире. */
function углы(x: number, z: number, c: number, s: number, ha: number, hb: number): { x: number; z: number }[] {
  return [[1, 1], [1, -1], [-1, -1], [-1, 1]].map(([i, j]) => ({
    x: x + i * ha * c - j * hb * s, z: z + i * ha * s + j * hb * c,
  }));
}

/** Лежит ли точка в коробке (с запасом `д`). */
function внутри(ф: Коробка, x: number, z: number, д = 1e-3): boolean {
  const dx = x - ф.x, dz = z - ф.z;
  return Math.abs(dx * ф.cos + dz * ф.sin) <= ф.вдоль + д && Math.abs(-dx * ф.sin + dz * ф.cos) <= ф.поперёк + д;
}

/**
 * Касание кузова с формой: нормаль ОТ формы к кузову, глубина и точка
 * касания (от неё зависит, закрутит ли машину). Коробка с коробкой —
 * по разделяющим осям, как чужие машины в `traffic.ts`: ось наименьшего
 * перекрытия и есть нормаль удара, а сторону решает середина кузова.
 */
function кузовО(
  ф: Форма, к: Коробка,
): { nx: number; nz: number; глубина: number; px: number; pz: number } | null {
  if (ф.вид === 'круг') {
    const dx = ф.x - к.x, dz = ф.z - к.z;
    const a = dx * к.cos + dz * к.sin, b = -dx * к.sin + dz * к.cos;
    const ca = Math.max(-к.вдоль, Math.min(к.вдоль, a)), cb = Math.max(-к.поперёк, Math.min(к.поперёк, b));
    const da = a - ca, db = b - cb, d = Math.hypot(da, db);
    const px = к.x + ca * к.cos - cb * к.sin, pz = к.z + ca * к.sin + cb * к.cos;
    if (d > 1e-9) {
      if (d >= ф.r) return null;
      // нормаль от столба к кузову — против направления «кузов → столб»
      return { nx: -(da * к.cos - db * к.sin) / d, nz: -(da * к.sin + db * к.cos) / d, глубина: ф.r - d, px, pz };
    }
    const доA = к.вдоль - Math.abs(a), доB = к.поперёк - Math.abs(b);
    if (доA < доB) {
      const k = a >= 0 ? -1 : 1;
      return { nx: k * к.cos, nz: k * к.sin, глубина: доA + ф.r, px: ф.x, pz: ф.z };
    }
    const k = b >= 0 ? -1 : 1;
    return { nx: -k * к.sin, nz: k * к.cos, глубина: доB + ф.r, px: ф.x, pz: ф.z };
  }
  const dx = к.x - ф.x, dz = к.z - ф.z;
  let глубина = Infinity, nx = 0, nz = 0;
  for (const [ux, uz] of [[к.cos, к.sin], [-к.sin, к.cos], [ф.cos, ф.sin], [-ф.sin, ф.cos]]) {
    const досягК = Math.abs(ux * к.cos + uz * к.sin) * к.вдоль + Math.abs(-ux * к.sin + uz * к.cos) * к.поперёк;
    const досягФ = Math.abs(ux * ф.cos + uz * ф.sin) * ф.вдоль + Math.abs(-ux * ф.sin + uz * ф.cos) * ф.поперёк;
    const зазор = dx * ux + dz * uz;
    const перекрытие = досягК + досягФ - Math.abs(зазор);
    if (перекрытие <= 0) return null;
    if (перекрытие < глубина) {
      глубина = перекрытие;
      const знак = зазор >= 0 ? 1 : -1;
      nx = ux * знак; nz = uz * знак;
    }
  }
  // точка касания: самый глубокий угол кузова в форме, иначе самый глубокий угол формы в кузове
  const уК = углы(к.x, к.z, к.cos, к.sin, к.вдоль, к.поперёк).sort((p, q) => (p.x * nx + p.z * nz) - (q.x * nx + q.z * nz));
  const уФ = углы(ф.x, ф.z, ф.cos, ф.sin, ф.вдоль, ф.поперёк).sort((p, q) => (q.x * nx + q.z * nz) - (p.x * nx + p.z * nz));
  const точка = внутри(ф, уК[0].x, уК[0].z) ? уК[0] : внутри(к, уФ[0].x, уФ[0].z) ? уФ[0] : { x: к.x - nx * к.вдоль, z: к.z - nz * к.вдоль };
  return { nx, nz, глубина, px: точка.x, pz: точка.z };
}

/**
 * МАШИНА: упереть кузов в твердь. Вызывается после КАЖДОГО шага физики.
 *
 * Удар — то же сохранение импульса, что о чужую машину, только у стены
 * масса бесконечна: скорость точки касания вдоль нормали гасится и
 * отражается с отскоком ОТСКОК, вдоль стены её ест трение, но не больше,
 * чем позволяет сила удара. Точка касания не в середине — поэтому удар
 * углом о столб разворачивает машину, а лобовой в стену — нет.
 *
 * Возвращает, с какой скоростью ударились (м/с по нормали), — для приборки
 * и проверок; 0 — не касались.
 */
export function упереть(
  т: Твердь, кузов: Кузов, габарит: { длина: number; ширина: number },
  масса: number, инерция: number,
): number {
  let удар = 0;
  рядом(т, кузов.x, кузов.z, Math.hypot(габарит.длина, габарит.ширина) / 2 + 0.5, найденные);
  for (const ф of найденные) {
    const к = коробка(кузов.x, кузов.z, кузов.yaw, габарит.длина, габарит.ширина);
    const к2 = кузовО(ф, к);
    if (к2 === null) continue;
    // вытолкнуть из перекрытия: стена не двигается, двигается машина
    кузов.x += к2.nx * к2.глубина;
    кузов.z += к2.nz * к2.глубина;
    const rx = к2.px - кузов.x, rz = к2.pz - кузов.z;
    const vx = кузов.vx - кузов.yawRate * rz, vz = кузов.vz + кузов.yawRate * rx;
    const vn = vx * к2.nx + vz * к2.nz;
    if (vn >= 0) continue;                              // уже расходятся
    const rn = rx * к2.nz - rz * к2.nx;
    const j = (-(1 + ОТСКОК) * vn) / (1 / масса + (rn * rn) / инерция);
    // вдоль стены: трение не больше, чем позволяет сила удара
    const tx = -к2.nz, tz = к2.nx;
    const vt = vx * tx + vz * tz;
    const rt = rx * tz - rz * tx;
    const jt = Math.max(-ТРЕНИЕ * j, Math.min(ТРЕНИЕ * j, -vt / (1 / масса + (rt * rt) / инерция)));
    кузов.vx += (j * к2.nx + jt * tx) / масса;
    кузов.vz += (j * к2.nz + jt * tz) / масса;
    кузов.yawRate += (j * rn + jt * rt) / инерция;
    удар = Math.max(удар, -vn);
  }
  return удар;
}

/** Насколько кузов зашёл в твердь, м: для проверок инварианта. 0 — не зашёл. */
export function глубинаКузова(т: Твердь, кузов: Кузов, габарит: { длина: number; ширина: number }): number {
  const к = коробка(кузов.x, кузов.z, кузов.yaw, габарит.длина, габарит.ширина);
  рядом(т, кузов.x, кузов.z, Math.hypot(габарит.длина, габарит.ширина) / 2 + 0.5, найденные);
  return найденные.reduce((м, ф) => Math.max(м, кузовО(ф, к)?.глубина ?? 0), 0);
}

/** Насколько круг (пешеход) зашёл в твердь, м. */
export function глубинаКруга(т: Твердь, x: number, z: number, R: number): number {
  рядом(т, x, z, R + 1, найденные);
  return найденные.reduce((м, ф) => Math.max(м, кругО(ф, x, z, R)?.глубина ?? 0), 0);
}
