/**
 * Радиус супермаркета — это радиус объекта ПЕРИОДИЧЕСКОГО спроса.
 * СП 42.13330: такие объекты обслуживают жилой район, радиус 1200 м.
 * Берём 1000 — с запасом внутрь норматива.
 */
export const РАДИУС_СУПЕРМАРКЕТА = 1000;

/** Сколько таких объектов нужно на столько-то жителей. Всегда вверх. */
export function сколькоНужно(людей: number): Record<Назначение, number> {
  const мест = (на1000: number): number => (людей * на1000) / 1000;
  return {
    жильё: 0, // жильё не считается штуками: оно и есть источник населения
    сад: Math.ceil(мест(НА_ТЫСЯЧУ.местВСаду) / ВМЕСТИМОСТЬ.сад),
    школа: Math.ceil(мест(НА_ТЫСЯЧУ.местВШколе) / ВМЕСТИМОСТЬ.школа),
    // магазинов у дома столько, сколько требует ПОКРЫТИЕ, а не площадь:
    // площадь добирает супермаркет. Здесь — только нижняя граница «хоть один».
    магазин: людей > 0 ? 1 : 0,
    супермаркет: 0, // считается после магазинов: см. сколькоСупермаркетов()
    // поликлиника — объект периодического спроса: одна на посёлок, дальше по людям
    поликлиника: людей < 1500 ? 0 : Math.ceil(людей / 20000),
  };
}

/** Сколько всего торговой площади требует норма, м². */
export function надоТорговли(людей: number): number {
  return Math.ceil((людей * (НА_ТЫСЯЧУ.торговляЕда + НА_ТЫСЯЧУ.торговляПрочее)) / 1000);
}

/**
 * Сколько супермаркетов добрать после магазинов у дома.
 *
 * Магазины у дома ставятся по покрытию и дают столько площади, сколько дают;
 * остаток нормы берёт на себя супермаркет. Поэтому «норма выполнена, а
 * магазины стоят в куче» стало невыразимо: лишней площади им не поручают.
 */
export function сколькоСупермаркетов(людей: number, магазинов: number): number {
  const остаток = надоТорговли(людей) - магазинов * ВМЕСТИМОСТЬ.магазин;
  return Math.max(0, Math.ceil(остаток / ВМЕСТИМОСТЬ.супермаркет));
}
