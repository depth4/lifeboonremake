/**
 * Самый узкий участок, какой бывает: по нему считается, влезет ли застройка
 * на сторону квартала вообще. Меньше этого участок не нарезается нигде.
 */
export function самыйУзкийУчасток(вид: keyof typeof ЗАСТРОЙКА): number {
  const ф = ЗАСТРОЙКА[вид].фронт;
  return Math.min(ф.магистральная.мин, ф.местная.мин);
}

