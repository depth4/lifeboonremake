/**
 * Что между домами: подход к подъезду и стоянка во дворе.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. `plan.ts` делит землю, `дом.ts` описывает здание,
 * `зелень.ts` сажает деревья. А то, ЧЕМ человек пользуется между улицей
 * и своей дверью, не принадлежит ни одному из них: подход начинается
 * у тротуара (это улица) и кончается у двери (это дом). Складывать его
 * в любой из двух файлов значило бы заставить их знать друг про друга.
 *
 * ЧТО СДЕЛАНО НЕВЫРАЗИМЫМ:
 *
 * - **подъезд, к которому не подойти.** Подход не расставляется и не
 *   хранится: он ВЫВОДИТСЯ из двери. Сколько дверей — столько подходов,
 *   и другого способа получить подход нет. Дверь без подхода записать негде;
 * - **подход, ведущий не туда.** Он идёт строго по курсу дома — то есть
 *   туда же, куда смотрит фасад, — и кончается ровно на краю тротуара.
 *   Ни длина, ни направление не задаются руками;
 * - **подход сквозь стену.** Начало — сама дверь, а она по построению
 *   на фасаде (`дом.ts`).
 *
 * Про экран этот файл не знает ничего.
 */

import { roadWidth, roadTypeForLanes } from '../world/road.ts';
import { type Дом } from './дом.ts';
import type { Объект, Посёлок, Улица } from './plan.ts';

/** Место на земле. Своего имени у него в этом файле нет — только x и z. */
interface Точка { readonly x: number; readonly z: number }

/** Ширина дорожки к подъезду, м. СП: пешеходная дорожка не менее 1.5 м. */
export const ШИРИНА_ПОДХОДА = 1.5;

/** На сколько дорожка приподнята над газоном, м. Настоящая тоже не вровень. */
export const ПОДЪЁМ_ПОДХОДА = 0.08;

export interface Подход {
  /** Начало у двери и конец у тротуара. */
  readonly отX: number;
  readonly отZ: number;
  readonly доX: number;
  readonly доZ: number;
  readonly ширина: number;
}

/** Внешний край тротуара улицы: дальше него дорожка не нужна. */
export function крайТротуара(улица: Улица): number {
  const тип = roadTypeForLanes(улица.полосВСторону);
  return roadWidth(тип) / 2 + тип.sidewalk;
}

/**
 * Подходы к дверям одного дома.
 *
 * `улица` нужна ровно за одним: где кончается тротуар. Дом этого не знает
 * и знать не должен — он не обязан помнить, на какой улице стоит.
 */
export function подходыКДому(
  дом: Дом, объект: Объект, улица: Улица,
  /**
   * `подходы: 'до половины'` — довести дорожку только до середины газона.
   * Заведомо сломанный вариант: подход, который никуда не приводит.
   *
   * До 21.09 здесь был другой: «ставить подход только у первого подъезда».
   * Он перестал что-либо ломать, когда городской фасад встал на красную
   * линию: в деревне у дома один подъезд, и «только первый» — это все.
   * Проверку, которая больше не может упасть, держать нельзя (правило 11).
   */
  как: { подходы?: false | 'до половины' } = {},
): Подход[] {
  const cos = Math.cos(дом.курс), sin = Math.sin(дом.курс);
  const вдольX = объект.вдольX;
  /** Насколько середина дома отстоит от оси улицы. */
  const доОси = Math.abs((вдольX ? дом.z : дом.x) - (вдольX ? улица.a.z : улица.a.x));
  const длина = доОси - дом.глубина / 2 - крайТротуара(улица);
  // тротуар вплотную к дому — подходить неоткуда и незачем
  if (длина <= 0.2) return [];

  const доля = как.подходы === 'до половины' ? 0.5 : 1;
  const двери = как.подходы === false ? дом.двери.slice(0, 1) : дом.двери;
  return двери.map((п) => {
    // дверь на фасаде: вперёд — половина глубины, вбок — её место вдоль фасада
    const отX = дом.x + (дом.глубина / 2) * cos - п.вдоль * sin;
    const отZ = дом.z + (дом.глубина / 2) * sin + п.вдоль * cos;
    return {
      отX, отZ,
      доX: отX + cos * длина * доля,
      доZ: отZ + sin * длина * доля,
      ширина: ШИРИНА_ПОДХОДА,
    };
  });
}

/** Все подходы посёлка. Один дом — столько подходов, сколько у него дверей. */
export function подходыПосёлка(
  п: Посёлок, дома: readonly Дом[], как: { подходы?: false | 'до половины' } = {},
): Подход[] {
  const из: Подход[] = [];
  п.объекты.forEach((о, i) => {
    const дом = дома[i];
    if (дом === undefined) return;
    из.push(...подходыКДому(дом, о, п.улицы[о.улица], как));
  });
  return из;
}

/**
 * У какой двери НЕТ подхода. Пусто — значит ни у одной.
 *
 * Меряется не «сколько подходов», а «дошёл ли подход до каждой двери»:
 * счёт совпал бы и при двух подходах к одной двери и ни одного к другой.
 */
export function дверьБезПодхода(
  дома: readonly Дом[], подходы: readonly Подход[],
  /**
   * Улица каждого дома — чтобы понять, НУЖЕН ли ему подход вообще.
   *
   * В городском квартале фасад стоит на красной линии, то есть дверь
   * выходит прямо на тротуар, и дорожка к ней — это дорожка нулевой длины.
   * Требовать её значило бы требовать невыразимого: подход по построению
   * идёт от двери до края тротуара, а тут они в одной точке.
   */
  улицаДома?: (i: number) => Улица | null,
): number {
  let без = 0;
  дома.forEach((д, i) => {
    const у = улицаДома?.(i) ?? null;
    // дверь на самом тротуаре — подход не нужен и не существует
    if (у !== null && доТротуара(д, у) <= 0.2) return;
    const cos = Math.cos(д.курс), sin = Math.sin(д.курс);
    for (const п of д.двери) {
      const x = д.x + (д.глубина / 2) * cos - п.вдоль * sin;
      const z = д.z + (д.глубина / 2) * sin + п.вдоль * cos;
      /**
       * Подход засчитывается, только если он начинается У ЭТОЙ двери
       * И ДОХОДИТ ДО ТРОТУАРА. Дорожка, оборвавшаяся посреди газона,
       * — такая же неправда, как её отсутствие.
       */
      const есть = подходы.some((под) => Math.hypot(под.отX - x, под.отZ - z) < 0.01
        && (у === null || Math.abs(Math.hypot(под.доX - под.отX, под.доZ - под.отZ)
          - доТротуара(д, у)) < 0.2));
      if (!есть) без++;
    }
  });
  return без;
}

/** Сколько метров от фасада дома до края тротуара его улицы. */
function доТротуара(дом: Дом, улица: Улица): number {
  const вдольX = улица.a.z === улица.b.z;
  const доОси = Math.abs((вдольX ? дом.z : дом.x) - (вдольX ? улица.a.z : улица.a.x));
  return доОси - дом.глубина / 2 - крайТротуара(улица);
}

/**
 * Откуда смотреть, чтобы увидеть двор: от въезда вглубь квартала.
 *
 * ЗАЧЕМ ЭТО ЗДЕСЬ. 18 сентября выяснилось, что построить мало — надо ещё
 * и показать. Дворы были все тридцать шесть, с проездами, стоянками
 * и машинами, а на экране их не было: каждый ракурс в меню — это пара
 * координат, зашитая в код, и ни одна из них на двор не смотрела.
 *
 * Место ВЫЧИСЛЯЕТСЯ из проезда, а не задаётся числами. Поэтому «ракурс,
 * смотрящий в пустоту» для двора невыразим: нет проезда — нет и ракурса.
 * Высоту сюда не кладём: про землю и про экран этот файл не знает.
 */
export function откудаСмотретьВоДвор(
  п: Посёлок,
  /**
   * `взгляд: 'наружу'` — заведомо сломанный вариант: камера смотрит из двора
   * на улицу, а не во двор. Ровно то, что даёт перепутанный порядок точек.
   */
  как: { взгляд?: 'наружу' } = {},
): { от: Точка; до: Точка; квартал: number } | null {
  let лучший = -1, ближе = Infinity;
  п.кварталы.forEach((к, i) => {
    if (к.проезд === null || к.проезд.length < 4) return;
    const d = Math.hypot((к.x0 + к.x1) / 2, (к.z0 + к.z1) / 2);
    if (d < ближе) { ближе = d; лучший = i; }
  });
  if (лучший < 0) return null;
  const л = п.кварталы[лучший].проезд as readonly Точка[];
  /**
   * Обе точки — НА ПРОЕЗДЕ, отмеренные по его длине.
   *
   * Первая редакция ставила камеру у самого устья: в кадр попадал длинный
   * пустой коридор, а стоянка с машинами оказывалась за сто метров и читалась
   * точками. Двадцать метров вглубь — это место, откуда двор виден как двор:
   * ближние машины у бордюра, подъезды, зелень.
   */
  const от = вдольЛоманой(л, ВГЛУБЬ_ДВОРА);
  const до = вдольЛоманой(л, ВГЛУБЬ_ДВОРА + ДАЛЬШЕ_ВЗГЛЯД);
  return как.взгляд === 'наружу'
    ? { от: до, до: от, квартал: лучший }
    : { от, до, квартал: лучший };
}

/** Сколько метров от устья вглубь стоит камера и куда смотрит. */
const ВГЛУБЬ_ДВОРА = 22;
const ДАЛЬШЕ_ВЗГЛЯД = 60;

/** Точка ломаной на заданном расстоянии от её начала, по самой ломаной. */
function вдольЛоманой(л: readonly Точка[], метров: number): Точка {
  let пройдено = 0;
  for (let i = 0; i + 1 < л.length; i++) {
    const шаг = Math.hypot(л[i + 1].x - л[i].x, л[i + 1].z - л[i].z);
    if (пройдено + шаг >= метров) {
      const t = шаг < 1e-6 ? 0 : (метров - пройдено) / шаг;
      return { x: л[i].x + (л[i + 1].x - л[i].x) * t, z: л[i].z + (л[i + 1].z - л[i].z) * t };
    }
    пройдено += шаг;
  }
  return л[л.length - 1];
}

/**
 * Занято ли место подходом. Нужно зелени: дерево растёт в газоне,
 * а дорожка — не газон.
 *
 * Спрашивается тем же способом, каким зелень уже спрашивает дороги:
 * не «есть ли в списке такой», а «далеко ли до ближайшего». Тогда правило
 * у дерева остаётся одно на всё: расти там, где ничего нет.
 */
export function подПодходом(подходы: readonly Подход[], x: number, z: number, запас: number): boolean {
  for (const п of подходы) {
    const dx = п.доX - п.отX, dz = п.доZ - п.отZ;
    const длина2 = dx * dx + dz * dz;
    if (длина2 < 1e-6) continue;
    // ближайшая точка отрезка к (x, z)
    let t = ((x - п.отX) * dx + (z - п.отZ) * dz) / длина2;
    t = Math.max(0, Math.min(1, t));
    const бx = п.отX + dx * t, бz = п.отZ + dz * t;
    if (Math.hypot(x - бx, z - бz) < п.ширина / 2 + запас) return true;
  }
  return false;
}
