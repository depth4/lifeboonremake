/**
 * Что между домами: подход к подъезду и стоянка во дворе.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. `plan.ts` делит землю, `дом.ts` описывает здание,
 * `зелень.ts` сажает деревья. А то, ЧЕМ человек пользуется между улицей
 * и своей дверью, не принадлежит ни одному из них: подход начинается
 * у тротуара (это улица) и кончается у двери (это дом). Складывать его
 * в любой из двух файлов значило бы заставить их знать друг про друга.
 *
 * ЧТО СДЕЛАНО НЕВЫРАЗИМЫМ:
 *
 * - **подъезд, к которому не подойти.** Подход не расставляется и не
 *   хранится: он ВЫВОДИТСЯ из двери. Сколько дверей — столько подходов,
 *   и другого способа получить подход нет. Дверь без подхода записать негде;
 * - **подход, ведущий не туда.** Он идёт строго по курсу дома — то есть
 *   туда же, куда смотрит фасад, — и кончается ровно на краю тротуара.
 *   Ни длина, ни направление не задаются руками;
 * - **подход сквозь стену.** Начало — сама дверь, а она по построению
 *   на фасаде (`дом.ts`).
 *
 * Про экран этот файл не знает ничего.
 */

import { roadWidth, roadTypeForLanes } from '../world/road.ts';
import { type Дом } from './дом.ts';
import { ПРОЕЗД, type Квартал, type Объект, type Посёлок, type Улица } from './plan.ts';

/** Место на земле. Своего имени у него в этом файле нет — только x и z. */
interface Точка { readonly x: number; readonly z: number }

/** Ширина дорожки к подъезду, м. СП: пешеходная дорожка не менее 1.5 м. */
export const ШИРИНА_ПОДХОДА = 1.5;

/** На сколько дорожка приподнята над газоном, м. Настоящая тоже не вровень. */
export const ПОДЪЁМ_ПОДХОДА = 0.08;

export interface Подход {
  /** Начало у двери и конец у тротуара. */
  readonly отX: number;
  readonly отZ: number;
  readonly доX: number;
  readonly доZ: number;
  readonly ширина: number;
}

/** Внешний край тротуара улицы: дальше него дорожка не нужна. */
export function крайТротуара(улица: Улица): number {
  const тип = roadTypeForLanes(улица.полосВСторону);
  return roadWidth(тип) / 2 + тип.sidewalk;
}

/**
 * Подходы к дверям одного дома.
 *
 * `улица` нужна ровно за одним: где кончается тротуар. Дом этого не знает
 * и знать не должен — он не обязан помнить, на какой улице стоит.
 */
export function подходыКДому(
  дом: Дом, объект: Объект, улица: Улица,
  /**
   * `подходы: 'до половины'` — довести дорожку только до середины газона.
   * Заведомо сломанный вариант: подход, который никуда не приводит.
   *
   * До 21.09 здесь был другой: «ставить подход только у первого подъезда».
   * Он перестал что-либо ломать, когда городской фасад встал на красную
   * линию: в деревне у дома один подъезд, и «только первый» — это все.
   * Проверку, которая больше не может упасть, держать нельзя (правило 11).
   */
  как: { подходы?: false | 'до половины' } = {},
): Подход[] {
  const cos = Math.cos(дом.курс), sin = Math.sin(дом.курс);
  const вдольX = объект.вдольX;
  /** Насколько середина дома отстоит от оси улицы. */
  const доОси = Math.abs((вдольX ? дом.z : дом.x) - (вдольX ? улица.a.z : улица.a.x));
  const длина = доОси - дом.глубина / 2 - крайТротуара(улица);
  // тротуар вплотную к дому — подходить неоткуда и незачем
  if (длина <= 0.2) return [];

  const доля = как.подходы === 'до половины' ? 0.5 : 1;
  const двери = как.подходы === false ? дом.двери.slice(0, 1) : дом.двери;
  return двери.map((п) => {
    // дверь на фасаде: вперёд — половина глубины, вбок — её место вдоль фасада
    const отX = дом.x + (дом.глубина / 2) * cos - п.вдоль * sin;
    const отZ = дом.z + (дом.глубина / 2) * sin + п.вдоль * cos;
    return {
      отX, отZ,
      доX: отX + cos * длина * доля,
      доZ: отZ + sin * длина * доля,
      ширина: ШИРИНА_ПОДХОДА,
    };
  });
}

/** Все подходы посёлка. Один дом — столько подходов, сколько у него дверей. */
export function подходыПосёлка(
  п: Посёлок, дома: readonly Дом[], как: { подходы?: false | 'до половины' } = {},
): Подход[] {
  const из: Подход[] = [];
  п.объекты.forEach((о, i) => {
    const дом = дома[i];
    if (дом === undefined) return;
    из.push(...подходыКДому(дом, о, п.улицы[о.улица], как));
  });
  return из;
}

/**
 * У какой двери НЕТ подхода. Пусто — значит ни у одной.
 *
 * Меряется не «сколько подходов», а «дошёл ли подход до каждой двери»:
 * счёт совпал бы и при двух подходах к одной двери и ни одного к другой.
 */
export function дверьБезПодхода(
  дома: readonly Дом[], подходы: readonly Подход[],
  /**
   * Улица каждого дома — чтобы понять, НУЖЕН ли ему подход вообще.
   *
   * В городском квартале фасад стоит на красной линии, то есть дверь
   * выходит прямо на тротуар, и дорожка к ней — это дорожка нулевой длины.
   * Требовать её значило бы требовать невыразимого: подход по построению
   * идёт от двери до края тротуара, а тут они в одной точке.
   */
  улицаДома?: (i: number) => Улица | null,
): number {
  let без = 0;
  дома.forEach((д, i) => {
    const у = улицаДома?.(i) ?? null;
    // дверь на самом тротуаре — подход не нужен и не существует
    if (у !== null && доТротуара(д, у) <= 0.2) return;
    const cos = Math.cos(д.курс), sin = Math.sin(д.курс);
    for (const п of д.двери) {
      const x = д.x + (д.глубина / 2) * cos - п.вдоль * sin;
      const z = д.z + (д.глубина / 2) * sin + п.вдоль * cos;
      /**
       * Подход засчитывается, только если он начинается У ЭТОЙ двери
       * И ДОХОДИТ ДО ТРОТУАРА. Дорожка, оборвавшаяся посреди газона,
       * — такая же неправда, как её отсутствие.
       */
      const есть = подходы.some((под) => Math.hypot(под.отX - x, под.отZ - z) < 0.01
        && (у === null || Math.abs(Math.hypot(под.доX - под.отX, под.доZ - под.отZ)
          - доТротуара(д, у)) < 0.2));
      if (!есть) без++;
    }
  });
  return без;
}

/** Сколько метров от фасада дома до края тротуара его улицы. */
function доТротуара(дом: Дом, улица: Улица): number {
  const вдольX = улица.a.z === улица.b.z;
  const доОси = Math.abs((вдольX ? дом.z : дом.x) - (вдольX ? улица.a.z : улица.a.x));
  return доОси - дом.глубина / 2 - крайТротуара(улица);
}

/**
 * Откуда смотреть, чтобы увидеть двор: от въезда вглубь квартала.
 *
 * ЗАЧЕМ ЭТО ЗДЕСЬ. 18 сентября выяснилось, что построить мало — надо ещё
 * и показать. Дворы были все тридцать шесть, с проездами, стоянками
 * и машинами, а на экране их не было: каждый ракурс в меню — это пара
 * координат, зашитая в код, и ни одна из них на двор не смотрела.
 *
 * Место ВЫЧИСЛЯЕТСЯ из проезда, а не задаётся числами. Поэтому «ракурс,
 * смотрящий в пустоту» для двора невыразим: нет проезда — нет и ракурса.
 * Высоту сюда не кладём: про землю и про экран этот файл не знает.
 */
export function откудаСмотретьВоДвор(
  п: Посёлок,
  /**
   * `взгляд: 'наружу'` — заведомо сломанный вариант: камера смотрит из двора
   * на улицу, а не во двор. Ровно то, что даёт перепутанный порядок точек.
   */
  как: { взгляд?: 'наружу' } = {},
): { от: Точка; до: Точка; квартал: number } | null {
  let лучший = -1, ближе = Infinity;
  п.кварталы.forEach((к, i) => {
    if (к.проезд === null || к.проезд.length < 4) return;
    const d = Math.hypot((к.x0 + к.x1) / 2, (к.z0 + к.z1) / 2);
    if (d < ближе) { ближе = d; лучший = i; }
  });
  if (лучший < 0) return null;
  const к = п.кварталы[лучший];
  const л = к.проезд as readonly Точка[];
  const д = к.двор as { x: number; z: number; ширина: number; глубина: number };
  /**
   * Смотрим НА ДВОР, а не вдоль проезда.
   *
   * Первая редакция ставила камеру на проезд и направляла её по нему —
   * и в кадр попадала дорога, а двор оставался сбоку. Ровно та же ошибка,
   * из-за которой 18.09 дворов «не было»: ракурс показывал не то, что
   * называется. Теперь камера стоит на проезде в самом близком к середине
   * двора месте и смотрит в эту середину — туда, где площадка и лавки.
   */
  // смотрим НА ПЛОЩАДКУ — то есть на то, ради чего двор вообще двор
  const середина = местоПлощадки(к) ?? { x: д.x, z: д.z };
  let от = л[0], ближайшее = Infinity;
  for (let i = 0; i + 1 < л.length; i++) {
    const dx = л[i + 1].x - л[i].x, dz = л[i + 1].z - л[i].z;
    const длина2 = dx * dx + dz * dz;
    let t = длина2 < 1e-9 ? 0 : ((середина.x - л[i].x) * dx + (середина.z - л[i].z) * dz) / длина2;
    t = Math.max(0, Math.min(1, t));
    const точка = { x: л[i].x + dx * t, z: л[i].z + dz * t };
    const d = Math.hypot(точка.x - середина.x, точка.z - середина.z);
    if (d < ближайшее) { ближайшее = d; от = точка; }
  }
  /**
   * Камера отходит на пару метров ОТ полотна в сторону двора: стоя ровно
   * на оси проезда, она упиралась в ствол придорожного дерева.
   */
  const кДвору = Math.hypot(середина.x - от.x, середина.z - от.z) || 1;
  const шаг = 3;
  const стоим = {
    x: от.x + ((середина.x - от.x) / кДвору) * шаг,
    z: от.z + ((середина.z - от.z) / кДвору) * шаг,
  };
  return как.взгляд === 'наружу'
    ? { от: середина, до: стоим, квартал: лучший }
    : { от: стоим, до: середина, квартал: лучший };
}

/**
 * Занято ли место подходом. Нужно зелени: дерево растёт в газоне,
 * а дорожка — не газон.
 *
 * Спрашивается тем же способом, каким зелень уже спрашивает дороги:
 * не «есть ли в списке такой», а «далеко ли до ближайшего». Тогда правило
 * у дерева остаётся одно на всё: расти там, где ничего нет.
 */
export function подПодходом(подходы: readonly Подход[], x: number, z: number, запас: number): boolean {
  for (const п of подходы) {
    const dx = п.доX - п.отX, dz = п.доZ - п.отZ;
    const длина2 = dx * dx + dz * dz;
    if (длина2 < 1e-6) continue;
    // ближайшая точка отрезка к (x, z)
    let t = ((x - п.отX) * dx + (z - п.отZ) * dz) / длина2;
    t = Math.max(0, Math.min(1, t));
    const бx = п.отX + dx * t, бz = п.отZ + dz * t;
    if (Math.hypot(x - бx, z - бz) < п.ширина / 2 + запас) return true;
  }
  return false;
}

/** Что стоит во дворе. Разные вещи — разные размеры и цвет, больше ничего. */
export type ЧтоВоДворе = 'площадка' | 'горка' | 'качели' | 'лавка' | 'баки';

export interface Вещь {
  readonly что: ЧтоВоДворе;
  readonly x: number;
  readonly z: number;
  /** Поперёк курса и вдоль него, м; высота над землёй, м. */
  readonly ширина: number;
  readonly длина: number;
  readonly высота: number;
  readonly курс: number;
}

/** Размеры настоящих вещей, м. Не на глаз: детская площадка по СП — от 50 м². */
const РАЗМЕРЫ: Record<ЧтоВоДворе, { ширина: number; длина: number; высота: number }> = {
  площадка: { ширина: 12, длина: 9, высота: 0.12 },
  горка: { ширина: 1.1, длина: 2.6, высота: 1.7 },
  качели: { ширина: 0.5, длина: 3.2, высота: 2.4 },
  лавка: { ширина: 0.5, длина: 1.8, высота: 0.45 },
  баки: { ширина: 1.1, длина: 4.4, высота: 1.2 },
};

/** Сколько метров от оси проезда занято им самим вместе с тротуарами. */
const ПОЛУШИРИНА_ПРОЕЗДА = roadWidth(ПРОЕЗД) / 2 + ПРОЕЗД.sidewalk;

/** Расстояние от точки до ломаной. */
function доЛоманой(л: readonly Точка[], x: number, z: number): number {
  let ближе = Infinity;
  for (let i = 0; i + 1 < л.length; i++) {
    const dx = л[i + 1].x - л[i].x, dz = л[i + 1].z - л[i].z;
    const длина2 = dx * dx + dz * dz;
    let t = длина2 < 1e-9 ? 0 : ((x - л[i].x) * dx + (z - л[i].z) * dz) / длина2;
    t = Math.max(0, Math.min(1, t));
    ближе = Math.min(ближе, Math.hypot(x - (л[i].x + dx * t), z - (л[i].z + dz * t)));
  }
  return ближе;
}

/**
 * ЧТО СТОИТ ВО ДВОРЕ: площадка, лавки вокруг неё, баки у проезда.
 *
 * ЗАЧЕМ. Двор до 22.09 был газоном с дорогой: проезд есть, стоянка есть,
 * подходы есть — а самого двора как места нет. Алекс сказал прямо:
 * «никаких проездов к домам, тропинок, придомовой территории».
 *
 * ЧТО СДЕЛАНО НЕВЫРАЗИМЫМ. Ничего не расставляется руками: место площадки
 * ВЫБИРАЕТСЯ как самая дальняя от проезда свободная точка двора, лавки
 * выводятся из неё, баки — из проезда. Поэтому «площадка посреди асфальта»,
 * «лавка в стене» и «двор без площадки там, где место есть» записать негде:
 * ни у одной вещи нет своих координат, все они следствие двора.
 *
 * `занято` — тот же вопрос, который задаёт зелень: занято ли место дорогой,
 * домом или дорожкой. Правило одно на весь город, и второго нет.
 */
export function вещиДвора(
  к: Квартал,
  занято: (x: number, z: number) => boolean,
  /**
   * `площадка: 'на проезде'` — поставить её посреди ломаной проезда, то есть
   * «в середину двора», как её легко перепутать. Заведомо сломанный вариант:
   * детская площадка оказывается на проезжей части.
   */
  как: { площадка?: 'на проезде' } = {},
): Вещь[] {
  if (к.двор === null || к.проезд === null) return [];
  const л = к.проезд;
  const вещь = (что: ЧтоВоДворе, x: number, z: number, курс = 0): Вещь =>
    ({ что, x, z, курс, ...РАЗМЕРЫ[что] });

  const площ = РАЗМЕРЫ.площадка;
  const место = как.площадка === 'на проезде'
    ? л[Math.floor(л.length / 2)] : местоПлощадки(к);
  if (место === null) return [];
  if (как.площадка !== 'на проезде' && занято(место.x, место.z)) return [];
  const лучшаяX = место.x, лучшаяZ = место.z;

  const из: Вещь[] = [вещь('площадка', лучшаяX, лучшаяZ)];
  // горки — НА площадке, по её длине; лавки — по краям, лицом к ней
  из.push(вещь('горка', лучшаяX - площ.ширина / 3, лучшаяZ - 1.4, Math.PI / 2));
  из.push(вещь('качели', лучшаяX + площ.ширина / 3, лучшаяZ + 1.2, 0));
  for (const сторона of [-1, 1] as const) {
    из.push(вещь('лавка', лучшаяX - 3, лучшаяZ + сторона * (площ.длина / 2 + 1.2), Math.PI / 2));
    из.push(вещь('лавка', лучшаяX + 3, лучшаяZ + сторона * (площ.длина / 2 + 1.2), Math.PI / 2));
  }

  /**
   * Баки стоят У ПРОЕЗДА: мусоровоз к ним подъезжает, а не идёт пешком.
   * Место — у первой точки проезда внутри двора, сбоку от полотна.
   */
  const где = л[Math.min(2, л.length - 1)];
  const куда = л[Math.min(3, л.length - 1)];
  const dx = куда.x - где.x, dz = куда.z - где.z;
  const d = Math.hypot(dx, dz) || 1;
  const вбок = ПОЛУШИРИНА_ПРОЕЗДА + 1.5;
  for (const сторона of [1, -1] as const) {
    const bx = где.x - (dz / d) * вбок * сторона;
    const bz = где.z + (dx / d) * вбок * сторона;
    if (занято(bx, bz)) continue;
    из.push(вещь('баки', bx, bz, Math.atan2(dz, dx)));
    break;
  }
  return из;
}

/** Запас от края двора: половина площадки плюс метр. */
function запасОтКрая(): number { return РАЗМЕРЫ.площадка.ширина / 2 + 1; }

/**
 * На сколько метров от полотна проезда стоит площадка.
 *
 * Не «как можно дальше»: двор бывает за сотню метров в поперечнике, и самая
 * дальняя от проезда точка оказывается посреди пустого поля — с проезда
 * её не видно, из окон тоже далеко. Двадцать с небольшим — это в виду окон
 * и при этом не у дороги: ребёнок под присмотром, мяч на проезжую часть
 * не выкатывается.
 */
const ПЛОЩАДКА_ОТ_ПРОЕЗДА = ПОЛУШИРИНА_ПРОЕЗДА + 16;

/**
 * ГДЕ ВО ДВОРЕ ПЛОЩАДКА — одно определение на весь проект.
 *
 * Им ставится сама площадка, и им же наводится ракурс «двор»: иначе камера
 * смотрела бы в одно место, а площадка стояла бы в другом. Ровно этим
 * 18.09 «не было дворов» — ракурс показывал не то, что называется.
 *
 * Чистая геометрия: ни домов, ни дорожек она не знает. Занятость проверяет
 * тот, кто ставит вещи, — и если занято, площадки просто нет.
 */
export function местоПлощадки(к: Квартал): Точка | null {
  if (к.двор === null || к.проезд === null) return null;
  const д = к.двор, л = к.проезд;
  let лучшее: Точка | null = null, лучшийПромах = Infinity;
  for (let x = д.x - д.ширина / 2 + запасОтКрая(); x <= д.x + д.ширина / 2 - запасОтКрая(); x += 2) {
    for (let z = д.z - д.глубина / 2 + запасОтКрая(); z <= д.z + д.глубина / 2 - запасОтКрая(); z += 2) {
      const до = доЛоманой(л, x, z);
      if (до <= ПОЛУШИРИНА_ПРОЕЗДА + 3) continue;
      // ближе всего к нужному отстоянию; при равенстве — ближе к середине двора
      const промах = Math.abs(до - ПЛОЩАДКА_ОТ_ПРОЕЗДА) * 100
        + Math.hypot(x - д.x, z - д.z);
      if (промах < лучшийПромах) { лучшийПромах = промах; лучшее = { x, z }; }
    }
  }
  return лучшее;
}

/** Вещи всех дворов посёлка. */
export function вещиПосёлка(
  п: Посёлок, занято: (x: number, z: number) => boolean,
  как: { площадка?: 'на проезде' } = {},
): Вещь[] {
  const из: Вещь[] = [];
  for (const к of п.кварталы) из.push(...вещиДвора(к, занято, как));
  return из;
}
