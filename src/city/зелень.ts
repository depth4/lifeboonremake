/**
 * Зелень улиц: деревья в полосе между тротуаром и красной линией.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Дерево — не дом (`дом.ts`), не участок (`plan.ts`)
 * и не участник движения (`traffic.ts`). Это свойство САМОЙ УЛИЦЫ: полоса
 * между тротуаром и красной линией существует потому, что улица шире
 * проезжей части, и растёт в ней то, что сажает город. Замерено на «большом
 * городе»: у местной улицы такой полосы четыре метра, у магистральной —
 * девять с половиной, и до сих пор в ней не было ничего, кроме газона.
 * С уровня глаз это первое, что выдаёт нарисованность: дома стоят в поле.
 *
 * ПОЧЕМУ ДЕРЕВО НЕ МОЖЕТ ОКАЗАТЬСЯ НА АСФАЛЬТЕ. Его место не хранится
 * и не подбирается: оно отсчитывается ОТ ВНЕШНЕГО КРАЯ ТРОТУАРА наружу,
 * на постоянные два с небольшим метра. Записать «дерево на проезжей части»
 * этим способом нельзя — отступ положительный и мерится от края наружу.
 *
 * ПОЧЕМУ ДЕРЕВЬЯ НЕ СТОЯТ НА ПЕРЕКРЁСТКЕ. Посадка идёт по метрам дороги,
 * и метры у обоих концов пропускаются на вылет узла (`net.reach`) с запасом
 * на скругление. Ряд обрывается перед перекрёстком сам, без особых случаев.
 *
 * ОДНА СЦЕНА — ОДИН И ТОТ ЖЕ ЛЕС. Ни высота, ни цвет, ни поворот не
 * случайны: всё выводится из номера дороги и метра посадки. Дерево нельзя
 * «пересоздать иначе», потому что его нигде и не создают — его вычисляют.
 *
 * Про экран этот файл не знает: он выдаёт места и размеры, рисует `render.ts`.
 */

import type { World } from '../world/world.ts';
import { type Network, along } from './traffic.ts';

/** Через сколько метров стоит следующее дерево в ряду. СП: 5–8 м. */
export const ШАГ_ПОСАДКИ = 8;

/** На сколько дерево отодвинуто от внешнего края тротуара, м. */
export const ОТ_ТРОТУАРА = 2.2;

/** Дерево: ствол коробкой и крона из двух коробок — той же природы, что дома. */
export interface Дерево {
  readonly x: number;
  readonly z: number;
  /** Высота ствола до низа кроны, м. */
  readonly ствол: number;
  /** Высота кроны, м. */
  readonly крона: number;
  /** Ширина кроны, м. */
  readonly ширина: number;
  /** Толщина ствола, м. */
  readonly толщина: number;
  /** Поворот вокруг своей оси, рад: чтобы ряд не выглядел штампом. */
  readonly курс: number;
  /** Оттенок листвы, 0…1. */
  readonly лист: number;
}

/**
 * Смешиватель: одно и то же число даёт одно и то же всегда и везде.
 * Тот же, что у жителей и домов, — чтобы «случайность» была одной на проект.
 */
function перемешать(x: number): number {
  let h = (x ^ 0x9e3779b9) >>> 0;
  h = Math.imul(h ^ (h >>> 16), 0x21f0aaad) >>> 0;
  h = Math.imul(h ^ (h >>> 15), 0x735a2d97) >>> 0;
  return ((h ^ (h >>> 15)) >>> 0) / 4294967296;
}

/**
 * Деревья вдоль всех улиц сети, по обе стороны.
 *
 * `сид` — тот же, что у посёлка: город и его зелень выводятся из одного числа.
 */
export function деревьяУлиц(world: World, net: Network, сид: number): Дерево[] {
  const деревья: Дерево[] = [];

  for (let shape = 0; shape < world.shapes.length; shape++) {
    const длина = net.length[shape];
    const край = world.shapes[shape].outerHalf;

    /**
     * Свободные метры дороги: от конца вылета одного узла до начала вылета
     * другого. Нет узла на конце (тупик) — свободен весь конец.
     */
    const [низ, верх] = net.ends[shape];
    const от = (низ === null ? 2 : net.reach[низ.junction] + 4);
    const до = длина - (верх === null ? 2 : net.reach[верх.junction] + 4);
    if (до - от < ШАГ_ПОСАДКИ) continue;

    // ряд начинается так, чтобы стоять посередине свободного куска
    const сколько = Math.floor((до - от) / ШАГ_ПОСАДКИ);
    const начало = от + ((до - от) - (сколько - 1) * ШАГ_ПОСАДКИ) / 2;

    for (let i = 0; i < сколько; i++) {
      const s = начало + i * ШАГ_ПОСАДКИ;
      const точка = along(world, shape, s);
      for (const сторона of [1, -1] as const) {
        const зерно = сид ^ (shape * 7919) ^ (i * 104729) ^ (сторона > 0 ? 0 : 0x5bf03635);
        const a = перемешать(зерно);
        const b = перемешать(зерно * 2654435761);
        /**
         * Отступ поперёк — от ВНЕШНЕГО КРАЯ ТРОТУАРА наружу. Ствол стоит
         * в газоне; ближе к проезжей части его быть не может по устройству.
         */
        const вбок = (край + ОТ_ТРОТУАРА) * сторона;
        // право по ходу — это cross(вперёд, вверх), как и у машин
        деревья.push({
          x: точка.x - точка.fz * вбок,
          z: точка.z + точка.fx * вбок,
          ствол: 2.2 + a * 1.2,
          крона: 3.4 + b * 2.2,
          ширина: 3.0 + a * 1.6,
          толщина: 0.34 + b * 0.16,
          курс: a * Math.PI,
          лист: b,
        });
      }
    }
  }

  return деревья;
}
