/**
 * Зелень улиц: деревья в полосе между тротуаром и красной линией.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Дерево — не дом (`дом.ts`), не участок (`plan.ts`)
 * и не участник движения (`traffic.ts`). Это свойство САМОЙ УЛИЦЫ: полоса
 * между тротуаром и красной линией существует потому, что улица шире
 * проезжей части, и растёт в ней то, что сажает город. Замерено на «большом
 * городе»: у местной улицы такой полосы четыре метра, у магистральной —
 * девять с половиной, и до сих пор в ней не было ничего, кроме газона.
 * С уровня глаз это первое, что выдаёт нарисованность: дома стоят в поле.
 *
 * ПОЧЕМУ ДЕРЕВО НЕ МОЖЕТ ОКАЗАТЬСЯ НА АСФАЛЬТЕ. Место отсчитывается
 * ОТ ВНЕШНЕГО КРАЯ ТРОТУАРА наружу — но этого мало, и 17 сентября это
 * поймали замером: двадцать деревьев из 1360 стояли на проезжей части.
 * Отступ мерился от СВОЕЙ дороги и ничего не знал о поперечной: у развилки
 * дерево уходило от своей улицы ровно в чужую. Одно из них выросло посреди
 * дороги перед камерой и закрыло кроной половину кадра.
 *
 * Теперь место сверяется с САМИМ МИРОМ: дерево принимается только там,
 * где до ближайшей дороги дальше, чем её внешняя половина, — то есть
 * в газоне, а не на полотне и не на тротуаре. Спрашивается при этом не
 * второй список дорог, а тот же самый мир, по которому едет колесо.
 *
 * ПОЧЕМУ ДЕРЕВЬЯ НЕ СТОЯТ НА ПЕРЕКРЁСТКЕ. Посадка идёт по метрам дороги,
 * и метры у обоих концов пропускаются на вылет узла (`net.reach`) с запасом
 * на скругление. Ряд обрывается перед перекрёстком сам, без особых случаев.
 *
 * ОДНА СЦЕНА — ОДИН И ТОТ ЖЕ ЛЕС. Ни высота, ни цвет, ни поворот не
 * случайны: всё выводится из номера дороги и метра посадки. Дерево нельзя
 * «пересоздать иначе», потому что его нигде и не создают — его вычисляют.
 *
 * Про экран этот файл не знает: он выдаёт места и размеры, рисует `render.ts`.
 */

import { type World, nearestRoad } from '../world/world.ts';
import { type Network, along } from './traffic.ts';
import type { Вид } from '../растения/дерево.ts';
import { type НаЗемле, занято } from './двор.ts';
import type { Квартал } from './plan.ts';

/** Через сколько метров стоит следующее дерево в ряду. СП: 5–8 м. */
export const ШАГ_ПОСАДКИ = 8;

/** На сколько дерево отодвинуто от внешнего края тротуара, м. */
export const ОТ_ТРОТУАРА = 2.2;

/**
 * Насколько дерево держится от того, что стоит на земле, м: от стены —
 * на крону, от дорожки и вещи двора — чтобы крона не висела над ними.
 * Один запас на страницу и на проверки: раньше страница и `морфология`
 * сажали деревья по-разному, и проверялись не те деревья, что показаны.
 */
export const ЗАПАС_ДЕРЕВА = { дом: 1.5, подход: 0.6, вещь: 1.5 };

/** Дерево: ствол коробкой и крона из двух коробок — той же природы, что дома. */
export interface Дерево {
  readonly x: number;
  readonly z: number;
  /** Высота ствола до низа кроны, м. */
  readonly ствол: number;
  /** Высота кроны, м. */
  readonly крона: number;
  /** Ширина кроны, м. */
  readonly ширина: number;
  /** Толщина ствола, м. */
  readonly толщина: number;
  /** Поворот вокруг своей оси, рад: чтобы ряд не выглядел штампом. */
  readonly курс: number;
  /** Оттенок листвы, 0…1. */
  readonly лист: number;
  /** Порода: из неё дерево растёт ветками (`растения/дерево.ts`). */
  readonly вид: Вид;
  /** Какое из деревьев этой породы — число, из которого оно растёт. */
  readonly вариант: number;
  /** Во сколько раз крупнее своей породы в среднем. */
  readonly масштаб: number;
}

/** Породы улиц и дворов — что растёт в российском городе у дома и вдоль проезда. */
const ПОРОДЫ: readonly Вид[] = ['липа', 'тополь', 'берёза', 'клён', 'рябина'];

/**
 * Порода места. Улицу сажают одной породой — липовая аллея, тополя вдоль
 * проезда, — поэтому у каждой улицы своя порода на семь деревьев из десяти,
 * остальные вперемешку. Всё из числа: одна улица — одна порода всегда.
 */
function породаМеста(улица: number, случай: number): Вид {
  const своя = ПОРОДЫ[Math.floor(перемешать(улица) * ПОРОДЫ.length)];
  if (случай < 0.7) return своя;
  return ПОРОДЫ[Math.floor(((случай - 0.7) / 0.3) * ПОРОДЫ.length) % ПОРОДЫ.length];
}

/**
 * Смешиватель: одно и то же число даёт одно и то же всегда и везде.
 * Тот же, что у жителей и домов, — чтобы «случайность» была одной на проект.
 */
function перемешать(x: number): number {
  let h = (x ^ 0x9e3779b9) >>> 0;
  h = Math.imul(h ^ (h >>> 16), 0x21f0aaad) >>> 0;
  h = Math.imul(h ^ (h >>> 15), 0x735a2d97) >>> 0;
  return ((h ^ (h >>> 15)) >>> 0) / 4294967296;
}

/**
 * Деревья вдоль всех улиц сети, по обе стороны.
 *
 * `сид` — тот же, что у посёлка: город и его зелень выводятся из одного числа.
 */
export function деревьяУлиц(
  world: World, net: Network, сид: number,
  /**
   * `газон: false` — не спрашивать мир, как было до 17.09. Деревья встают
   * на проезжую часть у развилок. Заведомо сломанный вариант.
   *
   * `занято` — что ещё занято, кроме дорог: дорожки к подъездам. Правило
   * у дерева остаётся одно — расти там, где ничего нет; растёт только
   * список того, что «что-то».
   */
  как: { газон?: boolean; занято?: (x: number, z: number) => boolean } = {},
): Дерево[] {
  const деревья: Дерево[] = [];

  for (let shape = 0; shape < world.shapes.length; shape++) {
    const длина = net.length[shape];
    const край = world.shapes[shape].outerHalf;

    /**
     * Свободные метры дороги: от конца вылета одного узла до начала вылета
     * другого. Нет узла на конце (тупик) — свободен весь конец.
     */
    const [низ, верх] = net.ends[shape];
    const от = (низ === null ? 2 : net.reach[низ.junction] + 4);
    const до = длина - (верх === null ? 2 : net.reach[верх.junction] + 4);
    if (до - от < ШАГ_ПОСАДКИ) continue;

    // ряд начинается так, чтобы стоять посередине свободного куска
    const сколько = Math.floor((до - от) / ШАГ_ПОСАДКИ);
    const начало = от + ((до - от) - (сколько - 1) * ШАГ_ПОСАДКИ) / 2;

    for (let i = 0; i < сколько; i++) {
      const s = начало + i * ШАГ_ПОСАДКИ;
      const точка = along(world, shape, s);
      for (const сторона of [1, -1] as const) {
        const зерно = сид ^ (shape * 7919) ^ (i * 104729) ^ (сторона > 0 ? 0 : 0x5bf03635);
        const a = перемешать(зерно);
        const b = перемешать(зерно * 2654435761);
        /**
         * Отступ поперёк — от ВНЕШНЕГО КРАЯ ТРОТУАРА наружу. Ствол стоит
         * в газоне; ближе к проезжей части его быть не может по устройству.
         */
        const вбок = (край + ОТ_ТРОТУАРА) * сторона;
        // право по ходу — это cross(вперёд, вверх), как и у машин
        const дx = точка.x - точка.fz * вбок;
        const дz = точка.z + точка.fx * вбок;
        /**
         * Газон — это то, что НЕ дорога. У развилки «наружу от своей улицы»
         * означает «внутрь поперечной», и дерево оказывалось на полотне.
         * Спрашиваем мир, а не свою улицу.
         */
        const рядом = как.газон === false ? null : nearestRoad(world, дx, дz);
        if (рядом !== null && рядом.distance < рядом.outerHalf) continue;
        if (как.газон !== false && как.занято?.(дx, дz) === true) continue;
        деревья.push({
          x: дx,
          z: дz,
          /**
           * Пропорции взяты у настоящего уличного дерева, а не на глаз.
           * Липа или клён двадцати-тридцати лет: высота 8–12 м, чистый
           * ствол до кроны 2.5–3.5 м, крона в поперечнике 5–8 м и по
           * высоте примерно столько же или чуть меньше.
           *
           * Главное здесь — **крона ШИРЕ, чем высока**. Первая редакция
           * делала наоборот (3.4–5.6 в высоту при 3.0–4.6 в ширину),
           * и ряд читался с уровня глаз не деревьями, а зелёным забором:
           * узкие высокие коробки сливались в сплошную стену.
           */
          ствол: 2.5 + a * 1.1,
          крона: 4.2 + b * 2.6,
          ширина: 5.0 + a * 3.0,
          толщина: 0.32 + b * 0.18,
          курс: a * Math.PI,
          лист: b,
          вид: породаМеста(сид ^ (shape * 2246822519), перемешать(зерно * 40503)),
          вариант: Math.floor(перемешать(зерно * 97) * 1000),
          масштаб: 0.85 + b * 0.3,
        });
      }
    }
  }

  return деревья;
}

/**
 * ДЕРЕВЬЯ ДВОРА — рощицами по газону.
 *
 * До 24.09 деревья росли только вдоль дорог, и двор в сто тридцать метров
 * был голым полем (Алекс: «внутри двора пустырь»). В настоящем дворе
 * деревья растут группами: где-то роща, где-то поляна. Группы — из числа:
 * место сетки 11 м сажается, если «пятно» в этом месте густое, а сам ствол
 * сдвинут в пределах клетки, чтобы не было рядов.
 *
 * Не ближе 5 м к стене — СП 42.13330, от наружной стены до ствола дерева
 * 5 м; не на дорожках, площадках, у подъездов и не на проезде — тот же
 * `занято`, что у всех, со своим запасом.
 */
export function деревьяДворов(
  н: НаЗемле, кварталы: readonly Квартал[], сид: number, покрытие: (x: number, z: number) => string,
): Дерево[] {
  const деревья: Дерево[] = [];
  const ШАГ = 11;
  const запас = { дом: 5, подход: 1.5, вещь: 3 };
  кварталы.forEach((к, ki) => {
    if (к.двор === null) return;
    const д = к.двор;
    for (let x = д.x - д.ширина / 2 + 4; x < д.x + д.ширина / 2 - 4; x += ШАГ) {
      for (let z = д.z - д.глубина / 2 + 4; z < д.z + д.глубина / 2 - 4; z += ШАГ) {
        const i = Math.round(x / ШАГ), j = Math.round(z / ШАГ);
        const зерно = сид ^ (ki * 7919) ^ Math.imul(i, 73856093) ^ Math.imul(j, 19349663);
        // пятно: густота меняется плавно — по крупной клетке втрое больше
        const пятно = перемешать(сид ^ Math.imul(Math.floor(i / 3), 83492791) ^ Math.imul(Math.floor(j / 3), 2654435761));
        if (перемешать(зерно) > пятно * 1.3) continue;
        const tx = x + (перемешать(зерно * 3) - 0.5) * ШАГ * 0.7;
        const tz = z + (перемешать(зерно * 5) - 0.5) * ШАГ * 0.7;
        if (покрытие(tx, tz) !== 'grass' || занято(н, tx, tz, запас)) continue;
        const a = перемешать(зерно * 7), b = перемешать(зерно * 11);
        деревья.push({
          x: tx, z: tz,
          ствол: 2.5 + a * 1.1, крона: 4.2 + b * 2.6, ширина: 5.0 + a * 3.0, толщина: 0.32 + b * 0.18,
          курс: a * Math.PI, лист: b,
          вид: породаМеста(сид ^ Math.imul(ki + 1, 2246822519) ^ Math.imul(Math.floor(i / 3) + 7, 40503), перемешать(зерно * 13)),
          вариант: Math.floor(перемешать(зерно * 97) * 1000),
          масштаб: 0.85 + b * 0.35,
        });
      }
    }
  });
  return деревья;
}

/** Что нужно показу, чтобы вырастить и поставить: и дереву, и кусту. */
export type Посадочное = Pick<Дерево, 'x' | 'z' | 'вид' | 'вариант' | 'курс' | 'масштаб'>;

/** Куст: у него нет «ствола до кроны» и «кроны» — только порода и место. */
export type Куст = Посадочное;

/** Насколько куст держится от стены, дорожки и вещи двора, м, и от ствола дерева. */
export const ЗАПАС_КУСТА = { дом: 0.9, подход: 1.0, вещь: 0.6 };
const ОТ_ДЕРЕВА = 2.2;

/**
 * Кусты двора.
 *
 * - **Сирень под окнами**: вдоль дворовой стены дома, в 1.8 м от неё,
 *   группами с просветами — так её сажают у пятиэтажек. Двор — за спиной
 *   дома: фасад смотрит на улицу по курсу, значит двор против курса.
 * - **Изгородь вокруг детской площадки**, в метре от её края, с двумя
 *   проходами посреди длинных сторон.
 *
 * Где можно — решает ОДНА проверка здесь же: на траве, не занято домом,
 * дорожкой или вещью, не вплотную к дереву. Её спрашивают и страница,
 * и `npm run деревья`: проверяются те самые кусты, что показаны.
 *
 * `как.где: 'не спрашивая'` — заведомо сломанный вариант: сажать, не спросив
 * покрытия и занятости. Кусты встают на дорожки и в асфальт проезда.
 */
export function кустыДворов(
  н: НаЗемле, сид: number,
  покрытие: (x: number, z: number) => string,
  деревья: readonly { x: number; z: number }[],
  как: { где?: 'не спрашивая' } = {},
): Куст[] {
  const можно = (x: number, z: number): boolean => как.где === 'не спрашивая' || (
    покрытие(x, z) === 'grass'
    && !занято(н, x, z, ЗАПАС_КУСТА)
    && деревья.every((д) => Math.hypot(д.x - x, д.z - z) > ОТ_ДЕРЕВА));
  const кусты: Куст[] = [];
  const посадить = (x: number, z: number, вид: Вид, зерно: number): void => {
    if (!можно(x, z)) return;
    кусты.push({
      x, z, вид,
      вариант: Math.floor(перемешать(зерно * 97) * 1000),
      курс: перемешать(зерно * 31) * Math.PI * 2,
      масштаб: 0.85 + перемешать(зерно * 57) * 0.3,
    });
  };

  н.дома.forEach((д, di) => {
    const c = Math.cos(д.курс), s = Math.sin(д.курс);
    const шаг = 3.6;
    const n = Math.floor((д.ширина - 3) / шаг);
    for (let k = 0; k < n; k++) {
      const зерно = сид ^ (di * 7919) ^ (k * 104729) ^ 0x2c1b3c6d;
      // группами: примерно треть мест пустует
      if (перемешать(зерно) < 0.35) continue;
      const t = (k - (n - 1) / 2) * шаг + (перемешать(зерно * 3) - 0.5) * 1.2;
      const от = д.глубина / 2 + 1.8 + (перемешать(зерно * 5) - 0.5) * 0.6;
      посадить(д.x - c * от - s * t, д.z - s * от + c * t, 'сирень', зерно);
    }
  });

  н.вещи.forEach((в, vi) => {
    if (в.что !== 'площадка') return;
    const c = Math.cos(в.курс), s = Math.sin(в.курс);
    const hl = в.длина / 2 + 1.1, hw = в.ширина / 2 + 1.1;
    let k = 0;
    const вдольСтороны = (lx0: number, lz0: number, lx1: number, lz1: number, проход: boolean): void => {
      const L = Math.hypot(lx1 - lx0, lz1 - lz0);
      const n = Math.max(1, Math.round(L / 0.8));
      for (let i = 0; i <= n; i++) {
        const t = i / n;
        // проход посреди длинной стороны
        if (проход && Math.abs(t - 0.5) * L < 1.3) continue;
        const lx = lx0 + (lx1 - lx0) * t, lz = lz0 + (lz1 - lz0) * t;
        посадить(в.x + lx * c - lz * s, в.z + lx * s + lz * c, 'изгородь', сид ^ (vi * 6151) ^ (k++ * 2654435761));
      }
    };
    вдольСтороны(-hl, -hw, hl, -hw, true);
    вдольСтороны(-hl, hw, hl, hw, true);
    вдольСтороны(-hl, -hw, -hl, hw, false);
    вдольСтороны(hl, -hw, hl, hw, false);
  });
  return кусты;
}
