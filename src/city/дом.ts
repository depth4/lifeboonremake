/**
 * Дом: что стоит на участке.
 *
 * `plan.ts` решает ГДЕ и ЧТО — какой участок под жильё, какой под школу.
 * Здесь решается, ЧЕМ ЭТОТ ОБЪЕКТ ЯВЛЯЕТСЯ: сколько этажей, где подъезды,
 * сколько квартир, сколько в нём живёт народу и сколько он весит.
 * Про экран этот файл не знает ничего — его можно посчитать без браузера,
 * и показ берёт отсюда готовое, ничего не додумывая.
 *
 * Зачем отдельный файл, а не строчка в `plan.ts`: план — это раскладка по
 * земле, и он одинаков для деревни и для мегаполиса. Дом — это объект со
 * своим устройством, и именно у него есть дверь, окна, крыша и вес.
 *
 * ЧТО СДЕЛАНО НЕВЫРАЗИМЫМ:
 *
 * - **дом без двери.** Подъезды не «расставляются», а нарезаются по фронту:
 *   у любого дома их хотя бы один, и все на грани входа — на улицу или
 *   во двор, как решил план;
 * - **население, назначенное числом.** Люди живут В КВАРТИРАХ, квартиры
 *   считаются из площади этажей, площадь — из объёма дома. Дома без квартир
 *   не могут иметь жителей: их негде записать;
 * - **окно в воздухе.** Окна нарезаются по этажам и по граням, поэтому окна
 *   выше крыши или сбоку от стены не существует;
 * - **дом шире участка.** Размеры выводятся из участка, а не задаются.
 */

import {
  ЗАСТРОЙКА, МЕТРОВ_НА_ЧЕЛОВЕКА, type Вид, type Назначение, РАЗМЕР, ВМЕСТИМОСТЬ,
} from './norms.ts';
import type { Объект } from './plan.ts';

/** Высота жилого этажа, м. Практика российского жилья: 2.7–3.0 в свету. */
export const ЭТАЖ = 3;
/** Полезная площадь квартир — доля от площади этажа. Остальное лестницы и стены. */
const ПОЛЕЗНАЯ = 0.75;
/**
 * Сколько весит кубометр здания в среднем, кг. Панельный дом с перекрытиями
 * и перегородками — около 350 кг/м³ полного объёма. Отсюда настоящая масса:
 * трёхэтажка на 20 метров фронта весит около полутора тысяч тонн.
 */
const ПЛОТНОСТЬ = 350;
/** Уклон скатной крыши: 25° — типовая двускатная. */
const УКЛОН_КРЫШИ = Math.tan((25 * Math.PI) / 180);
/** Окно: шаг по фронту и размеры, м. */
export const ОКНО = { шаг: 2.6, ширина: 1.3, высота: 1.5, отПола: 0.95 };
/** Дверь. */
export const ДВЕРЬ = { ширина: 1.5, высота: 2.3 };
/** На сколько квартир один подъезд. Практика: 3–4 квартиры на этаж. */
const КВАРТИР_НА_ПОДЪЕЗД = 12;
/** Палисадник: на сколько жилой дом отодвинут от красной линии, м. */
export const ПАЛИСАДНИК = 3;

/**
 * Занято ли место домом. Спрашивается тем же способом, каким зелень уже
 * спрашивает дороги и дорожки: не «есть ли в списке такой», а «внутри ли
 * я чего-нибудь». Тогда правило у дерева остаётся одно на всё: расти там,
 * где НИЧЕГО нет.
 *
 * Понадобилось 21.09, когда фасад встал на красную линию: до этого между
 * тротуаром и домом было семь метров, и дерево туда помещалось. Теперь
 * не помещается, и без этого вопроса деревья выросли внутри стен.
 */
export function вДоме(
  дома: readonly { x: number; z: number; курс: number; ширина: number; глубина: number }[],
  x: number, z: number, запас: number,
): boolean {
  for (const д of дома) {
    const cos = Math.cos(д.курс), sin = Math.sin(д.курс);
    const dx = x - д.x, dz = z - д.z;
    const вдоль = dx * cos + dz * sin, поперёк = -dx * sin + dz * cos;
    if (Math.abs(вдоль) < д.глубина / 2 + запас && Math.abs(поперёк) < д.ширина / 2 + запас) return true;
  }
  return false;
}

/**
 * Какая грань дома. Четыре, потому что у коробки их четыре, и до 22.09
 * ЧЕТВЁРТОЙ НЕ БЫЛО ВОВСЕ: фасад, два торца — и глухая стена во двор.
 * Дом, у которого дворовая сторона не может иметь окон, — это забор,
 * и с уровня глаз двор выглядел ровно забором в сто метров.
 */
export type Грань = 0 | 1 | -1 | 2;

/** Длина той грани, вдоль которой раскладываются проёмы. */
export function длинаГрани(
  д: { ширина: number; глубина: number }, грань: Грань,
): number {
  return грань === 0 || грань === 2 ? д.ширина : д.глубина;
}

/**
 * ГДЕ ПРОЁМ ПО ОТНОШЕНИЮ К ДОМУ — одно определение на весь проект.
 *
 * До 24.09 место двери считали в трёх местах по-своему: показ, дорожки
 * и жители. Все трое знали только фасад (`+глубина/2`), и дверь со двора
 * каждый из них поставил бы на улицу. Теперь спрашивают здесь.
 *
 * `вперёд`, `вбок` — смещение от середины дома в его осях (вперёд — к улице);
 * `доворот` — куда смотрит проём наружу относительно курса дома.
 */
export function осиПроёма(
  д: { глубина: number; ширина: number }, п: { грань: Грань; вдоль: number },
): { вперёд: number; вбок: number; доворот: number } {
  return п.грань === 0 || п.грань === 2
    ? { вперёд: (п.грань === 0 ? 1 : -1) * (д.глубина / 2), вбок: п.вдоль, доворот: п.грань === 0 ? 0 : Math.PI }
    : { вперёд: п.вдоль, вбок: (п.грань * д.ширина) / 2, доворот: (п.грань * Math.PI) / 2 };
}

/** Проём на земле: точка на стене и направление наружу. */
export function гдеПроём(
  д: { x: number; z: number; курс: number; глубина: number; ширина: number },
  п: { грань: Грань; вдоль: number },
): { x: number; z: number; nx: number; nz: number } {
  const о = осиПроёма(д, п);
  const cos = Math.cos(д.курс), sin = Math.sin(д.курс);
  const наружу = д.курс + о.доворот;
  return {
    x: д.x + о.вперёд * cos - о.вбок * sin,
    z: д.z + о.вперёд * sin + о.вбок * cos,
    nx: Math.cos(наружу), nz: Math.sin(наружу),
  };
}

/** Где на грани дома стоит проём. */
export interface Проём {
  /** Какая грань: 0 — фасад на улицу, 2 — во двор, 1 и −1 — торцы. */
  readonly грань: Грань;
  /** Метров вдоль грани от её середины. */
  readonly вдоль: number;
  /** Этаж, считая от нуля. У двери всегда 0. */
  readonly этаж: number;
}

export interface Дом {
  readonly что: Назначение;
  /** Середина дома по земле и куда смотрит фасад (радианы). */
  readonly x: number;
  readonly z: number;
  readonly курс: number;
  /** По фронту улицы и вглубь участка, м. */
  readonly ширина: number;
  readonly глубина: number;
  readonly этажей: number;
  /** Высота стен до карниза, м. Вычисляется, не задаётся. */
  readonly высота: number;
  readonly крыша: 'скатная' | 'плоская';
  /** Подъём конька над карнизом (скатная) или высота парапета (плоская), м. */
  readonly подъём: number;
  readonly цвет: number;
  readonly цветКрыши: number;
  /** Сколько квартир и сколько в них живёт. У нежилого — ноль и ноль. */
  readonly квартир: number;
  readonly жителей: number;
  /** Сколько мест даёт нежилой объект: учеников, посетителей. У жилья ноль. */
  readonly мест: number;
  /** Масса здания, тонны. Из объёма, а не из головы. */
  readonly тонн: number;
  readonly двери: readonly Проём[];
  readonly окна: readonly Проём[];
}

/** Одно и то же зерно даёт один и тот же дом. Всегда. */
function зерно(сид: number): () => number {
  let s = (сид ^ 0x85ebca6b) >>> 0;
  return () => {
    s = (Math.imul(s ^ (s >>> 13), 0x27d4eb2f) + 0x165667b1) >>> 0;
    return ((s ^ (s >>> 15)) >>> 0) / 4294967296;
  };
}

/** Цвет стен по назначению. Назначение видно с улицы — как в жизни. */
const ПАЛИТРА: Record<Назначение, number[]> = {
  жильё: [0xc9b79c, 0xd6c4a8, 0xb9a88e, 0xc2b49b, 0xd9cfbc, 0xcfc0a4, 0xa8967c],
  сад: [0xe8c86a, 0xe0bd5c],
  школа: [0xb06a4a, 0xa8654a],
  магазин: [0x7fa3c4, 0x6d93b8],
  поликлиника: [0xe6e6e0, 0xdcdcd4],
};
/** Крыша: шифер, железо, битум. */
const КРЫШИ = [0x5a5f64, 0x6b4a42, 0x47514a, 0x3f434a, 0x7a6a58];

/**
 * Дом, выведенный из участка.
 *
 * Сид дома складывается из сида посёлка и МЕСТА участка. Поэтому дом
 * не зависит от того, в каком порядке их считали, и один и тот же участок
 * всегда даёт один и тот же дом — а соседние дома получаются разными.
 * Раньше сид посёлка не участвовал вообще: три разных сида давали побайтово
 * один посёлок, и проверка «один сид — один посёлок» проходила впустую.
 */
export function домНаУчастке(
  участок: Объект, вид: Вид, сидПосёлка: number,
  /**
   * `ширина: 'во весь участок'` — взять фронт участка целиком, без прохода
   * между домами. Заведомо сломанный вариант: дом становится шире участка
   * ровно на тот проход, и соседние дома смыкаются стенами.
   */
  как: {
    ширина?: 'во весь участок'; палисадник?: 'наоборот';
    /**
     * `окна: 'одна длина на все грани'` — раскладывать ВСЕ ряды по ширине
     * дома, забыв, что у торца длина своя. Заведомо сломанный вариант,
     * и это ровно та ошибка, которой грозит общий `длинаГрани`: у дома
     * 20 × 14 окна торца уезжают за угол на три метра и висят в воздухе.
     */
    /**
     * `окна: 'глухой двор'` — не резать дворовую грань вовсе, как было
     * до 22.09. Заведомо сломанный вариант: квартал изнутри снова забор.
     */
    окна?: 'одна длина на все грани' | 'глухой двор';
  } = {},
): Дом {
  const место = Math.imul(Math.round(участок.x) | 0, 73856093)
    ^ Math.imul(Math.round(участок.z) | 0, 19349663)
    ^ Math.imul(сидПосёлка | 0, 83492791);
  const случайно = зерно(место);

  const жилой = участок.что === 'жильё';
  const норма = ЗАСТРОЙКА[вид];
  const размер = РАЗМЕР[участок.что];

  /**
   * Этажность гуляет вокруг нормы: на одной улице не бывает десяти
   * одинаковых домов. Разброс — целыми этажами, потому что полэтажа
   * не бывает, и не ниже одного.
   */
  const этажей = жилой
    ? Math.max(1, норма.этажей + (случайно() < 0.25 ? -1 : случайно() > 0.8 ? 1 : 0))
    : размер.этажей;

  /**
   * ПО ФРОНТУ ДОМ ЗАНИМАЕТ ВЕСЬ УЧАСТОК — в городе. В деревне между домами
   * остаётся проход.
   *
   * Это главное отличие городского квартала от посёлка, и оно не про красоту.
   * Замерено 18.09: дом занимал 86% фронта своего участка, то есть между
   * соседями зияло два-четыре метра, и сквозь них с улицы просматривалось
   * пустое поле внутри квартала. Настоящий городской квартал — сплошная
   * стена домов с общими брандмауэрами; двор за ней не виден вовсе.
   *
   * Четверть метра между домами оставлена не на проход, а на шов: при нуле
   * стены соседей совпали бы плоскость в плоскость и замерцали бы.
   */
  const ШОВ = 0.25;
  /**
   * Шире своего участка дом не бывает — это последнее слово, а не пожелание.
   * Нижняя граница в шесть метров нужна узким участкам служб, но она же
   * однажды перевесила ширину участка на двадцать сантиметров: поймано
   * проверкой 21.09.
   */
  const ширина = как.ширина === 'во весь участок'
    ? участок.фронт + 2
    : Math.min(участок.фронт - 0.1, вид === 'город'
      ? Math.max(6, участок.фронт - ШОВ)
      : Math.max(6, участок.фронт - (жилой ? 2 + случайно() * 2.5 : 2)));
  /**
   * Глубина дома выводится ИЗ ЕГО ШИРИНЫ, а не гуляет сама по себе.
   *
   * Сначала сделали независимо — и вытянутость следа уехала с 1.19 до 1.48
   * при настоящих 1.18: дома стали палками. Причина простая и её видно
   * в замере: у настоящего дома фронт 17.8 м при глубине 15.9, то есть
   * он почти квадратный, а разброс площадей берётся не из перекоса сторон,
   * а из того, что большой участок даёт большой дом В ОБЕ СТОРОНЫ.
   *
   * Поэтому глубина — это ширина, делённая на вытянутость, а гуляет сама
   * вытянутость, и гуляет узко (1.05…1.40 при настоящей медиане 1.18).
   * Площадь от этого разбрасывается как КВАДРАТ ширины, а форма остаётся
   * домом. Вилка глубины при этом остаётся пределом: ни уже, ни глубже
   * того, что бывает, дом не получится.
   */
  const вытянутость = 1.05 + случайно() * 0.35;
  const глубинаДома = жилой
    ? Math.min(норма.глубинаДома.макс,
      Math.max(норма.глубинаДома.мин, ширина / вытянутость))
    : размер.глубина;
  const высота = этажей * ЭТАЖ;

  /**
   * Крыша. Малоэтажное — скатное, многоэтажное и общественное — плоское
   * с парапетом. Это не украшение: именно по крыше с улицы читается,
   * жилой дом перед тобой или магазин.
   */
  const скатная = жилой && этажей <= 2;
  const подъём = скатная
    ? Math.min(3.2, (глубинаДома / 2) * УКЛОН_КРЫШИ)
    : 0.45 + случайно() * 0.35;

  /**
   * Дом придвинут К КРАСНОЙ ЛИНИИ: у жилья через палисадник, у магазина
   * витриной вплотную. Курс смотрит на улицу, поэтому сдвиг идёт ПО курсу.
   *
   * До 17.09 здесь стоял минус, и дом уезжал от улицы вместо того, чтобы
   * подходить к ней. Замерено: палисадник по норме 3 м, на деле выходил 9,
   * а витрина магазина, которой полагается стоять на красной линии,
   * оказывалась в восьми метрах от неё. Отсюда же и пустая полоса газона
   * между тротуаром и домами, которая с уровня глаз выдаёт нарисованность.
   */
  /**
   * ПАЛИСАДНИК — ДЕРЕВЕНСКАЯ ВЕЩЬ. В городском квартале фасад стоит НА
   * красной линии, вплотную к тротуару: так устроен периметральный квартал
   * везде, где он есть, и так же уже стояли магазины. Три метра газона
   * перед каждым домом — это ровно то, чем городская улица отличается
   * от загородной, и отличается в худшую сторону.
   */
  const отступ = жилой && вид === 'деревня' ? ПАЛИСАДНИК : 0;
  const вглубь = (участок.глубина - глубинаДома) / 2 - отступ;
  /** Заведомо сломанный вариант: сдвиг против курса — как было до 17.09. */
  const знак = как.палисадник === 'наоборот' ? -1 : 1;
  const x = участок.x + знак * Math.cos(участок.курс) * вглубь;
  const z = участок.z + знак * Math.sin(участок.курс) * вглубь;

  /**
   * Квартиры и жители. Не «столько-то человек на дом», а: площадь этажей →
   * полезная площадь → делённая на норму жилья = сколько людей помещается.
   * Квартира — то же самое число, только через среднюю площадь квартиры.
   */
  const площадьЭтажей = ширина * глубинаДома * этажей;
  const полезная = площадьЭтажей * ПОЛЕЗНАЯ;
  const жителей = жилой ? Math.max(1, Math.round(полезная / МЕТРОВ_НА_ЧЕЛОВЕКА)) : 0;
  const квартир = жилой ? Math.max(1, Math.round(жителей / 2.4)) : 0;
  const мест = жилой ? 0
    : участок.что === 'поликлиника' ? ВМЕСТИМОСТЬ.поликлиника
      : участок.что === 'сад' ? ВМЕСТИМОСТЬ.сад
        : участок.что === 'школа' ? ВМЕСТИМОСТЬ.школа : ВМЕСТИМОСТЬ.магазин;

  /** Масса: полный объём на среднюю плотность здания. Настоящие тонны. */
  const тонн = Math.round((ширина * глубинаДома * высота * ПЛОТНОСТЬ) / 1000);

  /**
   * Подъезды. У жилого — по одному на каждые двенадцать квартир, но
   * не гуще, чем позволяет фронт. У общественного — один главный вход.
   * Дом без двери здесь записать негде: подъездов всегда хотя бы один.
   */
  const подъездов = жилой
    ? Math.max(1, Math.min(Math.floor(ширина / 7), Math.ceil(квартир / КВАРТИР_НА_ПОДЪЕЗД)))
    : 1;
  /**
   * Дверь — на грани входа: фасад (0) или двор (2). Решил план (`Объект.вход`).
   *
   * Со двора подъезды встают только на ту часть задней стены, за которой
   * двор, а не бок соседнего крыла: у углового дома это лишь кусок стены.
   * Кусок — проекция прямоугольника двора на ось вдоль дома, в метре от краёв.
   * 24.09 без этого у угловых домов дорожки шли сквозь чужие стены.
   */
  const граньВхода: Грань = участок.вход.куда === 'двор' ? 2 : 0;
  let от = -ширина / 2, до = ширина / 2;
  if (участок.вход.куда === 'двор') {
    const в = участок.вход;
    const s = Math.sin(участок.курс), c = Math.cos(участок.курс);
    const проекции = [[в.x0, в.z0], [в.x1, в.z0], [в.x0, в.z1], [в.x1, в.z1]]
      .map(([x, z]) => (x - участок.x) * -s + (z - участок.z) * c);
    от = Math.max(от, Math.min(...проекции) + 1);
    до = Math.min(до, Math.max(...проекции) - 1);
  }
  const открыто = Math.max(ДВЕРЬ.ширина, до - от);
  const сколькоДверей = Math.max(1, Math.min(подъездов, Math.floor(открыто / 7)));
  const двери: Проём[] = [];
  for (let i = 0; i < сколькоДверей; i++) {
    двери.push({ грань: граньВхода, вдоль: от + ((i + 0.5) / сколькоДверей) * (до - от), этаж: 0 });
  }

  /**
   * Окна. Нарезаются ПО ГРАНИ И ПО ЭТАЖУ, и ряд считается из длины САМОЙ
   * ГРАНИ (`длинаГрани`), а не из того, что помнит про неё это место.
   * Поэтому «окно выше крыши» и «окно сбоку от стены» не существует.
   * На первом этаже окно пропускается там, где стоит дверь: два проёма
   * в одном месте — это не дом.
   *
   * **ДВОРОВАЯ ГРАНЬ (2) появилась 22.09, и до неё двор был забором.**
   * Окна были на фасаде и двух торцах — то есть ровно на тех сторонах,
   * которые видно с улицы. Со двора каждый дом показывал глухую стену,
   * и квартал изнутри читался не домами, а оградой. Найдено не проверкой,
   * а снимком с уровня глаз (правило 7): площадку поставили, сняли —
   * и на снимке она стоит посреди поля, обнесённого глухим забором.
   *
   * Дверей во двор до 24.09 не было: подход кончался только на тротуаре
   * улицы. Разговор состоялся (Алекс: «внутри двора пустырь»), и теперь
   * подход один на оба случая — от двери наружу до ближайшего полотна:
   * тротуара улицы или проезда двора (`двор.ts`).
   */
  const окна: Проём[] = [];
  const стороны = { ширина, глубина: глубинаДома };
  for (let этаж = 0; этаж < этажей; этаж++) {
    for (const грань of [0, 2, 1, -1] as const) {
      if (грань === 2 && как.окна === 'глухой двор') continue;
      const длина = как.окна === 'одна длина на все грани'
        ? ширина : длинаГрани(стороны, грань);
      const сколько = Math.max(1, Math.floor(длина / ОКНО.шаг));
      for (let i = 0; i < сколько; i++) {
        const вдоль = ((i + 0.5) / сколько - 0.5) * длина;
        // окно уступает двери там, где она стоит: на её грани, на первом этаже
        const занято = грань === граньВхода && этаж === 0
          && двери.some((д) => Math.abs(д.вдоль - вдоль) < (ДВЕРЬ.ширина + ОКНО.ширина) / 2);
        if (!занято) окна.push({ грань, вдоль, этаж });
      }
    }
  }

  return {
    что: участок.что,
    x, z, курс: участок.курс,
    ширина, глубина: глубинаДома,
    этажей, высота,
    крыша: скатная ? 'скатная' : 'плоская',
    подъём,
    цвет: ПАЛИТРА[участок.что][Math.floor(случайно() * ПАЛИТРА[участок.что].length)
      % ПАЛИТРА[участок.что].length],
    цветКрыши: КРЫШИ[Math.floor(случайно() * КРЫШИ.length) % КРЫШИ.length],
    квартир, жителей, мест, тонн,
    двери, окна,
  };
}
