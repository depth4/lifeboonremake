/**
 * Маршрут по улицам: как доехать отсюда туда.
 *
 * Зачем он вообще. Пока машина выбирает поворот НАУГАД, она никуда не едет —
 * она катается. Отсюда и всё остальное: паркуется где придётся, стоит до
 * чужого часа, а «приехал» сказать нельзя, потому что приезжать некуда.
 * Маршрут — это то, что превращает катание в поездку, и без него «город
 * работает» не выразить никакими заплатками.
 *
 * Устройство простое и честное: дорожная сеть — это граф узлов, длина ребра
 * это длина дороги, и кратчайший путь ищется обычным Дейкстрой. Сеть города
 * — сотни узлов, поэтому считать можно прямо на ходу; кэш нужен не для
 * скорости, а чтобы одна машина не пересчитывала одно и то же каждый кадр.
 *
 * Про экран этот файл не знает ничего.
 */

import type { Network } from './traffic.ts';

/** Куда едем: дорога и метр на ней. */
export interface Куда {
  readonly shape: number;
  readonly s: number;
  /**
   * По какую сторону от осевой стоит цель: знак важен, величина нет.
   * Машине это безразлично — она подъезжает по своей полосе. Пешеходу нет:
   * дом на той стороне улицы значит, что дорогу надо ПЕРЕЙТИ, а не пройти
   * мимо по своему тротуару.
   */
  readonly across?: number;
}

/**
 * Маршрут: по каким дорогам ехать по порядку. Первая — та, на которой мы
 * сейчас, последняя — та, где цель.
 */
export interface Маршрут {
  readonly дороги: readonly number[];
  readonly цель: Куда;
  /** Сколько метров ехать. Нужно, чтобы понять, когда «почти приехали». */
  readonly метров: number;
}

/**
 * Кратчайший путь от дороги к дороге.
 *
 * Ищется по УЗЛАМ, а не по дорогам: узел — это место, где можно свернуть,
 * и других мест не бывает. Возвращается последовательность дорог, потому
 * что ехать машина умеет только по дороге.
 */
export function путь(net: Network, откуда: Куда, куда: Куда): Маршрут | null {
  if (откуда.shape === куда.shape) {
    return { дороги: [откуда.shape], цель: куда, метров: Math.abs(куда.s - откуда.s) };
  }

  /** Стоимость до узла и как мы в него попали. */
  const цена = new Map<number, number>();
  const откудаПришли = new Map<number, { узел: number; дорога: number }>();
  /** Очередь: узел и накопленная цена. Сеть невелика, хватает списка. */
  const очередь: { узел: number; цена: number }[] = [];

  // старт: оба конца нашей дороги, каждый со своей ценой доезда
  for (const { узел, s } of концы(net, откуда.shape)) {
    const c = Math.abs(s - откуда.s);
    if (!цена.has(узел) || c < (цена.get(узел) ?? Infinity)) {
      цена.set(узел, c);
      откудаПришли.set(узел, { узел: -1, дорога: откуда.shape });
      очередь.push({ узел, цена: c });
    }
  }

  const цели = new Map<number, number>();
  for (const { узел, s } of концы(net, куда.shape)) цели.set(узел, Math.abs(s - куда.s));

  let лучший: { узел: number; цена: number } | null = null;
  while (очередь.length > 0) {
    очередь.sort((a, b) => a.цена - b.цена);
    const тек = очередь.shift() as { узел: number; цена: number };
    if (тек.цена > (цена.get(тек.узел) ?? Infinity)) continue;
    const доЦели = цели.get(тек.узел);
    if (доЦели !== undefined) {
      const всего = тек.цена + доЦели;
      if (лучший === null || всего < лучший.цена) лучший = { узел: тек.узел, цена: всего };
    }
    if (лучший !== null && тек.цена >= лучший.цена) break;

    for (const ветка of net.atJunction[тек.узел]) {
      for (const сосед of концы(net, ветка.shape)) {
        if (сосед.узел === тек.узел) continue;
        const шаг = Math.abs(сосед.s - ветка.s);
        const новая = тек.цена + шаг;
        if (новая >= (цена.get(сосед.узел) ?? Infinity)) continue;
        цена.set(сосед.узел, новая);
        откудаПришли.set(сосед.узел, { узел: тек.узел, дорога: ветка.shape });
        очередь.push({ узел: сосед.узел, цена: новая });
      }
    }
  }

  if (лучший === null) return null;

  // разматываем назад: получается список дорог от цели к старту
  const дороги: number[] = [куда.shape];
  let узел = лучший.узел;
  for (let шаг = 0; шаг < 1000; шаг++) {
    const пришли = откудаПришли.get(узел);
    if (пришли === undefined) break;
    дороги.push(пришли.дорога);
    if (пришли.узел < 0) break;
    узел = пришли.узел;
  }
  дороги.reverse();
  return { дороги, цель: куда, метров: лучший.цена };
}

/** Концы дороги: в какие узлы она упирается и на каком метре. */
function концы(net: Network, shape: number): { узел: number; s: number }[] {
  const из: { узел: number; s: number }[] = [];
  const начало = net.ends[shape][0];
  const конец = net.ends[shape][1];
  if (начало !== null) из.push({ узел: начало.junction, s: 0 });
  if (конец !== null) из.push({ узел: конец.junction, s: net.length[shape] });
  return из;
}

/**
 * По какой дороге ехать дальше, стоя на этой.
 *
 * Не «следующая в списке», а «первая из списка ПОСЛЕ текущей»: машина может
 * оказаться на дороге, которую маршрут проходит дважды, и тогда «следующая
 * по номеру» увела бы её назад.
 */
export function дальше(м: Маршрут, сейчас: number): number | null {
  const где = м.дороги.lastIndexOf(сейчас);
  if (где < 0 || где + 1 >= м.дороги.length) return null;
  return м.дороги[где + 1];
}
