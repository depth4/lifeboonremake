/**
 * Улица: всё, что стоит между проезжей частью и домом.
 *
 * Дома сделали улицу улицей, но между тротуаром и цоколем оставалось
 * ровное зелёное поле — и с уровня глаз это читалось как макет, а не как
 * место, где живут. Здесь появляется то, чего в макете не бывает: деревья,
 * фонари, дорожки к подъездам, парковочные карманы, остановки, заборы.
 *
 * **Машин здесь нет.** Машина в этом проекте одна — та, которая ездит
 * (решение 063). Нарисованная машина была вторым её сортом, и Алекс увидел
 * это первым.
 *
 * **Ничего не ставится «на глаз».** Всё считается от улицы: полуширина
 * проезжей части и тротуар берутся из типа дороги, красная линия — из норм,
 * а расстояния до дерева и до фонаря — из СП. Поэтому «дерево посреди
 * проезжей части» и «фонарь в стене» невыразимы: и то и другое
 * отсчитывается ОТ ОСИ улицы, и дальше красной линии не заходит.
 *
 * Про Three.js этот файл не знает ничего.
 */

import { roadTypeForLanes, roadWidth } from '../world/road.ts';
import { type Кусок, type Улица, двор as дворКвартала } from './plan.ts';
import type { Дом } from './house.ts';
import { type Вид, ДОМ, ЗАСТРОЙКА } from './norms.ts';
import {
  type Куча, type Сетка, квад, коробка, крона, куча, собрать, столб,
} from './mesh.ts';

/** Всё, что стоит на улице, одним куском. */
export interface Обстановка {
  readonly стены: Сетка;
  readonly свет: Сетка;
  /** Сколько чего встало. Число живёт здесь, а не переписывается в память. */
  readonly счёт: Record<string, number>;
}

/**
 * На сколько плоское покрытие поднято над землёй, м.
 *
 * Это не «подкрученная константа», а следствие замера: земля под посёлком
 * меняется примерно на полтора сантиметра на метр, а куски покрытия кладутся
 * отрезками по два метра. Подъёма в пять сантиметров не хватало — середина
 * отрезка проваливалась под землю, и дорожки с проездами были видны только
 * вблизи, где смотришь вдоль. Двенадцать сантиметров — это ещё и правда:
 * асфальтовая карта лежит выше газона, а не вровень с ним.
 */
const ЛЕЖИТ = 0.12;

/** Одно и то же зерно — одна и та же улица. Всегда. */
function зерно(сид: number): () => number {
  let s = (сид ^ 0x6d2b79f5) >>> 0;
  return () => {
    s = (Math.imul(s ^ (s >>> 15), 0x2c1b3c6d) + 0x9e3779b9) >>> 0;
    return ((s ^ (s >>> 16)) >>> 0) / 4294967296;
  };
}

/** Геометрия улицы: где кончается асфальт, где тротуар, где красная линия. */
interface Размеры {
  readonly вдольX: boolean;
  /** Положение оси: z для улицы вдоль X, x для улицы вдоль Z. */
  readonly ось: number;
  readonly от: number;
  readonly до: number;
  readonly полуширина: number;
  readonly тротуар: number;
  readonly красная: number;
}

function размеры(у: Улица): Размеры {
  const тип = roadTypeForLanes(у.полосВСторону);
  const вдольX = у.a.z === у.b.z;
  return {
    вдольX,
    ось: вдольX ? у.a.z : у.a.x,
    от: вдольX ? Math.min(у.a.x, у.b.x) : Math.min(у.a.z, у.b.z),
    до: вдольX ? Math.max(у.a.x, у.b.x) : Math.max(у.a.z, у.b.z),
    полуширина: roadWidth(тип) / 2,
    тротуар: тип.sidewalk,
    красная: у.отступ,
  };
}

/** Точка мира по «вдоль улицы» и «поперёк от оси». Одно место на весь файл. */
const где = (р: Размеры, вдоль: number, поперёк: number): { x: number; z: number } =>
  р.вдольX ? { x: вдоль, z: р.ось + поперёк } : { x: р.ось + поперёк, z: вдоль };

/**
 * Перекрёстки: где вдоль этой улицы проходит другая.
 *
 * Возле перекрёстка не ставят ничего — ни дерева, ни фонаря, ни машины:
 * они закрывают видимость, и это не вкус, а требование треугольника
 * видимости (ГОСТ Р 52766 и СП 42.13330: в зоне перекрёстка не должно быть
 * ничего выше 0.5 м).
 */
function перекрёстки(р: Размеры, улицы: readonly Улица[]): number[] {
  const из: number[] = [];
  for (const д of улицы) {
    const рд = размеры(д);
    if (рд.вдольX === р.вдольX) continue;
    из.push(рд.ось);
  }
  return из;
}

const далекоОтПерекрёстка = (вдоль: number, узлы: readonly number[], запас: number): boolean =>
  узлы.every((у) => Math.abs(вдоль - у) > запас);

