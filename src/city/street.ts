/**
 * Деревья вдоль улицы.
 *
 * Ряд идёт по газону между тротуаром и застройкой. СП 42.13330 (таблица
 * расстояний до зданий и сооружений): от наружной стены здания до оси ствола
 * дерева не менее 5 м, до края тротуара — не менее 0.7 м. Оба требования
 * выполняются ПО ПОСТРОЕНИЮ: ряд стоит на фиксированном отступе от оси
 * улицы, между тротуаром и красной линией.
 */
function деревья(
  к: Куча, р: Размеры, узлы: readonly number[],
  земля: (x: number, z: number) => number, случайно: () => number, счёт: Record<string, number>,
): void {
  const отТротуара = р.полуширина + р.тротуар;
  // между тротуаром и красной линией должно остаться место под крону
  const место = р.красная - отТротуара;
  if (место < УЛИЦА_ОБСТАНОВКА.дерево.отТротуара + 1.5) return;
  const поперёк = отТротуара + УЛИЦА_ОБСТАНОВКА.дерево.отТротуара;

  for (const сторона of [-1, 1] as const) {
    for (let вдоль = р.от + 6; вдоль < р.до - 6; вдоль += УЛИЦА_ОБСТАНОВКА.дерево.шаг) {
      if (!далекоОтПерекрёстка(вдоль, узлы, р.красная + 6)) continue;
      const т = где(р, вдоль, сторона * поперёк);
      const y = земля(т.x, т.z);
      const рост = УЛИЦА_ОБСТАНОВКА.дерево.высота * (0.8 + случайно() * 0.4);
      const ствол = рост * 0.42;
      столб(к, т.x, т.z, y - 0.2, y + ствол + 0.3, 0.14, ДОМ.цвет.ствол);
      крона(к, т.x, т.z, y + ствол * 0.92, рост - ствол * 0.92, рост * 0.21,
        ДОМ.цвет.листва[Math.floor(случайно() * ДОМ.цвет.листва.length)]);
      счёт.деревьев = (счёт.деревьев ?? 0) + 1;
    }
  }
}

/**
 * Опоры освещения.
 *
 * Стоят у бортового камня, а не в глубине газона: светят на проезжую часть.
 * Высота 8 м на магистральной и 6.5 м на местной, шаг 30 м — практика
 * (расчёт по СП 52.13330 даёт шаг три-четыре высоты опоры). Стороны
 * чередуются: на местной улице фонари по одной стороне, на магистральной
 * по обеим.
 */
function фонари(
  к: Куча, свет: Куча, р: Размеры, узлы: readonly number[], магистральная: boolean,
  земля: (x: number, z: number) => number, счёт: Record<string, number>,
): void {
  const высота = магистральная
    ? УЛИЦА_ОБСТАНОВКА.фонарь.высотаМагистральной
    : УЛИЦА_ОБСТАНОВКА.фонарь.высотаМестной;
  const поперёк = р.полуширина + Math.min(0.9, р.тротуар * 0.4);
  const стороны = магистральная ? [-1, 1] : [1];
  for (const сторона of стороны as (-1 | 1)[]) {
    for (let вдоль = р.от + 12; вдоль < р.до - 12; вдоль += УЛИЦА_ОБСТАНОВКА.фонарь.шаг) {
      if (!далекоОтПерекрёстка(вдоль, узлы, р.красная)) continue;
      const т = где(р, вдоль, сторона * поперёк);
      const y = земля(т.x, т.z);
      столб(к, т.x, т.z, y, y + высота, 0.11, ДОМ.цвет.опора);
      // вылет консоли над проезжей частью и сам светильник
      const вылет = где(р, вдоль, сторона * (поперёк - 1.4));
      квад(к,
        [т.x, y + высота - 0.1, т.z], [вылет.x, y + высота - 0.1, вылет.z],
        [вылет.x, y + высота, вылет.z], [т.x, y + высота, т.z], ДОМ.цвет.опора);
      коробка(свет, вылет.x, y + высота - 0.22, вылет.z, 0.9, 0.16, 0.34,
        р.вдольX ? 1 : 0, р.вдольX ? 0 : 1, ДОМ.цвет.лампа);
      счёт.фонарей = (счёт.фонарей ?? 0) + 1;
    }
  }
}

/**
 * Дорожка от тротуара к подъезду.
 *
 * Без неё жители ходят по газону, и это видно: в любом дворе тропа
 * протоптана ровно там, где дорожки нет. Дорожка идёт от тротуара прямо
 * ко входу и кладётся ПО ЗЕМЛЕ — высота берётся у той же земли, по которой
 * ходят, поэтому «дорожка, висящая над склоном» невыразима.
 */
function дорожки(
  к: Куча, дом: Дом, р: Размеры,
  земля: (x: number, z: number) => number, счёт: Record<string, number>,
): void {
  const fx = -дом.нz, fz = дом.нx;
  const фасадX = дом.x + дом.нx * (дом.глубина / 2);
  const фасадZ = дом.z + дом.нz * (дом.глубина / 2);
  const доТротуара = Math.abs((р.вдольX ? фасадZ : фасадX) - р.ось) - (р.полуширина + р.тротуар);
  if (доТротуара < 1) return;

  for (const п of дом.проёмы) {
    if (п.вид !== 'дверь' || п.стена !== 0 || п.этаж !== 0) continue;
    const вдольСтены = (п.от + п.до) / 2 - п.длинаСтены / 2;
    const x0 = фасадX + fx * вдольСтены;
    const z0 = фасадZ + fz * вдольСтены;
    const шагов = Math.max(2, Math.ceil(доТротуара / 2));
    const ш = УЛИЦА_ОБСТАНОВКА.дорожка / 2;
    for (let i = 0; i < шагов; i++) {
      const a = (доТротуара * i) / шагов;
      const b = (доТротуара * (i + 1)) / шагов;
      const ax = x0 + дом.нx * a, az = z0 + дом.нz * a;
      const bx = x0 + дом.нx * b, bz = z0 + дом.нz * b;
      квад(к,
        [ax - fx * ш, земля(ax, az) + 0.04, az - fz * ш],
        [bx - fx * ш, земля(bx, bz) + 0.04, bz - fz * ш],
        [bx + fx * ш, земля(bx, bz) + 0.04, bz + fz * ш],
        [ax + fx * ш, земля(ax, az) + 0.04, az + fz * ш],
        ДОМ.цвет.плитка);
    }
    // скамейка и урна у подъезда: по ним двор и узнаётся
    const лавка = { x: x0 + дом.нx * 2.2 + fx * 2.4, z: z0 + дом.нz * 2.2 + fz * 2.4 };
    const y = земля(лавка.x, лавка.z);
    коробка(к, лавка.x, y + 0.45, лавка.z, 1.8, 0.12, 0.45, fx, fz, ДОМ.цвет.скамейка);
    коробка(к, лавка.x, y + 0.22, лавка.z, 1.6, 0.08, 0.1, fx, fz, ДОМ.цвет.опора);
    счёт.подъездов = (счёт.подъездов ?? 0) + 1;
  }
}

/**
 * Парковка вдоль улицы и машины на ней.
 *
 * Уровень автомобилизации по СП 42.13330 — 350 автомобилей на 1000 жителей;
 * из этого и берётся, сколько мест нужно кварталу. Место 5.3 × 2.5 м —
 * размер машино-места для легкового автомобиля (СП 113.13330, практика).
 * Машины ставятся не «для красоты»: пустая парковка в жилом квартале
 * выглядит страннее, чем её отсутствие.
 */
function парковка(
  к: Куча, р: Размеры, узлы: readonly number[], сколькоМест: number,
  земля: (x: number, z: number) => number, случайно: () => number, счёт: Record<string, number>,
): void {
  const место = УЛИЦА_ОБСТАНОВКА.машиноМесто;
  const свободно = р.красная - (р.полуширина + р.тротуар);
  /**
   * Как ставить машины, решает арифметика, а не вкус: между тротуаром и
   * красной линией либо помещается КАРМАН (машина носом к дороге, 5.3 м
   * вглубь), либо не помещается, и тогда парковка вдоль — 2.5 м вглубь.
   * На местной улице с красной линией 20 м карман не влезает никогда,
   * и во дворах России это ровно так и выглядит.
   */
  const карманом = свободно >= место.длина + 1.2;
  const вглубь = карманом ? место.длина : место.ширина;
  const шагВдоль = карманом ? место.ширина : место.длина + 0.8;
  if (свободно < вглубь + 0.8) return;
  const поперёк = р.полуширина + р.тротуар + вглубь / 2 + 0.4;

  let поставлено = 0;
  for (const сторона of [-1, 1] as const) {
    for (let вдоль = р.от + 18; вдоль < р.до - 18; вдоль += шагВдоль) {
      if (поставлено >= сколькоМест) break;
      if (!далекоОтПерекрёстка(вдоль, узлы, р.красная + 10)) continue;
      const т = где(р, вдоль, сторона * поперёк);
      const y = земля(т.x, т.z);
      const вx = р.вдольX ? 1 : 0, вz = р.вдольX ? 0 : 1;
      // асфальт кармана
      коробка(к, т.x, y + 0.02, т.z,
        карманом ? место.ширина - 0.1 : место.длина, 0.04,
        карманом ? место.длина : место.ширина, вx, вz, ДОМ.цвет.асфальт);
      поставлено++;
      счёт.мест = (счёт.мест ?? 0) + 1;
      // не каждое место занято: пустых мест во дворе всегда часть
      if (случайно() > 0.62) continue;
      машина(к, т.x, y, т.z, карманом, вx, вz, случайно);
      счёт.машин = (счёт.машин ?? 0) + 1;
    }
  }
}

/**
 * Припаркованная машина: кузов, салон и четыре колеса. Больше и не нужно —
 * с тротуара машина читается силуэтом, а не деталями.
 *
 * В кармане она стоит поперёк улицы, вдоль улицы — по ней. Ось кузова
 * выводится из этого, а не задаётся: «машина поперёк парковочного места»
 * записать нечем.
 */
function машина(
  к: Куча, x: number, y: number, z: number,
  карманом: boolean, вx: number, вz: number, случайно: () => number,
): void {
  const цвет = ДОМ.цвет.машина[Math.floor(случайно() * ДОМ.цвет.машина.length)];
  // вдоль кузова: в кармане поперёк улицы, иначе вдоль улицы
  const кx = карманом ? -вz : вx;
  const кz = карманом ? вx : вz;
  коробка(к, x, y + 0.66, z, 4.4, 0.66, 1.78, кx, кz, цвет);
  коробка(к, x - кx * 0.25, y + 1.18, z - кz * 0.25, 2.3, 0.46, 1.6, кx, кz, ДОМ.цвет.стекло);
  for (const вдоль of [-1.45, 1.45]) {
    for (const поперёк of [-0.82, 0.82]) {
      const пx = -кz, пz = кx;
      коробка(к, x + кx * вдоль + пx * поперёк, y + 0.32, z + кz * вдоль + пz * поперёк,
        0.62, 0.62, 0.2, кx, кz, ДОМ.цвет.колесо);
    }
  }
}

/**
 * Остановка: павильон с навесом и посадочная площадка.
 *
 * ГОСТ Р 52766 требует посадочную площадку не менее 10 м длиной и 3 м
 * шириной и павильон. Ставится на тротуаре своей улицы, а не «где-то рядом»:
 * место остановки уже посчитано планом по нормам расстояния между ними.
 */
function остановка(
  к: Куча, свет: Куча, x: number, z: number, улицы: readonly Улица[],
  земля: (x: number, z: number) => number, счёт: Record<string, number>,
): void {
  // своя улица — ближайшая: остановка стоит на той, по которой идёт автобус
  let р: Размеры | null = null;
  let ближе = Infinity;
  for (const у of улицы) {
    const рр = размеры(у);
    const d = Math.abs((рр.вдольX ? z : x) - рр.ось);
    if (d < ближе) { ближе = d; р = рр; }
  }
  if (!р) return;
  const сторона = ((р.вдольX ? z : x) - р.ось) >= 0 ? 1 : -1;
  const поперёк = сторона * (р.полуширина + р.тротуар + 1.6);
  const вдоль = р.вдольX ? x : z;
  const т = где(р, вдоль, поперёк);
  const y = земля(т.x, т.z);
  const вx = р.вдольX ? 1 : 0, вz = р.вдольX ? 0 : 1;

  const П = УЛИЦА_ОБСТАНОВКА.павильон;
  // посадочная площадка
  коробка(к, т.x, y + 0.03, т.z, П.площадка, 0.06, 3.0, вx, вz, ДОМ.цвет.плитка);
  // задняя стенка и навес
  const зад = где(р, вдоль, поперёк + сторона * 1.2);
  коробка(к, зад.x, y + 1.3, зад.z, П.длина, 2.6, 0.12, вx, вz, ДОМ.цвет.павильон);
  коробка(к, т.x, y + 2.66, т.z, П.длина, 0.12, 2.6, вx, вz, ДОМ.цвет.павильон);
  for (const край of [-1, 1]) {
    const с = { x: т.x + вx * край * П.длина / 2, z: т.z + вz * край * П.длина / 2 };
    столб(к, с.x, с.z, y, y + 2.6, 0.07, ДОМ.цвет.опора);
  }
  // подсвеченная схема маршрутов: по ней остановку видно издалека
  коробка(свет, зад.x, y + 1.7, зад.z, 1.2, 0.9, 0.16, вx, вz, ДОМ.цвет.табло);
  счёт.остановок = (счёт.остановок ?? 0) + 1;
}

/**
 * Забор усадьбы и палисадник.
 *
 * В деревне улицу держит не дом — дом стоит в пяти метрах от красной линии, —
 * а ЗАБОР по красной линии. Без него дома стоят в чистом поле. Высота 1.8 м:
 * практика ИЖС, ограничена правилами землепользования, а не СП.
 */
function забор(
  к: Куча, дом: Дом, р: Размеры, участокФронт: number,
  земля: (x: number, z: number) => number, счёт: Record<string, number>,
): void {
  const fx = -дом.нz, fz = дом.нx;
  const сторона = ((р.вдольX ? дом.z : дом.x) - р.ось) >= 0 ? 1 : -1;
  const линия = р.ось + сторона * р.красная;
  const З = УЛИЦА_ОБСТАНОВКА.забор;
  const шагов = Math.max(2, Math.round(участокФронт / 2));
  for (let i = 0; i < шагов; i++) {
    const a = -участокФронт / 2 + (участокФронт * i) / шагов;
    const b = -участокФронт / 2 + (участокФронт * (i + 1)) / шагов;
    // калитка посередине: в забор без калитки не войти
    if (Math.abs((a + b) / 2) < 1.6) continue;
    const ax = р.вдольX ? дом.x + fx * a : линия;
    const az = р.вдольX ? линия : дом.z + fz * a;
    const bx = р.вдольX ? дом.x + fx * b : линия;
    const bz = р.вдольX ? линия : дом.z + fz * b;
    const y = земля(ax, az);
    квад(к, [ax, y, az], [bx, земля(bx, bz), bz],
      [bx, земля(bx, bz) + З.высота, bz], [ax, y + З.высота, az], ДОМ.цвет.забор);
  }
  счёт.заборов = (счёт.заборов ?? 0) + 1;
}

