/**
 * Размеры уличной обстановки. Каждое число — со статусом, как и всё
 * остальное в этом проекте.
 */
export const УЛИЦА_ОБСТАНОВКА = {
  /**
   * Дерево. `отТротуара` 2.0 м — так, чтобы до стены дома оставалось
   * не меньше 5 м (СП 42.13330), а до края тротуара не меньше 0.7 м.
   * Шаг 8 м и высота 9 м — практика уличного озеленения (липа, клён).
   */
  дерево: { отТротуара: 2.0, шаг: 9, высота: 7.5 },
  /**
   * Фонарь. Высоты 8 и 6.5 м и шаг 30 м — практика; расчёт освещённости
   * по СП 52.13330 даёт шаг в три-четыре высоты опоры.
   */
  фонарь: { высотаМагистральной: 8, высотаМестной: 6.5, шаг: 30 },
  /** Ширина дорожки к подъезду, м. Практика: одна полоса пешеходов 0.75 м. */
  дорожка: 1.5,
  /** Машино-место легкового автомобиля, м. СП 113.13330 и практика. */
  машиноМесто: { ширина: 2.5, длина: 5.3 },
  /**
   * Павильон остановки. ГОСТ Р 52766: посадочная площадка не менее 10 м
   * длиной и 3 м шириной, павильон обязателен.
   */
  павильон: { длина: 4.0, площадка: 10.0 },
  /** Забор усадьбы, м. Практика ИЖС. */
  забор: { высота: 1.8 },
} as const;

/**
 * Двор. СП 42.13330 п. 7.5 — площадь площадок на одного жителя и расстояния
 * до окон. Дословно подтвердить не удалось (нормативные сайты закрыты
 * сетевой политикой), статус помечен в `docs/how-cities-work.md`.
 */
export const ДВОР = {
  /** Площадка для игр детей, м² на жителя. */
  детскойНаЧеловека: 0.7,
  /** Детская площадка не ближе этого к окнам, м. */
  доОконДетской: 12,
  /** Хозяйственная площадка и мусоросборники — не ближе этого, м. */
  доОконХозяйственной: 20,
  /** Какая доля автомобилей квартала стоит во дворе гостевыми местами. */
  гостевых: 0.25,
  /** Ширина внутриквартального проезда, м: одна полоса. Практика. */
  проезд: 3.5,
  /** Высота дворового фонаря, м. Практика: во дворе ниже, чем на улице. */
  фонарь: 4.5,
  /** На сколько проезд отступает от дворового фасада, м. */
  отФасада: 2.5,
} as const;

/**
 * Собрать всю обстановку куска посёлка.
 *
 * Возвращает две сетки — обычную и светящуюся, — ровно как дома: в показе
 * они сливаются с домами в один вызов отрисовки. Цена показа меряется
 * вызовами, а не треугольниками (решение 053).
 */
export function обстановка(
  кусок: Кусок, вид: Вид, дома: readonly Дом[],
  земля: (x: number, z: number) => number, сид: number,
): Обстановка {
  const к = куча();
  const свет = куча();
  const случайно = зерно(сид ^ 0x5bf03635);
  const счёт: Record<string, number> = {};

  // ── сколько машино-мест требует квартал: из уровня автомобилизации
  const жителей = кусок.посёлок.людей;
  const всегоМест = Math.round(
    (жителей * (АВТО_НА_ТЫСЯЧУ / 1000)) * (кусок.объекты.length / Math.max(1, кусок.посёлок.объекты.length)),
  );
  const наУлицу = Math.max(4, Math.round(всегоМест / Math.max(1, кусок.улицы.length)));

  for (const у of кусок.улицы) {
    const р = размеры(у);
    const узлы = перекрёстки(р, кусок.улицы);
    деревья(к, р, узлы, земля, случайно, счёт);
    фонари(к, свет, р, узлы, у.вид === 'магистральная', земля, счёт);
    парковка(к, р, узлы, наУлицу, земля, счёт);
  }

  const участокФронт = ЗАСТРОЙКА[вид].фронт;
  for (const дом of дома) {
    const улица = кусок.улицы[дом.улица];
    if (!улица) continue;
    const р = размеры(улица);
    дорожки(к, дом, р, земля, счёт);
    if (вид === 'деревня' && дом.что === 'жильё') {
      забор(к, дом, р, участокФронт, земля, счёт);
    }
  }

  for (const о of кусок.остановки) остановка(к, свет, о.x, о.z, кусок.улицы, земля, счёт);
  кусок.кварталы.forEach((_, номер) => двор(к, свет, кусок, вид, номер, земля, случайно, счёт));

  return { стены: собрать(к), свет: собрать(свет), счёт };
}

/** Уровень автомобилизации, авт./1000 жителей. СП 42.13330. */
const АВТО_НА_ТЫСЯЧУ = 350;

