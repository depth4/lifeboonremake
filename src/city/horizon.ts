/**
 * Даль: земля за краем плиты.
 *
 * **Что было не так.** Мир — квадрат 240 на 240 метров, и за ним нет ничего.
 * Пока по нему ездили в середине, это не мешало; как только по нему пошли
 * пешком, край стало видно — плита кончается, и её поверхность висит в воздухе
 * тонким листом. Алекс увидел это первым и назвал «слой травы забагался».
 * Трава не забагалась: у мира просто нет края.
 *
 * **Что здесь делается.** Кольцо земли от настоящего края плиты наружу
 * на километр. Внутренняя кромка кольца идёт ТОЧНО по высотам плиты —
 * поэтому шва между ними нет и быть не может: это одни и те же точки.
 * Наружная лежит чуть ниже и тонет в тумане.
 *
 * **Чего здесь НЕ делается.** Это не мир. По этой земле нельзя ходить, на ней
 * ничего не стоит, машина её не чувствует: спросить высоту у неё нельзя,
 * потому что спрашивают у `GroundIndex`, а его она не трогает. Это ровно
 * то, чем кажется, — далёкий вид. Настоящая земля появится за краем тогда,
 * когда мир начнёт строиться плитками (это `src/surface/`, и туда без слова
 * Алекса нельзя).
 *
 * Поэтому и лежит модуль здесь, а не в `src/world/`: мир о нём не знает.
 */

import { WORLD_HALF } from '../world/terrain.ts';
import { type Сетка, квад, куча, собрать } from './mesh.ts';

/** Радиус наружной кромки, м. Дальше камера всё равно не берёт. */
const РАДИУС = 1220;
/** Шаг вдоль края, м: чем мельче, тем точнее кольцо садится на кромку. */
const ШАГ = 6;
/**
 * Цвет здесь не выбирается. Даль — это трава, а какого трава цвета, знает
 * показ (`src/render.ts`), и знает в одном месте. Своя краска у меня уже
 * была, и на снимке было ровно то, на что жаловался Алекс: по краю мира
 * лежал слой травы ДРУГОГО оттенка. Отсюда уходит белый цвет — показ
 * перекрашивает даль тем же зелёным и той же пятнистостью, что и плиту.
 */
const БЕЛЫЙ = 0xffffff;

/** Точки по периметру квадрата, замкнутым обходом. */
function периметр(R: number, шаг: number): { x: number; z: number }[] {
  const из: { x: number; z: number }[] = [];
  const сколько = Math.max(2, Math.round((2 * R) / шаг));
  const вдоль = (t: number): number => -R + (2 * R * t) / сколько;
  for (let i = 0; i < сколько; i++) из.push({ x: вдоль(i), z: -R });
  for (let i = 0; i < сколько; i++) из.push({ x: R, z: вдоль(i) });
  for (let i = 0; i < сколько; i++) из.push({ x: вдоль(сколько - i), z: R });
  for (let i = 0; i < сколько; i++) из.push({ x: -R, z: вдоль(сколько - i) });
  return из;
}

/**
 * Собрать даль. Высоту края спрашиваем у той же земли, по которой ходят, —
 * второй земли не существует (инвариант мира номер два).
 *
 * Наружная кромка — ОКРУЖНОСТЬ, а не увеличенный квадрат. Сначала я
 * растянул квадрат в квадрат, и с угла плиты мир кончался острым клином:
 * горизонт сходился в точку. Это тот же обрыв, только отодвинутый. У
 * окружности угла нет, и показать его неоткуда.
 *
 * Высота наружной точки — РОВНО ТА ЖЕ, что у её точки на кромке, а не общий
 * уровень на всё кольцо. Общий уровень я уже пробовал дважды и оба раза
 * получил пирамиду: край плиты «плато» гуляет от −2.7 до +2.6 м, и любая
 * одна высота оказывается ниже половины края — край её заслоняет, и с угла
 * видно зелёный клин на фоне неба (`shots/город-наводка-угол.png`). Земля
 * за краем обязана ПРОДОЛЖАТЬ землю, а продолжать её можно только локально.
 */
export function даль(земля: (x: number, z: number) => number): Сетка {
  const к = куча();
  const кромка = периметр(WORLD_HALF, ШАГ);
  const высоты = кромка.map((т) => земля(т.x, т.z));
  /** Наружу — в ту же сторону от середины, но до окружности. */
  const наружу = (т: { x: number; z: number }): { x: number; z: number } => {
    const д = Math.hypot(т.x, т.z) || 1;
    return { x: (т.x / д) * РАДИУС, z: (т.z / д) * РАДИУС };
  };

  for (let i = 0; i < кромка.length; i++) {
    const j = (i + 1) % кромка.length;
    const a = кромка[i], b = кромка[j];
    const A = наружу(a), B = наружу(b);
    // на 5 см ниже плиты: две поверхности касаются, а не спорят за пиксель
    const ya = высоты[i] - 0.05;
    const yb = высоты[j] - 0.05;
    квад(к, [a.x, ya, a.z], [b.x, yb, b.z], [B.x, yb, B.z], [A.x, ya, A.z], БЕЛЫЙ);
  }
  return собрать(к);
}
