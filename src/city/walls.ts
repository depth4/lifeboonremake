/**
 * Стены как ПРЕГРАДА, а не как картинка.
 *
 * Дома появились, в них видно окна, витрины и торговый зал — а пройти сквозь
 * них можно было насквозь. Это ломает присутствие сильнее, чем отсутствие
 * домов: войти в дверь и выйти сквозь стену хуже, чем не входить вовсе.
 *
 * **Устройство: дом — прямоугольник, у которого на одной стороне есть дырки.**
 * Внутри дома находиться МОЖНО — это и значит «войти». Нельзя только одно:
 * пересечь стену там, где нет проёма. Поэтому «прошёл сквозь стену» и «застрял
 * в стене» — разные вещи, и вторая здесь невыразима: преграда останавливает
 * движение, а не выталкивает из уже занятого места.
 *
 * Проёмы берутся у того же дома, который рисуется. Отдельного списка дверей
 * не существует: дверь, которая есть в геометрии и которой нет в преграде,
 * записать негде.
 *
 * Про экран этот файл не знает ничего.
 */

import type { Дом } from './house.ts';

/** Один дом как преграда: прямоугольник в плане плюс дырки на фасаде. */
export interface Преграда {
  readonly x: number;
  readonly z: number;
  /** Вектор наружу, к улице. Фронт лежит по перпендикуляру: (−нz, нx). */
  readonly нx: number;
  readonly нz: number;
  readonly полуФронт: number;
  readonly полуГлубина: number;
  /**
   * Проёмы первого этажа, в местных мерах: `сторона` 0 фасад, 1 правый торец,
   * 2 двор, 3 левый торец; `от`/`до` — вдоль своей стены от её середины.
   */
  readonly проходы: readonly { сторона: number; от: number; до: number }[];
}

/** Собрать преграды из тех самых домов, которые нарисованы. */
export function преграды(дома: readonly Дом[]): Преграда[] {
  return дома.map((д) => ({
    x: д.x, z: д.z, нx: д.нx, нz: д.нz,
    полуФронт: д.фронт / 2, полуГлубина: д.глубина / 2,
    проходы: д.проёмы
      .filter((п) => п.вид === 'дверь' && п.этаж === 0)
      .map((п) => ({
        сторона: п.стена,
        от: п.от - п.длинаСтены / 2,
        до: п.до - п.длинаСтены / 2,
      })),
  }));
}

/** Точка в местных мерах дома: вдоль фронта и вглубь (наружу положительно). */
function вМестные(п: Преграда, x: number, z: number): { a: number; b: number } {
  const dx = x - п.x, dz = z - п.z;
  return { a: dx * -п.нz + dz * п.нx, b: dx * п.нx + dz * п.нz };
}

function изМестных(п: Преграда, a: number, b: number): { x: number; z: number } {
  // оси дома: «вдоль фронта» это (−нz, нx), «наружу» это (нx, нz)
  return {
    x: п.x + a * -п.нz + b * п.нx,
    z: п.z + a * п.нx + b * п.нz,
  };
}

/**
 * Пройдёт ли отрезок сквозь стену — и если да, то где его остановить.
 *
 * Считается в местных мерах дома: четыре стены превращаются в четыре прямые
 * `a = ±полуФронт` и `b = ±полуГлубина`. Пересечение отрезка с прямой —
 * школьная задача, и вырожденных случаев у неё нет.
 *
 * **Плечо человека сдвигает барьер В ТУ СТОРОНУ, ГДЕ ЧЕЛОВЕК СЕЙЧАС.**
 * Это не мелочь: первая редакция просто раздувала прямоугольник на плечо,
 * и снаружи всё работало, а изнутри человек выходил сквозь заднюю стену —
 * раздутый барьер оказывался ЗА ней. Проверка «в дверь можно войти» это
 * и поймала: человек входил в дверь и выходил сквозь дом насквозь.
 */
function упёрся(
  п: Преграда, a0: number, b0: number, a1: number, b1: number, радиус: number,
): { доля: number; вдольA: boolean } | null {
  let лучшая: { доля: number; вдольA: boolean } | null = null;

  /** Одна стена: плоскость, её сторона и вдоль какой оси она тянется. */
  const плоскость = (
    полу: number, знак: 1 | -1, сторона: number, вдольA: boolean,
  ): void => {
    const [н0, н1] = вдольA ? [b0, b1] : [a0, a1];
    const [п0, п1] = вдольA ? [a0, a1] : [b0, b1];
    const стена = знак * полу;
    // барьер отступает от стены на плечо в ту сторону, где человек сейчас
    const снаружи = знак > 0 ? н0 > стена : н0 < стена;
    const барьер = стена + знак * радиус * (снаружи ? 1 : -1);
    if (Math.abs(н1 - н0) < 1e-9) return;
    const t = (барьер - н0) / (н1 - н0);
    if (t < 0 || t > 1) return;
    const вдоль = п0 + (п1 - п0) * t;
    const край = (вдольA ? п.полуФронт : п.полуГлубина) + радиус;
    if (Math.abs(вдоль) > край) return;
    // дверь: сквозь неё проходят, и это единственное исключение
    if (свободно(п, сторона, вдоль, радиус)) return;
    if (лучшая === null || t < лучшая.доля) лучшая = { доля: t, вдольA };
  };

  плоскость(п.полуГлубина, 1, 0, true);    // фасад
  плоскость(п.полуГлубина, -1, 2, true);   // дворовый фасад
  плоскость(п.полуФронт, 1, 1, false);     // правый торец
  плоскость(п.полуФронт, -1, 3, false);    // левый торец
  return лучшая;
}

/** Есть ли на этой стороне проём, в который человек проходит целиком. */
function свободно(п: Преграда, сторона: number, вдоль: number, радиус: number): boolean {
  return п.проходы.some((пр) => пр.сторона === сторона
    && вдоль > пр.от + радиус * 0.5 && вдоль < пр.до - радиус * 0.5);
}

/**
 * Двинуться из точки в точку, не проходя сквозь стены.
 *
 * Упёрлись — останавливаемся у стены и СКОЛЬЗИМ вдоль неё остатком движения.
 * Без скольжения человек прилипает к дому: идёшь вдоль фасада, чуть задел —
 * и встал намертво. Скольжение — это не поблажка, а то, как ходит живой
 * человек вдоль стены.
 */
export function пройти(
  стены: readonly Преграда[],
  x0: number, z0: number, x1: number, z1: number, радиус: number,
): { x: number; z: number } {
  let цx = x1, цz = z1;
  // двух проходов хватает: первый упирается в стену, второй — в соседнюю
  for (let проход = 0; проход < 2; проход++) {
    let стена: Преграда | null = null;
    let удар: { доля: number; вдольA: boolean } | null = null;
    for (const п of стены) {
      // грубый отсев: далеко — считать нечего
      const далеко = п.полуФронт + п.полуГлубина + радиус + 2;
      if (Math.abs(п.x - x0) > далеко + Math.abs(цx - x0)) continue;
      if (Math.abs(п.z - z0) > далеко + Math.abs(цz - z0)) continue;
      const н = вМестные(п, x0, z0);
      const к = вМестные(п, цx, цz);
      const это = упёрся(п, н.a, н.b, к.a, к.b, радиус);
      if (это !== null && (удар === null || это.доля < удар.доля)) { удар = это; стена = п; }
    }
    if (удар === null || стена === null) break;

    const н = вМестные(стена, x0, z0);
    const к = вМестные(стена, цx, цz);
    // встаём чуть НЕ ДОХОДЯ до стены, дальше идём только вдоль неё
    const почти = Math.max(0, удар.доля - 1e-3);
    const a = н.a + (к.a - н.a) * почти;
    const b = н.b + (к.b - н.b) * почти;
    // упёрлись в фасад — идём вдоль него; упёрлись в торец — вдоль торца
    const скольз = удар.вдольA ? { a: к.a, b } : { a, b: к.b };
    const мир = изМестных(стена, скольз.a, скольз.b);
    цx = мир.x; цz = мир.z;
  }
  return { x: цx, z: цz };
}

/**
 * В каком доме сейчас стоит человек. −1 — ни в каком.
 *
 * Тот же список преград, по которому он не проходит сквозь стены: «войти»
 * и «оказаться внутри» — одно и то же событие, и считается оно в одном месте.
 * Поэтому «интерьер построился не для того дома, в который вошли» записать
 * нечем.
 */
export function вКаком(стены: readonly Преграда[], x: number, z: number): number {
  for (let i = 0; i < стены.length; i++) {
    const м = вМестные(стены[i], x, z);
    if (Math.abs(м.a) < стены[i].полуФронт && Math.abs(м.b) < стены[i].полуГлубина) return i;
  }
  return -1;
}
