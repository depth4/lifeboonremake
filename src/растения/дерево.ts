/**
 * ДЕРЕВО ИЗ ВЕТОК. Про экран не знает: отдаёт скелет — ветки отрезками
 * и листья точками на них. Как это рисуется, решает `деревья.ts`.
 *
 * Зачем. До 23.09 дерево было двумя многогранниками на палке, и листья
 * на них читались «шаром с листьями» (слова Алекса). Форму дереву дают
 * ветки: листья сидят пучками на их концах, между пучками видно небо,
 * силуэт рваный. Поэтому дерево растёт так, как растёт настоящее
 * (по чужому опыту — EZ-Tree, SpeedTree): ствол отрезками, из него ветки
 * под своим углом, из веток ветки поменьше, листья на последних.
 *
 * ЧТО СДЕЛАНО НЕВЫРАЗИМЫМ:
 *
 * - **ветка в воздухе.** Начало ветки — точка на родителе, взятая между
 *   двумя его отрезками. Другого способа завести ветку нет;
 * - **лист в воздухе.** Место листа — точка последней ветки плюс черешок;
 * - **лист, оторвавшийся от ветки на ветру.** У каждой точки ветки есть
 *   «вес качания» (насколько она далеко по веткам от земли) и фаза своей
 *   ветки; лист получает их от точки, на которой сидит. Качание считается
 *   одной функцией для коры и для листа — они не могут разойтись;
 * - **два разных дерева с одним именем.** Дерево — функция вида и числа.
 */

/** Виды. Что растёт в российском дворе и на улице, плюс два куста. */
export type Вид = 'берёза' | 'липа' | 'клён' | 'тополь' | 'рябина' | 'сирень' | 'изгородь';

interface Вектор { x: number; y: number; z: number }

export interface ПараметрыВида {
  /** Высота всего дерева, м (середина вилки). */
  readonly высота: number;
  /** Сколько стволов выходит из земли: 1 у дерева, много у куста. */
  readonly стволов: number;
  /** Насколько стволы куста расходятся от вертикали, рад. */
  readonly развал: number;
  /** Толщина ствола у земли, м. */
  readonly толщина: number;
  /** Уровни: ствол (0), ветки (1), веточки (2), прутья (3). */
  readonly уровней: number;
  /** Сколько детей у ветки каждого уровня. */
  readonly детей: readonly number[];
  /** Угол отхода ребёнка от родителя по уровням, рад. */
  readonly угол: readonly number[];
  /** Длина ветки уровня в долях высоты дерева. */
  readonly длина: readonly number[];
  /** С какой доли родителя начинаются дети. */
  readonly начало: readonly number[];
  /** Корявость по уровням: насколько гнётся каждый отрезок. */
  readonly корявость: readonly number[];
  /** Тяга вверх (+) или вниз (−) по уровням: тянется к свету или свисает. */
  readonly тяга: readonly number[];
  /** Листьев на каждой ветке последнего уровня и их длина, м. */
  readonly листьев: number;
  readonly лист: number;
  /** Кора и лист: HSL. */
  readonly кора: readonly [number, number, number];
  readonly зелень: readonly [number, number, number];
  /** У берёзы кора белая с чёрными штрихами. */
  readonly полосатая: boolean;
}

