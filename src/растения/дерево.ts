/** Точка ветки: где, какой толщины и как качается. */
export interface Точка {
  readonly x: number; readonly y: number; readonly z: number;
  readonly радиус: number;
  /** Вес качания: сколько метров по веткам от земли, делённое на высоту. */
  readonly вес: number;
  /** Вес внутри своей ветки: 0 у основания, 1 на конце. */
  readonly своя: number;
  /** Фаза своей ветки, рад: соседние ветки качаются не в ногу. */
  readonly фаза: number;
}

export interface Ветка {
  readonly уровень: number;
  readonly точки: readonly Точка[];
}

export interface Лист {
  /** Где черешок: точка на ветке. */
  readonly x: number; readonly y: number; readonly z: number;
  /** Куда смотрит лист (единичный). */
  readonly nx: number; readonly ny: number; readonly nz: number;
  readonly длина: number;
  /** Качание — той точки ветки, на которой сидит лист. */
  readonly вес: number;
  readonly своя: number;
  readonly фаза: number;
}

export interface Скелет {
  readonly вид: Вид;
  readonly высота: number;
  /** Полуширина кроны — насколько далеко ветки уходят от оси, м. */
  readonly размах: number;
  readonly ветки: readonly Ветка[];
  readonly листья: readonly Лист[];
}

/** Повторяемый случай: число → то же число всегда. */
function случай(сид: number): () => number {
  let s = (сид * 2654435761) >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const норм = (v: Вектор): Вектор => {
  const l = Math.hypot(v.x, v.y, v.z) || 1;
  return { x: v.x / l, y: v.y / l, z: v.z / l };
};
const крест = (a: Вектор, b: Вектор): Вектор => ({ x: a.y * b.z - a.z * b.y, y: a.z * b.x - a.x * b.z, z: a.x * b.y - a.y * b.x });
/** Повернуть v вокруг единичной оси на угол. */
function повернуть(v: Вектор, ось: Вектор, угол: number): Вектор {
  const c = Math.cos(угол), s = Math.sin(угол), d = ось.x * v.x + ось.y * v.y + ось.z * v.z;
  const к = крест(ось, v);
  return {
    x: v.x * c + к.x * s + ось.x * d * (1 - c),
    y: v.y * c + к.y * s + ось.y * d * (1 - c),
    z: v.z * c + к.z * s + ось.z * d * (1 - c),
  };
}
/** Любой единичный вектор поперёк данного. */
const поперёк = (v: Вектор): Вектор => норм(крест(v, Math.abs(v.y) < 0.9 ? { x: 0, y: 1, z: 0 } : { x: 1, y: 0, z: 0 }));

/** Отрезков на ветку по уровням: ствол гнётся плавно, прутья — парой изломов. */
const ОТРЕЗКОВ = [10, 7, 5, 3];

/**
 * Вырастить дерево. `вариант` — число: один вид, разные числа — разные
 * деревья того же вида.
 */
export function вырастить(
  вид: Вид, вариант: number,
  /**
   * Заведомо сломанные варианты для проверки: `листья: 'на шаре'` — как
   * было утром 23.09, листья по поверхности эллипсоида кроны, а не на
   * ветках; `ветки: 'откуда попало'` — ветка начинается рядом с родителем,
   * а не на нём.
   */
  как: { листья?: 'на шаре'; ветки?: 'откуда попало' } = {},
): Скелет {
  const п = ВИДЫ[вид];
  const r = случай(вариант * 7919 + вид.length * 104729 + вид.charCodeAt(0));
  const H = п.высота * (0.85 + 0.3 * r());
  const ветки: Ветка[] = [];
  const листья: Лист[] = [];
  let размах = 0;

  interface Росток { из: Точка; куда: Вектор; длина: number; радиус: number; уровень: number; путь: number }
  const очередь: Росток[] = [];
  for (let k = 0; k < п.стволов; k++) {
    const а = (k / п.стволов) * Math.PI * 2 + r() * 0.8;
    const наклон = п.стволов > 1 ? п.развал * (0.6 + 0.8 * r()) : 0;
    const куда = норм({ x: Math.sin(наклон) * Math.cos(а), y: Math.cos(наклон), z: Math.sin(наклон) * Math.sin(а) });
    const у = п.стволов > 1 ? 0.12 * r() : 0;
    очередь.push({
      из: { x: у * Math.cos(а), y: 0, z: у * Math.sin(а), радиус: п.толщина, вес: 0, своя: 0, фаза: r() * 6.283 },
      куда, длина: H * п.длина[0] * (0.85 + 0.3 * r()), радиус: п.толщина * (0.8 + 0.4 * r()), уровень: 0, путь: 0,
    });
  }

  while (очередь.length > 0) {
    const р = очередь.shift() as Росток;
    const n = ОТРЕЗКОВ[р.уровень] ?? 3;
    const шаг = р.длина / n;
    const фаза = r() * 6.283;
    const точки: Точка[] = [];
    let p: Вектор = { x: р.из.x, y: р.из.y, z: р.из.z };
    let d = р.куда;
    for (let i = 0; i <= n; i++) {
      const доля = i / n;
      const радиус = р.радиус * (1 - 0.72 * доля) + (i === n && р.уровень === п.уровней ? -р.радиус * 0.2 : 0);
      const путь = р.путь + шаг * i;
      точки.push({ x: p.x, y: p.y, z: p.z, радиус: Math.max(0.004, радиус), вес: путь / H, своя: доля, фаза });
      размах = Math.max(размах, Math.hypot(p.x, p.z));
      // корявость: отрезок гнётся в случайную сторону, тоньше — сильнее
      const гнуть = п.корявость[р.уровень] * Math.max(1, 0.05 / Math.max(радиус, 0.01)) ** 0.3;
      d = повернуть(d, поперёк(d), (r() - 0.5) * 2 * гнуть);
      d = повернуть(d, норм(крест(d, поперёк(d))), (r() - 0.5) * 2 * гнуть);
      // тяга: к свету (+) или книзу (−) — поворот к вертикали
      const т = п.тяга[р.уровень] / Math.max(радиус, 0.02) * 0.1;
      const к = норм({ x: d.x, y: d.y + т, z: d.z });
      d = к;
      p = { x: p.x + d.x * шаг, y: p.y + d.y * шаг, z: p.z + d.z * шаг };
    }
    ветки.push({ уровень: р.уровень, точки });

    const концевая = р.уровень === п.уровней;
    /**
     * Листья — на последних ветках и на внешней половине предпоследних.
     * Только на последних — крона «поздней осенью»: 23.09 снимок показал
     * голые макушки и небо сквозь всё дерево.
     */
    // и на верхушке ствола — иначе у высокого дерева голая макушка
    const лидер = р.уровень === 0 && п.стволов === 1;
    const листьев = концевая ? п.листьев : р.уровень === п.уровней - 1 ? Math.round(п.листьев * 0.6)
      : лидер ? п.листьев * 3 : 0;
    const отДоли = концевая ? 0.3 : лидер ? 0.8 : 0.55;
    for (let k = 0; k < листьев; k++) {
      const доля = отДоли + (1 - отДоли) * ((k + r()) / листьев);
      const f = доля * n;
      const i = Math.min(n - 1, Math.floor(f)), t = f - i;
      const a = точки[i], b = точки[i + 1];
      const ось = норм({ x: b.x - a.x, y: b.y - a.y, z: b.z - a.z });
      const вбок = повернуть(поперёк(ось), ось, r() * 6.283);
      const наружу = норм({ x: вбок.x + ось.x * 0.5, y: вбок.y + ось.y * 0.5 - 0.25, z: вбок.z + ось.z * 0.5 });
      const шар = как.листья === 'на шаре';
      const θ = r() * 6.283, φ = Math.acos(1 - 2 * r());
      листья.push({
        x: шар ? Math.sin(φ) * Math.cos(θ) * H * 0.3 : a.x + (b.x - a.x) * t,
        y: шар ? H * 0.6 + Math.cos(φ) * H * 0.3 : a.y + (b.y - a.y) * t,
        z: шар ? Math.sin(φ) * Math.sin(θ) * H * 0.3 : a.z + (b.z - a.z) * t,
        nx: наружу.x, ny: наружу.y, nz: наружу.z,
        длина: п.лист * (0.75 + 0.5 * r()),
        вес: a.вес + (b.вес - a.вес) * t, своя: a.своя + (b.своя - a.своя) * t, фаза: a.фаза,
      });
    }
    if (!концевая) {
      // дети — вдоль родителя от «начала» до конца, по кругу через золотой угол
      const детей = п.детей[р.уровень];
      const поворот0 = r() * 6.283;
      for (let k = 0; k < детей; k++) {
        const доля = п.начало[р.уровень + 1] + (1 - п.начало[р.уровень + 1]) * ((k + r() * 0.8) / детей);
        const f = доля * n;
        const i = Math.min(n - 1, Math.floor(f)), t = f - i;
        const a = точки[i], b = точки[i + 1];
        const сдвиг = как.ветки === 'откуда попало' ? (r() - 0.5) * 1.2 : 0;
        const из: Точка = {
          x: a.x + (b.x - a.x) * t + сдвиг, y: a.y + (b.y - a.y) * t, z: a.z + (b.z - a.z) * t - сдвиг,
          радиус: a.радиус + (b.радиус - a.радиус) * t,
          вес: a.вес + (b.вес - a.вес) * t, своя: 0, фаза: a.фаза,
        };
        const ось = норм({ x: b.x - a.x, y: b.y - a.y, z: b.z - a.z });
        const вбок = повернуть(поперёк(ось), ось, поворот0 + k * 2.39996 + (r() - 0.5) * 0.5);
        const угол = п.угол[р.уровень + 1] * (0.8 + 0.4 * r());
        const куда = норм({
          x: ось.x * Math.cos(угол) + вбок.x * Math.sin(угол),
          y: ось.y * Math.cos(угол) + вбок.y * Math.sin(угол),
          z: ось.z * Math.cos(угол) + вбок.z * Math.sin(угол),
        });
        // ветка у верхушки короче: крона сужается кверху, а не шар
        const укорот = р.уровень === 0 ? 1 - 0.55 * доля * доля : 1 - 0.3 * доля;
        очередь.push({
          из, куда,
          длина: H * п.длина[р.уровень + 1] * укорот * (0.75 + 0.5 * r()),
          радиус: из.радиус * (0.45 + 0.2 * r()),
          уровень: р.уровень + 1,
          путь: из.вес * H,
        });
      }
    }
  }
  return { вид, высота: H, размах, ветки, листья };
}
