/**
 * СВЕТ И НЕБО ПО ЧАСАМ. Солнце стоит там, где оно стоит в этот час над
 * городом, а небо, дымка, свет неба и тень — из того же положения солнца.
 *
 * Зачем. До 27.09 солнце было прибито к одной точке на весь день: двор
 * в 3:00 ночи и в 21:00 был залит тем же полуденным светом, небо было
 * одним цветом, а тень лежала только в квадрате ±170 м вокруг середины
 * мира — у «города» (600 м) края были без теней вовсе. Алекс: «сделай
 * картинку такой, чтобы мне было приятно зайти».
 *
 * ЧТО СДЕЛАНО НЕВЫРАЗИМЫМ:
 *
 * - **ночь со светлым небом, закат с белым солнцем.** Всё, что зависит
 *   от времени суток, — функция ОДНОГО числа, высоты солнца (`погода`).
 *   Отдельно «цвет неба на 21:00» записать негде;
 * - **шов между небом и землёй вдали.** Цвет дымки и цвет неба у горизонта —
 *   одно поле `горизонт`: дальняя земля растворяется ровно в то небо,
 *   на фоне которого стоит;
 * - **тень, кончающаяся посреди улицы.** Квадрат тени ездит за глазом,
 *   с шагом в одну точку карты теней (иначе тени дрожат при ходьбе).
 */

import * as THREE from 'three';

/**
 * Где город на Земле. Номера машин — 73-го региона, значит Ульяновск:
 * 54.3° с. ш., 48.4° в. д., время UTC+4. Мировой север — −z, восток — +x.
 */
const ШИРОТА = 54.3 * (Math.PI / 180);
/** Солнечный полдень по часам города: долгота 48.4° при поясе 60° — на 46 минут позже 12:00. */
const ПОЛДЕНЬ = 12 + (60 - 48.4) * 4 / 60;
/** День года: конец сентября, как в календаре жизни города (склонение солнца почти ноль). */
const ДЕНЬ_ГОДА = 270;

/** Куда смотреть на солнце из города в этот час: единичный вектор мира. */
export function солнцеВЧас(час: number): THREE.Vector3 {
  const склонение = -23.44 * (Math.PI / 180) * Math.cos((2 * Math.PI / 365) * (ДЕНЬ_ГОДА + 10));
  const угол = (час - ПОЛДЕНЬ) * (Math.PI / 12);
  // вектор в осях «восток, верх, север»
  const вверх = Math.sin(ШИРОТА) * Math.sin(склонение) + Math.cos(ШИРОТА) * Math.cos(склонение) * Math.cos(угол);
  const восток = -Math.cos(склонение) * Math.sin(угол);
  const север = Math.cos(ШИРОТА) * Math.sin(склонение) - Math.sin(ШИРОТА) * Math.cos(склонение) * Math.cos(угол);
  return new THREE.Vector3(восток, вверх, -север).normalize();
}

/**
 * ЛУНА — ночью тот же направленный свет, только с неба напротив солнца,
 * холодный и слабый. Без неё ночь (27.09, первая редакция) была чёрным
 * кадром: в играх ночь читается формой и тенью от луны, а не темнотой.
 * Луна загорается, когда солнце уже погасло, поэтому смену направления
 * света не видно.
 */
export const ЛУНА = { цвет: 0xa8bcff, сила: 0.9, от: -0.1, до: -0.2 } as const;
export function лунаНад(солнце: THREE.Vector3): THREE.Vector3 {
  return new THREE.Vector3(-солнце.x * 0.6, 0.75, -солнце.z * 0.6 + 0.3).normalize();
}

/** Всё, что меняется за сутки, — из высоты солнца над горизонтом (синус угла). */
export interface Погода {
  readonly солнце: THREE.Color;
  readonly силаСолнца: number;
  readonly небо: THREE.Color;
  readonly земля: THREE.Color;
  readonly силаНеба: number;
  /** Цвет неба в зените и у горизонта; дымка вдали — цвет горизонта. */
  readonly зенит: THREE.Color;
  readonly горизонт: THREE.Color;
  /** Ореол вокруг солнца (закат — широкий и тёплый). */
  readonly ореол: THREE.Color;
  /**
   * Экспозиция — как глаз привыкает: ночью он открыт шире, днём прищурен.
   * Так делают все игры с временем суток (автоэкспозиция); без неё ночь —
   * чёрный кадр, а полдень — выгоревший.
   */
  readonly экспозиция: number;
}

/**
 * Опорные состояния по высоте солнца (синус). Между ними — плавно.
 * Числа — на глаз по фотографиям неба средней полосы; проверяются
 * листом снимков `tools/обход.ts`, а не справочником.
 */
const ОПОРЫ: readonly {
  h: number; солнце: number; силаСолнца: number; небо: number; земля: number; силаНеба: number;
  зенит: number; горизонт: number; ореол: number; экспозиция: number;
}[] = [
  // ночь: светит луна (см. `ЛУНА`), небо — рассеянный свет города и луны
  { h: -0.3, солнце: 0x8090c0, силаСолнца: 0, небо: 0x40527a, земля: 0x1c2028, силаНеба: 1.2, зенит: 0x0a1020, горизонт: 0x22304a, ореол: 0x22304a, экспозиция: 2.2 },
  // гражданские сумерки: синий час
  { h: -0.08, солнце: 0xff8a50, силаСолнца: 0, небо: 0x6a78a0, земля: 0x2a2a30, силаНеба: 1.3, зенит: 0x1c2848, горизонт: 0x6a6a8a, ореол: 0xc07058, экспозиция: 1.7 },
  // солнце на горизонте: золотой час
  { h: 0.02, солнце: 0xffa060, силаСолнца: 2.2, небо: 0x9aaccc, земля: 0x5a4a3a, силаНеба: 1.7, зенит: 0x3a5a90, горизонт: 0xf0b890, ореол: 0xffa060, экспозиция: 1.1 },
  { h: 0.18, солнце: 0xffe2bc, силаСолнца: 3.6, небо: 0xb8cbe0, земля: 0x646452, силаНеба: 2.1, зенит: 0x3f6fb0, горизонт: 0xc8d8e6, ореол: 0xffe0b0, экспозиция: 0.9 },
  // день
  { h: 0.6, солнце: 0xfff6ea, силаСолнца: 4.2, небо: 0xc6d6e8, земля: 0x6a6a58, силаНеба: 2.3, зенит: 0x3d78c8, горизонт: 0xcfe0ee, ореол: 0xfff4e0, экспозиция: 0.8 },
];

export function погода(высота: number): Погода {
  let i = 0;
  while (i < ОПОРЫ.length - 2 && высота > ОПОРЫ[i + 1].h) i++;
  const а = ОПОРЫ[i], б = ОПОРЫ[i + 1];
  const t = THREE.MathUtils.smoothstep(высота, а.h, б.h);
  const цвет = (к: 'солнце' | 'небо' | 'земля' | 'зенит' | 'горизонт' | 'ореол'): THREE.Color =>
    new THREE.Color(а[к]).lerp(new THREE.Color(б[к]), t);
  return {
    солнце: цвет('солнце'), силаСолнца: а.силаСолнца + (б.силаСолнца - а.силаСолнца) * t,
    небо: цвет('небо'), земля: цвет('земля'), силаНеба: а.силаНеба + (б.силаНеба - а.силаНеба) * t,
    зенит: цвет('зенит'), горизонт: цвет('горизонт'), ореол: цвет('ореол'),
    экспозиция: а.экспозиция + (б.экспозиция - а.экспозиция) * t,
  };
}

/**
 * Небо — купол с градиентом от горизонта к зениту, ореолом и диском солнца.
 * Купол следует за глазом, в глубину не пишет и рисуется первым: он всегда
 * «за всем». Туман на него не действует — он сам и есть цвет дымки.
 */
export function создатьНебо(): { купол: THREE.Mesh; задать(солнце: THREE.Vector3, п: Погода): void } {
  const uniforms = {
    uZenith: { value: new THREE.Color() },
    uHorizon: { value: new THREE.Color() },
    uGlow: { value: new THREE.Color() },
    uSun: { value: new THREE.Vector3(0, 1, 0) },
    uSunColor: { value: new THREE.Color() },
  };
  const материал = new THREE.ShaderMaterial({
    uniforms,
    side: THREE.BackSide,
    depthWrite: false,
    depthTest: false,
    fog: false,
    vertexShader: /* glsl */`
      varying vec3 vDir;
      void main() {
        vDir = normalize(position);
        vec4 p = projectionMatrix * modelViewMatrix * vec4(position, 1.0);
        gl_Position = p.xyww;
      }`,
    fragmentShader: /* glsl */`
      uniform vec3 uZenith, uHorizon, uGlow, uSun, uSunColor;
      varying vec3 vDir;
      void main() {
        vec3 d = normalize(vDir);
        float up = max(d.y, 0.0);
        // у горизонта небо светлее и держится полосой, к зениту темнеет
        vec3 col = mix(uHorizon, uZenith, pow(up, 0.55));
        // ниже горизонта — тот же цвет горизонта: земля вдали уходит в дымку
        float cosS = dot(d, uSun);
        float glow = pow(max(cosS, 0.0), 6.0) * 0.55 + pow(max(cosS, 0.0), 48.0) * 0.6;
        col += uGlow * glow * (1.0 - 0.6 * up);
        // диск солнца: мягкий край, над горизонтом
        float disc = smoothstep(0.99965, 0.99985, cosS) * smoothstep(-0.01, 0.01, uSun.y);
        col = mix(col, uSunColor * 4.0, disc);
        gl_FragColor = vec4(col, 1.0);
        #include <tonemapping_fragment>
        #include <colorspace_fragment>
      }`,
  });
  const купол = new THREE.Mesh(new THREE.SphereGeometry(1, 32, 16), материал);
  купол.name = 'небо';
  купол.frustumCulled = false;
  купол.renderOrder = -1000;
  купол.onBeforeRender = (_r, _s, камера) => { купол.position.copy(камера.position); };
  купол.scale.setScalar(100);
  return {
    купол,
    задать(солнце, п) {
      uniforms.uSun.value.copy(солнце);
      uniforms.uZenith.value.copy(п.зенит);
      uniforms.uHorizon.value.copy(п.горизонт);
      uniforms.uGlow.value.copy(п.ореол);
      uniforms.uSunColor.value.copy(п.солнце);
    },
  };
}
