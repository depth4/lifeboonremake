/**
 * ЧЕЛОВЕК НА УЛИЦЕ — фигура прохожего: из чего он собран и как ставится
 * в позу. Где он и что делает, решает город (`city/walkers.ts`), здесь —
 * только тело.
 *
 * Зачем переделано. До 27.09 прохожий был шестью коробками: коробка-голова
 * с тёмной накладкой лица, коробка-туловище, ноги и руки — прямые палки от
 * бедра до земли. Алекс прислал снимок: «пешеход выглядит ужасно». Коробки
 * не держали ни одной приметы человека — шеи, плеч шире талии, колена,
 * локтя, стопы, волос.
 *
 * Теперь:
 * - **пропорции — из роста**, по долям тела, как в анатомических таблицах
 *   (Дриллис и Контини): колено 0.285 роста, тазобедренный сустав 0.53,
 *   плечо 0.818, глаза 0.942. Отдельных «длина руки», «высота головы»
 *   нет — их нельзя назначить невпопад;
 * - **каждая часть висит на своём суставе**, и сустав считается от
 *   родителя: колено — от бедра, стопа — от колена, кисть — от локтя.
 *   «Нога оторвалась от колена» записать негде;
 * - **колено гнётся только назад, локоть только вперёд**: сгиб — число
 *   не меньше нуля, и знак у него один на всю фигуру;
 * - **пять пачек, как было**: корпус (таз, торс, шея, голова, волосы —
 *   одно жёсткое тело), бедро, голень со стопой, плечо, предплечье с
 *   кистью. Цвет части — номер «слота» в вершине (одежда, брюки, кожа,
 *   волосы, обувь), а цвета слотов — у каждого человека свои. Поэтому
 *   фигура сложнее, а вызовов отрисовки столько же.
 */

import * as THREE from 'three';
import { EYE_HEIGHT } from './person.ts';
import { РАСТВОРИТЬ, РАСТВОРИТЬ_ТОЧКУ } from '../растения/деревья.ts';

/** Рост взрослого прохожего, м. Глаза на EYE_HEIGHT — те же, что у игрока. */
export const РОСТ = EYE_HEIGHT / 0.942;
/** Доли роста (от подошвы). */
const ДОЛИ = { лодыжка: 0.039, колено: 0.285, бедро: 0.53, талия: 0.6, плечо: 0.818, локоть: 0.63, запястье: 0.485 };
const H = РОСТ;
/** Высоты суставов стоящего, м. */
const СУСТАВ = {
  бедро: ДОЛИ.бедро * H, колено: ДОЛИ.колено * H, лодыжка: ДОЛИ.лодыжка * H,
  плечо: ДОЛИ.плечо * H, локоть: ДОЛИ.локоть * H, запястье: ДОЛИ.запястье * H,
};
/** Сустав от оси тела вбок, м: плечи шире бёдер. */
const ВБОК = { бедро: 0.085, плечо: 0.19 };
/** Длины звеньев — разности высот суставов, а не свои числа. */
const ЗВЕНО = {
  бедро: СУСТАВ.бедро - СУСТАВ.колено,
  голень: СУСТАВ.колено - СУСТАВ.лодыжка,
  плечо: СУСТАВ.плечо - СУСТАВ.локоть,
  предплечье: СУСТАВ.локоть - СУСТАВ.запястье,
};

/** Слоты цвета: какой цвет человека красит вершину. */
const Слот = { одежда: 0, брюки: 1, кожа: 2, волосы: 3, обувь: 4 } as const;
type Слот = typeof Слот[keyof typeof Слот];

/**
 * Трубка по кольцам: каждое кольцо — высота и два радиуса (вперёд x,
 * вбок z) и сдвиг вперёд. Концы закрыты. Одна функция на туловище, руки
 * и ноги — форма задаётся числами колец, а не отдельным кодом.
 */
function трубка(кольца: readonly { y: number; rx: number; rz: number; dx?: number; слот: Слот }[], грани = 6): THREE.BufferGeometry {
  const pos: number[] = [], слоты: number[] = [], idx: number[] = [];
  кольца.forEach((к) => {
    for (let i = 0; i < грани; i++) {
      const a = (i / грани) * Math.PI * 2;
      pos.push((к.dx ?? 0) + Math.cos(a) * к.rx, к.y, Math.sin(a) * к.rz);
      слоты.push(к.слот);
    }
  });
  for (let r = 0; r + 1 < кольца.length; r++)
    for (let i = 0; i < грани; i++) {
      const a = r * грани + i, b = r * грани + ((i + 1) % грани), c = a + грани, d = b + грани;
      // кольца идут сверху вниз или снизу вверх — нормали наружу при любом порядке
      if (кольца[r + 1].y < кольца[r].y) idx.push(a, c, b, b, c, d); else idx.push(a, b, c, b, d, c);
    }
  // крышки: веер к середине конца
  for (const [r, наружу] of [[0, кольца[0].y > кольца[1].y], [кольца.length - 1, кольца[кольца.length - 1].y > кольца[кольца.length - 2].y]] as const) {
    const к = кольца[r];
    const центр = pos.length / 3;
    pos.push(к.dx ?? 0, к.y, 0);
    слоты.push(к.слот);
    for (let i = 0; i < грани; i++) {
      const a = r * грани + i, b = r * грани + ((i + 1) % грани);
      if (наружу) idx.push(центр, b, a); else idx.push(центр, a, b);
    }
  }
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
  g.setAttribute('slot', new THREE.Float32BufferAttribute(слоты, 1));
  g.setIndex(idx);
  g.computeVertexNormals();
  return g;
}

/** Эллипсоид: середина, три полуоси, слот. */
function яйцо(cx: number, cy: number, cz: number, rx: number, ry: number, rz: number, слот: Слот, вдоль = 8, поперёк = 6): THREE.BufferGeometry {
  const g = new THREE.SphereGeometry(1, вдоль, поперёк).deleteAttribute('uv');
  g.scale(rx, ry, rz).translate(cx, cy, cz);
  g.setAttribute('slot', new THREE.Float32BufferAttribute(new Float32Array(g.getAttribute('position').count).fill(слот), 1));
  return g;
}

/** Склеить части в одну геометрию (все индексированные, одни атрибуты). */
function склеить(части: THREE.BufferGeometry[]): THREE.BufferGeometry {
  const pos: number[] = [], nor: number[] = [], сл: number[] = [], idx: number[] = [];
  for (const g of части) {
    const база = pos.length / 3;
    pos.push(...(g.getAttribute('position').array as Float32Array));
    nor.push(...(g.getAttribute('normal').array as Float32Array));
    сл.push(...(g.getAttribute('slot').array as Float32Array));
    const и = g.getIndex()!;
    for (let i = 0; i < и.count; i++) idx.push(и.getX(i) + база);
    g.dispose();
  }
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
  g.setAttribute('normal', new THREE.Float32BufferAttribute(nor, 3));
  g.setAttribute('slot', new THREE.Float32BufferAttribute(сл, 1));
  g.setIndex(idx);
  return g;
}

/**
 * Корпус — от промежности до макушки, стоя, от подошвы. Таз в брюках,
 * торс в одежде, плечи шире талии, шея, голова-яйцо. Волосы — второе
 * яйцо, сдвинутое назад и вверх: сверху и сзади оно накрывает голову,
 * спереди лицо выступает из-под него. По волосам и видно, куда человек
 * смотрит (до 27.09 для этого была тёмная накладка «лица»).
 */
function корпус(): THREE.BufferGeometry {
  const т = (y: number): number => y * H;
  // талия уже груди и бёдер, плечи покатые: первая редакция была прямой
  // трубой с плоским верхом и читалась коробкой на вешалке
  const тело = трубка([
    { y: т(0.47), rx: 0.085, rz: 0.125, слот: Слот.брюки },
    { y: т(ДОЛИ.бедро), rx: 0.1, rz: 0.16, слот: Слот.брюки },
    { y: т(0.585), rx: 0.09, rz: 0.138, слот: Слот.брюки },
    { y: т(0.59), rx: 0.092, rz: 0.138, слот: Слот.одежда },
    { y: т(0.66), rx: 0.102, rz: 0.148, слот: Слот.одежда },
    { y: т(0.73), rx: 0.113, rz: 0.163, dx: 0.01, слот: Слот.одежда },
    { y: т(0.785), rx: 0.105, rz: 0.172, dx: 0.004, слот: Слот.одежда },
    { y: т(0.812), rx: 0.088, rz: 0.158, слот: Слот.одежда },
    { y: т(0.828), rx: 0.064, rz: 0.1, слот: Слот.одежда },
    { y: т(0.838), rx: 0.05, rz: 0.058, слот: Слот.одежда },
  ], 10);
  const шея = трубка([
    { y: т(0.83), rx: 0.05, rz: 0.05, слот: Слот.кожа },
    { y: т(0.885), rx: 0.046, rz: 0.046, dx: 0.01, слот: Слот.кожа },
  ], 8);
  // середина головы чуть ниже глаз; глаза — на EYE_HEIGHT, как у игрока
  const гy = EYE_HEIGHT - 0.01;
  const голова = яйцо(0.012, гy, 0, 0.098, 0.118, 0.08, Слот.кожа);
  const волосы = яйцо(-0.006, гy + 0.03, 0, 0.1, 0.11, 0.087, Слот.волосы);
  // нос: с трёх метров по нему видно, куда повёрнута голова
  const нос = new THREE.BoxGeometry(0.03, 0.04, 0.026).deleteAttribute('uv').translate(0.112, гy - 0.03, 0);
  нос.setAttribute('slot', new THREE.Float32BufferAttribute(new Float32Array(нос.getAttribute('position').count).fill(Слот.кожа), 1));
  return склеить([тело, шея, голова, волосы, нос]);
}

/** Бедро: висит на тазобедренном суставе, начало координат — в суставе. */
const бедро = (): THREE.BufferGeometry => трубка([
  { y: 0.06, rx: 0.085, rz: 0.08, слот: Слот.брюки },
  { y: 0, rx: 0.088, rz: 0.083, слот: Слот.брюки },
  { y: -ЗВЕНО.бедро * 0.55, rx: 0.07, rz: 0.066, слот: Слот.брюки },
  { y: -ЗВЕНО.бедро - 0.02, rx: 0.055, rz: 0.055, слот: Слот.брюки },
]);
/** Голень со стопой: начало — в колене. Ботинок носком вперёд. */
function голень(): THREE.BufferGeometry {
  const нога = трубка([
    { y: 0.03, rx: 0.056, rz: 0.055, слот: Слот.брюки },
    { y: -ЗВЕНО.голень * 0.35, rx: 0.058, rz: 0.052, dx: -0.008, слот: Слот.брюки },
    { y: -ЗВЕНО.голень, rx: 0.045, rz: 0.043, слот: Слот.брюки },
  ]);
  const низ = -ЗВЕНО.голень - СУСТАВ.лодыжка;
  const ботинок = new THREE.BoxGeometry(0.25, СУСТАВ.лодыжка + 0.03, 0.095).deleteAttribute('uv');
  ботинок.translate(0.06, низ + (СУСТАВ.лодыжка + 0.03) / 2, 0);
  ботинок.setAttribute('slot', new THREE.Float32BufferAttribute(new Float32Array(ботинок.getAttribute('position').count).fill(Слот.обувь), 1));
  return склеить([нога, ботинок]);
}
/** Плечо (от плечевого сустава до локтя) — в рукаве. */
const плечо = (): THREE.BufferGeometry => трубка([
  { y: 0.005, rx: 0.05, rz: 0.048, слот: Слот.одежда },
  { y: -ЗВЕНО.плечо * 0.4, rx: 0.052, rz: 0.048, слот: Слот.одежда },
  { y: -ЗВЕНО.плечо - 0.015, rx: 0.043, rz: 0.042, слот: Слот.одежда },
]);
/** Предплечье с кистью: начало — в локте. */
function предплечье(): THREE.BufferGeometry {
  const рука = трубка([
    { y: 0.015, rx: 0.043, rz: 0.042, слот: Слот.одежда },
    { y: -ЗВЕНО.предплечье + 0.02, rx: 0.036, rz: 0.034, слот: Слот.одежда },
  ]);
  const кисть = яйцо(0.01, -ЗВЕНО.предплечье - 0.06, 0, 0.042, 0.075, 0.022, Слот.кожа, 5, 4);
  return склеить([рука, кисть]);
}

/** Кто стоит на улице: где, куда смотрит, во что одет и что делает. */
export interface Прохожий {
  x: number; y: number; z: number; yaw: number;
  colour: number; штаны: number; кожа: number; фаза: number;
  /** Сидит (на лавке): таз на высоте сиденья, бёдра вперёд, голени вниз. */
  сидит?: boolean;
  /** Рост в долях взрослого: вся фигура в этом масштабе. */
  рост?: number;
  /** Говорит: фаза жеста, радианы. Нет — руки висят или машут в такт шагу. */
  жест?: number;
}

/**
 * Размах маха на полной скорости, радианы. У идущего бедро уходит вперёд-
 * назад примерно на 15–20° в каждую сторону, рука меньше. Первая редакция
 * (до 27.09) ставила 30°, и пешеход маршировал.
 */
const РАЗМАХ = { бедро: 0.26, рука: 0.22 };
/** Сиденье лавки над землёй, м. */
const СИДЕНЬЕ = 0.47;

/** Волосы и обувь — из цветов одежды: у одного человека всегда одни и те же. */
const ВОЛОСЫ = [0x2a1f18, 0x3b2a1e, 0x4e3524, 0x6b4a2e, 0x8a6a45, 0xb89a6a, 0x1a1614, 0x777370];
const ОБУВЬ = [0x1c1b1a, 0x2e2622, 0x4a3a2c, 0xd8d6d0, 0x23262c];
function примета(a: number, b: number, из: readonly number[]): number {
  let h = Math.imul(a ^ 0x9e3779b9, 0x85ebca6b) ^ Math.imul(b + 0x632be5ab, 0xc2b2ae35);
  h = Math.imul(h ^ (h >>> 13), 0x27d4eb2d);
  return из[((h ^ (h >>> 16)) >>> 0) % из.length];
}

/**
 * Дальше `ДАЛЬ` человек меньше трёх точек экрана: его не рисуют вовсе,
 * а в полосе перед этим он растворяется узором — тем же, что деревья
 * (`РАСТВОРИТЬ`), поэтому граница дальности не видна, а рисовать приходится
 * в разы меньше людей: пешеходы есть по всему городу.
 */
const ДАЛЬ = 220;
const ПОЛОСА = 40;

/** Люди улицы: пять пачек частей, растущих по мере надобности. */
export function создатьЛюдей(сцена: THREE.Scene, глаз: THREE.Camera): { поставить(люди: readonly Прохожий[]): void } {
  const формы = { корпус: корпус(), бедро: бедро(), голень: голень(), плечо: плечо(), предплечье: предплечье() };
  /** Материал раскрашивает вершину цветом её слота; цвета слотов — у экземпляра. */
  const материал = new THREE.MeshStandardMaterial({ roughness: 0.9 });
  const uEye = { value: new THREE.Vector3() };
  /** Растворение вдали — одно на тело и на его тень. */
  const вдали = (shader: THREE.WebGLProgramParametersWithUniforms): void => {
    shader.uniforms.uEye = uEye;
    shader.vertexShader = 'uniform vec3 uEye;\nvarying float vFade;\n' + shader.vertexShader.replace('#include <begin_vertex>', `#include <begin_vertex>
        vFade = 1.0;
        #ifdef USE_INSTANCING
          vFade = clamp((${ДАЛЬ.toFixed(1)} - distance(uEye.xz, instanceMatrix[3].xz)) / ${ПОЛОСА.toFixed(1)}, 0.0, 1.0);
        #endif`);
    shader.fragmentShader = РАСТВОРИТЬ + shader.fragmentShader.replace('void main() {', РАСТВОРИТЬ_ТОЧКУ);
  };
  материал.onBeforeCompile = (shader) => {
    вдали(shader);
    shader.vertexShader = 'attribute float slot;\nattribute vec3 cA;\nattribute vec3 cB;\nattribute vec3 cC;\nattribute vec3 cD;\nattribute vec3 cE;\nvarying vec3 vSlot;\n'
      + shader.vertexShader.replace('#include <color_vertex>', `#include <color_vertex>
        vSlot = slot < 0.5 ? cA : slot < 1.5 ? cB : slot < 2.5 ? cC : slot < 3.5 ? cD : cE;`);
    shader.fragmentShader = 'varying vec3 vSlot;\n' + shader.fragmentShader
      .replace('#include <color_fragment>', '#include <color_fragment>\n  diffuseColor.rgb *= vSlot;');
  };
  const тень = new THREE.MeshDepthMaterial({ depthPacking: THREE.RGBADepthPacking });
  тень.onBeforeCompile = вдали;
  тень.customProgramCacheKey = () => 'прохожий-тень';
  материал.customProgramCacheKey = () => 'прохожий';

  type Пачка = { меш: THREE.InstancedMesh; цвета: THREE.InstancedBufferAttribute[] };
  let пачки: Record<keyof typeof формы, Пачка> | null = null;
  let запас = 0;

  const собрать = (сколько: number): void => {
    if (пачки !== null) for (const п of Object.values(пачки)) { сцена.remove(п.меш); п.меш.dispose(); }
    запас = сколько;
    const пачка = (g: THREE.BufferGeometry, n: number): Пачка => {
      const гео = g.clone();
      const цвета = ['cA', 'cB', 'cC', 'cD', 'cE'].map((имя) => {
        const а = new THREE.InstancedBufferAttribute(new Float32Array(n * 3), 3);
        гео.setAttribute(имя, а);
        return а;
      });
      const меш = new THREE.InstancedMesh(гео, материал, n);
      меш.customDepthMaterial = тень;
      меш.castShadow = true;
      меш.receiveShadow = true;
      меш.frustumCulled = false;
      меш.name = 'прохожие';
      сцена.add(меш);
      return { меш, цвета };
    };
    пачки = {
      корпус: пачка(формы.корпус, сколько), бедро: пачка(формы.бедро, сколько * 2), голень: пачка(формы.голень, сколько * 2),
      плечо: пачка(формы.плечо, сколько * 2), предплечье: пачка(формы.предплечье, сколько * 2),
    };
  };

  const m = new THREE.Matrix4(), q = new THREE.Quaternion(), e = new THREE.Euler(), где = new THREE.Vector3(), размер = new THREE.Vector3();
  const цвет = new THREE.Color();
  return {
    поставить(все) {
      uEye.value.copy(глаз.position);
      // дальше края не рисуем: там человек уже растворён (`ДАЛЬ`)
      const люди = все.filter((ч) => (ч.x - глаз.position.x) ** 2 + (ч.z - глаз.position.z) ** 2 < ДАЛЬ * ДАЛЬ);
      if (люди.length === 0 && пачки === null) return;
      if (пачки === null || люди.length > запас) собрать(Math.max(64, люди.length * 2));
      const п = пачки!;
      п.корпус.меш.count = люди.length;
      for (const к of ['бедро', 'голень', 'плечо', 'предплечье'] as const) п[к].меш.count = люди.length * 2;

      let k = 1;
      /** Поставить часть: сустав в местных осях (вперёд, вверх, вбок) + поворот вперёд-назад. */
      const часть = (пачка: Пачка, номер: number, ч: Прохожий, вперёд: number, вверх: number, вбок: number, угол: number, цвета: readonly number[]): void => {
        const cos = Math.cos(ч.yaw), sin = Math.sin(ч.yaw);
        const a = вперёд * k, b = вверх * k, c = вбок * k;
        где.set(ч.x + a * cos - c * sin, ч.y + b, ч.z + a * sin + c * cos);
        e.set(0, -ч.yaw, угол, 'YZX');
        q.setFromEuler(e);
        m.compose(где, q, размер);
        пачка.меш.setMatrixAt(номер, m);
        цвета.forEach((ц, s) => { цвет.setHex(ц); пачка.цвета[s].setXYZ(номер, цвет.r, цвет.g, цвет.b); });
      };

      люди.forEach((ч, i) => {
        k = ч.рост ?? 1;
        размер.set(k, k, k);
        const цвета = [ч.colour, ч.штаны, ч.кожа, примета(ч.colour, ч.кожа, ВОЛОСЫ), примета(ч.штаны, ч.colour, ОБУВЬ)];
        const сидит = ч.сидит === true;
        /**
         * Мах растёт от того, идёт человек или стоит: стоящий фазу не двигает
         * вовсе, поэтому «стоит и семенит» невыразимо — махи из того же, что шаг.
         */
        const махРук = -Math.sin(ч.фаза) * РАЗМАХ.рука;
        // таз опускается к сиденью; корпус качается в такт — два покачивания за шаг
        const вниз = сидит ? СУСТАВ.бедро - СИДЕНЬЕ : 0;
        const качка = сидит ? 0 : Math.cos(ч.фаза * 2) * 0.014;
        часть(п.корпус, i, ч, 0, качка - вниз, 0, 0, цвета);
        for (const бок of [0, 1]) {
          const знак = бок === 0 ? 1 : -1;
          /**
           * Колено гнётся в переносе — когда бедро идёт вперёд (cos фазы > 0),
           * сильнее всего В СЕРЕДИНЕ переноса, когда бедро уже под телом;
           * в опоре — чуть согнуто. Первая редакция гнула сильнее всего сразу
           * после отрыва стопы, пока бедро ещё сзади, — голень задиралась
           * назад, и человек шёл выпадами. Сгиб не бывает меньше нуля: колено
           * назад не выворачивается по устройству.
           */
          const фаза = ч.фаза + (бок === 0 ? 0 : Math.PI);
          const уголБедра = сидит ? 1.45 : Math.sin(фаза) * РАЗМАХ.бедро;
          const сгибКолена = сидит ? 1.45 : 0.08 + 0.72 * Math.max(0, Math.cos(фаза - 0.15)) ** 3;
          const бедроY = СУСТАВ.бедро + качка - вниз;
          часть(п.бедро, i * 2 + бок, ч, 0, бедроY, знак * ВБОК.бедро, уголБедра, цвета);
          // колено — конец бедра, повёрнутого на свой угол
          const коленоX = Math.sin(уголБедра) * ЗВЕНО.бедро, коленоY = бедроY - Math.cos(уголБедра) * ЗВЕНО.бедро;
          часть(п.голень, i * 2 + бок, ч, коленоX, коленоY, знак * ВБОК.бедро, уголБедра - сгибКолена, цвета);

          // говорящий поднимает правую руку и водит ею; левая почти висит
          const уголПлеча = сидит ? 0.45
            : ч.жест !== undefined ? (бок === 0 ? 0.55 + Math.sin(ч.жест) * 0.25 : 0.08 + Math.sin(ч.жест * 0.6) * 0.05)
              : знак * махРук;
          const сгибЛоктя = сидит ? 0.9 : ч.жест !== undefined && бок === 0 ? 1.0 + Math.sin(ч.жест * 1.3) * 0.2 : 0.22 + 0.25 * Math.max(0, уголПлеча);
          const плечоY = СУСТАВ.плечо + качка - вниз;
          часть(п.плечо, i * 2 + бок, ч, 0, плечоY, знак * ВБОК.плечо, уголПлеча, цвета);
          const локотьX = Math.sin(уголПлеча) * ЗВЕНО.плечо, локотьY = плечоY - Math.cos(уголПлеча) * ЗВЕНО.плечо;
          часть(п.предплечье, i * 2 + бок, ч, локотьX, локотьY, знак * ВБОК.плечо, уголПлеча + сгибЛоктя, цвета);
        }
      });
      for (const пачка of Object.values(п)) {
        пачка.меш.instanceMatrix.needsUpdate = true;
        for (const а of пачка.цвета) а.needsUpdate = true;
      }
    },
  };
}
