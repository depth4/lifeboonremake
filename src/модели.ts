/**
 * Вещи двора — формой, а не коробкой.
 *
 * Зачем отдельный файл: до 24.09 каждая вещь двора рисовалась одной цветной
 * коробкой её размера, и детская площадка сверху читалась как «странное
 * строение из коробок» (Алекс, 24.09). Горку узнают по лесенке и скату,
 * качели — по А-образной раме, песочницу — по бортикам и грибку. Это форма,
 * и ей место не в `render.ts` (там уже полторы тысячи строк про всё сразу),
 * а здесь: одна вещь — один список частей.
 *
 * Оси модели те же, что у `Вещь` в `city/двор.ts`: x — вдоль (длина, курс),
 * z — поперёк (ширина), y — вверх от земли. Размеры настоящие, в метрах;
 * вещь одного вида всегда одного размера, поэтому модель ставится без растяжения.
 */

import * as THREE from 'three';
import type { ЧтоВоДворе } from './city/двор.ts';

export interface Часть {
  readonly форма: 'коробка' | 'цилиндр';
  /** Середина части. */
  readonly x: number; readonly y: number; readonly z: number;
  /** Размер: для цилиндра sx — диаметр, sy — высота. */
  readonly sx: number; readonly sy: number; readonly sz: number;
  readonly цвет: number;
  /** Наклон вокруг поперечной оси (z), радианы: скат горки, ноги качелей. */
  readonly наклонZ?: number;
  /** Наклон вокруг продольной оси (x), радианы. */
  readonly наклонX?: number;
}

const к = (x: number, y: number, z: number, sx: number, sy: number, sz: number, цвет: number,
  наклон: { z?: number; x?: number } = {}): Часть => ({ форма: 'коробка', x, y, z, sx, sy, sz, цвет, наклонZ: наклон.z, наклонX: наклон.x });
const ц = (x: number, y: number, z: number, d: number, h: number, цвет: number): Часть =>
  ({ форма: 'цилиндр', x, y, z, sx: d, sy: h, sz: d, цвет });

const ДЕРЕВО = 0x9b6a3f, МЕТАЛЛ = 0x39424a, КРАСНЫЙ = 0xc0392b, ЖЁЛТЫЙ = 0xe9b824, СИНИЙ = 0x2e6fb0;
const БЕТОН = 0x9c978f, ПЕСОК = 0xd9c48c, РЕЗИНА = 0xa9553f, ЗЕЛЁНЫЙ = 0x2f6b3a;

/** Горка: площадка на четырёх стойках, лесенка сзади, скат вперёд. */
function горка(): Часть[] {
  const ч: Часть[] = [];
  for (const sx of [-1, 1]) for (const sz of [-1, 1]) ч.push(ц(-0.6 + sx * 0.42, 0.85, sz * 0.42, 0.08, 1.7, КРАСНЫЙ));
  ч.push(к(-0.6, 1.2, 0, 0.95, 0.06, 0.95, ДЕРЕВО));
  for (const sz of [-1, 1]) ч.push(к(-0.6, 1.45, sz * 0.46, 0.95, 0.06, 0.04, КРАСНЫЙ));
  // лесенка
  for (const sz of [-1, 1]) ч.push(к(-1.25, 0.6, sz * 0.3, 0.05, 1.3, 0.05, МЕТАЛЛ, { z: -0.35 }));
  for (let i = 1; i <= 4; i++) ч.push(к(-1.25 - 0.04 * i + 0.1, i * 0.26, 0, 0.05, 0.04, 0.62, МЕТАЛЛ));
  // скат: от края площадки вниз к земле
  const a = { x: -0.13, y: 1.2 }, b = { x: 1.3, y: 0.25 };
  const L = Math.hypot(b.x - a.x, b.y - a.y), угол = Math.atan2(b.y - a.y, b.x - a.x);
  ч.push(к((a.x + b.x) / 2, (a.y + b.y) / 2, 0, L, 0.05, 0.56, ЖЁЛТЫЙ, { z: угол }));
  for (const sz of [-1, 1]) ч.push(к((a.x + b.x) / 2, (a.y + b.y) / 2 + 0.1, sz * 0.29, L, 0.2, 0.04, ЖЁЛТЫЙ, { z: угол }));
  return ч;
}

/** Качели: две А-образные рамы, перекладина, два сиденья на подвесах. */
function качели(): Часть[] {
  const ч: Часть[] = [];
  const Н = 2.3, раствор = 0.8;
  const нога = Math.hypot(Н, раствор), наклон = Math.atan2(раствор, Н);
  // нога идёт от земли (раствор в сторону) к перекладине (посередине): верх наклонён внутрь
  for (const sx of [-1.5, 1.5]) for (const sz of [-1, 1]) ч.push(к(sx, Н / 2, sz * раствор / 2, 0.08, нога, 0.08, СИНИЙ, { x: -sz * наклон }));
  ч.push(к(0, Н, 0, 3.1, 0.09, 0.09, СИНИЙ));
  for (const sx of [-0.7, 0.7]) {
    ч.push(к(sx, 0.45, 0, 0.45, 0.05, 0.25, ДЕРЕВО));
    for (const sz of [-1, 1]) ч.push(к(sx + sz * 0.2, (0.45 + Н) / 2, 0, 0.02, Н - 0.45, 0.02, МЕТАЛЛ));
  }
  return ч;
}

/** Лавка: три доски сиденья, две спинки, две опоры. */
function лавка(): Часть[] {
  const ч: Часть[] = [];
  for (let i = 0; i < 3; i++) ч.push(к(0, 0.45, -0.12 + i * 0.13, 1.8, 0.04, 0.11, ДЕРЕВО));
  for (const y of [0.66, 0.82]) ч.push(к(0, y, -0.22, 1.8, 0.1, 0.03, ДЕРЕВО));
  for (const sx of [-0.7, 0.7]) {
    ч.push(к(sx, 0.22, 0, 0.07, 0.44, 0.42, МЕТАЛЛ));
    ч.push(к(sx, 0.64, -0.21, 0.07, 0.44, 0.05, МЕТАЛЛ));
  }
  return ч;
}

/** Баки: три контейнера с крышками за трёхсторонней оградкой. */
function баки(): Часть[] {
  const ч: Часть[] = [];
  for (const sx of [-1.45, 0, 1.45]) {
    ч.push(к(sx, 0.5, 0.05, 1.25, 1.0, 0.95, ЗЕЛЁНЫЙ));
    ч.push(к(sx, 1.03, 0.05, 1.3, 0.06, 1.0, 0x24502c));
  }
  ч.push(к(0, 0.8, -0.6, 4.6, 1.6, 0.08, БЕТОН));
  for (const sx of [-2.3, 2.3]) ч.push(к(sx, 0.8, 0, 0.08, 1.6, 1.2, БЕТОН));
  return ч;
}

/** Песочница: бортики, песок и «грибок» — столб с круглой крышей. */
function песочница(): Часть[] {
  const ч: Часть[] = [];
  for (const s of [-1, 1]) {
    ч.push(к(s * 1.44, 0.15, 0, 0.12, 0.3, 3.0, ДЕРЕВО));
    ч.push(к(0, 0.15, s * 1.44, 3.0, 0.3, 0.12, ДЕРЕВО));
  }
  ч.push(к(0, 0.1, 0, 2.8, 0.2, 2.8, ПЕСОК));
  ч.push(ц(1.0, 1.1, 1.0, 0.1, 2.2, ДЕРЕВО));
  ч.push(ц(1.0, 2.2, 1.0, 2.0, 0.12, КРАСНЫЙ));
  return ч;
}

/** Карусель: круглый настил на оси, поручни крестом. */
function карусель(): Часть[] {
  const ч: Часть[] = [ц(0, 0.2, 0, 0.3, 0.4, МЕТАЛЛ), ц(0, 0.4, 0, 2.2, 0.08, КРАСНЫЙ), ц(0, 0.9, 0, 0.08, 1.0, МЕТАЛЛ)];
  for (let i = 0; i < 4; i++) {
    const а = (i * Math.PI) / 2, cx = Math.cos(а) * 0.45, cz = Math.sin(а) * 0.45;
    ч.push(к(cx, 1.05, cz, Math.abs(Math.cos(а)) * 0.9 + 0.04, 0.04, Math.abs(Math.sin(а)) * 0.9 + 0.04, ЖЁЛТЫЙ));
    ч.push(к(Math.cos(а) * 0.9, 0.72, Math.sin(а) * 0.9, 0.04, 0.6, 0.04, МЕТАЛЛ));
  }
  return ч;
}

/** Хоккейная коробка: асфальт, борта, двое ворот. */
function коробка(): Часть[] {
  const Д = 26, Ш = 14;
  /**
   * Пол — плита от метра под землёй до 4 см над ней. Коробка 26×14 встаёт на
   * самую высокую землю под следом (`верхЗемли`), и земля под ней ниже —
   * тонкая плита висела бы над ней, а земля пробивала бы её полосами.
   */
  const ч: Часть[] = [к(0, -0.48, 0, Д, 1.04, Ш, 0x5c6066)];
  for (const s of [-1, 1]) {
    ч.push(к(0, 0.6, s * Ш / 2, Д, 1.2, 0.08, 0xd8d6cf));
    ч.push(к(s * Д / 2, 0.6, 0, 0.08, 1.2, Ш - 3, 0xd8d6cf));
    // ворота: две стойки и перекладина
    for (const sz of [-1, 1]) ч.push(к(s * (Д / 2 - 1.5), 0.6, sz * 0.9, 0.06, 1.2, 0.06, КРАСНЫЙ));
    ч.push(к(s * (Д / 2 - 1.5), 1.2, 0, 0.06, 0.06, 1.86, КРАСНЫЙ));
    ч.push(к(s * (Д / 2 - 1.1), 0.6, 0, 0.8, 1.2, 1.8, 0xe8e8e8));
  }
  return ч;
}

/** Беседка: настил, четыре столба, низкие перила с трёх сторон, крыша. */
function беседка(): Часть[] {
  const ч: Часть[] = [к(0, 0.08, 0, 4, 0.16, 4, ДЕРЕВО)];
  for (const sx of [-1, 1]) for (const sz of [-1, 1]) ч.push(к(sx * 1.9, 1.4, sz * 1.9, 0.14, 2.6, 0.14, ДЕРЕВО));
  for (const s of [-1, 1]) ч.push(к(0, 0.55, s * 1.9, 3.8, 0.8, 0.06, ДЕРЕВО));
  ч.push(к(-1.9, 0.55, 0, 0.06, 0.8, 3.8, ДЕРЕВО));
  ч.push(к(0, 2.72, 0, 4.6, 0.14, 4.6, ЗЕЛЁНЫЙ));
  ч.push(к(0, 2.95, 0, 3.0, 0.32, 3.0, ЗЕЛЁНЫЙ));
  ч.push(к(0, 3.2, 0, 1.4, 0.2, 1.4, ЗЕЛЁНЫЙ));
  return ч;
}

/** Стол доминошников: столешница на двух ногах. */
function стол(): Часть[] {
  return [к(0, 0.74, 0, 1.8, 0.05, 0.9, ДЕРЕВО), к(-0.7, 0.36, 0, 0.08, 0.72, 0.7, МЕТАЛЛ), к(0.7, 0.36, 0, 0.08, 0.72, 0.7, МЕТАЛЛ)];
}

/** Сушилка для белья: две Т-образные стойки и четыре верёвки. */
function сушилка(): Часть[] {
  const ч: Часть[] = [];
  for (const sx of [-3, 3]) {
    ч.push(ц(sx, 1.0, 0, 0.08, 2.0, МЕТАЛЛ));
    ч.push(к(sx, 1.95, 0, 0.06, 0.06, 1.2, МЕТАЛЛ));
  }
  for (let i = 0; i < 4; i++) ч.push(к(0, 1.93, -0.45 + i * 0.3, 6, 0.015, 0.015, 0xe0e0e0));
  return ч;
}

/** Клумба: бетонный бортик, земля и цветы — от места, не случайно. */
function клумба(): Часть[] {
  const ч: Часть[] = [];
  for (const s of [-1, 1]) {
    ч.push(к(s * 0.95, 0.15, 0, 0.1, 0.3, 1.0, БЕТОН));
    ч.push(к(0, 0.15, s * 0.45, 2.0, 0.3, 0.1, БЕТОН));
  }
  ч.push(к(0, 0.13, 0, 1.8, 0.26, 0.8, 0x4a3526));
  const цвета = [0xd6334a, 0xf2c230, 0xe98ab0, 0xf4f1ea, 0xc8452c, 0x8e5cc2];
  for (let i = 0; i < 18; i++) {
    const x = -0.78 + ((i * 0.618) % 1) * 1.56, z = -0.3 + ((i * 0.414 + 0.2) % 1) * 0.6;
    ч.push(к(x, 0.3 + (i % 3) * 0.04, z, 0.11, 0.1, 0.11, цвета[i % цвета.length]));
    ч.push(к(x, 0.24, z, 0.03, 0.14, 0.03, 0x3f7a2e));
  }
  return ч;
}

/** Турник: две стойки и перекладина. */
function турник(): Часть[] {
  return [ц(-1, 1.2, 0, 0.08, 2.4, МЕТАЛЛ), ц(1, 1.2, 0, 0.08, 2.4, МЕТАЛЛ), к(0, 2.3, 0, 2.0, 0.04, 0.04, МЕТАЛЛ)];
}

/** Детская площадка — сама земля: резиновое покрытие в низком бортике. */
function площадка(): Часть[] {
  const Д = 12, Ш = 9;
  // покрытие и бортик — до метра под землёй, как пол коробки: земля под следом неровная
  const ч: Часть[] = [к(0, -0.46, 0, Д, 1.08, Ш, РЕЗИНА)];
  for (const s of [-1, 1]) {
    ч.push(к(0, -0.42, s * Ш / 2, Д, 1.16, 0.12, БЕТОН));
    ч.push(к(s * Д / 2, -0.42, 0, 0.12, 1.16, Ш, БЕТОН));
  }
  return ч;
}

const СОСТАВ: Record<ЧтоВоДворе, () => Часть[]> = {
  площадка, горка, качели, лавка, баки, песочница, карусель, коробка, беседка, стол, сушилка, клумба, турник,
};

/**
 * Из каких частей вещь. Тот же список, из которого собирается её сетка,
 * отдаётся и тверди (`city/твердь.ts`): твёрдо ровно то, что нарисовано.
 */
export const частиВещи = (что: ЧтоВоДворе): readonly Часть[] => СОСТАВ[что]();

/** Собрать вещь в одну сетку с цветами вершин: одна вещь вида — один экземпляр пачки. */
export function модельВещи(что: ЧтоВоДворе): THREE.BufferGeometry {
  const поз: number[] = [], норм: number[] = [], цвет: number[] = [];
  const с = new THREE.Color();
  const м = new THREE.Matrix4(), кв = new THREE.Quaternion(), эйлер = new THREE.Euler();
  for (const ч of частиВещи(что)) {
    const g0 = ч.форма === 'коробка' ? new THREE.BoxGeometry(ч.sx, ч.sy, ч.sz) : new THREE.CylinderGeometry(ч.sx / 2, ч.sx / 2, ч.sy, 10);
    const g = g0.toNonIndexed();
    g0.dispose();
    эйлер.set(ч.наклонX ?? 0, 0, ч.наклонZ ?? 0);
    кв.setFromEuler(эйлер);
    м.compose(new THREE.Vector3(ч.x, ч.y, ч.z), кв, new THREE.Vector3(1, 1, 1));
    g.applyMatrix4(м);
    const p = g.getAttribute('position'), n = g.getAttribute('normal');
    с.setHex(ч.цвет);
    for (let i = 0; i < p.count; i++) {
      поз.push(p.getX(i), p.getY(i), p.getZ(i));
      норм.push(n.getX(i), n.getY(i), n.getZ(i));
      цвет.push(с.r, с.g, с.b);
    }
    g.dispose();
  }
  const итог = new THREE.BufferGeometry();
  итог.setAttribute('position', new THREE.Float32BufferAttribute(поз, 3));
  итог.setAttribute('normal', new THREE.Float32BufferAttribute(норм, 3));
  итог.setAttribute('color', new THREE.Float32BufferAttribute(цвет, 3));
  return итог;
}
